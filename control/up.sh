#!/usr/bin/env bash
# Подъём контроллера одной командой: образ → контейнер → отвечает.
#
#   ./control/up.sh                поднять контроллер (петля, порт 8090)
#   ./control/up.sh --build        собрать образ из исходников и поднять — путь РАЗРАБОТЧИКА
#   ./control/up.sh status         что сейчас: контейнер, здоровье, порт, состояние
#   ./control/up.sh down           снять контроллер; состояние (ключи, скоупы) остаётся
#   ./control/up.sh down --with-state   снять вместе с состоянием: ключи и скоупы стираются
#
# ┌─────────────────────────────────────────────────────────────────────────────────────┐
# │ КОНТРОЛЛЕР СТАВИТ ЧЕЛОВЕК, И ТОЛЬКО ЧЕЛОВЕК. Ни мир, ни другой контроллер его не      │
# │ разворачивают: цепочка начинается с юзера, и первое звено не автоматизируется         │
# │ (`control/README.md`, `WORLD2` 3.7). Эта команда — то самое первое звено.             │
# │                                                                                      │
# │ Ставь его там, где не жалко: у контроллера есть докер-сокет, то есть власть над этой  │
# │ машиной. Захватили контроллер — захватили ЭТОТ ресурс. Поэтому наружу он по умолчанию │
# │ не торчит: публикация только в петлю (`CONTROL_BIND`).                                │
# └─────────────────────────────────────────────────────────────────────────────────────┘
#
# ┌─────────────────────────────────────────────────────────────────────────────────────┐
# │ ОБРАЗ ПРИЕЗЖАЕТ ГОТОВЫМ — ЮЗЕР ЕГО НЕ СОБИРАЕТ (`WORLD2-110`).                        │
# │                                                                                      │
# │ Собрать контроллер значит собрать пульт, а пульту нужно ПОЛЕ: пакеты лежат на складе, │
# │ видном только соседям по сети мира. Требовать поле от того, кто мир ещё не поднял, —  │
# │ это круг. Поэтому умолчание перевёрнуто: тянем готовое, а сборка осталась ключом      │
# │ `--build` для того, кто правит саму зону.                                             │
# │                                                                                      │
# │ ЧТО ЗДЕСЬ ЗАМЕНИЛО ПРЕЖНЕЕ `--build` ВСЕГДА. Раньше образ пересобирался на каждом     │
# │ подъёме, и это была защита от «поднял старый образ и не заметил» (`WORLD2-92`) —      │
# │ ложного результата, из-за которого проба зеленеет впустую. Готовый образ эту защиту   │
# │ снимает, поэтому вместо неё:                                                          │
# │   1. образ тянется ЯВНО и отдельным шагом — не «как-нибудь получится» при подъёме;    │
# │   2. подъём говорит, ЧТО именно поднято: тег и digest, снятые с живого контейнера.    │
# │ Молчаливого «поднял то, что валялось» не бывает ни в одной ветке.                     │
# └─────────────────────────────────────────────────────────────────────────────────────┘
#
# Имена переменных ЛАТИНСКИЕ: bash не поддерживает не-ASCII в именах и молча превращает
# `ПОРТ=8090` в «команда не найдена». Тексты и комментарии — русские.
set -euo pipefail
# Ступени отказов различаются по тексту системных сообщений, а он переводится.
export LC_ALL=C

HERE="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd -- "$HERE/.." && pwd)"
COMPOSE_FILE="$HERE/compose.yaml"
NAME=world-control

# Порт, петля и время ожидания — значения, а не константы: их называет хозяин машины.
PORT="${CONTROL_PORT:-8090}"
BIND="${CONTROL_BIND:-127.0.0.1}"
# Адрес, по которому МАШИНА видит свой же опубликованный порт. Отдельным значением по той
# же причине, что у соседа (`deploy/up.sh`): демон докера и человек не всегда на одной
# петле (живой случай — докер в WSL, команда из Git Bash).
HOST="${CONTROL_HOST:-127.0.0.1}"
WAIT="${CONTROL_WAIT:-60}"
# Спрашивать ли реестр. `1` — не спрашивать и поднять то, что уже лежит на машине. Это
# СОЗНАТЕЛЬНЫЙ выход из отказа «реестр недоступен», а не удобство: он назван вслух в самом
# отказе и вслух же назван при подъёме. Умолчанием такого не делают — с него и начинался
# ложный результат `WORLD2-92`.
OFFLINE="${CONTROL_OFFLINE:-0}"

usage() {
    cat <<'USAGE'
Контроллер мира — руки юзера: ./control/up.sh <команда>

  (без команды)          поднять контроллер: притянуть готовый образ и запустить
  --build                собрать образ ЗДЕСЬ из исходников и поднять — путь разработчика
                         зоны; ему нужно поле (внутрь образа кладётся собранный пульт)
  status                 что сейчас: контейнер, здоровье, порт, образ, состояние
  down [--with-state]    снять; --with-state стирает ключи и заведённые здесь скоупы
  -h --help              эта подсказка

Значения:
  CONTROL_PORT=8090        хост-порт контроллера
  CONTROL_BIND=127.0.0.1   на какой петле публиковать; 0.0.0.0 — наружу, СОЗНАТЕЛЬНО
  CONTROL_HOST=127.0.0.1   адрес, по которому эта машина видит свой опубликованный порт
  CONTROL_WAIT=60          сколько секунд ждём, пока контроллер станет здоровым
  CONTROL_IMAGE=…          какой образ поднимать; умолчание — в control/compose.yaml.
                           Так поднимают НАЗВАННЫЙ выпуск вместо подвижного latest:
                           CONTROL_IMAGE=ghcr.io/omnifield/world-control:sha-a030d21
  CONTROL_OFFLINE=1        реестр не спрашивать, поднять образ, который уже лежит здесь
  WORLD_PORT=8080          хост-порт двери на ресурсах, которые контроллер будет добавлять

Что появляется на этой машине: контейнер world-control и три тома (ключи, контексты
докера, скоупы, заведённые здесь). Больше ничего — ни файлов, ни пакетов.

ПУЛЬТ (лицо для человека) приезжает ВНУТРИ образа — собирать его юзеру не нужно и нечем:
сборке нужно поле. Собранный пульт требуется только пути --build.

Отказ печатается двумя строками: причина и выход — человеку, `CONTROL-REFUSAL: <код>` —
машине. Коды: no-docker · no-compose · no-daemon · no-compose-file · no-image-name ·
no-registry · no-image-tag · image-denied · pull-failed · no-image-local · bad-value ·
no-pult-artifact · port-busy · up-failed · control-silent · no-container.
USAGE
}

# ------------------------------------------------------------------ разговор
step()   { printf '\n\033[1m→ %s\033[0m\n' "$*" >&2; }
ok()     { printf '  ✓ %s\n' "$*" >&2; }
warn()   { printf '  \033[33m!\033[0m %s\n' "$*" >&2; }
say()    { printf '%s\n' "$*" >&2; }
detail() { printf '      %s\n' "$*" >&2; }

# refuse <код> <причина> <выход…> — единственный способ выйти с ошибкой. Причина и выход
# обязательны оба: «нельзя» без выхода — провал самого мира (`WORLD2` 2.3). Код идёт в
# stdout и предназначен машине; проба стережёт КОД, а не формулировку (`WORLD2` 4.2).
refuse() {
    local code="$1" why="$2"; shift 2
    printf 'CONTROL-REFUSAL: %s\n' "$code"
    printf '\n\033[1;31m✗ отказ:\033[0m %s\n' "$why" >&2
    local line; for line in "$@"; do printf '  выход: %s\n' "$line" >&2; done
    exit 1
}

# Место под вывод докера: причину отказа мы РАЗБИРАЕМ, а значит она должна где-то лежать
# целиком. Убирается всегда — и на отказе тоже.
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# ------------------------------------------------------------------ чем поднимаем
need_tools() {
    command -v docker >/dev/null 2>&1 || refuse no-docker \
        "докера на этой машине нет — поднимать контроллер нечем" \
        "поставь Docker Engine либо Docker Desktop: https://docs.docker.com/engine/install/" \
        "докер — единственное, что мир требует на машине юзера (TECH 2)"

    docker compose version >/dev/null 2>&1 || refuse no-compose \
        "у докера нет compose v2 (плагина docker-compose-plugin)" \
        "поставь плагин: https://docs.docker.com/compose/install/" \
        "им же поднимается дверь — тот же плагин нужен и зоне deploy"

    docker info >/dev/null 2>&1 || refuse no-daemon \
        "докер есть, а демон не отвечает — контроллеру нечем распоряжаться машиной" \
        "запусти его: systemctl start docker (либо открой Docker Desktop)" \
        "демон работает — дело в правах: usermod -aG docker \$USER и перезайти"

    [ -f "$COMPOSE_FILE" ] || refuse no-compose-file \
        "файла запуска $COMPOSE_FILE нет" \
        "зови скрипт из репозитория: ./control/up.sh" \
        "файл потерян — возьми его из репозитория заново"
}

compose() { docker compose -f "$COMPOSE_FILE" "$@"; }

# ------------------------------------------------------------------ образ
# Имя образа спрашиваем у файла запуска, а не держим здесь второй копией. Копия разъехалась
# бы с оригиналом молча — и подъём тянул бы не тот образ, который публикует выпуск соседа.
compose_image() { compose config --images 2>/dev/null | head -n1; }

# image_here <имя> — лежит ли образ на этой машине.
image_here() { docker image inspect "$1" >/dev/null 2>&1; }

# offline_way <имя> — последняя строка выхода у всех отказов про реестр. Отказ обязан вести
# куда-то (`WORLD2` 2.3), а куда — зависит от того, есть ли образ на машине. Говорить «возьми
# то, что лежит» когда там ничего не лежит, значит отправлять человека в пустоту.
offline_way() {
    if image_here "$1"; then
        printf 'образ уже лежит на этой машине — поднять ЕГО, не спрашивая реестр: CONTROL_OFFLINE=1 ./control/up.sh'
    else
        printf 'образа на этой машине тоже нет — поднимать нечего, пока реестр недоступен'
    fi
}

# pull_image <имя> — притянуть образ и назвать ступень, на которой не вышло.
#
# Ступеней три, и чинят их РАЗНЫЕ люди: дороги нет (сеть, реестр молчит) — хозяин машины;
# такого тега нет — тот, кто выпускает; доступ закрыт — хозяин организации в реестре. Общее
# «не скачалось» отправило бы человека чинить наугад; та же лестница у шлюза и у ручек
# контроллера (`control/README.md`, «ступени связи»).
pull_image() {
    local image="$1" log="$TMP/pull.log" out
    docker pull "$image" >"$log" 2>&1 && return 0

    out="$(cat "$log" 2>/dev/null || true)"
    printf '%s\n' "$out" | tail -n 3 | while IFS= read -r l; do detail "$l"; done

    # Разбираем то, что сказал докер. Порядок веток — от точного к общему: `denied` у ghcr
    # приходит и на закрытый пакет, и на «нет входа», и докер их не различает.
    case "$out" in
        *denied*|*unauthorized*|*"authentication required"*|*"403 Forbidden"*)
            refuse image-denied \
                "реестр не отдал $image: доступ закрыт" \
                "ПЕРВЫЙ выпуск создаёт ПРИВАТНЫЙ пакет — таково умолчание реестра, и снаружи это выглядит как «образа нет». Открывает его хозяин организации, один раз, руками" \
                "тем же «denied» реестр отвечает и на образ, которого у него нет вовсе: этих двух случаев докер не различает — проверь имя, прежде чем идти в настройки пакета" \
                "если пакет закрыт намеренно — войди своим ключом: docker login ${image%%/*}" \
                "$(offline_way "$image")" ;;
        *"manifest unknown"*|*"manifest for"*|*"no such manifest"*|*"not found"*)
            refuse no-image-tag \
                "реестр ответил, а образа $image у него нет" \
                "проверь имя и тег: они приходят из control/compose.yaml либо из CONTROL_IMAGE" \
                "такой выпуск мог ещё не выйти — возьми подвижный latest либо тег другого выпуска" \
                "$(offline_way "$image")" ;;
        *"dial tcp"*|*"no such host"*|*"i/o timeout"*|*"connection refused"*|*"network is unreachable"*|*"TLS handshake"*|*"certificate"*|*"proxyconnect"*)
            refuse no-registry \
                "до реестра ${image%%/*} нет дороги — сети нет либо он не отвечает" \
                "проверь выход наружу с этой машины: docker pull hello-world" \
                "$(offline_way "$image")" ;;
        *)
            refuse pull-failed \
                "образ $image не притянулся, и докер назвал причину выше" \
                "повтори руками, чтобы увидеть её целиком: docker pull $image" \
                "$(offline_way "$image")" ;;
    esac
}

# report_running — что ПОДНЯТО на самом деле. Спрашиваем живой контейнер, а не свои же
# намерения: выведенное состояние врёт ровно тогда, когда на него смотрят (`WORLD2` 4.2).
# Тег отвечает «что просили», digest — «что приехало»; без второго `latest` неотличим от
# `latest` недельной давности.
report_running() {
    local asked real digest created gone=
    asked="$(docker inspect --format '{{.Config.Image}}' "$NAME" 2>/dev/null || true)"
    real="$(docker inspect --format '{{.Image}}' "$NAME" 2>/dev/null || true)"
    # Спрашиваем образ ОТДЕЛЬНО от чтения его полей: пустой ответ на поле и «образа нет
    # вовсе» — разные вещи, а выглядят одинаково. Первое значит «собран здесь», второе —
    # «контейнер живёт образом, которого на машине уже нет», и выдать одно за другое
    # значит соврать ровно там, где этот вывод и читают.
    if [ -n "$real" ] && docker image inspect "$real" >/dev/null 2>&1; then
        digest="$(docker image inspect --format '{{if .RepoDigests}}{{index .RepoDigests 0}}{{end}}' "$real" 2>/dev/null || true)"
        created="$(docker image inspect --format '{{.Created}}' "$real" 2>/dev/null || true)"
    else
        gone=1
    fi
    say ""
    say "поднят образ : ${asked:-НЕИЗВЕСТЕН — докер не сказал, чем поднят контейнер}"
    if [ -n "$gone" ]; then
        say "  digest     : не спросить — образа, которым поднят контейнер, на машине уже нет"
    elif [ -n "${digest:-}" ]; then
        say "  digest     : ${digest#*@}"
    else
        # Молчать тут нельзя: пустая строка читается как «всё в порядке», а это ровно тот
        # случай, когда поднято НЕ то, что лежит в реестре.
        say "  digest     : нет — образ собран на этой машине и в реестре не лежит"
    fi
    [ -n "${created:-}" ] && say "  собран     : $created"
    return 0
}

# ------------------------------------------------------------------ up
cmd_up() {
    # Значение, которого мы не понимаем, не проглатывается молча — то же правило, что и у
    # ручек контроллера с лишним полем в теле. Написавший `CONTROL_OFFLINE=true` ждал
    # офлайна, а получил бы поход в реестр и отказ про сеть: причину не свою и не ту.
    case "$OFFLINE" in
        0|1) ;;
        *) refuse bad-value \
            "CONTROL_OFFLINE=$OFFLINE — такого значения нет, а угадывать за тебя нельзя" \
            "спрашивать реестр (как обычно): убери переменную либо CONTROL_OFFLINE=0" \
            "не спрашивать и поднять то, что уже лежит здесь: CONTROL_OFFLINE=1" ;;
    esac

    need_tools

    step "порт $BIND:$PORT"
    # Занятый порт ловим ДО подъёма: иначе компоуз скажет своё «bind: address already in
    # use», и человек будет искать поломку в контроллере, а не в том, кто занял порт.
    if docker ps --format '{{.Names}}\t{{.Ports}}' | grep -v "^$NAME	" | grep -q ":$PORT->"; then
        refuse port-busy \
            "порт $PORT на этой машине уже занят другим контейнером" \
            "возьми другой: CONTROL_PORT=8091 ./control/up.sh" \
            "посмотри, кто занял: docker ps --format '{{.Names}}\t{{.Ports}}'"
    fi
    ok "свободен"

    if [ -n "$BUILD" ]; then
        # ── путь РАЗРАБОТЧИКА ЗОНЫ ────────────────────────────────────────────────────
        # Пульт ДОЛЖЕН БЫТЬ СОБРАН к этому моменту: контроллер раздаёт лицо для человека
        # (`WORLD2` 3.7), и образ кладёт его внутрь. Ловим здесь, до сборки: иначе тем же
        # отказом ответит `RUN test -s` внутри докера — верно, но чужими словами и в
        # середине длинного вывода сборки.
        #
        # Собрать пульт САМИ мы не беремся, хотя команда известна. Сборка требует поля
        # (склад пакетов пульта виден только соседям по сети мира), а подъём поля требовать
        # не должен — это правило зоны `deploy`, и нарушать его чужой командой нельзя.
        # Юзера это уже не касается: ему образ приезжает готовым, с пультом внутри.
        step "собранный пульт"
        PULT="$ROOT/deploy/.build/web-dist/index.html"
        [ -s "$PULT" ] || refuse no-pult-artifact \
            "собранного пульта нет: $PULT пуст или отсутствует" \
            "собери его первым шагом: ./deploy/build.sh --only-web (для этого шага нужно поле)" \
            "и повтори: ./control/up.sh --build" \
            "поля нет — тогда не собирай вовсе: ./control/up.sh притянет готовый образ"
        ok "пульт собран — уедет в образ"

        step "собираю образ ЗДЕСЬ и поднимаю"
        CONTROL_PORT="$PORT" CONTROL_BIND="$BIND" compose up -d --build || refuse up-failed \
            "контроллер не поднялся" \
            "посмотри, что сказал докер: docker compose -f $COMPOSE_FILE up --build" \
            "образ не собрался — сборка идёт из корня репозитория, зови команду из него"
        ok "контейнер $NAME запущен из образа, собранного здесь"
    else
        # ── путь ЮЗЕРА: образ приезжает готовым ───────────────────────────────────────
        step "образ"
        IMAGE="$(compose_image)"
        [ -n "$IMAGE" ] || refuse no-image-name \
            "у файла запуска $COMPOSE_FILE не спросить имя образа" \
            "проверь, что репозиторий полон и файл читается: docker compose -f $COMPOSE_FILE config" \
            "второй копии имени в этом скрипте нет намеренно — источник один, и он там"

        if [ "$OFFLINE" = 1 ]; then
            # Сознательный выход из отказа про реестр. Проверяем, что поднимать вообще
            # есть что, и говорим об этом ГРОМКО: тихий офлайн — это и есть «поднял то,
            # что валялось».
            image_here "$IMAGE" || refuse no-image-local \
                "CONTROL_OFFLINE=1, а образа $IMAGE на этой машине нет" \
                "убери CONTROL_OFFLINE и дай подъёму притянуть образ: ./control/up.sh" \
                "посмотри, что вообще лежит: docker image ls"
            warn "реестр НЕ СПРАШИВАЛИ (CONTROL_OFFLINE=1) — поднимается то, что уже лежит здесь"
            detail "свежее ли оно, никто не проверял: digest ниже сверь с тем, что в реестре"
        else
            # Тянем ЯВНО и отдельным шагом. Отдать это компоузу (`up` тянет недостающее
            # сам) значило бы отдать ему и молчание: он берёт local, если он есть, и не
            # говорит об этом ни слова.
            ok "тяну $IMAGE"
            pull_image "$IMAGE"
            ok "притянут"
        fi

        step "поднимаю контроллер"
        # `--no-build` — не украшение. Раздел `build:` в файле запуска остался (им
        # пользуется выпуск соседа), и компоуз, не найдя образа, молча собрал бы его сам —
        # на машине юзера сборка пульта упёрлась бы в поле, которого у него нет. Запрет
        # ключом, а не надежда на то, что образ на месте.
        CONTROL_PORT="$PORT" CONTROL_BIND="$BIND" compose up -d --no-build || refuse up-failed \
            "контроллер не поднялся" \
            "посмотри, что сказал докер: docker compose -f $COMPOSE_FILE up --no-build" \
            "образ притянут — значит дело в самом запуске: порт, сокет или тома"
        ok "контейнер $NAME запущен"
    fi

    step "жду, пока контроллер ответит (до ${WAIT}с)"
    local waited=0 health
    while [ "$waited" -lt "$WAIT" ]; do
        health="$(docker inspect --format '{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}' "$NAME" 2>/dev/null || true)"
        case "$health" in
            healthy|running) break ;;
            exited|dead)
                say ""
                docker logs --tail 20 "$NAME" >&2 || true
                refuse up-failed \
                    "контроллер поднялся и тут же вышел" \
                    "журнал выше — в нём причина" \
                    "полный журнал: docker logs $NAME" ;;
        esac
        sleep 1; waited=$((waited + 1))
    done
    [ "$health" = healthy ] || [ "$health" = running ] || refuse control-silent \
        "контроллер за ${WAIT}с так и не стал здоровым (сейчас: ${health:-неизвестно})" \
        "журнал: docker logs $NAME" \
        "дай больше времени: CONTROL_WAIT=120 ./control/up.sh"
    ok "контроллер здоров"

    # ЧТО ИМЕННО ПОДНЯТО — главное требование этого захода, а не украшение вывода. Пока
    # образ пересобирался всегда, вопрос не стоял; теперь он приезжает готовым, и человек
    # обязан видеть, какой именно, не спрашивая.
    report_running

    # Образ мира на ЭТОЙ машине — не требование к подъёму контроллера, но требование к
    # добавлению ресурса: дверь туда едет копией отсюда (`WORLD2` 1.5). Сказать об этом
    # надо СЕЙЧАС, а не в момент, когда человек нажал «добавить ресурс».
    if ! docker image inspect omnifield/world:dev >/dev/null 2>&1; then
        warn "образа мира omnifield/world:dev на этой машине нет"
        detail "добавление ресурса откажет кодом no-image: дверь туда везётся копией отсюда"
        detail "собрать: ./deploy/build.sh"
    fi

    say ""
    say "контроллер: http://$HOST:$PORT"
    say ""
    say "  лицо для человека: открой http://$HOST:$PORT в браузере"
    say "  кто я сейчас   : curl http://$HOST:$PORT/api/me"
    say "  войти в скоуп  : curl -X POST http://$HOST:$PORT/api/session -d '{\"addr\":\"/scope/я\",\"create\":true,\"name\":\"я\"}'"
    say "  что дальше     : control/README.md"
}

# ------------------------------------------------------------------ status
cmd_status() {
    need_tools
    local state
    state="$(docker ps -a --filter "name=^$NAME$" --format '{{.Status}}' 2>/dev/null | head -n1 || true)"

    say ""
    say "контейнер : ${state:-нет}"
    [ -n "$state" ] || { say ""; say "  поднять: ./control/up.sh"; return 0; }

    # Каждая строка — отдельный вопрос. Состояние, выведенное вместо измеренного, врёт
    # ровно тогда, когда на него смотрят (`WORLD2` 4.2).
    say "здоровье  : $(docker inspect --format '{{if .State.Health}}{{.State.Health.Status}}{{else}}HEALTHCHECK-а нет{{end}}' "$NAME" 2>/dev/null || echo неизвестно)"
    say "порт      : $(docker port "$NAME" 2>/dev/null | tr '\n' ' ' || echo 'публикации не видно')"
    say "сокет     : $(docker inspect --format '{{range .Mounts}}{{if eq .Destination "/var/run/docker.sock"}}отдан{{end}}{{end}}' "$NAME" 2>/dev/null || true)"
    say "состояние : $(docker volume ls --format '{{.Name}}' | grep -E '^world-control_control-(keys|docker|scope)$' | tr '\n' ' ' || echo 'томов нет')"
    # Тот же вопрос, что и при подъёме, — «чем он поднят». Спрашивают его чаще всего ПОТОМ,
    # когда подъёмный вывод уже уехал из терминала, а разбираются, почему пульт прежний.
    report_running
    say ""
    say "  журнал: docker logs $NAME"
    say "  снять : ./control/up.sh down"
}

# ------------------------------------------------------------------ down
cmd_down() {
    need_tools
    local with_state="${1:-}"

    docker ps -a --format '{{.Names}}' | grep -qx "$NAME" || refuse no-container \
        "контроллера на этой машине нет — снимать нечего" \
        "посмотри, что есть: docker ps -a" \
        "поднять: ./control/up.sh"

    step "снимаю контроллер"
    if [ "$with_state" = "--with-state" ]; then
        # Состояние стирается только по явному слову: в томах лежат ключи юзера и его
        # скоупы, заведённые здесь. Снести их «заодно» значит потерять личность.
        compose down --volumes || refuse up-failed \
            "контроллер не снялся" \
            "посмотри, что сказал докер: docker compose -f $COMPOSE_FILE down --volumes"
        ok "контроллер и его состояние сняты — ключи и скоупы стёрты"
    else
        compose down || refuse up-failed \
            "контроллер не снялся" \
            "посмотри, что сказал докер: docker compose -f $COMPOSE_FILE down"
        ok "контроллер снят"
        say ""
        say "  осталось на машине: ключи ресурсов, контексты докера и скоупы, заведённые здесь"
        say "  снять и их       : ./control/up.sh down --with-state"
        say "  двери на ресурсах НЕ сняты — они живут своей жизнью: ./deploy/remote.sh list"
    fi
}

# ------------------------------------------------------------------ разбор
# Ключ и команда разбираются отдельно: `--build` относится к подъёму, `--with-state` — к
# снятию, и приставить их к чужой команде нельзя. Молча проглоченный ключ здесь опаснее
# обычного: `down --build` человек прочитал бы как «пересобрать», а получил бы снятие.
CMD=
BUILD=
WITH_STATE=
while [ $# -gt 0 ]; do
    case "$1" in
        -h|--help)     usage; exit 0 ;;
        --build)       BUILD=1 ;;
        --with-state)  WITH_STATE=--with-state ;;
        up|status|down)
            [ -z "$CMD" ] || { usage >&2; printf '\nкоманд названо две: %s и %s\n' "$CMD" "$1" >&2; exit 2; }
            CMD="$1" ;;
        *)             usage >&2; printf '\nнепонятный ключ или команда: %s\n' "$1" >&2; exit 2 ;;
    esac
    shift
done
CMD="${CMD:-up}"

[ -z "$BUILD" ]      || [ "$CMD" = up ]   || { usage >&2; printf '\n--build относится к подъёму, а не к %s\n' "$CMD" >&2; exit 2; }
[ -z "$WITH_STATE" ] || [ "$CMD" = down ] || { usage >&2; printf '\n--with-state относится к снятию, а не к %s\n' "$CMD" >&2; exit 2; }

case "$CMD" in
    up)     cmd_up ;;
    status) cmd_status ;;
    down)   cmd_down "$WITH_STATE" ;;
esac

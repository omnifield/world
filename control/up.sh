  ПУТЬ РАЗРАБОТЧИКА ЗОНЫ. Юзер поднимает пульт одной командой docker run — она
  напечатана в control/README.md и репозитория не требует вовсе. Здесь же живёт
  то, чего у юзера нет: сборка из исходников и подъём компоузом.

  (без команды)          поднять контроллер: притянуть готовый образ и запустить
  --build                собрать образ ЗДЕСЬ из исходников и поднять — путь разработчика
                         зоны; ему нужно поле (внутрь образа кладётся собранный пульт)
  status                 что сейчас: контейнер, здоровье, порт, образ, состояние
  down [--with-state]    снять; --with-state стирает времянки — ключи и контексты докера.

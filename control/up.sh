#!/usr/bin/env bash
# Подъём контроллера ИЗ РЕПОЗИТОРИЯ: образ → контейнер → отвечает.
#
# ┌─────────────────────────────────────────────────────────────────────────────────────┐
# │ ЭТО ПУТЬ РАЗРАБОТЧИКА ЗОНЫ, А НЕ ПУТЬ ЮЗЕРА, и путать их больше нельзя. Этот скрипт  │
# │ и файл запуска лежат В РЕПОЗИТОРИИ, а на машине юзера репозитория нет и не будет:    │
# │ он ставит докер и тянет образ (`TECH` 2). Пульт у него поднимается ОДНОЙ командой     │
# │ `docker run` — она напечатана в `control/README.md`, а всё, что этот скрипт делает    │
# │ вокруг подъёма, живёт для неё в точке входа образа (`control/control-entry.sh`,      │
# │ `WORLD2-120`).                                                                       │
# │                                                                                      │
# │ Здесь остаётся то, чего у юзера нет и не должно быть: сборка из исходников, подъём    │
# │ компоузом, явный `pull` с разбором ступеней реестра и снятие вместе с состоянием.     │
# └─────────────────────────────────────────────────────────────────────────────────────┘
#
#   ./control/up.sh                поднять контроллер (наружу, порт 8090)
#   ./control/up.sh --build        собрать образ из исходников и поднять — путь РАЗРАБОТЧИКА
#   ./control/up.sh status         что сейчас: контейнер, здоровье, порт, состояние
#   ./control/up.sh down           снять контроллер; времянки (ключи, контексты) остаются
#   ./control/up.sh down --with-state   снять вместе с ними: ключи и контексты стираются
#
# ЛИЧНОСТЬ ЮЗЕРА НИ ОДНА ИЗ ЭТИХ КОМАНД НЕ ТРОГАЕТ (`WORLD2-124`): скоуп лежит по адресу,
# на машине юзера, и раздаётся раздачей. Снёс контроллер — не потерял ничего.
#
# ┌─────────────────────────────────────────────────────────────────────────────────────┐
# │ КОНТРОЛЛЕР СТАВИТ ЧЕЛОВЕК, И ТОЛЬКО ЧЕЛОВЕК. Ни мир, ни другой контроллер его не      │
# │ разворачивают: цепочка начинается с юзера, и первое звено не автоматизируется         │
# │ (`control/README.md`, `WORLD2` 3.7). Эта команда — то самое первое звено.             │
# │                                                                                      │
# │ Ставь его там, где не жалко: у контроллера есть докер-сокет, то есть власть над этой  │
# │ машиной. Захватили контроллер — захватили ЭТОТ ресурс.                                │
# │                                                                                      │
# │ ПУЛЬТ ПУБЛИКУЕТСЯ НАРУЖУ УМОЛЧАНИЕМ (решение user 2026-08-18, `WORLD2-150` B4): зайти │
# │ в него может любой, кто знает адрес. Значит строка выше перестала быть советом и      │
# │ стала УСЛОВИЕМ — и подъём произносит её вслух каждый раз, а не прячет в этот файл.    │
# │ Закрыть обратно в петлю хозяин может сознательно: `CONTROL_BIND=127.0.0.1`.           │
# └─────────────────────────────────────────────────────────────────────────────────────┘
#
# ┌─────────────────────────────────────────────────────────────────────────────────────┐
# │ ОБРАЗ ПРИЕЗЖАЕТ ГОТОВЫМ — ЮЗЕР ЕГО НЕ СОБИРАЕТ (`WORLD2-110`).                        │
# │                                                                                      │
# │ Собрать контроллер значит собрать пульт, а пульту нужно ПОЛЕ: пакеты лежат на складе, │
# │ видном только соседям по сети мира. Требовать поле от того, кто мир ещё не поднял, —  │
# │ это круг. Поэтому умолчание перевёрнуто: тянем готовое, а сборка осталась ключом      │
# │ `--build` для того, кто правит саму зону.                                             │
# │                                                                                      │
# │ ЧТО ЗДЕСЬ ЗАМЕНИЛО ПРЕЖНЕЕ `--build` ВСЕГДА. Раньше образ пересобирался на каждом     │
# │ подъёме, и это была защита от «поднял старый образ и не заметил» (`WORLD2-92`) —      │
# │ ложного результата, из-за которого проба зеленеет впустую. Готовый образ эту защиту   │
# │ снимает, поэтому вместо неё:                                                          │
# │   1. образ тянется ЯВНО и отдельным шагом — не «как-нибудь получится» при подъёме;    │
# │   2. подъём говорит, ЧТО именно поднято: тег и digest, снятые с живого контейнера.    │
# │ Молчаливого «поднял то, что валялось» не бывает ни в одной ветке.                     │
# └─────────────────────────────────────────────────────────────────────────────────────┘
#
# Имена переменных ЛАТИНСКИЕ: bash не поддерживает не-ASCII в именах и молча превращает
# `ПОРТ=8090` в «команда не найдена». Тексты и комментарии — русские.
set -euo pipefail
# Ступени отказов различаются по тексту системных сообщений, а он переводится.
export LC_ALL=C

HERE="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd -- "$HERE/.." && pwd)"
COMPOSE_FILE="$HERE/compose.yaml"
NAME=world-control

# Порт, петля и время ожидания — значения, а не константы: их называет хозяин машины.
PORT="${CONTROL_PORT:-8090}"
# НАРУЖУ — УМОЛЧАНИЕ (`WORLD2-150` B4). Значение одно на оба пути: этот скрипт и файл
# запуска берут его отсюда, точка входа образа — из команды `docker run`. Разъедься они —
# у разработчика зоны и у юзера получились бы два разных пульта.
BIND="${CONTROL_BIND:-0.0.0.0}"
# Адрес, по которому МАШИНА видит свой же опубликованный порт. Отдельным значением по той
# же причине, что у соседа (`deploy/up.sh`): демон докера и человек не всегда на одной
# петле (живой случай — докер в WSL, команда из Git Bash).
HOST="${CONTROL_HOST:-127.0.0.1}"
WAIT="${CONTROL_WAIT:-60}"
# Спрашивать ли реестр. `1` — не спрашивать и поднять то, что уже лежит на машине. Это
# СОЗНАТЕЛЬНЫЙ выход из отказа «реестр недоступен», а не удобство: он назван вслух в самом
# отказе и вслух же назван при подъёме. Умолчанием такого не делают — с него и начинался
# ложный результат `WORLD2-92`.
OFFLINE="${CONTROL_OFFLINE:-0}"


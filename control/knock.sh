#!/usr/bin/env bash
# СТУК В КОНТРОЛЛЕР — жив ли он и отвечает ли СВОИМ языком.
#
#   control-knock.sh [порт]      порт по умолчанию берётся из CONTROL_ADDR
#
# Стучащихся двое, и файл поэтому один: HEALTHCHECK образа (`control/Dockerfile`) и точка
# входа, которая дожидается ответа при подъёме (`control/control-entry.sh`). Две копии
# одного стука однажды разошлись бы в мелочи, и «здоров по докеру, мёртв по нам» стало бы
# вопросом без ответа — а разбирать его пришлось бы на живой машине юзера.
#
# ЧЕМ МЕРЯЕТСЯ ЗДОРОВЬЕ: контроллер отвечает СВОИМ отказом. `not-signed-in` на `/api/me` без
# входа — это полноценный ответ, а не поломка (`WORLD2` 2.3: каждое «нет» приходит тройкой).
# Проверка «порт открыт» зеленела бы на повисшем процессе; проверка «код 200» потребовала бы
# завести ручку ради проверки. Метку сессии стук не шлёт намеренно — потому и ответ у него
# всегда один и тот же, независимо от того, вошёл ли кто-то в скоуп.
#
# ЧЕМ СТУЧИМ: `/dev/tcp` самого bash. Ни `curl`, ни `wget` в образе контроллера нет, и
# ставить их ради проверки значило бы тянуть в поставку инструмент, которым больше никто не
# пользуется. bash в образе стоит не ради нас — на нём написан готовый подъём двери
# (`deploy/remote.sh`), который контроллер зовёт.
set -u

ADDR="${CONTROL_ADDR:-:8090}"
PORT="${1:-${ADDR##*:}}"

# Соединение может быть принято ядром и не обслужено повисшим процессом — тогда чтение ждало
# бы вечно. У HEALTHCHECK на этот случай свой `--timeout`, у точки входа его нет, поэтому
# граница живёт ЗДЕСЬ: она нужна обоим и в обоих случаях одна и та же.
exec timeout "${CONTROL_KNOCK_TIMEOUT:-3}" bash -c '
    exec 3<>/dev/tcp/127.0.0.1/"$1" || exit 1
    printf "GET /api/me HTTP/1.0\r\n\r\n" >&3
    grep -q not-signed-in <&3
' _ "$PORT"

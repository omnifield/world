// ┌─────────────────────────────────────────────────────────────────────────────────────┐
// │ ЧТО СТЕРЕЖЁТСЯ ЗДЕСЬ (`WORLD2-146`): контроллер вещей своей версией НЕ ПИНИТ, а       │
// │ поднимает тем, что назвал рецепт, — и при КАЖДОМ подъёме говорит вслух, чем поднял.   │
// │                                                                                      │
// │ Публикация раздельная, у каждого образа своя версия: «раз я такой сборки, то и вещи   │
// │ такой же» — неправда, и держать это правило в голове нельзя. Первая проверка ниже —   │
// │ сторож на порчу «вернуть подстановку версии в подъём вещи».                            │
// │                                                                                      │
// │ Строка в журнале при этом ОСТАЛАСЬ (`WORLD2-130`): молчащий подъём был дефектом и им  │
// │ остаётся — `latest` подвижен, и «поднял старое и не заметил» ловится только ею.        │
// └─────────────────────────────────────────────────────────────────────────────────────┘

// имяОбраза — подстановки ИМЕНИ ОБРАЗА в рецептах соседей. Здесь они написаны нарочно, хотя
// в самой зоне их больше нет: проверка требует назвать то, чего контроллер посылать НЕ
// вправе. Возьми она список из кода зоны — порча «завести подстановку заново» унесла бы с
// собой и сторожа.
var имяОбраза = []string{"WORLD_IMAGE", "SHARE_IMAGE"}

// рецептОтвечает — подставной компоуз: рецепт называет один образ, и он МЕНЯЕТСЯ, если
// подстановка названа снаружи. Меняется он не для нас, а потому, что так ведёт себя
// настоящий компоуз: значение читает рецепт, а не контроллер.
func рецептОтвечает(умолчание string) func(run.Command) (run.Result, error) {
	return func(c run.Command) (run.Result, error) {
		if !есть(c.Args, "compose") {
			return докерОтвечает(c)
		}
		for _, e := range c.Env {
			for _, name := range имяОбраза {
				if strings.HasPrefix(e, name+"=") {
					return run.Result{Out: strings.TrimPrefix(e, name+"=") + "\n"}, nil
				}
			}
		}
		return run.Result{Out: умолчание + "\n"}, nil
	}
}

// журнал — куда подъём говорит, чем поднято. Подменяем его, потому что проверяем ИМЕННО
// эти строки: молчащий подъём и есть дефект, ради которого узел заведён.
func журнал(m *Manager) *[]string {
	var строки []string
	m.Logf = func(f string, a ...any) { строки = append(строки, fmt.Sprintf(f, a...)) }
	return &строки
}

// подъёмПозван — окружение, с которым позвали подъём вещи. Смотреть надо ИМЕННО его вызов:
// снятие зовётся тем же путём, и порча, найденная «где-нибудь в журнале», зеленела бы на
// соседней строке про другое действие.
func подъёмПозван(t *testing.T, fake *run.Fake, что string) []string {
	t.Helper()
	for i := range fake.Calls() {
		if strings.Contains(fake.Line(i), "remote.sh "+что) {
			return fake.Calls()[i].Env
		}
	}
	t.Fatalf("подъём с «%s» не позван вовсе: %v", что, fake.Calls())
	return nil
}

// ГЛАВНОЕ ПРАВИЛО ЗАХОДА, И ОНО ПОД СТОРОЖЕМ, А НЕ В ГОЛОВЕ: версия вещи контроллера не
// касается. Своя версия у него есть — в подъём вещи она не уходит ни одним значением.
func TestВерсияКонтроллераВПодъёмВещиНеУходит(t *testing.T) {
	m, fake, _ := стенд(t, рецептОтвечает("ghcr.io/omnifield/world:latest"))
	строки := журнал(m)

	if ref := m.Raise(context.Background(), "vps", "world@10.8.0.5", рецептДвери, nil); ref != nil {
		t.Fatal(ref.Why)
	}

	for _, e := range подъёмПозван(t, fake, "add") {
		for _, name := range имяОбраза {
			if strings.HasPrefix(e, name+"=") {
				t.Fatalf("контроллер подставляет имя образа в подъём вещи: %q", e)
			}
		}
	}
	// И то же самое — на снятии: пин уезжал туда вторым путём.
	if _, ref := m.Lower(context.Background(), "vps", рецептДвери, "", false, true); ref != nil {
		t.Fatal(ref.Why)
	}
	for _, e := range подъёмПозван(t, fake, "drop") {
		for _, name := range имяОбраза {
			if strings.HasPrefix(e, name+"=") {
				t.Fatalf("контроллер подставляет имя образа в снятие вещи: %q", e)
			}
		}
	}

	// Вещь при этом поднимается тем, что назвал рецепт, и это СКАЗАНО.
	сказано := strings.Join(*строки, " ")
	if !strings.Contains(сказано, "ghcr.io/omnifield/world:latest") {
		t.Fatalf("не названо, чем поднято на самом деле: %v", *строки)
	}
	if !strings.Contains(сказано, "так назвал рецепт") {
		t.Fatalf("сказано не про рецепт — а решает теперь он: %v", *строки)
	}
}

// Имя, названное ХОЗЯИНОМ снаружи, читает сам рецепт — и подъём называет то, что вышло.
// Контроллер здесь ничего не решает и ничего не переписывает (`WORLD2` 0.1).
func TestИмяНазванноеСнаружиЧитаетРецептИОноНазвано(t *testing.T) {
	m, _, _ := стенд(t, рецептОтвечает("ghcr.io/omnifield/world:latest"))
	строки := журнал(m)

	// Значение приходит окружением подъёма — ровно так, как оно приходит в живом контроллере
	// из его собственного окружения.
	if ref := m.Raise(context.Background(), "vps", "world@10.8.0.5", рецептДвери,
		[]string{"WORLD_IMAGE=своя/дверь:мояверсия"}); ref != nil {
		t.Fatal(ref.Why)
	}
	if !strings.Contains(strings.Join(*строки, " "), "своя/дверь:мояверсия") {
		t.Fatalf("названо не то, что и правда поехало: %v", *строки)
	}
}

// СВОЯ ВЕЩЬ ЮЗЕРА — та же дорога и без единой оговорки: её образ не наш, и рецепт называет
// его сам. Раньше здесь было исключение («пином не пиним»), теперь исключения нет вовсе.
func TestСвояВещьЮзераПоднимаетсяТемЖеПутём(t *testing.T) {
	m, _, _ := стенд(t, рецептОтвечает("весы:1.2"))
	строки := журнал(m)

	if ref := m.Raise(context.Background(), "vps", "world@10.8.0.5", "/рецепты/весы.yaml", nil); ref != nil {
		t.Fatal(ref.Why)
	}
	if !strings.Contains(strings.Join(*строки, " "), "весы:1.2") {
		t.Fatalf("не названо, чем поднята своя вещь юзера: %v", *строки)
	}
}

// ТРИ СОСТОЯНИЯ ПУСТОГО ОТВЕТА, И ОНИ РАЗНЫЕ (`WORLD2-145`). `docker compose config` — это
// всё или ничего: рецепт, который не читается целиком, отдаёт ровно ту же пустоту, что
// рецепт без образов. Сложи их в одно — и следующая поломка рецепта придёт человеку как
// безобидная оговорка, а именно так она и приходила дважды.
func TestРецептНеЧитаетсяИРецептБезОбразаЭтоРазныеОтветы(t *testing.T) {
	tests := []struct {
		имя    string
		ответ  run.Result
		ждём   string
		неждём string
	}{{
		имя:    "рецепт не читается",
		ответ:  run.Result{Code: 1, Err: "error while interpolating services.share.environment.SHARE_PASSWORD: required variable SHARE_PASSWORD is missing\n"},
		ждём:   "не читается",
		неждём: "не назвал",
	}, {
		имя:    "рецепт прочитан, образа в нём нет",
		ответ:  run.Result{Out: "\n\n"},
		ждём:   "не назвал",
		неждём: "не читается",
	}}
	for _, tt := range tests {
		m, _, _ := стенд(t, func(c run.Command) (run.Result, error) {
			if есть(c.Args, "compose") {
				return tt.ответ, nil
			}
			return докерОтвечает(c)
		})
		строки := журнал(m)

		if ref := m.Raise(context.Background(), "vps", "world@10.8.0.5", рецептДвери, nil); ref != nil {
			t.Fatalf("%s: подъём отказал, а это не поломка подъёма: %s", tt.имя, ref.Why)
		}
		сказано := strings.Join(*строки, " ")
		if !strings.Contains(сказано, tt.ждём) {
			t.Fatalf("%s: в журнале нет «%s»: %v", tt.имя, tt.ждём, *строки)
		}
		if strings.Contains(сказано, tt.неждём) {
			t.Fatalf("%s: состояние названо чужими словами («%s»): %v", tt.имя, tt.неждём, *строки)
		}
	}
}

// Причина, по которой рецепт не прочитался, доезжает до человека ЦЕЛИКОМ. Проглоти мы её —
// человек получил бы «не читается» без единого слова о том, чего файлу не хватило, а
// стдерр компоуза называет это точнее нас (`WORLD2-145`).
func TestПричинаНечитаемогоРецептаДоезжаетДоЧеловека(t *testing.T) {
	m, _, _ := стенд(t, func(c run.Command) (run.Result, error) {
		if есть(c.Args, "compose") {
			return run.Result{Code: 1, Err: "required variable SHARE_PASSWORD is missing\n"}, nil
		}
		return докерОтвечает(c)
	})
	строки := журнал(m)

	if ref := m.Raise(context.Background(), "vps", "world@10.8.0.5", рецептДвери, nil); ref != nil {
		t.Fatal(ref.Why)
	}
	if !strings.Contains(strings.Join(*строки, " "), "SHARE_PASSWORD") {
		t.Fatalf("причина не доехала — чинить нечего: %v", *строки)
	}
}

// Рецепт с НЕСКОЛЬКИМИ образами — законная вещь, и называются ВСЕ. Выбрать из них «наш»
// нечем, а назвать один значило бы выдать часть за целое (`WORLD2` 3.7).
func TestРецептСНесколькимиОбразамиНазываетИхВсе(t *testing.T) {
	m, _, _ := стенд(t, func(c run.Command) (run.Result, error) {
		if есть(c.Args, "compose") {
			return run.Result{Out: "первый:latest\nвторой:1.2\n"}, nil
		}
		return докерОтвечает(c)
	})
	строки := журнал(m)

	if ref := m.Raise(context.Background(), "vps", "world@10.8.0.5", "/рецепты/пара.yaml", nil); ref != nil {
		t.Fatal(ref.Why)
	}
	сказано := strings.Join(*строки, " ")
	if !strings.Contains(сказано, "первый:latest") || !strings.Contains(сказано, "второй:1.2") {
		t.Fatalf("названы не все образы рецепта: %v", *строки)
	}
}

// Рецепт спрашивается ТЕМ ЖЕ окружением, с которым позовут подъём. Спроси мы его без нашего
// же значения — журнал говорил бы про один подъём, а случался бы другой (`WORLD2` 4.2 п. 5).
func TestРецептСпрашиваетсяТемЖеОкружениемЧтоИПодъём(t *testing.T) {
	m, fake, _ := стенд(t, рецептОтвечает("ghcr.io/omnifield/world:latest"))
	_ = журнал(m)

	if ref := m.Raise(context.Background(), "vps", "world@10.8.0.5", рецептДвери, nil); ref != nil {
		t.Fatal(ref.Why)
	}
	var спрошено []string
	for i := range fake.Calls() {
		if есть(fake.Calls()[i].Args, "compose") {
			спрошено = fake.Calls()[i].Env
		}
	}
	// `WORLD_PORT` — наше значение, и оно едет подъёму. Рецепт двери читает его сам, и
	// спрашивать его без порта значило бы мерить не тот рецепт.
	if !есть(спрошено, "WORLD_PORT=8080") {
		t.Fatalf("рецепт спрошен не тем окружением, с которым идёт подъём: %v", спрошено)
	}
}

package resource

// ЧЕМ ПОДНИМАТЬ ВЕЩЬ: контроллер ставит вещи СВОЕЙ сборкой (`WORLD2-130`).
//
// ┌─────────────────────────────────────────────────────────────────────────────────────┐
// │ ОБРАЗ ЗНАЕТ СВОЮ ВЕРСИЮ, И КОНТРОЛЛЕР ЧИТАЕТ ЕЁ У СЕБЯ: `WORLD_VERSION`.             │
// │                                                                                      │
// │ Штамп ставит выпуск (`deploy/build.sh`), и значение его РАВНО неподвижному тегу       │
// │ образа: `sha-<7>`. Собирать этот тег второй раз здесь нельзя — префикс разъедется;    │
// │ значение подставляется как есть: `<имя>:$WORLD_VERSION`.                              │
// │                                                                                      │
// │ Переменной нет — версии нет. Это ЗАКОННОЕ состояние (образ собран не выпуском, а на   │
// │ месте), и тогда вещь поднимается тем, что назовёт рецепт, то есть `latest`. Молчать   │
// │ об этом нельзя: для разработчика зоны это норма, для юзера — нет.                     │
// └─────────────────────────────────────────────────────────────────────────────────────┘
//
// ПОЧЕМУ ЭТО НЕ УДОБСТВО. Выпуск возит ТРОЙКУ одной сборки под одним `sha-<7>` и печатает
// это вслух: «по нему видно, что они одной сборки» (`WORLD2-138`). Подъём эту гарантию
// выбрасывал: рецепты по умолчанию говорят `latest`, и контроллер одной сборки ставил юзеру
// дверь другой — молча (найдено живым прогоном 2026-08-17, `WORLD2-130`).
//
// ┌─────────────────────────────────────────────────────────────────────────────────────┐
// │ ПИН ПРОВЕРЯЕТСЯ ИЗМЕРЕНИЕМ, А НЕ ДОГАДКОЙ (`WORLD2` 4.2 п. 5).                       │
// │                                                                                      │
// │ Читает ли рецепт нашу подстановку — знает только он сам. Поэтому мы СПРАШИВАЕМ его    │
// │ дважды: как он назовёт свой образ без наших значений и с ними. Совпало с ожидаемым —  │
// │ пин сработал, и в журнале стоит правда. Не совпало — так и сказано: рецепт имя        │
// │ образа подстановкой не берёт, поднимается то, что называет он.                        │
// │                                                                                      │
// │ Иначе журнал врал бы ровно там, где его завели: «поднимаю sha-X» при поднятом latest. │
// └─────────────────────────────────────────────────────────────────────────────────────┘

import (
	"context"
	"fmt"
	"strings"

	"github.com/omnifield/world/control/internal/run"
)

// ImageVars — подстановки ИМЕНИ ОБРАЗА в рецептах мира. Это ШОВ: значения посылаем мы,
// читают их рецепты соседей (`deploy/compose.yaml` — `WORLD_IMAGE`, `share/compose.yaml` —
// `SHARE_IMAGE`). Проба стережёт их у соседей и краснеет, если подстановка исчезла.
//
// Перечня ВЕЩЕЙ здесь нет и не заводится (`WORLD2` 3.7): это имена значений, а не список
// того, что бывает в мире. Какое из них прочтёт рецепт — решает он, и мы у него же это и
// спрашиваем; рецепт, который не читает ни одного, о них и не узнает — ровно так же, как о
// `WORLD_PORT`.
var ImageVars = []string{"WORLD_IMAGE", "SHARE_IMAGE"}

// pin — чем поднимаем вещь и что об этом сказано человеку.
type pin struct {
	// env — добавка к окружению подъёма. Пусто — пина нет.
	env []string
	// say — строка в журнал. Пустой не бывает: подъём обязан называть, чем поднято.
	say string
}

// pinFor собирает пин для названного рецепта. Ни одного отказа отсюда не выходит: не
// сумели пинить — это не поломка, а состояние, и оно называется словами.
func (m *Manager) pinFor(ctx context.Context, recipePath string, env []string) pin {
	// ЯВНОЕ ИМЯ ОТ ЮЗЕРА СТАРШЕ ПИНА (`WORLD2` 0.1: мир не решает за юзера). Хозяин назвал
	// образ при подъёме контроллера — значит он и поедет; наше дело сказать это вслух, а не
	// молча переписать его слово своим.
	for _, name := range ImageVars {
		if value := strings.TrimSpace(m.Named[name]); value != "" {
			return pin{say: fmt.Sprintf("имя образа названо снаружи (%s=%s) — оно старше моего пина", name, value)}
		}
	}

	version := strings.TrimSpace(m.Version)
	if version == "" {
		return pin{say: "своей версии не знаю: штампа WORLD_VERSION в образе нет — значит собран он не выпуском, " +
			"а на месте. Поднимаю тем, что назовёт рецепт, — обычно это подвижный latest"}
	}

	before, ref := m.recipeImages(ctx, recipePath, env)
	if ref != "" {
		return pin{say: fmt.Sprintf("имя образа у рецепта %s не спросить (%s) — поднимаю тем, что назовёт он сам", recipePath, ref)}
	}
	if len(before) != 1 {
		// Рецепт с несколькими образами пином не пинится: какой из них наш — знает он, а не
		// мы, и подставить всем один значило бы поднять не то (`WORLD2` 3.7).
		return pin{say: fmt.Sprintf("рецепт называет образов: %d — пином не пиню, чем поднято, скажет он сам", len(before))}
	}

	pinned, ok := withTag(before[0], version)
	if !ok {
		return pin{say: fmt.Sprintf("рецепт называет образ digest'ом (%s) — он и так неподвижен, пином не трогаю", before[0])}
	}

	// Ставим значения и СПРАШИВАЕМ РЕЦЕПТ ЗАНОВО: прочёл он их или нет, знает только он.
	add := make([]string, 0, len(ImageVars))
	for _, name := range ImageVars {
		add = append(add, name+"="+pinned)
	}
	after, ref := m.recipeImages(ctx, recipePath, append(append([]string{}, env...), add...))
	if ref != "" || len(after) != 1 || after[0] != pinned {
		return pin{say: fmt.Sprintf("рецепт %s имя образа подстановкой не берёт — поднимается то, что называет он: %s",
			recipePath, before[0])}
	}
	return pin{
		env: add,
		say: fmt.Sprintf("поднимаю %s — своей сборкой %s", pinned, version),
	}
}

// recipeImages — какие образы называет рецепт ПРИ ЭТИХ значениях. Спрашиваем компоуз, а не
// разбираем YAML глазами: разъехавшийся разбор хуже отсутствующего — он выглядит знанием
// (`WORLD2` 4.2). Вторым значением возвращается причина, по которой спросить не вышло.
func (m *Manager) recipeImages(ctx context.Context, recipePath string, env []string) ([]string, string) {
	res, err := m.Runner.Run(ctx, run.Command{
		Name: m.Docker,
		Args: []string{"compose", "-f", recipePath, "config", "--images"},
		Env:  env,
	})
	if err != nil {
		return nil, tail(err.Error())
	}
	if res.Code != 0 {
		return nil, tail(res.Err)
	}
	var out []string
	for _, line := range strings.Split(res.Out, "\n") {
		if name := strings.TrimSpace(line); name != "" {
			out = append(out, name)
		}
	}
	if len(out) == 0 {
		return nil, "компоуз не назвал ни одного образа"
	}
	return out, ""
}

// withTag — то же имя образа с НАШИМ тегом. Значение штампа уже готовый тег (`sha-<7>`), и
// собирать его второй раз нельзя: приставка разъехалась бы с той, что ставит выпуск.
//
// Образ, названный digest'ом (`имя@sha256:…`), не трогаем вовсе: он и так неподвижен, а
// подмена его тегом означала бы поднять другое содержимое под видом того же.
func withTag(image, tag string) (string, bool) {
	if strings.Contains(image, "@") {
		return "", false
	}
	// Двоеточие бывает и в адресе реестра (`localhost:5000/вещь`), поэтому тег ищем только
	// ПОСЛЕ последней косой черты — иначе портом реестра стал бы тег.
	if colon := strings.LastIndex(image, ":"); colon > strings.LastIndex(image, "/") {
		image = image[:colon]
	}
	return image + ":" + tag, true
}

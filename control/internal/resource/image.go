package resource

// ЧЕМ ПОДНЯТА ВЕЩЬ: контроллер её СТАВИТ, а не сверяет (`WORLD2-146`).
//
// ┌─────────────────────────────────────────────────────────────────────────────────────┐
// │ ВЕРСИЯ ВЕЩИ КОНТРОЛЛЕРА НЕ КАСАЕТСЯ. Что поднимать — говорит РЕЦЕПТ, и только он.     │
// │                                                                                      │
// │ Стоит в рецепте `${SHARE_IMAGE:-…:latest}` — значит `latest`, и это законно: у         │
// │ контроллера своя версия, у мира своя. Публикация раздельная, у каждого образа свой     │
// │ выпуск (`WORLD2-146`), поэтому «раз я такой сборки, то и вещи такой же» — неправда.    │
// │                                                                                      │
// │ Стык держит ФОРМА (канон `3.4`, «Розетка раздачи»), а не общий тег: раздача может быть │
// │ написана юзером с нуля, и её версия не наше дело вовсе (`WORLD2` 0.3). Пока мы         │
// │ подставляли свой тег, чужая вилка обязана была носить наши имена — то есть быть        │
// │ догоняющей, а не равной.                                                              │
// └─────────────────────────────────────────────────────────────────────────────────────┘
//
// ┌─────────────────────────────────────────────────────────────────────────────────────┐
// │ ЧТО ОСТАЛОСЬ: КОНТРОЛЛЕР ГОВОРИТ ВСЛУХ, ЧЕМ ПОДНЯЛ (`WORLD2-130`).                   │
// │                                                                                      │
// │ Строка при каждом подъёме — не про пин, а ПРО ФАКТ: какой образ пошёл на ту машину.   │
// │ Молчание тут было дефектом и им останется: `latest` подвижен, и «поднял старое и не    │
// │ заметил» — ровно тот ложный результат, ради которого узел заведён (`WORLD2-92`).       │
// │                                                                                      │
// │ Факт мы ИЗМЕРЯЕМ, а не выводим (`WORLD2` 4.2 п. 5): имя образа спрашиваем у рецепта   │
// │ тем же окружением, с которым позовём подъём. Скажи мы «поднимаю X», не спросив, — это │
// │ было бы наше намерение, выданное за состояние машины.                                 │
// └─────────────────────────────────────────────────────────────────────────────────────┘
//
// Своя версия сборки у контроллера ОСТАЛАСЬ и по-прежнему называется в журнале при подъёме
// (`cmd/control`, штамп `WORLD_VERSION`) — она про него самого, а не про вещи. Здесь её нет
// намеренно: этому пакету она больше ни для чего не нужна.

import (
	"context"
	"fmt"
	"strings"

	"github.com/omnifield/world/control/internal/run"
)

// raisedWith — ЧЕМ поднимается вещь по этому рецепту, словами для журнала. Пустой строки
// отсюда не выходит и отказа отсюда не выходит тоже: «имя образа не спросить» — это не
// поломка подъёма, а состояние, и оно называется словами.
//
// `env` — то самое окружение, с которым мы позовём подъём. Спрашивать рецепт БЕЗ него
// значило бы мерить не то: значение, названное хозяином снаружи, рецепт читает сам.
func (m *Manager) raisedWith(ctx context.Context, recipePath string, env []string) string {
	images, unreadable := m.recipeImages(ctx, recipePath, env)
	switch {
	// ТРИ СОСТОЯНИЯ, И ОНИ РАЗНЫЕ (`WORLD2-145`): рецепт не читается · читается, а образа
	// в нём нет · образ назван. Сложить первые два в одно «не спросить» значило бы отправить
	// человека чинить не то: первое — поломка файла, второе — поломка его содержимого.
	case unreadable != "":
		return fmt.Sprintf("рецепт %s не читается (%s) — чем поднимется вещь, отсюда не видно",
			recipePath, unreadable)
	case len(images) == 0:
		return fmt.Sprintf("рецепт %s прочитан, а образа в нём не назвал — на этом откажет и сам подъём", recipePath)
	case len(images) == 1:
		return fmt.Sprintf("поднимаю %s — так назвал рецепт", images[0])
	default:
		// Рецепт с несколькими образами — законная вещь: сколько их у неё, знает он.
		// Называем ВСЕ: выбрать из них «наш» нам нечем, а назвать один значило бы выдать
		// часть за целое (`WORLD2` 3.7).
		return fmt.Sprintf("рецепт называет образов: %d (%s) — поднимаются они",
			len(images), strings.Join(images, ", "))
	}
}

// recipeImages — какие образы называет рецепт ПРИ ЭТИХ значениях. Спрашиваем компоуз, а не
// разбираем YAML глазами: разъехавшийся разбор хуже отсутствующего — он выглядит знанием
// (`WORLD2` 4.2).
//
// Вторым значением возвращается ПРИЧИНА, по которой файл не прочитался, и она не украшение:
// `docker compose config` — это ВСЁ ИЛИ НИЧЕГО, и рецепт, который не читается целиком
// (незакавыченное двоеточие — `WORLD2-140`, необъявленная обязательная переменная —
// `WORLD2-145`), отдаёт ровно ту же пустоту, что рецепт без образов. Проглоти мы её —
// «рецепт не читается» приезжало бы человеку как «образа нет», и следующая поломка рецепта
// снова пришла бы безобидной оговоркой.
//
// Пустой список при пустой причине — это третье состояние: файл прочитан, образов в нём нет.
func (m *Manager) recipeImages(ctx context.Context, recipePath string, env []string) ([]string, string) {
	res, err := m.Runner.Run(ctx, run.Command{
		Name: m.Docker,
		Args: []string{"compose", "-f", recipePath, "config", "--images"},
		Env:  env,
	})
	if err != nil {
		return nil, tail(err.Error())
	}
	if res.Code != 0 {
		return nil, tail(res.Err)
	}
	var out []string
	for _, line := range strings.Split(res.Out, "\n") {
		if name := strings.TrimSpace(line); name != "" {
			out = append(out, name)
		}
	}
	return out, ""
}

// Пакет address — АДРЕС ЛОКАЦИИ. Одна формула и ничего кроме неё.
//
// ┌─────────────────────────────────────────────────────────────────────────────────────┐
// │ АДРЕС НЕ НАЗНАЧАЕТСЯ — ОН ВЫВОДИТСЯ ИЗ ЯРУСОВ (`WORLD2` 2.1, `0.9`, `2.0` п. 3).     │
// │                                                                                      │
// │     скоуп юзера → территория → имя локации                                           │
// │                                                                                      │
// │ ТРИ ЯРУСА, А НЕ ЧЕТЫРЕ. Поле из формулы убрано 2026-08-22 решением user: поле — это  │
// │ комьюнити и область видимости (`1.3`), а не место, на котором вещь стоит. Участок     │
// │ состоит в скольких угодно комьюнити (`2.5` п. 3), и по прежней формуле у одной        │
// │ локации оказалось бы столько адресов, во скольких комьюнити стоит её участок.         │
// │                                                                                      │
// │ ПРИСОЕДИНЕНИЕ И ОТВЯЗКА АДРЕС НЕ ДВИГАЮТ (`2.1` п. 5, `2.2` п. 4). Меняется от них    │
// │ ровно одно — кто вещь видит.                                                          │
// └─────────────────────────────────────────────────────────────────────────────────────┘
//
// ЧЕГО ЗДЕСЬ НЕТ — ПРОВЕРКИ УНИКАЛЬНОСТИ. Она держится сама, тремя данностями (`2.1` п. 4):
// на одном участке два имени не совпадут · имена участков в скоупе не повторяются (`2.5`
// п. 11) · чужие скоупы не пересекаются. Появись здесь правило «а проверь-ка имена» —
// это значило бы, что формула собрана неверно, и уникальность стала требованием к юзеру
// вместо данности (`0.2`).
//
// ЧТО АДРЕС ДВИГАЕТ — ровно два хода: перенос локации на другой участок и переименование
// участка. Больше ничего.
package address

import "strings"

// Sep — чем ярусы разделены в записи.
//
// ФОРМА ЗАПИСИ КАНОНОМ НЕ ЗАДАНА — задан ПОРЯДОК ярусов (`2.1` п. 2). Косая черта взята
// как самая обычная запись перечисления сверху вниз и названа допущением в отчёте по
// `WORLD2-122`: решит architect иначе — меняется эта константа и ничего больше, потому что
// собирается адрес в одном месте.
const Sep = "/"

// Location — адрес локации: три яруса и ничего сверх них.
//
// Держится ярусами, а не строкой: строка — это ЗАПИСЬ адреса, а сам он — перечисление
// ярусов. Тот, кто адрес читает, чаще спрашивает «на каком участке», чем «как выглядит
// целиком», и вырезать это обратно из строки значило бы разбирать то, что мы же и склеили.
type Location struct {
	// Scope — ярус личности: то, чем юзер зовётся в мире (`3.4`). НЕ адрес раздачи: где
	// лежит сам файл личности, к имени вещи отношения не имеет (`3.4`, решение user
	// 2026-08-20), и юзер волен наклонировать состояний сколько угодно — адреса его
	// локаций от этого не двигаются.
	Scope string
	// Territory — ИМЯ участка, которое дал ему юзер (`2.5` п. 11), а не адрес машины: мир
	// не знает, на каком железе что исполняется (`5.3`). Сменил юзер хостинг, оставив
	// имя, — адреса локаций на нём не дрогнули.
	Territory string
	// Name — имя локации. Единственное из трёх, что даёт сама локация (`2.0` п. 3).
	Name string
}

// Of — собрать адрес. Ничего не проверяет: годность ярусов — дело того, у кого они лежат,
// а здесь живёт только формула.
func Of(scope, territory, name string) Location {
	return Location{
		Scope:     strings.TrimSpace(scope),
		Territory: strings.TrimSpace(territory),
		Name:      strings.TrimSpace(name),
	}
}

// String — запись адреса. Ярусы перечислены сверху вниз, тем же порядком, каким их
// называет канон.
func (l Location) String() string {
	return l.Scope + Sep + l.Territory + Sep + l.Name
}

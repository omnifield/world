// Пакет run — единственное место, где контроллер выходит наружу процессом.
//
// Наружу он выходит часто: докер (`docker context ls`, `docker --context … inspect`),
// ssh (скоуп лежит на чужом ресурсе и берётся СВЯЗЬЮ, а не копией — `WORLD2` 1.6) и
// готовый подъём двери (`deploy/remote.sh`). Ни одного из них контроллер не переписывает
// и не подменяет своим — он их ЗОВЁТ.
//
// Почему запуск вынесен отдельным типом, а не `exec.Command` по месту:
//
//  1. проба и тесты обязаны прогоняться там, где нет ни докера, ни ssh, ни второго
//     ресурса. Подменяемый запускатель — единственный способ проверить ПОВЕДЕНИЕ
//     контроллера (какой код отказа, что откатили), не имея под рукой контура;
//  2. отказ «инструмента нет вовсе» отличается от отказа «инструмент сказал нет», и
//     различать их надо в одном месте, а не в каждом вызове;
//  3. LC_ALL=C нужен КАЖДОМУ вызову: ступени «ключ не принят» и «дороги нет» различаются
//     по тексту системной ошибки, а он переводится (та же грабля, что у `gate` и
//     `deploy`). Забыть его в одном вызове из десяти — значит получить на локализованной
//     машине один отказ вместо двух разных.
package run

import (
	"bytes"
	"context"
	"errors"
	"io/fs"
	"os/exec"
	"strings"
	"time"
)

// Command — что запускаем. Аргументы МАССИВОМ, строки-команды здесь нет и не будет:
// склейка строкой означает разбор её оболочкой, а значения (адрес, путь, имя) приходят
// от человека снаружи.
type Command struct {
	Name  string
	Args  []string
	Stdin string
	// Env — добавка к окружению процесса (`КЛЮЧ=значение`), а не замена ему: докеру и
	// ssh нужен HOME и PATH, и вычищать их незачем.
	Env []string
	// OnLine — строка stdout, отданная ВЫЗЫВАЮЩЕМУ В ТОТ МОМЕНТ, КОГДА ОНА ПРИШЛА, а не
	// после выхода процесса.
	//
	// Заведено не ради удобства. Сосед печатает метку пути (`REMOTE-PATH: image-copy`)
	// ДО самого пути, потому что путь занимает минуты и ждущий вправе знать, чего он
	// ждёт (`WORLD2-150` B2). Собери мы весь вывод в буфер и разбери его после `Wait`,
	// метка доехала бы до человека вместе с итогом — то есть перестала бы быть
	// предупреждением и стала бы отчётом. Свойство «ДО» живёт здесь, а не у читателя.
	//
	// Зовётся из горутины, которую заводит `exec` под трубу вывода: вызывающий в это
	// время ждёт в `Run`. Значит всё, чего касается `OnLine`, обязано быть под замком.
	OnLine func(string)
}

// Result — что ответила команда. Код возврата здесь ЗНАЧЕНИЕ, а не ошибка: «сказал нет» —
// это нормальный ответ инструмента, из которого контроллер собирает отказ с причиной.
type Result struct {
	Out  string
	Err  string
	Code int
}

// Runner — запускатель. Подменяется в тестах и в пробе.
type Runner interface {
	Run(ctx context.Context, c Command) (Result, error)
}

// waitDelay — сколько ждём после того, как процесс убит по пределу: столько ему даётся
// на то, чтобы отпустить трубы вывода вместе со своими детьми.
const waitDelay = time.Second

// ErrNoTool — инструмента нет на машине вовсе. Отдельная ошибка, потому что отказ
// получается другой: «докера нет» чинит хозяин образа, «докер сказал нет» — хозяин
// ресурса. Сложить их в одно значило бы отправить человека чинить не то (`WORLD2` 2.3).
var ErrNoTool = errors.New("инструмента нет на этой машине")

// Exec — настоящий запускатель.
type Exec struct {
	// Timeout — общий предел на одну команду. Ноль — без предела, но так мы не ходим:
	// ssh на молчащий адрес висит минутами, а ручка HTTP обязана ответить.
	Timeout time.Duration
}

func (e Exec) Run(ctx context.Context, c Command) (Result, error) {
	if e.Timeout > 0 {
		var cancel context.CancelFunc
		ctx, cancel = context.WithTimeout(ctx, e.Timeout)
		defer cancel()
	}

	cmd := exec.CommandContext(ctx, c.Name, c.Args...)
	// WaitDelay — не украшение. По пределу времени убивается ЗАПУЩЕННЫЙ процесс, но его
	// собственные дети (у `ssh` и у `docker` они бывают) держат трубы вывода открытыми, и
	// без этого ожидание длится ровно столько, сколько живёт самый упрямый внук. Предел
	// времени, который не ограничивает время, — это ложь в настройке.
	cmd.WaitDelay = waitDelay
	// Окружение наследуется целиком и дополняется: LC_ALL=C идёт последним и потому
	// побеждает то, что стоит в системе.
	cmd.Env = append(cmd.Environ(), c.Env...)
	cmd.Env = append(cmd.Env, "LC_ALL=C")
	if c.Stdin != "" {
		cmd.Stdin = strings.NewReader(c.Stdin)
	}

	var out, errBuf bytes.Buffer
	cmd.Stderr = &errBuf
	if c.OnLine == nil {
		cmd.Stdout = &out
	} else {
		// Поток раздваивается, а не подменяется: вызывающий по-прежнему получает `Out`
		// целиком (по нему разбирается код отказа), и вдобавок узнаёт каждую строку в
		// момент её появления. Один источник, два читателя — второго сбора вывода здесь
		// нет, иначе они разъехались бы ровно на последней строке.
		cmd.Stdout = &lineTee{buf: &out, on: c.OnLine}
	}

	err := cmd.Run()
	res := Result{Out: out.String(), Err: errBuf.String()}

	// Предел времени проверяется ДО разбора кода возврата. Убитый по пределу процесс
	// приходит сюда обычной `*ExitError` («signal: killed»), и разобрать её как «команда
	// сказала нет» значит выдать молчание за ответ: человек получил бы отказ про код
	// возврата вместо отказа «ресурс не ответил».
	if ctx.Err() != nil {
		res.Code = -1
		return res, ctx.Err()
	}

	switch {
	case err == nil:
		return res, nil
	// Два РАЗНЫХ способа не найти инструмент, и оба означают одно и то же для человека:
	// «в образе этого нет». `ErrNotFound` приходит, когда искали по PATH; `fs.ErrNotExist` —
	// когда назван путь целиком (`/opt/world/deploy/remote.sh`). Поймать только первый —
	// значит на втором выдать «инструмент промолчал» вместо «инструмента нет», и человек
	// пойдёт чинить связь вместо образа. Найдено собственной пробой.
	case errors.Is(err, exec.ErrNotFound), errors.Is(err, fs.ErrNotExist):
		return res, ErrNoTool
	default:
		var ee *exec.ExitError
		if errors.As(err, &ee) {
			res.Code = ee.ExitCode()
			return res, nil
		}
		// Предел времени и убитый процесс приходят сюда же. Код -1 говорит «ответа не
		// было», и вызывающий обязан разобрать это как молчание, а не как «сказал нет».
		res.Code = -1
		return res, err
	}
}

// lineTee — накопитель вывода, который вдобавок отдаёт ЗАВЕРШЁННЫЕ строки по мере их
// появления. Незавершённый хвост не отдаётся вовсе: половина строки — это не строка, и
// метка, разрезанная на границе записи в трубу, доехала бы до читателя обрубком.
type lineTee struct {
	buf  *bytes.Buffer
	tail []byte
	on   func(string)
}

func (t *lineTee) Write(p []byte) (int, error) {
	t.buf.Write(p)
	t.tail = append(t.tail, p...)
	for {
		i := bytes.IndexByte(t.tail, '\n')
		if i < 0 {
			return len(p), nil
		}
		line := strings.TrimRight(string(t.tail[:i]), "\r")
		t.tail = t.tail[i+1:]
		t.on(line)
	}
}

var _ Runner = Exec{}

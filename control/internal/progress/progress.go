// Пакет progress — то, что контроллер говорит ждущему, ПОКА шаг ещё идёт.
//
// ┌─────────────────────────────────────────────────────────────────────────────────────┐
// │ ЭТО ИСПОЛНЕНИЕ `B2`: ВСЛУХ ГОВОРИТ КОНТРОЛЛЕР, А НЕ ТОЛЬКО ПОДЪЁМ.                    │
// │                                                                                      │
// │ `deploy/remote.sh` называет путь человеку у СЕБЯ — словами в stderr и меткой          │
// │ `REMOTE-PATH: <путь>` в stdout, и называет ДО того, как путь занял минуты. Но у       │
// │ пульта нет ни того stderr, ни того stdout: между ним и подъёмом стоит контроллер.     │
// │ Значит довезти метку обязан он — и довезти ПОКА ШАГ ИДЁТ, иначе она перестаёт быть    │
// │ предупреждением и становится отчётом о том, чего человек уже дождался.                │
// │                                                                                      │
// │ Копия образа по ssh — самый долгий шаг, и подъём предупреждает об этом сам. Человек,  │
// │ не знающий, чего он ждёт, читает молчание как повисший пульт.                         │
// └─────────────────────────────────────────────────────────────────────────────────────┘
//
// ЗДЕСЬ НЕ СОСТОЯНИЕ, А ХОД ТЕКУЩЕГО ДЕЙСТВИЯ. Пережить перезапуск контроллера ему не
// надо и незачем: контроллер — времянка (`WORLD2` 1.9), а действие, которое он вёл,
// перезапуск не переживает тем более.
//
// ┌─────────────────────────────────────────────────────────────────────────────────────┐
// │ ЧЕГО ЗДЕСЬ НЕТ И НЕ БУДЕТ: АДРЕСА МАШИНЫ, КРЕД И ПАРОЛЯ.                              │
// │                                                                                      │
// │ Ход действия читается БЕЗ входа в скоуп — иначе его не прочесть в единственный        │
// │ момент, ради которого он заведён: `POST /api/scope` ещё не выдал метку сессии, а       │
// │ раздача уже поднимается. Решением user пульт публикуется наружу (`WORLD2-150` B4),    │
// │ значит читать это может любой, кто знает адрес пульта. Поэтому наружу отдаётся только │
// │ метка пути, род действия и ИМЯ УЧАСТКА — то слово, которое юзер придумал сам. Адрес   │
// │ машины сюда не кладётся: он назван юзером в теле запроса и оттуда никуда не уезжает.  │
// └─────────────────────────────────────────────────────────────────────────────────────┘
package progress

import (
	"sync"
	"time"
)

// Step — одна метка пути и когда она пришла.
type Step struct {
	// Path — слово соседа, довезённое ДОСЛОВНО: `docker-install` · `image-present` ·
	// `image-copy` · `image-pull`. Своего словаря путей у контроллера нет и не заводится —
	// второй разъехался бы с первым на первой правке соседа (тот же довод, что у кодов
	// отказа в `internal/refusal`).
	Path string `json:"path"`
	At   string `json:"at"`
}

// Snapshot — ход действия глазами того, кто ждёт.
type Snapshot struct {
	// Busy — действие ИДЁТ ПРЯМО СЕЙЧАС. Отдельным полем, а не выводом из непустого
	// списка шагов: закончившееся действие оставляет шаги, и выводить «идёт» из них
	// значило бы показывать ждущему вечное ожидание.
	Busy bool `json:"busy"`
	// What — род действия: `scope-create` · `resource-add`.
	What string `json:"what,omitempty"`
	// Name — имя участка, которое дал юзер (`WORLD2` 2.5 п. 11). Адреса здесь нет.
	Name string `json:"name,omitempty"`
	// Path — последняя метка. Она же последний элемент `steps`; отдельным полем, потому
	// что спрашивают у хода именно её, а список — подробность.
	Path  string `json:"path,omitempty"`
	Steps []Step `json:"steps"`
}

// Live — ход текущего действия. Пишет в него подъём из чужой горутины (`run.Command.OnLine`),
// читает ручка из своей — значит замок обязателен, и он здесь один на всё.
type Live struct {
	mu   sync.Mutex
	busy bool
	what string
	name string
	// steps ПЕРЕЖИВАЮТ окончание действия и стираются только следующим `Start`. Причина:
	// пульт спрашивает ход не непрерывно, и шаг, длившийся секунду, иначе исчезал бы
	// между двумя вопросами — а «путь не назвали» и «путь прошёл быстро» это разное.
	steps []Step
	Now   func() time.Time
}

func (l *Live) now() time.Time {
	if l.Now != nil {
		return l.Now()
	}
	return time.Now()
}

// Start — начали действие. Прежние шаги стираются здесь, а не в `Done`: пока не начато
// новое, ждущий вправе дочитать, чем кончилось прежнее.
func (l *Live) Start(what, name string) {
	if l == nil {
		return
	}
	l.mu.Lock()
	defer l.mu.Unlock()
	l.busy, l.what, l.name, l.steps = true, what, name, nil
}

// Path — метка, названная соседом. Кладётся ДОСЛОВНО и без разбора: что значит слово,
// знает тот, кто его сказал.
func (l *Live) Path(path string) {
	if l == nil || path == "" {
		return
	}
	l.mu.Lock()
	defer l.mu.Unlock()
	l.steps = append(l.steps, Step{Path: path, At: l.now().UTC().Format(time.RFC3339)})
}

// Done — действие кончилось. Шаги остаются: их стирает следующий `Start`.
func (l *Live) Done() {
	if l == nil {
		return
	}
	l.mu.Lock()
	defer l.mu.Unlock()
	l.busy = false
}

// Snapshot — ход на этот миг. Список копируется, а не отдаётся ссылкой: отданный наружу
// срез продолжил бы меняться под читателем.
func (l *Live) Snapshot() Snapshot {
	if l == nil {
		return Snapshot{Steps: []Step{}}
	}
	l.mu.Lock()
	defer l.mu.Unlock()

	out := Snapshot{Busy: l.busy, What: l.what, Name: l.name, Steps: make([]Step, len(l.steps))}
	copy(out.Steps, l.steps)
	if n := len(out.Steps); n > 0 {
		out.Path = out.Steps[n-1].Path
	}
	return out
}

// │                                                                                      │
// │ Членство лежит в ДВУХ местах, и оба законные: у юзера — в каких комьюнити его        │
// │ участок состоит, у поля — чьи участки в нём состоят. Это не дублирование, а две      │
// │ стороны доступа (`9.1`).                                                              │
// │                                                                                      │
// │ САМО ПРИСОЕДИНЕНИЕ — НЕ ЗДЕСЬ. Условия входа проверяет служба поля, она же ведёт     │
// │ список участников (`1.3`, `WORLD2-123`, зона `field`). Записать себе «я в комьюнити» │
// │ и считать, что присоединился, нельзя — но и держать это знание где-то ещё тоже: оно  │
// │ ЕГО, и едет с ним (`3.4` п. 2).                                                       │
// └─────────────────────────────────────────────────────────────────────────────────────┘

// JoinField — записать участок в комьюнити.
//
// Имя комьюнити обязано быть В ЕГО ЖЕ СПИСКЕ ПОЛЕЙ, и это не строгость ради строгости:
// раздел `поля` держит адреса известных юзеру комьюнити, а территория ссылается на них ПО
// ИМЕНИ — ровно так же, как на ключ (`3.4`, «Почему так», п. 4). Имя, за которым не стоит
// адреса, — это членство, до которого потом не дотянуться.
func (s *State) JoinField(territory, field string) *refusal.Refusal {
	field = strings.TrimSpace(field)
	if field == "" {
		return refusal.New(http.StatusBadRequest, "no-name",
			"комьюнити не названо, а безымянного комьюнити не бывает",
			"назови его: field=«дом»",
			"посмотри, какие известны: GET /api/fields")
	}
	i, ref := s.index(territory)
	if ref != nil {
		return ref
	}
	if _, есть := s.field(field); !есть {
		return refusal.New(http.StatusNotFound, "no-such-field",
			fmt.Sprintf("комьюнити «%s» в твоей личности не записано, а участок ссылается на него по имени — за именем должен стоять адрес", field),
			"заведи запись: POST /api/fields -d '{\"name\":\""+field+"\"}'",
			"посмотри, какие известны: GET /api/fields")
	}
	s.fill()
	for _, есть := range s.Territories[i].Fields {
		if есть == field {
			// Повтор — не «всё в порядке» и не молчание: юзер думал, что делает что-то, а
			// не происходит ничего (`WORLD2` 2.3 п. 1). Состоять дважды нечем.
			return refusal.New(http.StatusConflict, "already-joined",
				fmt.Sprintf("участок «%s» уже состоит в комьюнити «%s» — состоять в нём дважды нечем", territory, field),
				"посмотри, где он состоит: GET /api/resources",
				"выйти оттуда: DELETE /api/resources/"+territory+"/fields/"+field)
		}
	}
	s.Territories[i].Fields = append(s.Territories[i].Fields, field)
	return nil
}

// LeaveField — убрать участок из комьюнити.
//
// ЭТО ТОЛЬКО НАША ПОЛОВИНА. Отвязка ОБЪЯВЛЯЕТСЯ полю (`2.2` п. 5, `1.3` п. 6): молча уйти
// нельзя, иначе список участников останется врать. Уведомление — работа службы поля
// (`WORLD2-123`), и обещать здесь его доставку мы не вправе.
func (s *State) LeaveField(territory, field string) *refusal.Refusal {
	field = strings.TrimSpace(field)
	i, ref := s.index(territory)
	if ref != nil {
		return ref
	}
	kept := make([]string, 0, len(s.Territories[i].Fields))
	нашли := false
	for _, есть := range s.Territories[i].Fields {
		if есть == field {
			нашли = true
			continue
		}
		kept = append(kept, есть)
	}
	if !нашли {
		return refusal.New(http.StatusNotFound, "not-joined",
			fmt.Sprintf("участок «%s» в комьюнити «%s» не состоит — отвязывать нечего", territory, field),
			"посмотри, где он состоит: GET /api/resources")
	}
	s.Territories[i].Fields = kept
	s.fill()
	return nil
}

// Declare — участок заявляет свой ресурс (`2.5` пп. 2, 6, 7).
//
// НИЧЕГО НЕ ПРОВЕРЯЕТ И НИЧЕМ НЕ ОТКАЗЫВАЕТ, кроме отсутствия самого участка. Пустое
// значение законно и означает «снял заявление»: мир ресурс не меряет и не сторожит, а
// нехватка его — данность, а не отказ (`0.2`).
func (s *State) Declare(territory, resource string) *refusal.Refusal {
	i, ref := s.index(territory)
	if ref != nil {
		return ref
	}
	s.Territories[i].Resource = strings.TrimSpace(resource)
	s.fill()
	return nil
}

// index — где участок лежит в списке. Отдельно от Territory: та отдаёт КОПИЮ, и правка по
// ней уехала бы в пустоту — молча, что здесь хуже всего.
func (s *State) index(name string) (int, *refusal.Refusal) {
	for i := range s.Territories {
		if s.Territories[i].Name == name {
			return i, nil
		}
	}
	return -1, refusal.New(http.StatusNotFound, "no-such-resource",
		fmt.Sprintf("участка «%s» в твоём скоупе нет", name),
		"посмотри, какие есть: GET /api/resources")
}

// field — запись о комьюнити по имени.
func (s *State) field(name string) (Field, bool) {
	for _, f := range s.Fields {
		if f.Name == name {
			return f, true
		}
	}
	return Field{}, false
}

// ── связка ключей ────────────────────────────────────────────────────────────

// Key — ключ по имени.
func (s *State) Key(name string) (Key, bool) {
	for _, k := range s.Keys {
		if k.Name == name {
			return k, true
		}
	}
	return Key{}, false
}

// SetKey — положить ключ в связку скоупа. Нужен там, где ключ заводится РАНЬШЕ территории:
// пароль обменивается на ключ до того, как на машине что-либо поднято.
func (s *State) SetKey(k Key) {
	s.fill()
	s.setKey(k)
}

func (s *State) setKey(k Key) {
	for i := range s.Keys {
		if s.Keys[i].Name == k.Name {
			s.Keys[i] = k
			return
		}
	}
	s.Keys = append(s.Keys, k)
}

func (s *State) dropKey(name string) {
	kept := s.Keys[:0]
	for _, k := range s.Keys {
		if k.Name != name {
			kept = append(kept, k)
		}
	}
	s.Keys = kept
}

// keyUsed — на ключ ссылается кто-то ещё. Ключ у мира один на связку, и снимать его вместе
// с одним участком, пока на него смотрит второй, значит оборвать связь с живой машиной.
func (s *State) keyUsed(name string) bool {
	for _, t := range s.Territories {
		if t.Key == name {
			return true
		}
	}
	return false
}

// ── поля ─────────────────────────────────────────────────────────────────────

// AddField — завести ЗАПИСЬ о поле. Само поле при этом не поднимается, и говорить об этом
// надо вслух: человек, не увидевший этой строки, ждал бы поднятого поля.
func (s *State) AddField(name string) *refusal.Refusal {
	name = strings.TrimSpace(name)
	if name == "" {
		return refusal.New(http.StatusBadRequest, "no-name",
			"у поля должно быть имя, а оно не названо",
			"назови его: name=«дом»")
	}
	for _, f := range s.Fields {
		if f.Name == name {
			return refusal.New(http.StatusConflict, "field-exists",
				fmt.Sprintf("поле «%s» в твоём списке уже есть", name),
				"назови другое имя",
				"или посмотри список: GET /api/fields")
		}
	}
	s.fill()
	s.Fields = append(s.Fields, Field{Name: name})
	return nil
}

// sample — что именно приехало, коротким куском. Целиком чужой файл в отказ не кладём:
// человеку нужна причина, а не дамп; но БЕЗ образца отказ «не тот формат» не проверить.
func sample(data []byte) string {
	const limit = 60
	text := strings.TrimSpace(string(data))
	if text == "" {
		return "пустота"
	}
	if !utf8.ValidString(text) {
		return fmt.Sprintf("%d байт, и это не текст", len(data))
	}
	if line, _, cut := strings.Cut(text, "\n"); cut {
		text = line
	}
	runes := []rune(text)
	if len(runes) > limit {
		return fmt.Sprintf("%d байт, начинается с «%s…»", len(data), string(runes[:limit]))
	}
	return fmt.Sprintf("%d байт: «%s»", len(data), text)
}

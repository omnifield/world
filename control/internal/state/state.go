// LocationAddress — адрес локации на названном участке (`WORLD2` 2.1, `internal/address`).
//
// СЧИТАЕТСЯ, А НЕ ХРАНИТСЯ. Записанный адрес стал бы второй правдой рядом с ярусами и
// разъехался бы с ними на первом же переименовании участка — молча, потому что сверять его
// не с чем. Поэтому в файле состояния адреса локации нет и не будет.
//
// НА КОМЬЮНИТИ ЭТА ФОРМУЛА НЕ СМОТРИТ ВОВСЕ — и это её главное свойство (`2.1` п. 5).
// Список `поля` участка сюда не приходит ни одним путём.
func (s *State) LocationAddress(territory, location string) (address.Location, *refusal.Refusal) {
	location = strings.TrimSpace(location)
	if location == "" {
		return address.Location{}, refusal.New(http.StatusBadRequest, "no-name",
			"имя локации не названо, а его даёт юзер — мир его не выдумывает (`WORLD2` 2.1 п. 1)",
			"назови его: ?location=baser")
	}
	i, ref := s.index(territory)
	if ref != nil {
		return address.Location{}, ref
	}
	if strings.TrimSpace(s.Identity.Name) == "" {
		return address.Location{}, refusal.New(http.StatusBadGateway, "scope-broken",
			"у личности в этом состоянии нет имени, а имя — верхний ярус адреса локации",
			"поправь файл: раздел «личность», поле «имя»")
	}
	return address.Of(s.Identity.Name, s.Territories[i].Name, location), nil
}


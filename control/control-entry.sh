# ------------------------------------------------------------------ 4. образ двери
# Дверь едет на новый ресурс КОПИЕЙ отсюда (`WORLD2` 1.5), поэтому образ двери должен лежать
# на машине контроллера. Сказать об этом надо СЕЙЧАС, а не в момент, когда человек уже нажал
# «добавить ресурс».
#
# ОБРАЗ ПРОВЕРЯЕМ ТОТ, КОТОРЫМ БУДЕМ ПОДНИМАТЬ, и теперь это выходит само: подъём идёт тем,
# что назвал рецепт (`WORLD2-146`), и мы спрашиваем ровно его — тем же вопросом, тем же
# окружением. Своего тега контроллер больше не подставляет, поэтому и подставлять его в
# проверку нечего: пока пин был, проверка обязана была повторять его порядок, иначе врала бы
# в обе стороны (`WORLD2-130`, живой прогон 2026-08-17).
step "образ двери — им дверь едет на добавляемый ресурс"
obraz_recepta "$DOOR_COMPOSE"
case "$OBRAZ_OTVET" in

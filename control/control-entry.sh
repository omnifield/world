        detail "это НЕ «образа нет»: файл не разобран целиком, и имени образа в нём не назвал никто"
        detail "тот же вопрос руками: $DOCKER compose -f $DOOR_COMPOSE config --images"
        detail "файл кладёт в образ сборка контроллера — проверь, цел ли образ: docker run --rm --entrypoint ls <образ> -l ${DOOR_COMPOSE%/*}" ;;
    net-obraza)

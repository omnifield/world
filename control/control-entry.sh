            detail "это НЕ «образа нет»: файл не разобран целиком, и имени образа в нём не назвал никто"
            detail "тот же вопрос руками: SHARE_PASSWORD=x $DOCKER compose -f $SHARE_RECIPE config --images"
            detail "«завести скоуп» на таком рецепте откажет отказом подъёма: он не разберёт файл целиком" ;;
        net-obraza)
            warn "рецепт раздачи $SHARE_RECIPE прочитан, а образа в нём не названо"
            detail "это НЕ «рецепт сломан»: файл разобран целиком, в нём просто нет имени образа"
            detail "«завести скоуп» откажет отказом подъёма — поднимать ему нечего" ;;

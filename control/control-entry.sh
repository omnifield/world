    detail "файл кладёт в образ сборка контроллера — проверь, цел ли образ: docker run --rm --entrypoint ls <образ> -l ${DOOR_COMPOSE%/*}"
fi

# РАЗДАЧА СКОУПА — ВТОРАЯ ВЕЩЬ, и поднимается она тем же путём, что дверь: рецептом. Ей тут
# отдельная строка не потому, что она особенная, а потому, что без неё не завести ЛИЧНОСТЬ,
# то есть не начать вовсе. Узнать об этом человек обязан сейчас, а не в момент, когда он уже

#!/usr/bin/env bash
# ТОЧКА ВХОДА ОБРАЗА КОНТРОЛЛЕРА — пульт поднимается ОДНОЙ командой на машине, где есть
# только докер.
#
#   docker run -d --name world-control --restart unless-stopped \
#     -p 0.0.0.0:8090:8090 \
#     -v /var/run/docker.sock:/var/run/docker.sock \
#     -v world-control-keys:/root/.ssh \
#     -v world-control-docker:/root/.docker \
#     ghcr.io/omnifield/world-control:latest
#
# ТОМА ПОД СКОУП В ЭТОЙ КОМАНДЕ НЕТ И НЕ БУДЕТ (`WORLD2-124`). Личность юзера лежит там,
# где он её положил, и раздаётся раздачей по адресу (`WORLD2` 3.4); контроллер до неё
# дотягивается. Два тома выше — ВРЕМЯНКИ: ключи и контексты раскладываются из скоупа при
# входе и снимаются при выходе.
#
# ЗАЧЕМ ПРОВЕРКИ ПЕРЕЕХАЛИ СЮДА. Раньше их делал `control/up.sh` снаружи — но и он, и файл
# запуска лежат В РЕПОЗИТОРИИ, а репозитория на машине юзера нет и не будет (`TECH` 2: он
# ставит докер, больше ничего). Значит выбор был не «скрипт или образ», а «проверки в образе
# или проверок нет вовсе»: юзер, у которого пульт молча не встал, остался бы с пустым
# `docker ps` и без единой причины. `up.sh` при этом никуда не делся — он остался путём
# РАЗРАБОТЧИКА ЗОНЫ, и говорит это вслух сам.
#
# У КОНТРОЛЛЕРА ЕСТЬ ДОКЕР-СОКЕТ — И ЭТО ГЛАВНОЕ ОТЛИЧИЕ ЕГО КОМАНДЫ ОТ КОМАНДЫ ДВЕРИ.
# Дверь смотрит наружу машины, и власти над машиной у неё не будет никогда (`WORLD2` 3.7):
# у входной двери не бывает ключей от всего дома. Контроллер — наоборот, он и есть руки
# юзера; поэтому сокет в его команде ЕСТЬ и виден человеку глазами. Даёт власть ХОЗЯИН,
# явно, а не образ берёт её себе сам. Отсюда два прямых следствия для этого файла:
#
#   · сокета нет — это ОТКАЗ, а не предупреждение: контроллер без него не руки, а лицо;
#   · пульт публикуется НАРУЖУ умолчанием (`-p 0.0.0.0:…`, решение user 2026-08-18,
#     `WORLD2-150` B4): зайти в него может любой, кто знает адрес. Раз так — цена обязана
#     быть НАЗВАНА ВСЛУХ в этом выводе, а не спрятана в комментарий: кто дошёл до пульта,
#     дошёл до докер-сокета, то есть до машины. «Ставь контроллер там, где не жалко»
#     перестало быть советом и стало условием.
#
# ЧЕГО ОТСЮДА НЕ ВИДНО — сказано вслух, а не спрятано (`WORLD2` 4.2): занятость ХОСТ-порта и
# сама публикация живут СНАРУЖИ контейнера. Проверку `port-busy`, которая была у `up.sh`,
# заменить изнутри нечем — занятый порт назовёт сам `docker run`, и назовёт внятно.
#
# ЧТО СТАЛО С КОДАМИ `up.sh`. Перенесены: `bad-value`, `no-docker`, `no-daemon`,
# `control-silent`. Добавлены: `no-socket` (власть над машиной не отдана — снаружи это
# отдельная поломка с отдельным выходом) и `control-dead` (поднялся и вышел сам; у `up.sh`
# это было общим `up-failed`, а общего здесь быть не может — поднимает докер, а не мы).
# Потеряли смысл ЗДЕСЬ и остались у `up.sh`: `no-compose`, `no-compose-file`,
# `no-image-name`, `no-registry`, `no-image-tag`, `image-denied`, `pull-failed`,
# `no-image-local`, `no-pult-artifact`, `port-busy`, `up-failed`, `no-container` — всё это
# про то, как образ ДОБЫВАЮТ и поднимают снаружи. Изнутри образа этого вопроса уже нет: его
# задаёт `docker run`, и отвечает на него докер своим языком.
#
# ЯЗЫК — bash, а не POSIX sh (у двери sh). Причина одна и названная: стук в контроллер идёт
# через `/dev/tcp`, которого в busybox ash нет. Тем же стуком проверяет здоровье HEALTHCHECK
# образа — два разных стука в один контроллер однажды разошлись бы в мелочи, и «здоров по
# докеру, мёртв по нам» стало бы вопросом без ответа. bash в образе стоит не ради нас: на нём
# написан готовый подъём двери (`deploy/remote.sh`), который контроллер зовёт.
#
# Имена переменных ЛАТИНСКИЕ: bash не поддерживает не-ASCII в именах и молча превращает
# `ПОРТ=8090` в «команда не найдена». Тексты русские.
#
# ОТКАЗ = КОД В stdout + ПРИЧИНА С ВЫХОДОМ В stderr, ровно как у `up.sh` и у соседа: машине
# код, человеку причина. Отказ всегда заканчивается выходом из процесса — «отказал и
# продолжил» это не отказ, а жалоба.
#
# Прогоняется этот файл БЕЗ докера: `control/probe-control.sh`, раздел «точка входа образа».
# Потому он и отдельный файл, а не строка `RUN cat > … <<EOF` в Dockerfile: точка входа,
# которую нельзя ни прочитать, ни прогнать, проверяется только живым подъёмом — то есть на
# юзере.
set -u

# Попросили другую команду (`docker run … bash`, `ls -Ra /opt/world`) — отдаём её и в
# контроллер не играем. Так устроены все образы, у которых точка входа не сама программа:
# аргумент, начинающийся с дефиса, это ключ КОНТРОЛЛЕРА, всё остальное — чужая команда.
case "${1:-}" in
    ''|-*) ;;
    *)     exec "$@" ;;
esac

# Бинарь контроллера и стук лежат РЯДОМ с этим файлом — все трое кладёт `control/Dockerfile`
# в `/usr/local/bin`. Спрашиваем путь у самих себя (`${0%/*}`), а не пишем
# `/usr/local/bin/control` второй копией: копия разъехалась бы с раскладкой образа молча, и
# отказ говорил бы про файл, которого нет.
BIN="${0%/*}/control"
KNOCK="${0%/*}/control-knock.sh"
[ "$BIN" = "$0" ] && { BIN="control"; KNOCK="control-knock.sh"; }

# Контракт значений — `control/README.md` и подсказка самого контроллера (`control help`);
# здесь мы их только ЧИТАЕМ, чтобы проверять то же самое, чем будет пользоваться он, а не
# свои представления о нём.
ADDR="${CONTROL_ADDR:-:8090}"
PORT="${ADDR##*:}"
KEYS="${CONTROL_KEYS:-/root/.ssh}"
PULT="${CONTROL_PULT:-/opt/world/pult}"
DOCKER="${CONTROL_DOCKER:-docker}"
# Сколько секунд ждать ответа контроллера. Имя то же, что у `up.sh`: значение одно и то же,
# и заводить ему второе имя значило бы спрашивать у человека дважды одно и то же.
WAIT="${CONTROL_WAIT:-60}"
# Готовый подъём двери, который контроллер зовёт, и файл запуска РЯДОМ С НИМ — оба кладёт в
# образ `control/Dockerfile`, оба принадлежат зоне `deploy`. Имя образа двери спрашиваем у
# этого файла, а не пишем копией (см. блок «образ двери» ниже).
REMOTE_SH="${CONTROL_REMOTE_SH:-/opt/world/deploy/remote.sh}"
DOOR_COMPOSE="${REMOTE_SH%/*}/compose.yaml"
# Каталог рецептов — ЧТО контроллер умеет поднимать. Значение то же и с тем же умолчанием,
# что у самого контроллера: проверять полагается то, чем он будет пользоваться, а не своё
# представление о нём.
RECIPES="${CONTROL_RECIPES:-${REMOTE_SH%/*}/recipes}"
# Докер-сокет. ЗНАЧЕНИЕ, а не константа, по двум причинам: у rootless-докера сокет лежит не
# в `/var/run` (`$XDG_RUNTIME_DIR/docker.sock`), и проверку надо уметь прогонять без докера.
SOCKET="${CONTROL_SOCKET:-/var/run/docker.sock}"
# Каталоги времянок. Их ДВА, и оба объявлены В ОБРАЗЕ (`control/Dockerfile`) и смонтированы
# КОМАНДОЙ (`-v`). Копий здесь быть не должно, поэтому берём то, чем пользуются сами
# инструменты: связку — из значения контроллера, контексты — из значения докера. Что эти
# четыре места (Dockerfile, файл запуска, команда в README и этот файл) не разъехались,
# стережёт проба.
#
# Третьего каталога — под скоупы — больше нет: личность лежит по адресу, а не здесь.
DOCKER_CFG="${DOCKER_CONFIG:-${HOME:-/root}/.docker}"
# Рецепт РАЗДАЧИ СКОУПА: им контроллер поднимает личность юзера на названной им машине.
# Значение то же и с тем же умолчанием, что у самого контроллера: проверять полагается то,
# чем он будет пользоваться, а не своё представление об этом.
SHARE_RECIPE="${CONTROL_SHARE_RECIPE:-${REMOTE_SH%/*/*}/share/compose.yaml}"

step()   { printf '\n\033[1m→ %s\033[0m\n' "$*" >&2; }
ok()     { printf '  ✓ %s\n' "$*" >&2; }
warn()   { printf '  \033[33m!\033[0m %s\n' "$*" >&2; }
detail() { printf '    %s\n' "$*" >&2; }

# refuse КОД ПРИЧИНА ВЫХОД… — единственный способ выйти с ошибкой. Выход обязателен: отказ
# без следующего действия это диагноз, а не отказ (`WORLD2` 2.3).
refuse() {
    local code="$1" why="$2"; shift 2
    printf 'CONTROL-REFUSAL: %s\n' "$code"
    printf '\n\033[1;31m✗ контроллер не поднят: %s\033[0m\n' "$why" >&2
    local line; for line in "$@"; do printf '  выход: %s\n' "$line" >&2; done
    exit 1
}

# knock ПОРТ — постучаться в контроллер. Стук вынесен ОТДЕЛЬНЫМ файлом (`control/knock.sh`)
# и лежит рядом: тем же стуком меряет здоровье HEALTHCHECK образа. Две копии одного стука
# разошлись бы в мелочи, и «здоров по докеру, мёртв по нам» стало бы вопросом без ответа.
knock() { "$KNOCK" "$1" >/dev/null 2>&1; }

# chislo ЗНАЧЕНИЕ — целое больше нуля. Пустое и всё, где есть не-цифра, — не число: `[ -lt ]`
# на таком не «вернёт ложь», а СЛОМАЕТСЯ, напечатав ошибку оболочки нашему юзеру.
chislo() {
    case "$1" in ''|*[!0-9]*) return 1 ;; esac
    [ "$1" -gt 0 ]
}

# ┌─────────────────────────────────────────────────────────────────────────────────────┐
# │ ПУСТОЙ ОТВЕТ БЫВАЕТ ДВУХ РОДОВ, И ПУТАТЬ ИХ НЕЛЬЗЯ (`WORLD2-145`, `WORLD2-146`).      │
# │                                                                                      │
# │ `docker compose config` — это ВСЁ ИЛИ НИЧЕГО. Рецепт, который не читается целиком     │
# │ (незакавыченное двоеточие — `WORLD2-140`, необъявленная обязательная переменная —      │
# │ `WORLD2-145`), отдаёт ровно ту же пустоту, что рецепт без образов. Пока здесь стоял    │
# │ один ответ «имя не спросить» да заглушённый стдерр, проверка образа раздачи была       │
# │ МЕРТВА С РОЖДЕНИЯ: обе её ветки не печатались ни на какой машине, ни при каком         │
# │ состоянии — и это дважды пришло к нам безобидной оговоркой в журнале.                  │
# │                                                                                      │
# │ Поэтому ответов ТРИ, они называются полем, а не фразой, и причину нечитаемого файла    │
# │ мы ЗАБИРАЕМ у компоуза: он называет её точнее нас.                                     │
# └─────────────────────────────────────────────────────────────────────────────────────┘
#
# obraz_recepta ФАЙЛ [ИМЯ=значение…] — какой образ называет рецепт. Ответ кладётся в:
#   OBRAZ_OTVET=nazvan          OBRAZ — имя образа (первое, если их несколько);
#   OBRAZ_OTVET=net-obraza      файл прочитан, а образа в нём не названо;
#   OBRAZ_OTVET=ne-chitaetsya   компоуз файл не разобрал; чего не хватило — OBRAZ_PRICHINA.
#
# СВОЕЙ КОПИИ ИМЕНИ ОБРАЗА В ЭТОЙ ЗОНЕ НЕТ НАМЕРЕННО, поэтому мы и спрашиваем: копия уже
# разъезжалась молча (`WORLD2-121` сменил имя двери), и предупреждение начало бы врать при
# правильно названном образе на месте — то есть учить человека не читать предупреждения.
obraz_recepta() {
    local file="$1"; shift
    # СБРОС В ПУСТОЕ ПИШЕТСЯ ЗНАКАМИ, а не голым `=`: голое `=` одинаково похоже на нарочный
    # сброс и на оборванное присваивание — потому линтер о нём и говорит (`SC1007`, погашен
    # на месте, `WORLD2-157`). Для вызываемого это одно и то же: переменная задана и пуста.
    OBRAZ='' OBRAZ_OTVET='' OBRAZ_PRICHINA=''
    local oshibki kod vyvod
    # Стдерр НЕ глушим, а ЗАБИРАЕМ в файл. Слить его со stdout нельзя: компоуз пишет туда
    # и предупреждения при УСПЕХЕ, и они стали бы «именем образа».
    oshibki="$(mktemp 2>/dev/null || printf '%s' "${TMPDIR:-/tmp}/control-obraz.$$")"
    kod=0
    vyvod="$(env "$@" "$DOCKER" compose -f "$file" config --images 2>"$oshibki")" || kod=$?
    OBRAZ_PRICHINA="$(grep -v '^[[:space:]]*$' "$oshibki" 2>/dev/null | tail -n1)"
    rm -f "$oshibki"
    if [ "$kod" -ne 0 ]; then
        OBRAZ_OTVET=ne-chitaetsya
        [ -n "$OBRAZ_PRICHINA" ] || OBRAZ_PRICHINA="компоуз вышел с кодом $kod и промолчал"
        return
    fi
    OBRAZ="$(printf '%s\n' "$vyvod" | grep -v '^[[:space:]]*$' | head -n1)"
    [ -n "$OBRAZ" ] && OBRAZ_OTVET=nazvan || OBRAZ_OTVET=net-obraza
}

# ------------------------------------------------------------------ 0. значения снаружи
# ЗНАЧЕНИЕ С ФОРМОЙ ПРОВЕРЯЕТСЯ ДО ПОДЪЁМА, и это не педантизм: находка ревью `WORLD2-121` у
# соседа. `CONTROL_WAIT=abc` сломал бы сравнение в цикле ожидания — цикл не выполнился бы ни
# разу, стука не было бы вообще, — и следом сработал бы `control-silent`, убивающий ЗДОРОВЫЙ
# контроллер. То есть опечатка в переменной дала бы уверенный неверный диагноз, а в вывод
# уехала бы сырая ошибка оболочки: не наш язык и не наш формат.
step "значения, пришедшие снаружи"

chislo "$WAIT" || refuse bad-value \
    "CONTROL_WAIT=$WAIT — это не число секунд, а ждать ответа контроллера надо столько-то" \
    "назови целое больше нуля: -e CONTROL_WAIT=120 (умолчание 60)" \
    "оставь как было — просто убери переменную из команды" \
    "проверяем это ДО подъёма нарочно: иначе сломанное ожидание объявило бы живой контроллер молчащим"

ok "ожидание $WAIT с · связка $KEYS · пульт $PULT"

# Порт для СТУКА выводим из `CONTROL_ADDR`, но не судим его: адрес принадлежит контроллеру,
# и негодное значение он назовёт сам и точнее нас. Не вышло числа — стучаться нам нечем, и
# это говорится вслух; ожидание при этом пропускается, а не превращается в отказ. Убить
# контроллер из-за того, что мы не умеем в него постучаться, было бы подменой причины.
stuk=1
chislo "$PORT" || stuk=
[ -n "$stuk" ] || warn "из CONTROL_ADDR=$ADDR не вывести числовой порт — стучаться мне нечем"

# ЧЕГО ОТСЮДА НЕ ПРОВЕРИТЬ. Говорим это ЗДЕСЬ, до подъёма, а не в конце: человек, который
# читает журнал сверху вниз, обязан узнать границу раньше, чем упрётся в неё.
detail "занятость ХОСТ-порта и саму публикацию изнутри контейнера не видно — их назовёт docker run"

# ------------------------------------------------------------------ 1. власть над машиной
# Контроллер — руки юзера (`WORLD2` 3.7): подъём дверей, список ресурсов, работа с местами.
# Всё это он делает докером. Без сокета он поднимется и будет отвечать `no-docker` на каждый
# осмысленный запрос — то есть выглядеть работающим, не будучи им. Поэтому здесь ОТКАЗ:
# лучше не встать с названной причиной, чем встать пустышкой.
step "власть над машиной: докер-сокет"

command -v "$DOCKER" >/dev/null 2>&1 || refuse no-docker \
    "докера нет в самом образе (искали «$DOCKER») — контроллеру нечем распоряжаться машиной" \
    "это поломка ОБРАЗА, а не твоей машины: докер-клиент кладётся в него сборкой" \
    "проверь, не переопределён ли инструмент: -e CONTROL_DOCKER=<путь>" \
    "возьми образ заново: docker pull ghcr.io/omnifield/world-control:latest"

if [ -n "${DOCKER_HOST:-}" ]; then
    # Хозяин назвал демона сам — сокет в контейнере тогда ни при чём, и требовать его файл
    # значило бы отказывать на верной раскладке.
    ok "демона назвали через DOCKER_HOST=$DOCKER_HOST — сокет в контейнере не смотрим"
else
    [ -S "$SOCKET" ] || refuse no-socket \
        "докер-сокета $SOCKET в контейнере нет — власть над машиной контроллеру не отдали" \
        "добавь в команду: -v /var/run/docker.sock:/var/run/docker.sock" \
        "докер rootless — сокет лежит в другом месте: -v \$XDG_RUNTIME_DIR/docker.sock:/var/run/docker.sock" \
        "демон не на этой машине — назови его: -e DOCKER_HOST=ssh://user@host" \
        "без сокета контроллер поднялся бы и отвечал no-docker на каждый ресурс — это не контроллер, а лицо"
fi

"$DOCKER" info >/dev/null 2>&1 || refuse no-daemon \
    "сокет отдан, а демон докера не отвечает" \
    "запусти его на ХОЗЯЙСКОЙ машине: systemctl start docker (либо открой Docker Desktop)" \
    "демон работает — дело в правах на сокет: посмотри ls -l $SOCKET на машине хозяина" \
    "тот же вопрос снаружи, с машины хозяина: docker info"
ok "демон отвечает — контроллеру есть чем распоряжаться машиной"

# ┌─────────────────────────────────────────────────────────────────────────────────────┐
# │ ЦЕНА ПУБЛИКАЦИИ ГОВОРИТСЯ В ИТОГОВОМ БЛОКЕ, А НЕ ЗДЕСЬ (`WORLD2-150` B4).            │
# │                                                                                      │
# │ Строкой выше подтверждено, что у контроллера есть власть над этой машиной, — отсюда   │
# │ цена и берётся. Но сказать её надо ТАМ, ГДЕ ЧЕЛОВЕК ЧИТАЕТ: подъём печатает десятки   │
# │ строк, и предупреждение, стоящее в начале, уезжает из терминала прежде, чем он        │
# │ дочитает. Поэтому цена стоит в конце, в блоке «контроллер поднят», и стоит ОДИН РАЗ:  │
# │ второй копией она разошлась бы с первой молча, и сторож перестал бы различать, из     │
# │ какого места её потеряли. Проверено порчей: пока копий было две, снятие любой из них   │
# │ проходило зелёным.                                                                    │
# └─────────────────────────────────────────────────────────────────────────────────────┘

# ------------------------------------------------------------------ 2. времянки
# ДВА КАТАЛОГА, И ОБА — ВРЕМЯНКИ (`WORLD2` 1.9): ключи территорий и контексты докера
# раскладываются ИЗ СКОУПА при входе и снимаются при выходе. Забыл `-v` — докер всё равно
# создаст тома, но БЕЗ ИМЕНИ, и найти их через полгода будет нечем (`kb:WORLD-28`).
#
# ЗДЕСЬ ПРЕДУПРЕЖДЕНИЕ, А НЕ ОТКАЗ — в отличие от двери, и разница не в строгости. Дверь
# бежит не из-под root, состояние поля это ВСЁ, что она делает, и непишущийся каталог у неё
# означает мёртвую дверь. Контроллер бежит из-под root, и каждый каталог нужен СВОЕЙ части
# работы. Отказывать целиком из-за одной части значило бы запретить рабочие раскладки — а
# молчать нельзя, поэтому каждая называет свой будущий отказ.
# ┌─────────────────────────────────────────────────────────────────────────────────────┐
# │ ЧЕМ ПОДНЯТ САМ КОНТРОЛЛЕР — И ТОЛЬКО ОН (`WORLD2-130`, `WORLD2-146`).                │
# │                                                                                      │
# │ Спрашивать некого: версия лежит в его собственном окружении — штампом, который       │
# │ вписал выпуск. Ни сокета, ни `docker inspect` для этого не нужно, и это важно: свою   │
# │ версию вещь обязана знать всегда и без чужой помощи.                                  │
# │                                                                                      │
# │ ПРО ВЕЩИ ЭТА ВЕРСИЯ НЕ ГОВОРИТ НИЧЕГО. Здесь стояло обещание «дверь и раздача встанут │
# │ ТОЙ ЖЕ сборки» — и оно стало ложью в тот же день, когда публикация стала раздельной:   │
# │ у каждого образа свой выпуск и своя версия (`WORLD2-146`). Вывод, обещающий            │
# │ несуществующее, мы уже чинили (`WORLD2-129`), и второй раз заводить его не станем.     │
# │                                                                                      │
# │ Строка стоит ЗДЕСЬ, а не только в журнале контроллера: юзер поднимает пульт одной     │
# │ командой и читает ровно этот вывод. Полезное, лежащее там, куда юзер не ходит, — то   │
# │ самое, из-за чего узел и заведён.                                                     │
# └─────────────────────────────────────────────────────────────────────────────────────┘

            warn "образа двери $OBRAZ на этой машине нет — и это НЕ поломка"
            detail "добавление ресурса пройдёт: та машина притянет образ из реестра сама (путь image-pull)"
            detail "это дольше копии по ssh и требует, чтобы ТА машина доставала до реестра"

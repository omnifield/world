        kill -0 "$upravlenie" 2>/dev/null || break   # вышел сам — ждать нечего
        if knock "$PORT"; then otvet=1; break; fi
        sleep 1
        i=$((i + 1))
    done
else
    # Стучаться нечем — но дать контроллеру мгновение и посмотреть, не вышел ли он сам, мы
    # обязаны: это единственное, что здесь ещё можно проверить честно.
    step "ответа не жду — из CONTROL_ADDR=$ADDR не вывести порт для стука"
    sleep 1
fi

if ! kill -0 "$upravlenie" 2>/dev/null; then
    wait "$upravlenie"; code=$?
    refuse control-dead \
        "контроллер вышел сам, код $code — пульта нет" \
        "причину назвал он сам, строкой выше: это его журнал, а не наш" \
        "чаще всего это занятый порт ВНУТРИ контейнера или нечитаемое состояние" \
        "весь журнал: docker logs world-control"
fi

if [ -n "$stuk" ] && [ -z "$otvet" ]; then
    kill -TERM "$upravlenie" 2>/dev/null
    refuse control-silent \
        "контроллер запущен, а за ${WAIT}с так и не ответил на http://127.0.0.1:$PORT/api/me" \
        "журнал контроллера — выше: если он падает, причина названа там первой же строкой" \
        "машина медленная и первый запуск дольше — дай времени: -e CONTROL_WAIT=120" \
        "стучимся ИЗНУТРИ контейнера: снаружи тишина может быть и от публикации, а здесь она не при чём"
fi

if [ -n "$otvet" ]; then
    ok "контроллер отвечает"
else
    # Контроллер ЖИВ (процесс не вышел), но здоровье не проверено. Говорим это ровно так:
    # непроверенное называется непроверенным (`WORLD2` 4.2), а не выдаётся за подтверждение.
    warn "здоровье контроллера НЕ проверено — стучаться было нечем; процесс при этом работает"
    detail "состояние покажет сам докер: docker ps (HEALTHCHECK образа стучится на :8090)"
    detail "порт внутри контейнера фиксирован — CONTROL_ADDR крутить не надо, наружу крутится хост-порт"

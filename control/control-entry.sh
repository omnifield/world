        detail "это НЕ «рецепт сломан»: файл разобран целиком, в нём просто нет имени образа"
        detail "добавление ресурса откажет отказом подъёма — поднимать ему нечего" ;;
    *)
        if "$DOCKER" image inspect "$OBRAZ" >/dev/null 2>&1; then

    curl -X POST http://<адрес контроллера>/api/session \\
      -d '{"addr":"http://<машина со скоупом>:8070/","password":"<пароль скоупа>"}'

  СКОУПА ЕЩЁ НЕТ — заводится он ТАМ, где будет лежать, а не здесь: юзер называет машину
  (адрес, креды, имя участка) и сам скоуп (адрес раздачи и пароль):
    curl -X POST http://<адрес контроллера>/api/scope -d '{
      "scope":{"addr":"http://<машина>:8070/","password":"<пароль>"},
      "identity":{"name":"я","brand":""},
      "machine":{"name":"vps","addr":"user@<машина>","creds":{"kind":"key","value":"<ключ ssh>"}}}'

  ХОДА «ЗАВЕСТИ ЗДЕСЬ» У КОНТРОЛЛЕРА НЕТ (WORLD2 3.7). Он времянка: снёс, поднял на другой
  машине, вошёл тем же адресом — всё на месте. Личность на нём не лежит никогда.

  ЗАВЕДЕНИЕ — ЭТО ПОДЪЁМ РАЗДАЧИ, И БОЛЬШЕ НИЧЕГО: мир поднял её на названной машине и УШЁЛ.
  В свежем скоупе лежит личность и пустота — ни территорий, ни ключей. Нужна эта машина
  участком — заведи её отдельным решением: POST /api/resources.

  СНЯТЬ СКОУП — та же ручка глаголом DELETE, то же тело МИНУС личность. Имя участка назови
  ТО ЖЕ, что при заведении: из него и порта собрано имя раздачи, и снимается она по нему.
    curl -X DELETE http://<адрес контроллера>/api/scope -d '{
      "scope":{"addr":"http://<машина>:8070/","password":"<пароль>"},
      "machine":{"name":"vps","addr":"user@<машина>","creds":{"kind":"key","value":"<ключ ssh>"}}}'

  ТОМ РАЗДАЧИ ПРИ ЭТОМ ОСТАЁТСЯ: снятие вещи не означает потерю личности. Стереть её —
  отдельно и явно: DELETE /api/scope?with-state=1. Оба исхода контроллер называет вслух.

  КРЕДЫ К МАШИНЕ — ключ либо пароль, как в PuTTY. Дал пароль — контроллер зайдёт им ОДИН
  раз и положит в ~/.ssh/authorized_keys той машины одну подписанную строку (публичный ключ
  юзера); сам пароль не сохраняется нигде. Дальше строка живёт по-разному, и разница
  названа вслух: на ЗАВЕДЕНИИ И СНЯТИИ СКОУПА мир убирает её сразу — ходить туда ему больше
  незачем; на ТЕРРИТОРИИ она остаётся, потому что мир на неё ходит, и убрать доступ можно,
  удалив её.

  ДВЕРИ НА ТЕРРИТОРИЯХ поднимает контроллер, а не эта команда: заведи территорию — дверь
  встанет там сама. Дверь на ЭТОЙ машине поднимается своей командой, и она в другом README.

  журнал   docker logs -f world-control
  снять    docker rm -f world-control    (ключи и контексты — времянки, скоуп лежит не здесь)

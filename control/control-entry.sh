sostoyanie() {
    local dir="$1" chto="$2" chem="$3"
    if [ ! -d "$dir" ]; then
        warn "каталога $dir нет — $chto"
        detail "каталог заводит сам образ, значит его перекрыли монтированием: проверь -v в команде"
        detail "$chem"
        return
    fi
    if [ ! -w "$dir" ]; then
        warn "каталог $dir не пишется — $chto"
        detail "чаще всего это монтирование только на чтение (:ro) либо чужой владелец тома"
        detail "$chem"
        return
    fi
    ok "$dir на месте и пишется"
}


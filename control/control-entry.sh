# Права связки — отдельный вопрос, и он ТИХИЙ: ключ в каталоге, открытом всем, ssh просто не
# возьмёт, а скажет про формат. Час на такую находку человек тратит целиком.
if [ -d "$KEYS" ]; then
    # Права СПРАШИВАЕМ, а не вычитываем из листинга: `ls` печатает имена файлов, и разбор
    # его вывода — то, о чём линтер говорит не зря (`SC2012`, погашен на месте,
    # `WORLD2-157`). Здесь нам нужно не имя, а один ответ про каталог, и его даёт `stat`.
    prava="$(stat -c '%A' "$KEYS" 2>/dev/null || true)"
    case "$prava" in
        drwx------) ;;
        # НЕПРОВЕРЕННОЕ НАЗЫВАЕТСЯ НЕПРОВЕРЕННЫМ (`WORLD2` 4.2). Прежде пустой ответ молчал
        # заодно с «права в порядке», и человек читал молчание как «посмотрели».
        "") warn "права связки $KEYS посмотреть не вышло — эта проверка НЕ выполнялась"
           detail "посмотреть руками на этой машине: stat -c '%A' $KEYS — штатно drwx------" ;;
        *) warn "связка $KEYS открыта шире, чем ssh согласен терпеть ($prava)"
           detail "ssh молча не возьмёт из неё ключ и скажет про формат — это стоит часа поисков"
           detail "свой каталог образ заводит с правами 700; такие права приезжают с чужим монтированием"
           detail "поправить у себя: chmod 700 <каталог, который смонтирован в $KEYS>" ;;
    esac
fi


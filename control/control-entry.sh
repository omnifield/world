# Контроллер уходит в фон, а не `exec`, ровно ради одной вещи: «запущен» и «отвечает» —
# разные вещи, и подтверждать надо вторую. Плата за это — оболочка первым процессом, поэтому
# сигналы передаём руками: без этого `docker stop` десять секунд ждал бы того, кто его не
# слышит, и добивал бы контроллер по таймауту.
step "поднимаю контроллер на $ADDR"
"$BIN" "$@" &
upravlenie=$!
trap 'kill -TERM "$upravlenie" 2>/dev/null' TERM INT

# ------------------------------------------------------------------ 6. контроллер отвечает

#!/usr/bin/env bash
# Подъём ЛОКАЦИИ одной командой: конфиг → сеть → контейнер → сторож отвечает → ВХОД В ПОЛЕ.
#
#   cp deploy/location.env.example deploy/location.env   # заполнить имя и «что даёт»
#   ./deploy/location-up.sh
#
# Это второе изделие мира (`kb:WORLD-53`): образ мира разворачивает мир, образ локации —
# локацию, которая САМА входит в поле. Человек заполняет конфиг и даёт одну команду; больше
# от него ничего не требуется — ни `curl` с телом регистрации руками, ни правки чьих-то
# конфигов, ни консоли на ноде. Образу нужен только докер.
#
# ЛОКАЦИЯ ВПРАВЕ БЫТЬ ПУСТОЙ (`kb:WORLD-54`). Внутри может не стоять ничего: вход в
# пространство и стройка внутри него — разные вещи, и стройка идёт ПОСЛЕ входа. Поэтому
# поднимается здесь СТОРОЖ — минимальная служба «я здесь», и этого довольно, чтобы место
# существовало в поле: присутствие проверяется достижимостью, а не обещанием.
#
# ПОРЯДОК ВНУТРИ — СНАЧАЛА СТОРОЖ, ПОТОМ ВХОД, и он не переставляется. `world join` первым
# делом стучится в собственный объявленный адрес: побеги он раньше, чем встал сторож,
# локация честно откажет `self-unreachable` (контракт зоны `core`, `tasker:WORLD-83`).
#
# Скрипт ничего не решает сам — раскладка в `deploy/location-compose.yaml`, а правила имени,
# адреса и отказов живут в двери и в бинаре. Он существует ради трёх вещей, которых нет у
# компоуза: общая сеть создаётся ДО контейнера, вход в поле делается после того, как сторож
# ОТВЕТИЛ, и каждый отказ называет причину и выход (`kb:WORLD-31`).
#
# Имена переменных ЛАТИНСКИЕ: bash не поддерживает не-ASCII в именах переменных и молча
# превращает `ИМЯ=x` в «команда не найдена». Тексты и комментарии — русские.
set -euo pipefail

HERE="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
CONFIG="${WORLD_LOCATION_ENV:-$HERE/location.env}"

# Адрес, по которому машина видит опубликованный порт ДВЕРИ (умолчание `127.0.0.1`, довод
# целиком — в `up.sh`). Своего порта у локации нет и не будет, поэтому здесь значение
# участвует ровно в одном месте — в подсказке «куда смотреть»: назови мы там адрес, до
# которого на этой машине не дойти, человек пошёл бы искать несуществующую поломку.
HOST="${WORLD_HOST:-127.0.0.1}"

want_build="${WORLD_BUILD:-}"

usage() {
    cat <<'USAGE'
Подъём локации: ./deploy/location-up.sh [--build] [--config ФАЙЛ]

  (без ключей)   поднять из образа, который уже лежит на машине, и войти в поле
  --build        пересобрать образ локации и поднять. СБОРКЕ ПОЛЕ НЕ НУЖНО:
                 внутрь едет один бинарь, стройки фронта здесь нет вовсе
  --config ФАЙЛ  другой конфиг (умолчание deploy/location.env). Так на одной
                 машине поднимаются несколько локаций — по конфигу на каждую
  -h, --help     эта подсказка

Конфиг — четыре значения, и два из них с умолчаниями:
  WORLD_NAME     имя локации в поле = её маршрут за дверью и имя в общей сети
  WORLD_GIVES    что локация даёт, одной строкой
  WORLD_DOOR     адрес двери «имя:порт»   (умолчание door:8080)
  WORLD_NET      общая сеть               (умолчание omnifield-gateway)

Образец — deploy/location.env.example:
  cp deploy/location.env.example deploy/location.env

Переменные среды:
  WORLD_LOCATION_ENV=ФАЙЛ   то же, что --config
  WORLD_BUILD=1             то же, что --build
  WORLD_HOST=10.8.1.1       адрес, по которому машина видит хост-порт двери —
                            в подсказке «куда смотреть» (умолчание 127.0.0.1)

Локация НЕ публикует порт наружу: наружу торчит ровно одна дверь (kb:FUND-5), и
снаружи локация доступна через неё — по маршруту /<имя>/.
USAGE
}

while [ $# -gt 0 ]; do
    case "$1" in
        --build)   want_build=1 ;;
        --config)  shift; [ $# -gt 0 ] || { printf 'у --config нет значения: --config deploy/location.env\n' >&2; exit 2; }
                   CONFIG="$1" ;;
        --config=*) CONFIG="${1#--config=}" ;;
        -h|--help) usage; exit 0 ;;
        *) usage >&2; printf '\nнепонятный ключ: %s\n' "$1" >&2; exit 2 ;;
    esac
    shift
done

step() { printf '\n\033[1m→ %s\033[0m\n' "$*" >&2; }
ok()   { printf '  ✓ %s\n' "$*" >&2; }
warn() { printf '  \033[33m!\033[0m %s\n' "$*" >&2; }

# fail ПРИЧИНА ВЫХОД… — единственный способ выйти с ошибкой. Выход обязателен: отказ без
# следующего действия это диагноз, а не отказ (`kb:WORLD-31`).
fail() {
    local why="$1"; shift
    printf '\n\033[1;31m✗ локация не поднялась: %s\033[0m\n' "$why" >&2
    local line
    for line in "$@"; do printf '  выход: %s\n' "$line" >&2; done
    exit 1
}

# docker_noconv … — вызов докера, в аргументах которого НЕТ путей хоста, но есть
# КОНТЕЙНЕРНЫЕ (`/app/world`). Git Bash (MSYS) переписал бы их в виндовые, и `docker exec`
# пошёл бы искать `C:/Program Files/Git/app/world`. Правило зоны и довод целиком — в
# `build.sh` рядом с таким же помощником: путь хоста в аргументе — обычный `docker`;
# путей хоста нет вовсе — `docker_noconv`. Глобально глушить нельзя: `docker compose -f
# <файл>` подаёт путь ХОСТА, и его переводить как раз обязаны.
docker_noconv() { MSYS_NO_PATHCONV=1 MSYS2_ARG_CONV_EXCL='*' docker "$@"; }

# ------------------------------------------------------------------ 1. конфиг
# Чтение конфига — общая часть с `location-down.sh` (`location-config.sh`): подъём и снятие
# обязаны находить ОДНУ И ТУ ЖЕ локацию, а два отдельных чтения разъезжаются молча.
step "конфиг локации: ${CONFIG#"$HERE/"}"

# shellcheck source=location-config.sh
. "$HERE/location-config.sh"

# «Что даёт» спрашивает ВХОД в поле, а не снятие, — потому проверка здесь, а не в общей
# части: снимать локацию, забыв, что она давала, вполне можно.
[ -n "$WORLD_GIVES" ] || fail \
    "в конфиге не сказано, что локация даёт (WORLD_GIVES пусто): $CONFIG" \
    "без этой строки локация попадёт в список за дверью безымянной, и взять её осмысленно будет нельзя" \
    "заполни WORLD_GIVES в $CONFIG — одной строкой, человеку"

ok "локация «$WORLD_NAME» — $WORLD_GIVES"
ok "дверь $WORLD_DOOR, общая сеть $WORLD_NET"

# ------------------------------------------------------------------ 2. чем поднимаем
step "проверяю, чем поднимать"

command -v docker >/dev/null 2>&1 || fail \
    "докера на машине нет" \
    "поставь Docker Engine либо Docker Desktop: https://docs.docker.com/engine/install/" \
    "больше локации ничего не нужно — ни ноды, ни девконтейнера, ни консоли мира"

docker info >/dev/null 2>&1 || fail \
    "докер есть, а демон не отвечает" \
    "запусти его: systemctl start docker (либо открой Docker Desktop)" \
    "если демон работает — дело в правах: usermod -aG docker \$USER и перезайти"

"${COMPOSE[@]}" version >/dev/null 2>&1 || fail \
    "у докера нет compose v2 (плагина docker-compose-plugin)" \
    "поставь плагин: https://docs.docker.com/compose/install/" \
    "проверка: docker compose version"

ok "докер и compose v2 на месте"

# ------------------------------------------------------------------ 3. общая сеть
# Идемпотентно: сеть уже есть — не сделано ничего. Локация в неё ВХОДИТ, а не заводит её:
# сеть общая на машину и старше любого компоуз-проекта.
step "общая сеть $WORLD_NET"
if docker network inspect "$WORLD_NET" >/dev/null 2>&1; then
    ok "сеть уже есть"
else
    docker network create "$WORLD_NET" >/dev/null || fail \
        "общую сеть $WORLD_NET не создать" \
        "посмотри, что мешает: docker network create $WORLD_NET"
    ok "сеть создана"
    warn "сети не было вовсе — значит и двери в ней нет; мир поднимается ./deploy/up.sh"
fi

# ------------------------------------------------------------------ 4. образ
# Имя образа берём из файла запуска, а не держим вторую копию здесь: разъедутся — подъём
# начнёт собирать заново каждый раз, и причина будет выглядеть посторонней.
IMAGE="$("${COMPOSE[@]}" config --images 2>/dev/null | head -n1 || true)"
[ -n "$IMAGE" ] || IMAGE=omnifield/location:dev

step "образ $IMAGE"
if [ -z "$want_build" ] && docker image inspect "$IMAGE" >/dev/null 2>&1; then
    ok "образ на машине есть — собирать не нужно (пересобрать: --build)"
else
    if [ -z "$want_build" ]; then
        warn "образа на машине нет — собираю"
    fi
    # Сборка образа локации ПОЛЯ НЕ ТРЕБУЕТ — в этом вся разница с образом мира: внутрь
    # едет один бинарь, а у `core` зависимостей нет. Поэтому здесь нет ни отдельного
    # `build.sh`, ни проверки склада, ни первого шага: собирать нечего, кроме Go.
    step "собираю образ локации (сети у сборки нет — тянуть нечего)"
    "${COMPOSE[@]}" build || fail \
        "образ локации не собрался" \
        "полный вывод — выше, причина названа там" \
        "начисто: docker compose -f deploy/location-compose.yaml build --no-cache" \
        "базовые образы (golang, alpine) тянет докер — если машина без сети, перенеси готовый: docker save omnifield/location:dev | docker load"
    ok "образ собран"
fi

# ------------------------------------------------------------------ 5. контейнер
step "поднимаю локацию «$WORLD_NAME» (сторож на :8080 внутри сети, наружу не публикуется)"
"${COMPOSE[@]}" up -d --no-build --remove-orphans || fail \
    "контейнер локации не встал" \
    "журнал: docker compose -p $PROJECT -f deploy/location-compose.yaml logs" \
    "имя контейнера уже занято другой локацией — возьми другое имя в $CONFIG" \
    "сеть $WORLD_NET существует? docker network inspect $WORLD_NET"
ok "контейнер запущен"

CID="$("${COMPOSE[@]}" ps -q "$SERVICE" 2>/dev/null | head -n1 || true)"
[ -n "$CID" ] || fail \
    "контейнер поднялся, а найти его не вышло (compose ps не назвал id)" \
    "посмотри сам: docker compose -p $PROJECT -f deploy/location-compose.yaml ps" \
    "журнал: docker compose -p $PROJECT -f deploy/location-compose.yaml logs"

# ------------------------------------------------------------------ 6. сторож ОТВЕЧАЕТ
# «Запущен» и «отвечает» — разные вещи, и вход в поле обязан ждать второго. Стучимся
# ИЗНУТРИ контейнера: наружу локация не публикуется вовсе, а изнутри это ровно тот стук,
# которым проверяет себя HEALTHCHECK образа.
#
# Петля в адресе ниже — СОБСТВЕННАЯ ПЕТЛЯ КОНТЕЙНЕРА, и она к `WORLD_HOST` отношения не
# имеет: `WORLD_HOST` про то, как машина видит ОПУБЛИКОВАННЫЙ порт, а здесь публикации нет
# вовсе — стук идёт внутри контейнера, где адрес всегда один и тот же. Заменить его
# настройкой значило бы отправить стук наружу из места, у которого наружу ничего не торчит.
step "жду, пока сторож ответит"
guard_ready=
for try in {1..30}; do
    if docker_noconv exec "$CID" wget -q -T 2 -O- http://127.0.0.1:8080/healthz >/dev/null 2>&1; then
        guard_ready=1
        ok "сторож отвечает: место существует"
        break
    fi
    if [ "$try" = 30 ]; then break; fi
    sleep 1
done

[ -n "$guard_ready" ] || {
    printf '\n--- последние строки журнала локации ---\n' >&2
    "${COMPOSE[@]}" logs --tail=40 >&2 || true
    fail \
        "сторож не ответил за 30 секунд — входить в поле нечем" \
        "журнал выше: локация называет причину сама, первой же строкой" \
        "состояние контейнера: docker ps -a --filter id=$CID" \
        "в поле локация НЕ вошла — маршрута в пустоту не появилось, это нарочно"
}

# ------------------------------------------------------------------ 7. ВХОД В ПОЛЕ
# Тот же бинарь, другая команда. Отказ входа НЕ переписываем: правила имени и адреса живут
# в двери, и своя формулировка здесь потеряла бы выход, который дверь уже назвала
# (`core/README.md`, «Отказы»).
step "вхожу в поле — дверь $WORLD_DOOR"
join_err="$(mktemp)"
trap 'rm -f "$join_err"' EXIT

set +e
join_out="$(docker_noconv exec "$CID" /app/world join 2>"$join_err")"
join_status=$?
set -e

if [ "$join_status" != 0 ]; then
    printf '\n--- что сказала локация ---\n' >&2
    cat "$join_err" >&2
    fail \
        "локация поднялась, но в поле не вошла" \
        "причина — прямо выше, её словами: локация и дверь называют и причину, и выход" \
        "мир поднят? docker ps --filter name=world-door — если нет: ./deploy/up.sh" \
        "дверь видна из сети? docker exec $CID wget -qO- http://$WORLD_DOOR/healthz" \
        "контейнер локации ОСТАВЛЕН поднятым — войти повторно можно тем же: ./deploy/location-up.sh$CONFIG_KEY"
fi

printf '%s\n' "$join_out" >&2

# ------------------------------------------------------------------ куда смотреть
# Адрес застройки — свойство МЕСТА, и заявляет его человек: мир место не сканирует и не
# угадывает («не заявлено — не видно», `core/README.md`). Поэтому подъём обязан сказать
# вслух, что именно он заявил, — молчание здесь неотличимо от «заявил, да не то», а узнаётся
# это по маршруту, то есть позже и не тем человеком.
if [ -n "${WORLD_BUILD_ADDR:-}" ]; then
    build_say="застройка заявлена: $WORLD_BUILD_ADDR — маршрут места ведёт туда
    поднимать её мир не будет: это твоя вещь и твой процесс внутри места"
else
    build_say="застройки не заявлено — внутри стоит СТОРОЖ и больше ничего, и маршрут
    места отвечает его присутствием. Это законное состояние, а не недоделка: место
    существует, стройка внутри него идёт отдельно и может не идти вовсе.
    Поднимешь внутри места свою вещь — назови её адрес в WORLD_BUILD_ADDR ($CONFIG)
    и подними локацию заново"
fi

cat >&2 <<GOTOVO

$(printf '\033[1;32m✓ локация «%s» в поле\033[0m' "$WORLD_NAME")

  снаружи машины — ЧЕРЕЗ ДВЕРЬ, своего порта у локации нет:
    http://$HOST:<хост-порт двери>/$WORLD_NAME/     (умолчание порта — 8080,
    адрес крутится WORLD_HOST)

  изнутри общей сети $WORLD_NET:
    http://$WORLD_NAME:8080/            сама локация, минуя дверь
    http://$WORLD_DOOR/$WORLD_NAME/     она же через дверь

  кто сейчас в поле   docker exec $CID /app/world who
  журнал локации      docker compose -p $PROJECT -f deploy/location-compose.yaml logs -f
  снять с поля        ./deploy/location-down.sh$CONFIG_KEY

  что стоит на месте:
    $build_say

  чем место располагает изначально — ЛАНДШАФТ, а не инструменты:
    git · node с npm · curl · ca-certificates       посмотреть: docker exec $CID git --version
    склад под застройку  /place  (том ${PROJECT}_place — переживает пересоздание контейнера)

  ВОЙТИ В МЕСТО И РАБОТАТЬ РУКАМИ — место жилое, вход не от root:
    docker exec -it $CID sh        и там: cd /place
    правки делай в /place — всё, что вне тома, живёт до пересоздания контейнера
    редактором: VS Code → Attach to Running Container (окно должно быть запущено
    там, где есть докер). Git Bash подменяет пути вида /place — пиши //place
    либо MSYS_NO_PATHCONV=1. Подробности: deploy/README.md, «Как войти в место»

GOTOVO

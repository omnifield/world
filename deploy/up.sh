#!/usr/bin/env bash
# Подъём мира одной командой: сеть → контейнер → дверь отвечает.
#
#   ./deploy/up.sh                 дверь на :8080 из того образа, что уже лежит
#   ./deploy/up.sh --build         пересобрать образ и поднять (нужно поле, см. ниже)
#   WORLD_PORT=8090 ./deploy/up.sh дверь на :8090
#
# У двери ДВА входа, и путать их не надо: хост-порт — для человека снаружи машины, имя в
# сети `omnifield-gateway` — для соседей по полю (`door:8080`, настраивается
# `WORLD_DOOR_ALIAS`). Соседу хост-публикация не нужна вовсе: он ходит по имени.
#
# ПОДЪЁМ НЕ ТРЕБУЕТ ПОЛЯ. Образ лежит на машине — мир встаёт из него, и больше ничего не
# нужно: ни склада пакетов, ни сети наружу, ни ноды. Скоуп не вправе зависеть от того, идёт
# ли в нём стройка (`kb:WORLD-54`), а сборка это стройка. Поэтому сборка здесь — отдельный
# шаг с отдельным ключом, и всё, что ей нужно, спрашивается ТОЛЬКО когда её просят.
#
# Образа на машине нет — тогда собрать придётся, и тогда же понадобится поле: пакеты пульта
# лежат на складе локации `probe-web`, а он виден лишь соседям по `omnifield-gateway`
# (`kb:FUND-5`). Готовый образ переносится и без поля: `docker save … | docker load`.
#
# Скрипт ничего не решает сам — вся раскладка в `deploy/compose.yaml`. Он существует ради
# двух вещей, которых у компоуза нет: общая сеть создаётся ДО контейнера (войти в
# несуществующую сеть докер не даёт, и первый подъём на чистой машине без этого не встаёт),
# и каждый отказ называет причину и выход, а не только код возврата (`kb:WORLD-31`).
#
# Имена переменных ЛАТИНСКИЕ, хотя весь репозиторий говорит по-русски. Это не небрежность:
# bash не поддерживает не-ASCII в именах переменных и молча превращает `ПОРТ=8080` в
# «команда не найдена», а `$ПОРТ` — в четыре буквы текста. Тексты и комментарии русские,
# идентификаторы латинские.
set -euo pipefail

NET=omnifield-gateway
PORT="${WORLD_PORT:-8080}"
# Адрес, по которому МАШИНА видит свой же опубликованный порт. Умолчание прежнее —
# `127.0.0.1`, и для тех, у кого хост-петля доходит до докера, ничего не меняется.
#
# Зачем это значение вообще. Опубликованный порт живёт там, где живёт ДЕМОН докера, а
# команду даёт человек — и это не всегда одна и та же петля. Живой случай (`tasker:WORLD-97`):
# докер в WSL, команда из Git Bash на Windows; дверь поднялась и отвечает снаружи, а стук в
# `127.0.0.1` не доходит — и подъём объявлял живую дверь мёртвой. Проверять надо то, что
# есть, а не то, что предполагалось.
#
# Адрес НЕ УГАДЫВАЕТСЯ перебором нескольких: перебор однажды выберет чужую дверь и будет
# проверять её — молча и убедительно. Значение называет человек, один раз.
HOST="${WORLD_HOST:-127.0.0.1}"
# Контрактное имя двери в общей сети — то, по чему СОСЕД входит в поле (`door:8080`).
# Настраивается ровно затем, чтобы имя можно было освободить, если в поле оно уже занято.
#
# Умолчание написано и здесь, и в `compose.yaml` — двумя копиями одного слова. Так вышло не
# от небрежности: файл запуска обязан работать и напрямую, без этого скрипта, а скрипт
# обязан НАЗВАТЬ адрес человеку до того, как компоуз его подставит. Чтобы копии не
# разъехались молча, за ними следит проба ветвления (`probe-branching.sh`).
ALIAS="${WORLD_DOOR_ALIAS:-door}"
HERE="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
COMPOSE=("docker" "compose" "-f" "$HERE/compose.yaml")

# Пересборку просят явно — ключом либо переменной. Умолчание «не собирать» это и есть
# главное свойство: подъём и стройка разведены.
want_build="${WORLD_BUILD:-}"

usage() {
    cat <<'USAGE'
Подъём мира: ./deploy/up.sh [--build]

  (без ключей)   поднять из образа, который уже лежит на машине. Поле не нужно.
  --build        пересобрать образ и поднять. Сборку делает ./deploy/build.sh,
                 и ЕЙ нужно поле: пакеты пульта лежат на складе probe-web,
                 видном только соседям по сети omnifield-gateway.
  -h, --help     эта подсказка.

Переменные:
  WORLD_PORT=8090        хост-порт двери — вход для человека СНАРУЖИ машины
                         (умолчание 8080)
  WORLD_HOST=10.8.1.1    адрес, по которому МАШИНА видит опубликованный порт —
                         по нему подъём и проверяет дверь (умолчание 127.0.0.1).
                         Крутят его, когда хост-петля до опубликованного порта не
                         доходит: типичный случай — докер живёт в WSL, а команду
                         даёт Windows. Проверить снаружи: curl http://АДРЕС:8080/healthz
  WORLD_DOOR_ALIAS=door  имя двери в общей сети omnifield-gateway — вход для
                         СОСЕДЕЙ по полю (умолчание door, адрес door:8080).
                         Меняют его тогда, когда имя в поле уже занято
  WORLD_BUILD=1          то же, что --build

Образа на машине нет — он соберётся сам, и тогда поле понадобится. Перенести
готовый образ можно без поля:  docker save omnifield/world:dev | docker load
USAGE
}

while [ $# -gt 0 ]; do
    case "$1" in
        --build)    want_build=1 ;;
        -h|--help)  usage; exit 0 ;;
        *)          usage >&2; printf '\nнепонятный ключ: %s\n' "$1" >&2; exit 2 ;;
    esac
    shift
done

step() { printf '\n\033[1m→ %s\033[0m\n' "$*" >&2; }
ok()   { printf '  ✓ %s\n' "$*" >&2; }
warn() { printf '  \033[33m!\033[0m %s\n' "$*" >&2; }

# fail ПРИЧИНА ВЫХОД… — единственный способ выйти с ошибкой. Выход обязателен: отказ без
# следующего действия это диагноз, а не отказ.
fail() {
    local why="$1"; shift
    printf '\n\033[1;31m✗ не поднялось: %s\033[0m\n' "$why" >&2
    local line
    for line in "$@"; do printf '  выход: %s\n' "$line" >&2; done
    exit 1
}

# ------------------------------------------------------------------ 1. чем поднимаем
step "проверяю, чем поднимать"

command -v docker >/dev/null 2>&1 || fail \
    "докера на машине нет" \
    "поставь Docker Engine либо Docker Desktop: https://docs.docker.com/engine/install/" \
    "больше миру ничего не нужно — ни ноды, ни девконтейнера"

docker info >/dev/null 2>&1 || fail \
    "докер есть, а демон не отвечает" \
    "запусти его: systemctl start docker (либо открой Docker Desktop)" \
    "если демон работает — дело в правах: usermod -aG docker \$USER и перезайти"

"${COMPOSE[@]}" version >/dev/null 2>&1 || fail \
    "у докера нет compose v2 (плагина docker-compose-plugin)" \
    "поставь плагин: https://docs.docker.com/compose/install/" \
    "проверка: docker compose version"

ok "докер и compose v2 на месте"

# ------------------------------------------------------------------ 2. общая сеть
# Идемпотентно: сеть уже есть — не сделано ничего. Ровно то же делает девбокс своим
# initializeCommand, и по той же причине.
step "общая сеть $NET"
if docker network inspect "$NET" >/dev/null 2>&1; then
    ok "сеть уже есть"
else
    docker network create "$NET" >/dev/null || fail \
        "общую сеть $NET не создать" \
        "посмотри, что мешает: docker network create $NET"
    ok "сеть создана"
fi

# ------------------------------------------------------------------ 3. образ
# Имя образа берём из файла запуска, а не держим вторую копию здесь: разъедутся — подъём
# начнёт собирать заново каждый раз, и причина будет выглядеть посторонней.
IMAGE="$("${COMPOSE[@]}" config --images 2>/dev/null | head -n1 || true)"
[ -n "$IMAGE" ] || IMAGE=omnifield/world:dev

step "образ $IMAGE"
if docker image inspect "$IMAGE" >/dev/null 2>&1; then
    have_image=1
    ok "образ на машине есть"
else
    have_image=
    warn "образа на машине нет — придётся собрать, а для сборки нужно поле"
fi

if [ -z "$want_build" ] && [ -n "$have_image" ]; then
    ok "собирать не нужно — поднимаю из того, что лежит (пересобрать: --build)"
else
    # Сборка живёт в `deploy/build.sh` и целиком: она из двух шагов разной природы
    # (пульт — контейнером в сети, образ — `docker build` без сети), и держать её половину
    # здесь значило бы развести подъём и стройку на словах, а не на деле. Всё, что сборке
    # нужно — сеть, склад, проверки, — спрашивает она сама, и только когда её позвали.
    step "нужна сборка — отдаю её deploy/build.sh"
    "$HERE/build.sh" >&2 || fail \
        "образ не собрался" \
        "причина названа выше — её печатает сама сборка" \
        "повторить только сборку: ./deploy/build.sh (шаг за шагом: --only-web, --only-image)" \
        "образ уже был и ломать его не хотелось — подними прежний: ./deploy/up.sh без --build"
fi

# ------------------------------------------------------------------ 4. контейнер
step "поднимаю дверь: хост-порт $PORT, имя в сети $ALIAS"
if ! WORLD_PORT="$PORT" WORLD_DOOR_ALIAS="$ALIAS" \
        "${COMPOSE[@]}" up -d --no-build --remove-orphans; then
    fail \
        "контейнер не встал на порт $PORT" \
        "порт $PORT занят кем-то ещё — возьми другой: WORLD_PORT=8090 $0" \
        "кто держит порт: docker ps --filter publish=$PORT (либо ss -ltnp | grep :$PORT)" \
        "наружу торчит ровно одна дверь (kb:FUND-5) — второй мир на той же машине поднимают на другом хост-порту"
fi
ok "контейнер запущен"

# ------------------------------------------------------------------ 5. дверь отвечает
# «Запущен» и «отвечает» — разные вещи, и подтверждать надо второе. Стучимся СНАРУЖИ
# контейнера, по опубликованному порту: изнутри опубликованный порт не проверить, а
# HEALTHCHECK образа как раз изнутри и стучится — он про процесс, а не про публикацию.
#
# Чем стучимся — тем, что есть на машине. Стук не часть подъёма (миру нужен только докер),
# поэтому отсутствие curl и wget здесь не отказ, а пропуск с честной строкой.
knock() {
    if command -v curl >/dev/null 2>&1; then
        curl -fsS -m 2 -o /dev/null "$1"
    elif command -v wget >/dev/null 2>&1; then
        wget -q -T 2 -O /dev/null "$1"
    else
        return 2   # нечем
    fi
}

step "жду, пока дверь ответит на http://$HOST:$PORT/healthz"
for try in {1..30}; do
    knock "http://$HOST:$PORT/healthz" && answer=yes || answer=$?
    if [ "$answer" = yes ]; then
        ok "дверь отвечает на http://$HOST:$PORT/healthz"
        break
    fi
    if [ "$answer" = 2 ]; then
        printf '  · ни curl, ни wget на машине нет — проверить дверь снаружи нечем\n' >&2
        printf '    состояние процесса покажет сам докер: docker ps --filter name=world-door\n' >&2
        break
    fi
    if [ "$try" = 30 ]; then
        # Отказ обязан назвать не только «не ответила», но и ГДЕ стучались и куда машина
        # опубликовала порт. Иначе живая дверь выглядит мёртвой, и чинить идут не то:
        # ровно этим отказ и провалился в `tasker:WORLD-97`. Факты собираем у докера, а
        # не предполагаем: состояние контейнера и его публикация — то, что есть на самом
        # деле (`kb:WORLD-31`).
        state="$(docker ps -a --filter 'name=^world-door$' --format '{{.Status}}' 2>/dev/null | head -n1 || true)"
        published="$(docker port world-door 2>/dev/null | tr '\n' ' ' || true)"
        printf '\n--- последние строки журнала двери ---\n' >&2
        "${COMPOSE[@]}" logs --tail=40 >&2 || true
        fail \
            "дверь не ответила за 30 секунд по адресу http://$HOST:$PORT/healthz" \
            "контейнер world-door: ${state:-не найден}; порт опубликован так: ${published:-публикации не видно}" \
            "порт выше опубликован, а по адресу проверки тишина — значит стучимся не туда: задай адрес машины, WORLD_HOST=<адрес> $0 (умолчание 127.0.0.1)" \
            "частый случай — докер живёт в WSL, а команду даёт Windows: порт публикуется внутри WSL, и хост-петля до него не доходит. Проверь снаружи: curl http://<адрес машины>:$PORT/healthz" \
            "журнал выше — если дверь падает, мир называет причину сам, первой же строкой" \
            "весь журнал: docker compose -f deploy/compose.yaml logs -f"
    fi
    sleep 1
done

# ------------------------------------------------------------------ куда смотреть
cat >&2 <<GOTOVO

$(printf '\033[1;32m✓ мир поднят\033[0m')

  человеку СНАРУЖИ машины — хост-порт (адрес крутится WORLD_HOST, умолчание 127.0.0.1):
    вход в поле   http://$HOST:$PORT/            пульт: кто сейчас в поле
    проба жизни   http://$HOST:$PORT/healthz
    кто в поле    http://$HOST:$PORT/api/locations

  СОСЕДУ по полю — имя в сети $NET (хост-публикация ему не нужна):
    адрес двери   $ALIAS:8080
    войти в поле  POST http://$ALIAS:8080/api/locations {"name":…,"addr":…,"gives":…}
    как именно    deploy/README.md, раздел «Как сосед входит в поле»

  дверь СТОИТ: политика перезапуска unless-stopped — вернётся после падения и после
  старта демона докера. Чего для «всегда» не хватает — сказано в deploy/README.md.

  состояние поля живёт на томе world-field и переживает пересоздание контейнера
  журнал        docker compose -f deploy/compose.yaml logs -f
  снять         docker compose -f deploy/compose.yaml down          (поле остаётся)
  снять с полем docker compose -f deploy/compose.yaml down -v       (поле стирается)

  проверить подъём целиком: ./deploy/probe.sh   (ВНИМАНИЕ: проба ломает живой мир — см. её -h)
GOTOVO

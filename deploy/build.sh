#!/usr/bin/env bash
# Сборка образов — ТРИ ШАГА, и они разные по природе.
#
#   ./deploy/build.sh              шаг 2 — образ МИРА (сети не нужно вовсе)
#   ./deploy/build.sh --control    шаги 1 и 3 — образ КОНТРОЛЛЕРА
#
#   шаг 1  собрать пульт             обычный контейнер с обычной сетью НАРУЖУ
#   шаг 2  сложить образ мира        `docker build` БЕЗ СЕТИ вообще
#   шаг 3  сложить образ контроллера `docker build` с обычной сетью наружу
#
# ПОЛЯ СБОРКЕ НЕ НУЖНО НИ НА ОДНОМ ШАГЕ, и это первое, что надо знать про этот файл. Сеть
# `omnifield-gateway` здесь не создаётся, не спрашивается и не подаётся в контейнер вовсе.
# Раньше поле требовал шаг 1: пакеты пульта лежали на складе локации `probe-web`, видном
# только соседям по полю. Панель отвязана от продуктов этого мира (`WORLD2-127`) — она
# ставится из обычного реестра, — и требование ушло ВМЕСТЕ С ПРИЧИНОЙ, а не осталось
# ключом «на всякий случай». Вход в мир не зависит от инструментов мира (`WORLD2` 3.7):
# зависимость сборки пульта от локации, которую надо было сперва поднять В МИРУ, — это
# ровно тот круг, которого канон не допускает.
#
# ПУЛЬТ НУЖЕН ОДНОМУ ОБРАЗУ ИЗ ДВУХ. Лицо для человека живёт при КОНТРОЛЛЕРЕ (`WORLD2` 3.7):
# дверь — вход и выход, она ничего не показывает, и собранный пульт в её образ не едет ни
# слоем, ни каталогом, ни переменной. Значит шаг 1 обслуживает только контроллер.
#
# ЧЕМ ШАГ 2 ОТЛИЧАЕТСЯ ОТ ОСТАЛЬНЫХ — сетью, и это не мелочь. Образ мира не тянет ничего
# (`network: none` в его файле запуска, и это доказательство, а не аскеза): он компилирует
# Go без зависимостей и складывает бинарь. Шагам 1 и 3 обычный ВЫХОД НАРУЖУ нужен: первый
# ставит зависимости пульта из реестра, второй кладёт в образ контроллера докер-клиент,
# compose и ssh (`control/Dockerfile`), без которых руки юзера не работают.
#
# Почему шаг 1 не занесён внутрь `docker build`. Не потому, что «иначе не выйдет»: с тех
# пор как склад из уравнения ушёл, технически он туда занесётся. Раскладка та же по СВОЕЙ
# причине — **стройка снаружи образа, образ только складывает готовое** (`kb:WORLD-54`).
# Собранный пульт нужен образу КОНТРОЛЛЕРА, а не миру, и собирается он ровно один раз, чем
# бы его потом ни складывали. Заодно `docker build` остаётся проверяемо офлайновым:
# `network: none` в файле запуска мира — не украшение, а доказательство, что на втором
# шаге не тянется ничего.
#
# (Историческая заметка, чтобы её не переоткрывали: `build.network: omnifield-gateway`
# не работал в принципе — buildkit произвольную сеть в сборке не поддерживает, сети умеет
# только контейнерный драйвер, созданный заранее. Проверено живым прогоном,
# `tasker:WORLD-37`. Теперь это неважно: произвольной сети сборке не нужно.)
#
# Что куда ложится:
#
#   web/                      исходник пульта — читается, НЕ правится (чужая зона)
#   deploy/.build/web-dist/   собранный пульт — сюда пишет шаг 1, отсюда читает шаг 3
#
# Собранное кладётся в СВОЮ зону, а не в `web/dist`: зона `web` — чужая, и затирать в ней
# рабочую сборку разработчика сборка мира не вправе.
#
# ШАГ 1 НЕ МОНТИРУЕТ НИЧЕГО: исходник подаётся в контейнер ПОТОКОМ, собранное забирается
# потоком обратно. Причина — Windows: единственный настоящий докер у нас на нём, значит там
# сборка и проверяется, а Git Bash (MSYS) переписывает аргументы, похожие на пути. В
# `-v "$ROOT/web:/src/web:ro"` он переписывал контейнерную часть, монтирование уезжало не
# туда, и сборка падала на `cp: can't stat '/src/web/.'` (живой прогон, `tasker:WORLD-37`).
# Перевод можно заглушить, но это чинит ВЫЗОВ, а не класс: следующий `-v` напишут снова.
# Потоком переводить нечего — путей хоста в аргументах не остаётся вовсе.
#
# Имена переменных латинские: bash не поддерживает не-ASCII в именах переменных и молча
# превращает `ПОРТ=8080` в «команда не найдена». Тексты и комментарии — русские.
set -euo pipefail

NODE_IMAGE=node:24-alpine
PNPM_VERSION=11.17.0
STORE_VOLUME=world-pnpm-store

HERE="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd -- "$HERE/.." && pwd)"
OUT="$HERE/.build/web-dist"
COMPOSE=("docker" "compose" "-f" "$HERE/compose.yaml")
# Образ контроллера складывается ЕГО ЖЕ файлом запуска, а не нашей копией правил. Так у
# раскладки контроллера (контекст сборки, путь к Dockerfile, имя образа) остаётся ровно
# один источник — зона `control`; держи мы здесь второй, они разъехались бы, и сборка
# из этой зоны начала бы делать не тот образ, который потом поднимают.
CONTROL_COMPOSE=("docker" "compose" "-f" "$ROOT/control/compose.yaml")

usage() {
    cat <<'USAGE'
Сборка образов: ./deploy/build.sh [--only-web|--control|--only-control]

  (без ключей)     образ МИРА: шаг 2, без сети вовсе. Пульт ему не нужен —
                   дверь ничего не показывает, лицо живёт при контроллере
  --only-web       только шаг 1 — собрать пульт в deploy/.build/web-dist
  --control        образ КОНТРОЛЛЕРА: шаг 1, потом шаг 3. Образ мира не трогается
  --only-control   только шаг 3 — сложить образ контроллера из готового пульта
  -h, --help       эта подсказка

ПОЛЯ СБОРКЕ НЕ НУЖНО НИ НА ОДНОМ ШАГЕ. Сеть omnifield-gateway здесь не создаётся и не
спрашивается: панель ставится из обычного реестра и ни одного продукта этого мира не
знает (WORLD2-127). Собирать можно на машине, где поля нет и никогда не было.

Шаг 1 сеть НАРУЖУ имеет — он ставит зависимости пульта из реестра.
Шаг 2 сети не имеет вовсе — он компилирует Go без зависимостей и складывает бинарь.
Шаг 3 сеть НАРУЖУ имеет — в образ контроллера ставятся докер-клиент, compose и ssh.

Пульт едет ТОЛЬКО в образ контроллера. В образе мира его нет — ни слоя, ни каталога.

Шаг 1 НИЧЕГО НЕ МОНТИРУЕТ: исходник едет в контейнер потоком, собранное — потоком
обратно. Так сборка работает и в Git Bash на Windows, где пути в аргументах докера
переписываются в виндовые и монтирование уезжает не туда.

ПОДЪЁМУ сеть не нужна вовсе: ./deploy/up.sh и ./control/up.sh поднимают готовые образы
и ничего не собирают. Поле нужно там ДРУГОМУ — чтобы дверь и локации видели друг друга
по именам; к сборке эта надобность отношения не имеет.
USAGE
}

# Шаг 1 по умолчанию ВЫКЛЮЧЕН: умолчание собирает образ мира, а ему пульт не нужен.
# Оставь мы его включённым — сборка двери молча требовала бы сети и ноды ради артефакта,
# который в её образ не едет, и падала бы там, где ей нечего было делать.
do_web=
do_image=1
do_control=
while [ $# -gt 0 ]; do
    case "$1" in
        --only-web)     do_web=1; do_image=; do_control= ;;
        # Умолчание НЕ трогаем: `./deploy/build.sh` как собирал образ мира, так и собирает.
        # Добавь мы контроллер в умолчание — сборка мира стала бы молча требовать выхода
        # наружу, которого шагу 2 не нужно, и ломалась бы там, где раньше работала.
        --control)      do_web=1; do_image=; do_control=1 ;;
        --only-control) do_web=;  do_image=; do_control=1 ;;
        -h|--help)      usage; exit 0 ;;
        *) usage >&2; printf '\nнепонятный ключ: %s\n' "$1" >&2; exit 2 ;;
    esac
    shift
done

step() { printf '\n\033[1m→ %s\033[0m\n' "$*" >&2; }
ok()   { printf '  ✓ %s\n' "$*" >&2; }
warn() { printf '  \033[33m!\033[0m %s\n' "$*" >&2; }

fail() {
    local why="$1"; shift
    printf '\n\033[1;31m✗ не собралось: %s\033[0m\n' "$why" >&2
    local line
    for line in "$@"; do printf '  выход: %s\n' "$line" >&2; done
    exit 1
}

# docker_noconv … — вызов докера, в аргументах которого НЕТ НИ ОДНОГО пути хоста.
#
# Git Bash (MSYS) переписывает похожие на пути аргументы в виндовые, и КОНТЕЙНЕРНЫЕ пути
# от этого страдают: `target=/pnpm-store` превратился бы в `C:/Program Files/Git/pnpm-store`.
# Здесь переписывать нечего — значит перевод глушим. ЛОКАЛЬНО, для одной команды.
#
# Глобально глушить нельзя, и это главное: `docker compose -f "$HERE/compose.yaml"` подаёт
# путь ХОСТА, и вот его перевести как раз обязаны — иначе виндовый докер не найдёт файла.
# Поэтому правило зоны звучит так: путь хоста в аргументе — обычный `docker`; путей хоста
# нет вовсе — `docker_noconv`. Тот же помощник живёт в `probe.sh` (правило зоны, не файла).
docker_noconv() { MSYS_NO_PATHCONV=1 MSYS2_ARG_CONV_EXCL='*' docker "$@"; }

command -v docker >/dev/null 2>&1 || fail "докера на машине нет" \
    "поставь Docker Engine: https://docs.docker.com/engine/install/"
docker info >/dev/null 2>&1 || fail "докер есть, а демон не отвечает" \
    "запусти его: systemctl start docker (либо открой Docker Desktop)"
command -v tar >/dev/null 2>&1 || fail \
    "на машине нет tar, а исходник пульта подаётся в контейнер потоком" \
    "в Git Bash tar есть из коробки; в локации — apk add tar (alpine) либо apt-get install tar"

# ============================================================== ШАГ 1 — собрать пульт
if [ -n "$do_web" ]; then
    # ---------- ни сети поля, ни пробы склада ----------
    # Здесь стояли два блока: создание сети `omnifield-gateway` и стук в склад локации
    # `probe-web` перед сборкой. Оба существовали ради ОДНОГО — пакетов пульта, которые
    # лежали на складе и наружу не торчали. Панель отвязана от продуктов мира
    # (`WORLD2-127`), пакеты приезжают из обычного реестра — и проверять стало нечего.
    #
    # Снято ЦЕЛИКОМ, а не спрятано за ключ. Проверка снятого требования зеленела бы на
    # пустоте и читалась бы как проверенное свойство (`WORLD2` 4.2), а ключ «а вдруг
    # понадобится» — это то же требование, только необязательное к исполнению и потому
    # никем не проверяемое.
    #
    # Сеть у шага всё равно есть — ОБЫЧНАЯ, наружу: `pnpm install` тянет зависимости из
    # реестра. Ей не нужно ни создавать сеть, ни знать про соседей: сборщик запускается
    # обычным `docker run`, и умолчания докера хватает.

    # ---------- сама сборка пульта ----------
    # Ни одного монтирования, кроме именованного тома под стор pnpm (без него каждая сборка
    # качала бы половину npm заново). Исходник уезжает потоком на stdin, собранное приезжает
    # потоком со stdout — см. шапку. Зона `web` при этом не трогается вообще: ни
    # `node_modules`, ни `dist` в ней от сборки мира не появляется, и даже смонтирована она
    # не бывает.
    #
    # `chown` по `id -u`/`id -g` исчез вместе с монтированием, и это не потеря, а починка:
    # на Windows у `id` свои числа, к контейнеру отношения не имеющие, — там он сработал бы
    # вхолостую либо испортил права. Теперь на диск хоста пишет не контейнер, а хостовый
    # `tar` от имени того, кто запустил сборку. Владелец получается правильный по построению.
    #
    # ВЕСЬ вывод сборщика уходит в stderr (`1>&2`), потому что stdout занят: по нему едет
    # tar. Одна забытая строка в stdout — и поток собранного окажется битым.
    step "шаг 1 — собираю пульт в контейнере (обычная сеть наружу, поля не нужно)"
    mkdir -p "$HERE/.build"
    stream="$HERE/.build/web-dist.tar.part"

    set +e
    tar -C "$ROOT/web" --exclude=./node_modules --exclude=./dist -cf - . \
        | docker_noconv run --rm -i \
            --mount "source=$STORE_VOLUME,target=/pnpm-store" \
            "$NODE_IMAGE" sh -euc '
                mkdir -p /work && cd /work
                tar -xf -
                rm -rf node_modules dist
                npm install -g pnpm@'"$PNPM_VERSION"' 1>&2
                pnpm install --frozen-lockfile --store-dir /pnpm-store </dev/null 1>&2
                pnpm build </dev/null 1>&2
                [ -s dist/index.html ] || {
                    echo "pnpm build отработал, а dist/index.html не появился" >&2
                    exit 3
                }
                tar -C dist -cf - .
            ' > "$stream"
    stages=("${PIPESTATUS[@]}")
    set -e

    # Разбираем ПО ПОРЯДКУ: сначала сборщик, потом подача. Порядок не косметический —
    # когда сборщик падает, он закрывает поток, и хостовый `tar` получает SIGPIPE (код 141).
    # Спроси мы сначала про `tar`, отказ назвал бы «исходник не прочитался», то есть НЕ ТУ
    # сторону: сломан сборщик, а виноватой выглядела бы зона web.
    [ "${stages[1]}" = 0 ] || { rm -f "$stream"; fail \
        "пульт не собрался (код ${stages[1]})" \
        "полный вывод сборщика — выше, причина названа там" \
        "чаще всего это выход наружу (pnpm не достучался до реестра) либо локфайл разъехался с package.json" \
        "повторить только этот шаг: ./deploy/build.sh --only-web"; }

    case "${stages[0]}" in
        0)   ;;
        141) rm -f "$stream"; fail \
                "сборщик закрыл поток раньше, чем исходник дочитался (tar убит SIGPIPE)" \
                "сборщик при этом отчитался успехом — значит он не дочитал stdin до конца" \
                "полный вывод шага 1 — выше" ;;
        *)   rm -f "$stream"; fail \
                "исходник пульта не прочитался: tar над $ROOT/web вышел с кодом ${stages[0]}" \
                "проверь, что зона web на месте и читается: ls $ROOT/web" ;;
    esac

    # Поток мог прийти пустым или без витрины — а код возврата при этом нулевой. Смотрим в
    # то, что реально приехало, ДО того как снести прежнюю сборку.
    [ -s "$stream" ] || { rm -f "$stream"; fail \
        "сборщик отработал без ошибки, а собранного не прислал — поток пуст" \
        "чаще всего это лишняя строка в stdout контейнера: по нему едет tar, и он ломается" \
        "повторить: ./deploy/build.sh --only-web"; }

    # Опись читаем В ПЕРЕМЕННУЮ, а не через конвейер: `grep -q` закрывает трубу на первом
    # совпадении, `tar` получает SIGPIPE, и при `pipefail` успешная проверка выглядела бы
    # провалом — тем чаще, чем больше файлов в сборке. Такое ловится не всегда и не сразу.
    listing="$(tar -tf "$stream" 2>/dev/null)"
    grep -qE '(^|/)index\.html$' <<<"$listing" || { rm -f "$stream"; fail \
        "в присланном потоке нет index.html — собралось не то" \
        "посмотри вывод шага 1 выше: pnpm build мог отработать вхолостую" \
        "повторить: ./deploy/build.sh --only-web"; }

    # Прежняя сборка сносится ТОЛЬКО ЗДЕСЬ — когда новая уже на руках и проверена. Иначе
    # неудачная сборка оставляла бы зону без пульта, и подъём терял бы то, что работало.
    rm -rf "$OUT"
    mkdir -p "$OUT"
    tar -C "$OUT" -xf "$stream" || { rm -f "$stream"; fail \
        "собранное не разложилось из потока в $OUT" \
        "проверь права на каталог: ls -la $HERE/.build"; }
    rm -f "$stream"

    ok "пульт собран в ${OUT#"$ROOT"/}"
fi

# ============================================================== ШАГ 2 — сложить образ
if [ -n "$do_image" ]; then
    # Сети у этого шага нет вовсе (`network: none` в файле запуска). Он ничего не тянет —
    # только компилирует Go, у которого зависимостей нет, и складывает бинарь.
    #
    # Проверки «а собран ли пульт» здесь БОЛЬШЕ НЕТ, и это не упрощение, а причина: пульт
    # в образ двери не едет (`deploy/Dockerfile`). Оставленная проверка требовала бы ноды
    # и сети ради артефакта, который никуда не кладётся, — то есть стерегла бы пустоту.
    step "шаг 2 — складываю образ мира (без сети вовсе)"

    "${COMPOSE[@]}" build || fail \
        "образ не сложился" \
        "полный вывод — выше, причина названа там" \
        "начисто: docker compose -f deploy/compose.yaml build --no-cache"
    ok "образ сложен"
fi

# ============================================================== ШАГ 3 — образ контроллера
# Лицо для человека живёт ПРИ КОНТРОЛЛЕРЕ (`WORLD2` 3.7): пульт раздаёт он, а не дверь.
# Значит собранный пульт обязан оказаться в его образе — и кладёт его туда ТА ЖЕ сборка,
# что и собрала, а не человек руками (`TECH` 2: он делает одно движение, а не три).
#
# Забирает пульт из контекста сам образ контроллера (`control/Dockerfile`:
# `COPY deploy/.build/web-dist/ /opt/world/pult/`). Наша здесь ровно одна вещь — ПОРЯДОК:
# пульт собран, проверен и лежит на месте ДО того, как начнётся его сборка. Собирается он
# снаружи образа, потому что стройка живёт снаружи (`kb:WORLD-54`), а не потому, что
# «иначе не выйдет»: с уходом склада это ограничение отпало вместе с ним.
if [ -n "$do_control" ]; then
    step "шаг 3 — складываю образ контроллера (нужен обычный выход наружу)"

    [ -f "$ROOT/control/compose.yaml" ] || fail \
        "файла запуска контроллера нет: $ROOT/control/compose.yaml" \
        "зона control не на месте — проверь, что репозиторий полон: ls $ROOT/control" \
        "раскладку контроллера держит его зона; здесь её копии нет намеренно"

    # Пульта нет — образ контроллера его только складывает, а не изготавливает. Ловим
    # ЗДЕСЬ, а не внутри `docker build`: там отказ придёт от `RUN test -s` чужой зоны и
    # будет говорить про каталог, которого человек не называл. Своя причина ближе к тому,
    # что он сделал. Это единственное место сборки, где готовый пульт обязателен.
    [ -s "$OUT/index.html" ] || fail \
        "собранного пульта в $OUT нет, а образ контроллера его только складывает" \
        "собери пульт: ./deploy/build.sh --only-web" \
        "либо оба шага сразу: ./deploy/build.sh --control" \
        "пульт нужен ТОЛЬКО этому образу: в образ мира он не едет вовсе"

    "${CONTROL_COMPOSE[@]}" build || fail \
        "образ контроллера не сложился" \
        "полный вывод — выше, причина названа там" \
        "в отличие от образа мира этому шагу нужен ВЫХОД НАРУЖУ: внутрь ставятся docker-cli, compose и ssh" \
        "начисто: docker compose -f control/compose.yaml build --no-cache"
    ok "образ контроллера сложен — пульт внутри, в /opt/world/pult"
fi


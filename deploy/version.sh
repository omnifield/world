#!/usr/bin/env bash
# ВЕРСИЯ ОБРАЗА — единственное место в зоне, где она выводится из гита.
#
#   ./deploy/version.sh --door             напечатать версию образа двери: sha-<7 знаков>
#   ./deploy/version.sh --share            то же для раздачи
#   ./deploy/version.sh --control          то же для контроллера
#   ./deploy/version.sh --control --plan   ту же версию на ГРЯЗНОМ перечне — ТОЛЬКО ЧТОБЫ ПОКАЗАТЬ
#   ./deploy/version.sh --pult             версия ИСХОДНИКА ПУЛЬТА — ею сборка подписывает
#                                          собранный пульт (`WORLD2-115`), а не образ
#
# ВЕРСИЯ ПРИНАДЛЕЖИТ ОБРАЗУ, А НЕ РЕПОЗИТОРИЮ, и это главное, что изменилось (`WORLD2-146`).
# Раньше здесь брался `HEAD` — один `sha` на всю тройку, — и тег отвечал на вопрос «когда
# собрано». Отвечать он обязан на другой: «ИЗ ЧЕГО собрано». Пока образы уезжали пачкой,
# разницы не было видно; публикация стала раздельной, и разница стала ценой: тег двери
# сдвигался от правки в `share/`, то есть по нему нельзя было понять, менялась дверь или нет.
#
# Поэтому `sha` берётся у ПОСЛЕДНЕГО КОММИТА, ТРОНУВШЕГО ТО, ЧТО В ЭТОТ ОБРАЗ ЕДЕТ. Перечень
# путей объявлен в `deploy/sostav.sh` — там же довод, почему «папка с именем зоны» не годится
# (в образ контроллера едет пульт из `web/`, и по `control/` его сдвиг не виден вовсе).
#
# ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ, а не две строки в двух скриптах. Версия попадает в ДВА места:
#
#   · в ТЕГ, которым выпуск метит образ в реестре (`release.sh`);
#   · в ШТАМП, который сборка вписывает ВНУТРЬ образа (`build.sh`), — им образ называет себя
#     сам, и выпуск сверяет штамп с тегом до первого `push` (`WORLD2-130`).
#
# Считай их два разных куска кода — они разъедутся. Образ будет утверждать одно, а тег
# означать другое, и снаружи это НЕ ОТЛИЧИТЬ: тег `sha-abc1234` и штамп `sha-9999999` оба
# выглядят правдой. Цена ошибки — необратимая публикация. Поэтому вычисление ОДНО, и оно
# здесь; перечень, по которому оно идёт, — тоже один, и он в `sostav.sh`.
#
# ПОЧЕМУ МОЛЧАНИЕ, А НЕ `unknown`. Версии может не быть: собирают и из распакованного архива,
# и в репозитории без коммитов, и посреди работы на грязном дереве. Соблазн написать в такой
# образ `unknown` (или пустую строку) велик — и это худший из исходов: приблизительная запись
# не отличима от измеренной, а `:unknown` потом уедет в тег и в отказ «образа нет». Не
# измерил — не записывай (`WORLD2` 4.2 п. 5). Поэтому здесь ЛИБО настоящая версия, ЛИБО
# ничего на stdout и названная причина — а звать читателя выдумывать своё умолчание нельзя.
#
# ГРЯЗНОЕ — ЭТО ТОЖЕ «ВЕРСИИ НЕТ», и вот почему, хотя коммит на месте. `sha-abc1234` это
# утверждение «собрано из abc1234». Собрано же — из дерева с правками, которых в abc1234
# нет; в реестре такого тега не будет вовсе. То есть честной версии не существует, и
# придумывать её не наше дело.
#
# ЧИСТОТУ ПРОВЕРЯЕМ ПО ПЕРЕЧНЮ ОБРАЗА, А НЕ ПО ВСЕМУ РЕПОЗИТОРИЮ — и это не послабление, а
# та же честность с другой стороны. Тег утверждает про СВОЙ образ; правка в `share/` не
# делает утверждение о двери ложным, значит и мешать выпуску двери она не должна. Мешать
# обязана ровно та правка, из-за которой соврал бы ЭТОТ тег.
#
# ЧТО ЗДЕСЬ НЕ ЖИВЁТ: имена образов, теги с реестром, докер и сам ПЕРЕЧЕНЬ. Здесь только один
# вопрос — «из какого коммита собран этот образ»; куда ответ потом впишут, решают те, кто
# спрашивает, а что в образ едет — объявляет `sostav.sh`.
#
# Имена переменных латинские: bash не поддерживает не-ASCII в именах переменных и молча
# превращает `ВЕРСИЯ=1` в «команда не найдена». Тексты и комментарии — русские.
set -uo pipefail

# Свой каталог выводим СРЕЗОМ, а не `dirname`: этот файл обязан уметь ответить «гита нет»
# даже там, где в `PATH` нет вообще ничего, — иначе он сломался бы раньше, чем дошёл до
# ответа, и вместо названной причины человек получил бы ошибку оболочки. Из внешних команд
# здесь остаётся ровно одна — сам `git`.
HERE="${BASH_SOURCE[0]%/*}"
[ "$HERE" = "${BASH_SOURCE[0]}" ] && HERE=.
HERE="$(cd -- "$HERE" && pwd)"
ROOT="$(cd -- "$HERE/.." && pwd)"

# Перечень ПОДКЛЮЧАЕМ, а не запускаем отдельной командой: запуск потребовал бы `env` из
# `PATH`, а этот файл обязан доходить до ответа `no-git` и с пустым `PATH` (сценарий 32c).
# Подключённый `sostav.sh` только объявляет и не печатает ничего — так он и написан.
. "$HERE/sostav.sh"

usage() {
    cat <<'USAGE'
Версия образа: ./deploy/version.sh <образ> [--plan] | --pult

  --door         версия образа ДВЕРИ
  --share        версия образа РАЗДАЧИ
  --control      версия образа КОНТРОЛЛЕРА
  --pult         версия ИСХОДНИКА ПУЛЬТА — того пути, из которого его собирают
                 (объявлен в deploy/sostav.sh). Не версия образа: ею не метят и не
                 штампуют. Ею сборка подписывает собранный пульт и потом узнаёт,
                 из этого ли дерева он собран (WORLD2-115)
  --plan         та же версия, даже если перечень образа ГРЯЗЕН. Нужна одному:
                 показать человеку план («поехало бы вот это»). Метить и штамповать
                 ею нельзя — она описывает НЕ то, что лежит в дереве
  -h, --help     эта подсказка

Версия принадлежит ОБРАЗУ: sha берётся у последнего коммита, тронувшего то, что в
этот образ едет. Перечень путей объявлен в deploy/sostav.sh — там же довод, почему
«папка с именем зоны» не годится. Посмотреть перечень: ./deploy/sostav.sh <образ>

Выход:
  stdout   sha-<7>   и ничего больше — это значение подставляют в тег и в штамп
  stderr   VERSION-STATE: <код>   для машины, следом причина словами для человека
  код      0 — версия есть · 1 — версии нет · 2 — непонятный ключ

Коды состояния (стережёт их проба, а не формулировки):
  no-image         образ не назван либо зона такого не знает
  no-git           гита нет на машине, а версия выводится из коммита
  not-a-repo       это не репозиторий — брать версию неоткуда
  no-commit        репозиторий есть, коммитов нет
  not-in-history   коммиты есть, но перечня этого образа не касался ни один
  dirty            перечень образа не чист: честной версии не существует
  no-path          в перечне назван путь, которого в дереве нет
  no-pult          исходник пульта не назван в перечне образа контроллера
USAGE
}

obraz=
plan=
pult=
while [ $# -gt 0 ]; do
    case "$1" in
        --door|--share|--control) obraz="${1#--}" ;;
        --pult)    pult=1 ;;
        --plan)    plan=1 ;;
        -h|--help) usage; exit 0 ;;
        *)         usage >&2; printf '\nнепонятный ключ: %s\n' "$1" >&2; exit 2 ;;
    esac
    shift
done

# net КОД ПРИЧИНА — версии нет. Код для машины, причина словами для человека: тот, кто
# спрашивал, передаёт её дословно, а не пересказывает (`WORLD2` 2.3).
net() {
    printf 'VERSION-STATE: %s\n' "$1" >&2
    printf '%s\n' "$2" >&2
    exit 1
}

# ПУЛЬТ — ОТДЕЛЬНЫЙ ВОПРОС, И ОН НЕ ПРО ОБРАЗ. Спрашивают его затем, чтобы подписать
# СОБРАННЫЙ пульт и потом узнать, из этого ли дерева он собран (`WORLD2-115`): «в каталоге
# что-то лежит» и «в каталоге пульт этого дерева» — разные утверждения, и второе без такой
# подписи не проверить ничем.
#
# Считается он ЗДЕСЬ, а не в сборке, по правилу зоны: счёт из гита живёт в одном файле.
# Заведи его сборка у себя — в зоне стало бы два счёта, и они разъехались бы молча (это
# правило стережёт проба, часть 32, и оно же поймало первую редакцию этой правки).
#
# Ключ спрашивается ВМЕСТЕ с проверкой перечня контроллера: пульт обязан быть в нём назван,
# иначе он приедет в образ, а в версию не войдёт — ровно то, ради чего перечень и заведён.
if [ -n "$pult" ]; then
    [ -z "$obraz" ] || net no-image \
        "--pult спрашивают отдельно: это версия исходника пульта, а не образа — назови что-то одно"
    sostav_proverit control || net "$SOSTAV_STATE" "$SOSTAV_SLOVAMI"
    puti=("$(sostav_pult)")
else

# ОБРАЗ НАЗЫВАЮТ ЯВНО, умолчания нет и не будет. Умолчание здесь означало бы «версия
# репозитория» — ровно то понятие, которого больше не существует: у каждого образа она своя.
[ -n "$obraz" ] || net no-image \
    "образ не назван, а версия принадлежит образу: ./deploy/version.sh --door|--share|--control"

# Перечень сверяется с деревом ДО того, как по нему считают: перечень, разошедшийся с
# деревом, врёт молча, и версия, выведенная по остатку, выглядела бы правдой.
sostav_proverit "$obraz" || net "$SOSTAV_STATE" "$SOSTAV_SLOVAMI"

puti=()
while IFS= read -r p; do [ -n "$p" ] && puti+=("$p"); done < <(sostav_puti "$obraz")

fi

# ЧЕЙ СЧЁТ ИДЁТ — называется ОДНИМ значением и подставляется во все причины ниже. Иначе
# отказы говорили бы «перечня образа «»» там, где спросили исходник пульта: причина, которая
# называет пустоту, отправляет чинить не туда (`WORLD2` 2.3).
if [ -n "$pult" ]; then
    predmet="исходник пульта ($(sostav_pult))"
else
    predmet="перечень образа «$(sostav_zovem "$obraz")»"
fi

command -v git >/dev/null 2>&1 || net no-git \
    "гита на машине нет, а версия образа выводится из коммита"

git -C "$ROOT" rev-parse --git-dir >/dev/null 2>&1 || net not-a-repo \
    "это не репозиторий: в $ROOT нет гита, а версия образа выводится из коммита"

# Два разных «коммита нет», и путать их нельзя: в пустом репозитории версии нет ни у одного
# образа, а «перечня не касался ни один коммит» — это про ЭТОТ образ и чинится иначе.
# Спрашиваем ЗНАЧЕНИЕ, а не код возврата: гит на пустом репозитории отвечает по-разному в
# разных сборках, а пустой ответ означает одно и то же везде.
est_kommity="$(git -C "$ROOT" rev-parse --short=7 HEAD 2>/dev/null || true)"
[ -n "$est_kommity" ] || net no-commit \
    "в репозитории нет ни одного коммита — версии образа ещё не существует"

# `%h` с явным `--abbrev=7`: длину задаём мы, а не настройка `core.abbrev` в чужом
# репозитории, — иначе форма тега зависела бы от того, у кого выпускают.
sha="$(git -C "$ROOT" log -1 --format=%h --abbrev=7 -- "${puti[@]}" 2>/dev/null || true)"
[ -n "$sha" ] || net not-in-history \
    "$predmet не касался ни один коммит — версии у него ещё нет"

# Форма штампа и тега ОДНА, и собирается она здесь: `sha-` + семь знаков. Кто спрашивает,
# получает готовое значение и не складывает его сам — сложил бы по-своему хоть один из двоих,
# и тег со штампом разошлись бы на префиксе.
versiya="sha-$sha"

# `--plan` отвечает ДО проверки чистоты: он про то, «какой коммит стоит за перечнем», а не
# про то, «есть ли честная версия». Разница названа в подсказке, и спрашивают его ровно там,
# где рядом печатают, что перечень грязен.
[ -z "$plan" ] || { printf '%s\n' "$versiya"; exit 0; }

# Чистота — ТОЛЬКО по перечню образа. Довод целиком в шапке: тег утверждает про свой образ,
# и мешать ему обязана ровно та правка, из-за которой он соврал бы.
[ -z "$(git -C "$ROOT" status --porcelain -- "${puti[@]}" 2>/dev/null || true)" ] || net dirty \
    "$predmet не чист — $versiya описывает НЕ то, что лежит в дереве"

printf '%s\n' "$versiya"

# Конфиг локации: чтение, проверка, вычисление проекта. ОБЩАЯ ЧАСТЬ ДВУХ СКРИПТОВ.
#
# Это не самостоятельный скрипт — его подключают `location-up.sh` и `location-down.sh`
# (`. "$HERE/location-config.sh"`). Общая она не ради экономии строк: подъём и снятие
# обязаны найти ОДНУ И ТУ ЖЕ локацию. Разъедься эти два чтения на одну кавычку — снятие
# уводило бы из поля не ту локацию либо не находило бы её вовсе, и выглядело бы это как
# «дверь потеряла запись».
#
# Что должен определить вызывающий ДО подключения: `HERE` (каталог зоны), `CONFIG` (путь к
# конфигу) и печать `warn` / `fail` (у подъёма и снятия слова отказа свои).
#
# Что появляется после подключения:
#   WORLD_NAME · WORLD_GIVES · WORLD_DOOR · WORLD_NET   значения конфига (экспортированы)
#   WORLD_BUILD_ADDR                                    то же, необязательное: где внутри
#                                                       места стоит застройка (пусто — нет)
#   WORLD_SECRETS                                       то же, необязательное: имя тома со
#                                                       связкой ключей юзера (пусто — нет)
#   PROJECT                                             имя компоуз-проекта локации
#   COMPOSE[@]                                          вызов компоуза с этим конфигом
#   CONFIG_KEY                                          « --config ФАЙЛ» для подсказок, если
#                                                       конфиг не умолчальный
#   SERVICE                                             имя службы в файле запуска
#
# Читаем САМИ, а не `source`: конфиг — это данные, а не программа, и выполнять его значило
# бы отдать ему всё, что может bash. Заодно читается то же самое, что прочтёт компоуз:
# «ключ=значение до конца строки», кавычки снимаются, если стоят парой.
#
# Шебанга у файла нет и не будет — его подключают, а не запускают. Оболочку линтеру
# называем директивой: без неё он не знает, чьи правила применять, и молчит обо всём.
# shellcheck shell=bash

SERVICE=world-location   # имя службы в файле запуска; адрес локации — не оно, а имя в поле

[ -f "$CONFIG" ] || fail \
    "конфига локации нет: $CONFIG" \
    "возьми образец: cp deploy/location.env.example deploy/location.env" \
    "в нём заполняются два значения — WORLD_NAME (имя в поле) и WORLD_GIVES (что даёт)" \
    "конфиг лежит в другом месте — назови его: --config ПУТЬ"

env_name="${WORLD_NAME:-}"; env_gives="${WORLD_GIVES:-}"
env_door="${WORLD_DOOR:-}"; env_net="${WORLD_NET:-}"
env_build_addr="${WORLD_BUILD_ADDR:-}"; env_secrets="${WORLD_SECRETS:-}"
WORLD_NAME=; WORLD_GIVES=; WORLD_DOOR=; WORLD_NET=; WORLD_BUILD_ADDR=; WORLD_SECRETS=

lineno=0
while IFS= read -r line || [ -n "$line" ]; do
    lineno=$((lineno + 1))
    line="${line#"${line%%[![:space:]]*}"}"          # пробелы слева
    case "$line" in ''|'#'*) continue ;; esac
    case "$line" in *=*) ;; *)
        warn "строка $lineno не похожа на «КЛЮЧ=значение», пропускаю: $line"; continue ;;
    esac
    key="${line%%=*}"; value="${line#*=}"
    key="${key#"${key%%[![:space:]]*}"}"; key="${key%"${key##*[![:space:]]}"}"
    # Пробелы по краям значения снимаем ДО кавычек — ровно так же, как это делает компоуз:
    # `КЛЮЧ = значение` он читает как `значение`, и разойдись мы с ним здесь, подъём и файл
    # запуска взяли бы из одной строки два разных значения.
    value="${value#"${value%%[![:space:]]*}"}"       # пробелы слева
    value="${value%"${value##*[![:space:]]}"}"       # пробелы справа
    case "$value" in
        '"'*'"') value="${value#\"}"; value="${value%\"}" ;;
        "'"*"'") value="${value#\'}"; value="${value%\'}" ;;
    esac
    case "$key" in
        WORLD_NAME|WORLD_GIVES|WORLD_DOOR|WORLD_NET|WORLD_BUILD_ADDR|WORLD_SECRETS) printf -v "$key" '%s' "$value" ;;
        *) warn "строка $lineno: ключ $key конфигу локации неизвестен, он его не читает" ;;
    esac
done < "$CONFIG"

# Конфиг СИЛЬНЕЕ окружения — и молчать об этом нельзя: человек, экспортировавший переменную,
# должен узнать, что победил файл, здесь, а не по чужому имени в поле.
for pair in "WORLD_NAME:$env_name" "WORLD_GIVES:$env_gives" "WORLD_DOOR:$env_door" "WORLD_NET:$env_net" \
            "WORLD_BUILD_ADDR:$env_build_addr" "WORLD_SECRETS:$env_secrets"; do
    var="${pair%%:*}"; was="${pair#*:}"
    [ -n "$was" ] || continue
    [ "$was" != "${!var}" ] || continue
    warn "переменная среды $var=$was перекрыта конфигом (${!var:-<пусто>}) — читается файл"
done

[ -n "$WORLD_NAME" ] || fail \
    "в конфиге не сказано имя локации (WORLD_NAME пусто): $CONFIG" \
    "имя — это её маршрут за дверью и её же имя в общей сети, вывести его не из чего" \
    "заполни WORLD_NAME в $CONFIG (образец — deploy/location.env.example)"

# Проверяем ровно то, что нужно ДОКЕРУ: имя уезжает в имя проекта, имя контейнера и алиас
# в сети, и с неподходящим именем мы до двери просто не дойдём. Правило имени в ПОЛЕ здесь
# не повторяется — оно живёт в двери, и её отказ `name-invalid` называет его целиком; вторая
# копия правила разъезжается с первой молча.
case "$WORLD_NAME" in
    [a-z0-9]*)
        case "$WORLD_NAME" in *[!a-z0-9-]*)
            fail "имя «$WORLD_NAME» не годится ни в имя контейнера, ни в имя в общей сети" \
                 "докеру годятся строчные латинские буквы, цифры и дефис" \
                 "правило имени в ПОЛЕ держит дверь — но с таким именем мы до неё не дойдём" ;;
        esac ;;
    *)  fail "имя «$WORLD_NAME» не годится ни в имя контейнера, ни в имя в общей сети" \
             "начинаться оно обязано со строчной латинской буквы или цифры" ;;
esac

WORLD_DOOR="${WORLD_DOOR:-door:8080}"
WORLD_NET="${WORLD_NET:-omnifield-gateway}"
# У адреса застройки умолчания НЕТ и быть не может: пустое место законно и остаётся нормой
# (`core/README.md`, канон `WORLD2` 1.0). Пусто здесь значит «не заявлено» — маршрут места
# отвечает присутствием сторожа, как и до появления этой настройки. Подставить сюда что-то
# «разумное» значило бы завести маршрут в вещь, которой человек не поднимал.
# У связки ключей умолчания тоже нет: назвать том за человека значило бы подключить месту
# состояние, которого он не давал. Место без связки законно — оно просто отрезано от его
# гита и складов, и это его выбор, а не отказ (`WORLD2` 3.0).
export WORLD_NAME WORLD_GIVES WORLD_DOOR WORLD_NET WORLD_BUILD_ADDR WORLD_SECRETS

# Имя проекта — по имени локации, и это единственное, что разводит две локации на одной
# машине. Без него компоуз взял бы имя каталога (`deploy`), и вторая локация молча заменила
# бы первую: для компоуза это была бы та же служба того же проекта.
PROJECT="world-loc-$WORLD_NAME"
COMPOSE=("docker" "compose" "-p" "$PROJECT" "--env-file" "$CONFIG" "-f" "$HERE/location-compose.yaml")

# Связка ключей приезжает НАДСТРОЙКОЙ, вторым `-f`, и только когда она названа: монтирование
# в компоузе не бывает условным (довод целиком — в шапке `location-secrets.yaml`). Надстройку
# добавляют ОБА скрипта, потому что вызов компоуза у них общий: разойдись они — снятие
# смотрело бы на другой состав файлов, чем подъём.
[ -z "$WORLD_SECRETS" ] || COMPOSE+=("-f" "$HERE/location-secrets.yaml")

# Конфиг не умолчальный — значит все дальнейшие подсказки обязаны его называть: команда,
# в которой конфиг не назван, поднимет и снимет ДРУГУЮ локацию.
CONFIG_KEY=
[ "$CONFIG" = "$HERE/location.env" ] || CONFIG_KEY=" --config $CONFIG"

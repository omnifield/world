#!/bin/sh
# ТОЧКА ВХОДА ОБРАЗА ДВЕРИ — мир поднимается ОДНОЙ командой на машине, где есть только докер.
#
#   docker run -d --name world-door --restart unless-stopped -p 8080:8080 \
#     -v world-field:/field -v world-stand:/stand ghcr.io/omnifield/world:latest
#
# ЗАЧЕМ ПРОВЕРКИ ПЕРЕЕХАЛИ СЮДА. Раньше их делал `deploy/up.sh` снаружи — но и он, и файл
# запуска лежат в репозитории, а репозитория на машине юзера нет и не будет (роадмап
# «Итерация 1 — поток юзера»: докер и `docker pull`, больше ничего). Значит выбор был не
# «скрипт или образ», а «проверки в образе или проверок нет вовсе»: юзер, у которого дверь
# молча не встала, остался бы с пустым `docker ps` и без единой причины.
#
# У ДВЕРИ НЕТ ДОКЕР-СОКЕТА — И ЭТО ГЛАВНОЕ ОТЛИЧИЕ ЕЁ КОМАНДЫ ОТ КОМАНДЫ ПУЛЬТА. Дверь
# смотрит наружу машины, и власти над машиной у неё не должно быть никогда (`WORLD2` 3.7):
# у входной двери не бывает ключей от всего дома. Отсюда прямое следствие для этого файла —
# ЧЕГО ЗДЕСЬ НЕТ и не появится:
#
#   · создания общей сети. Её создаёт тот, у кого есть сокет: хозяин руками либо контроллер;
#   · проверки занятости ХОСТ-порта. Публикация живёт снаружи контейнера, изнутри её не видно;
#   · подъёма, пересборки и снятия чего-либо рядом.
#
# Что от этого теряется — сказано вслух в выводе, а не спрятано: непроверенное обязано
# называться непроверенным (`WORLD2` 4.2).
#
# ЧЕМ ПОЛЬЗУЕМСЯ ИЗ ОБРАЗА: оболочкой и `wget` — базовым апплетом busybox, на котором стоит
# и HEALTHCHECK. Ничего не ставится и не тянется. Правило зоны: всё, чем пользуемся из
# базового образа, обязано быть БАЗОВЫМ, а не «было там в прошлый раз» — апплет `httpd`,
# уехавший в отдельный пакет, уже ронял нам пробу (`tasker:WORLD-37`).
#
# ЯЗЫК — POSIX sh: в образе `/bin/sh` это busybox ash, башизмов здесь быть не может.
# Имена переменных латинские (оболочка не поддерживает не-ASCII), тексты русские.
#
# ОТКАЗ = КОД В stdout + ПРИЧИНА С ВЫХОДОМ В stderr, ровно как в `deploy/remote.sh`: машине
# код, человеку причина. Отказ всегда заканчивается выходом из процесса — «отказал и
# продолжил» это не отказ, а жалоба.
#
# Прогоняется этот файл БЕЗ докера: `deploy/probe-branching.sh`, раздел 30. Потому он и
# отдельный файл, а не строка `RUN` в Dockerfile: точка входа, которую нельзя ни прочитать,
# ни прогнать, проверяется только живым подъёмом — то есть на юзере.
set -u

# Попросили другую команду (`docker run … sh`, `ls -Ra /app`) — отдаём её и в дверь не
# играем. Так устроены все образы, у которых точка входа не сама программа: аргумент,
# начинающийся с дефиса, это ключ ДВЕРИ, всё остальное — чужая команда.
case "${1:-}" in
    ''|-*) ;;
    *)     exec "$@" ;;
esac

# Бинарь лежит рядом с этим файлом — оба кладёт `deploy/Dockerfile` в `/app`. Спрашиваем
# путь у самих себя (`${0%/*}`), а не пишем `/app/world` второй копией: копия разъедется с
# раскладкой образа молча, и отказ будет говорить про каталог, которого нет.
BIN="${0%/*}/world"
[ "$BIN" = "$0" ] && BIN="./world"

# Контракт переменных — `core/README.md`; здесь мы их только ЧИТАЕМ, чтобы проверять то же
# самое, чем будет пользоваться мир, а не свои представления о нём.
ADDR="${WORLD_ADDR:-:8080}"
PORT="${ADDR##*:}"
FIELD_FILE="${WORLD_DOOR_FILE:-/field/locations.json}"
FIELD_DIR="${FIELD_FILE%/*}"
STAND_DIR="${WORLD_STAND_DIR:-/stand}"
# Каталог из имени файла выводится СРЕЗОМ ДО ПОСЛЕДНЕГО СЛЭША, и если слэша нет вовсе, срез
# возвращает саму строку — то есть «каталог locations.json». Это проверяется ниже отдельным
# значением, а не молча превращается в отказ про несуществующий каталог.
FIELD_HAS_DIR=
case "$FIELD_FILE" in */*) FIELD_HAS_DIR=1 ;; esac
# Контрактное имя двери в общей сети: по нему сосед входит в поле (`door:8080`). Здесь оно
# нужно ровно для одной вещи — постучаться в себя ПО ЭТОМУ ИМЕНИ и узнать, видно ли нас в
# поле. Имя в команде задают `--network-alias`, а нам называют этой переменной.
ALIAS="${WORLD_DOOR_ALIAS:-door}"
# Сколько секунд ждать, пока дверь ответит. Значение, а не зашитое число: на медленной
# машине первый запуск бывает дольше, и человек должен уметь дать времени, а не гадать.
WAIT="${WORLD_WAIT:-30}"

step()   { printf '\n\033[1m→ %s\033[0m\n' "$*" >&2; }
ok()     { printf '  ✓ %s\n' "$*" >&2; }
warn()   { printf '  \033[33m!\033[0m %s\n' "$*" >&2; }
detail() { printf '    %s\n' "$*" >&2; }

# refuse КОД ПРИЧИНА ВЫХОД… — единственный способ выйти с ошибкой. Выход обязателен: отказ
# без следующего действия это диагноз, а не отказ (`kb:WORLD-31`).
refuse() {
    refuse_code="$1"; refuse_why="$2"; shift 2
    printf 'WORLD-REFUSAL: %s\n' "$refuse_code"
    printf '\n\033[1;31m✗ дверь не поднята: %s\033[0m\n' "$refuse_why" >&2
    for refuse_line in "$@"; do printf '  выход: %s\n' "$refuse_line" >&2; done
    exit 1
}

# knock АДРЕС — постучаться. Тем же `wget`, что стоит в HEALTHCHECK: два разных стука в одну
# дверь однажды разошлись бы в мелочи, и «здоров по докеру, мёртв по нам» стало бы вопросом
# без ответа.
knock() { wget -q -T 2 -O /dev/null "$1" 2>/dev/null; }

# chislo ЗНАЧЕНИЕ — целое больше нуля. Пустое и всё, где есть не-цифра, — не число: `[ -lt ]`
# на таком не «вернёт ложь», а СЛОМАЕТСЯ, напечатав ошибку оболочки нашему юзеру.
chislo() {
    case "$1" in ''|*[!0-9]*) return 1 ;; esac
    [ "$1" -gt 0 ]
}

# ------------------------------------------------------------------ 0. значения снаружи
# ЗНАЧЕНИЕ С ФОРМОЙ ПРОВЕРЯЕТСЯ ДО ПОДЪЁМА, и вот почему это не педантизм. `WORLD_WAIT=abc`
# ломал сравнение в цикле ожидания: цикл не выполнялся ни разу — стука не было вообще, — и
# следом срабатывал `door-silent`, который убивал ЗДОРОВЫЙ мир. То есть опечатка в
# переменной давала уверенный неверный диагноз и показывала пальцем на дверь (находка ревью
# `WORLD2-121`). Сырая ошибка оболочки при этом уезжала в вывод — не наш язык и не наш формат.
#
# Отсюда правило для этого файла: то, что мы САМИ потребляем как число или как путь,
# проверяется здесь и отказывает СВОИМ кодом. А то, что принадлежит миру (`WORLD_ADDR`), мы
# не судим — им распоряжается он, и если значение негодное, он скажет это сам и точнее нас.
# ------------------------------------------------------------------ 0. чем поднята дверь
# ПЕРВОЕ, ЧТО ГОВОРИТ ЖУРНАЛ, — какой сборкой поднята дверь. Раньше не говорил ничего, и это
# был тот же ложный результат, ради которого защиту и ставили (`WORLD2-92`, `WORLD2-130`):
# `latest` — тег подвижный, юзер тянет его, поднимает и не может узнать, что именно получил.
#
# СПРАШИВАЕМ У СЕБЯ, А НЕ У ДОКЕРА. У двери нет и не будет сокета (`WORLD2` 3.7) — спросить
# «под каким я digest'ом» ей физически нечем, и это законная разница с контроллером, у
# которого сокет есть. Зато версию вписывает в образ СБОРКА (`deploy/build.sh`), и лежит она
# там, куда дверь смотрит сама, — в своём окружении. Сокет для этого не нужен вовсе.
#
# ШТАМПА НЕТ — ГОВОРИМ ЭТО ВСЛУХ, а не подставляем «unknown»: образ, собранный не выпуском,
# честно не знает своей версии, и приблизительная запись здесь была бы хуже отсутствующей
# (`WORLD2` 4.2 п. 5). Молчать нельзя тем более: молчание и есть тот дефект, который здесь
# чинится.
step "чем поднята дверь"

VERSIYA="${WORLD_VERSION:-}"
if [ -n "$VERSIYA" ]; then
    ok "версия образа $VERSIYA — им она и поднята"
    detail "это неподвижный тег выпуска: docker pull ghcr.io/omnifield/world:$VERSIYA даст ровно этот образ"
else
    warn "версии не знаю: штампа в образе нет — значит собран он не выпуском, а на месте"
    detail "это законное состояние для разработчика зоны и НЕ норма для юзера:"
    detail "юзер тянет выпущенный образ, и тот свою версию знает"
    detail "чем поднято на самом деле, снаружи скажет: docker inspect --format '{{.Image}}' world-door"
fi

step "значения, пришедшие снаружи"

chislo "$WAIT" || refuse bad-value \
    "WORLD_WAIT=$WAIT — это не число секунд, а ждать ответа двери надо столько-то" \
    "назови целое больше нуля: -e WORLD_WAIT=60 (умолчание 30)" \
    "оставь как было — просто убери переменную из команды" \
    "проверяем это ДО подъёма нарочно: иначе сломанное ожидание объявило бы живую дверь молчащей"

[ -n "$FIELD_HAS_DIR" ] || refuse bad-value \
    "WORLD_DOOR_FILE=$FIELD_FILE — в имени нет каталога, а из него выводится, где лежит поле" \
    "назови путь целиком: -e WORLD_DOOR_FILE=/field/locations.json (это и есть умолчание)" \
    "каталог из такого имени вышел бы равным самому имени, и отказ говорил бы про несуществующий каталог"

ok "ожидание $WAIT с · реестр $FIELD_FILE · стенд $STAND_DIR"

# Порт для СТУКА выводим из `WORLD_ADDR`, но не судим его: адрес принадлежит миру. Не вышло
# числа — стучаться нам нечем, и это говорится вслух; ожидание при этом пропускается, а не
# превращается в отказ. Убить дверь из-за того, что мы не умеем в неё постучаться, было бы
# ровно той подменой причины, которую этот блок и чинит.
stuk=1
chislo "$PORT" || stuk=
[ -n "$stuk" ] || warn "из WORLD_ADDR=$ADDR не вывести числовой порт — стучаться в дверь мне нечем"

# Имя в общей сети едет в адрес стука. Не годится в сетевое имя — скажем это настоящей
# причиной, а не «в поле не видно»: второе было бы враньём про сеть.
imya=1
case "$ALIAS" in ''|*[!a-zA-Z0-9.-]*) imya= ;; esac
[ -n "$imya" ] || warn "WORLD_DOOR_ALIAS=$ALIAS не годится в сетевое имя — по нему не постучаться"

# tom_istochnik ПУТЬ — где каталог лежит НА МАШИНЕ: печатает источник монтирования, если
# смог его узнать. Читаем `/proc/self/mountinfo` — ядро, а не docker-cli: сокета у нас нет,
# и спросить у докера нечем. Не смогли — молчим и говорим об этом отдельно; догадка тут
# хуже незнания.
tom_istochnik() {
    [ -r /proc/self/mountinfo ] || return 1
    while read -r _ _ _ _ mi_point mi_rest; do
        [ "$mi_point" = "$1" ] || continue
        # После разделителя ` - ` идут тип, ИСТОЧНИК и опции. Разделитель именно такой —
        # это формат ядра, а не наша догадка о нём. Режем оболочкой: чем меньше внешних
        # команд, тем меньше поводов однажды не найтись в базовом образе.
        mi_tail="${mi_rest##* - }"      # тип источник опции
        mi_tail="${mi_tail#* }"         # источник опции
        printf '%s' "${mi_tail%% *}"
        return 0
    done < /proc/self/mountinfo
    return 1
}

# ------------------------------------------------------------------ 1. состояние
# Проверяем ТО ЖЕ, чем будет пользоваться мир, и до того, как он начнёт. Пустой именованный
# том докер создаёт правами каталога, поверх которого монтирует; приехал он root'овым —
# первая же регистрация локации упадёт на записи, и выглядеть это будет как «мир сломан».
step "состояние: поле в $FIELD_DIR, журнал прогонов в $STAND_DIR"

for d in "$FIELD_DIR" "$STAND_DIR"; do
    [ -d "$d" ] || refuse state-missing \
        "каталога $d нет, а мир держит в нём состояние" \
        "каталог создаёт сам образ — значит его перекрыли монтированием: проверь -v в команде" \
        "штатно это именованные тома: -v world-field:/field -v world-stand:/stand"
    [ -w "$d" ] || refuse state-not-writable \
        "каталог $d не пишется — состоянию некуда ложиться" \
        "мир бежит НЕ из-под root (внутри он пользователь world), а том приехал root'овым" \
        "снеси пустой том и подними заново: docker volume rm world-field (поле в нём было пусто)" \
        "посмотреть права: docker run --rm -v world-field:/field alpine ls -ld /field"
done
ok "оба каталога на месте и пишутся"

# ГДЕ состояние лежит на машине — вопрос не праздный: безымянного хранилища мир не признаёт
# (`kb:WORLD-28`). Забудь юзер `-v`, докер всё равно создаст том (в образе объявлен VOLUME),
# но БЕЗ ИМЕНИ — и найти его через полгода будет нечем. Это предупреждение, а не отказ:
# имя тома мы выводим из раскладки докера, а вывод — не то основание, по которому отказывают.
field_src="$(tom_istochnik "$FIELD_DIR" || true)"
case "$field_src" in
    "")               detail "где состояние лежит на машине — изнутри не видно; снаружи: docker inspect world-door" ;;
    */volumes/*/_data)
        tom="${field_src%/_data}"; tom="${tom##*/}"
        # Имя из 64 шестнадцатеричных знаков докер выдаёт САМ — это и есть безымянный том.
        bezymyannyy=
        [ "${#tom}" = 64 ] && case "$tom" in *[!0-9a-f]*) ;; *) bezymyannyy=1 ;; esac
        if [ -n "$bezymyannyy" ]; then
            warn "поле легло на БЕЗЫМЯННЫЙ том — найти его потом будет нечем (kb:WORLD-28)"
            detail "подними с именованным: -v world-field:/field -v world-stand:/stand"
            detail "этот том никуда не денется, но искать его придётся по идентификатору $tom"
        else
            ok "поле на томе $tom — переживёт пересоздание контейнера"
        fi ;;
    *)                ok "поле лежит на $field_src — это место назвал хозяин машины" ;;
esac

# ------------------------------------------------------------------ 2. поднимаем мир
# Мир уходит в фон, а не `exec`, ровно ради одной вещи: «запущен» и «отвечает» — разные
# вещи, и подтверждать надо вторую. Плата за это — оболочка первым процессом, поэтому
# сигналы передаём руками: без этого `docker stop` десять секунд ждал бы того, кто его не
# слышит, и добивал бы дверь по таймауту.
step "поднимаю мир на $ADDR"
"$BIN" "$@" &
door=$!
trap 'kill -TERM "$door" 2>/dev/null' TERM INT

# ------------------------------------------------------------------ 3. дверь отвечает
otvet=
if [ -n "$stuk" ]; then
    step "жду, пока дверь ответит на http://127.0.0.1:$PORT/healthz"
    i=0
    while [ "$i" -lt "$WAIT" ]; do
        if ! kill -0 "$door" 2>/dev/null; then break; fi   # мир вышел сам — ждать нечего
        if knock "http://127.0.0.1:$PORT/healthz"; then otvet=1; break; fi
        sleep 1
        i=$((i + 1))
    done
else
    # Стучаться нечем — но дать миру мгновение и посмотреть, не вышел ли он сам, мы обязаны:
    # это единственное, что здесь ещё можно проверить честно.
    step "ответа двери не жду — из WORLD_ADDR=$ADDR не вывести порт для стука"
    sleep 1
fi

if ! kill -0 "$door" 2>/dev/null; then
    wait "$door"; code=$?
    refuse door-dead \
        "мир вышел сам, код $code — дверь не открылась" \
        "причину назвал он сам, строкой выше: это его журнал, а не наш" \
        "чаще всего это занятый порт ВНУТРИ контейнера или нечитаемое состояние" \
        "весь журнал: docker logs world-door"
fi

if [ -n "$stuk" ] && [ -z "$otvet" ]; then
    kill -TERM "$door" 2>/dev/null
    refuse door-silent \
        "мир запущен, а дверь за ${WAIT}с так и не ответила на http://127.0.0.1:$PORT/healthz" \
        "журнал мира — выше: если он падает, причина названа там первой же строкой" \
        "машина медленная и первый запуск дольше — дай времени: -e WORLD_WAIT=60" \
        "стучимся ИЗНУТРИ контейнера: снаружи тишина может быть и от публикации, а здесь она не при чём"
fi

if [ -n "$otvet" ]; then
    ok "дверь отвечает"
else
    # Дверь ЖИВА (мир не вышел), но здоровье не проверено. Говорим это ровно так: непроверенное
    # называется непроверенным (`WORLD2` 4.2), а не выдаётся за подтверждение.
    warn "здоровье двери НЕ проверено — стучаться было нечем; мир при этом работает"
    detail "состояние покажет сам докер: docker ps (HEALTHCHECK образа стучится на :8080)"
    detail "порт внутри контейнера фиксирован — WORLD_ADDR крутить не надо, наружу крутится хост-порт"
fi

# ------------------------------------------------------------------ 4. видно ли меня в поле
# Стучимся В СЕБЯ ПО КОНТРАКТНОМУ ИМЕНИ. Это единственный способ узнать изнутри, стоим ли мы
# в общей сети под тем именем, по которому сосед войдёт в поле: имени сети изнутри не видно
# вовсе, а имя разрешается только на пользовательской сети докера.
#
# Не отказ, а предупреждение — и намеренно. Дверь на пустой машине, где поля ещё нет, это
# законное первое состояние: сеть создаст тот, у кого есть сокет. Отказывай мы здесь, первая
# же команда юзера падала бы на том, что он ещё не успел сделать.
#
# ЭТА ПРОВЕРКА СЛАБЕЕ СОСЕДСКОЙ, и знать это обязательно. Она отвечает на вопрос «стою ли я
# в общей сети под этим именем», а НЕ на вопрос «видит ли меня сосед»: стучимся мы в себя.
# Контракт соседа (`door:8080`) проверяется только из ЧУЖОГО контейнера — это делает
# `deploy/probe.sh` (проверка 6), и заменить её отсюда нечем. Поэтому здесь зелёная строка
# говорит ровно то, что проверено, и ни слова больше.
step "видно ли меня в поле по имени $ALIAS"
if [ -z "$imya" ] || [ -z "$stuk" ]; then

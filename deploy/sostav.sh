#!/usr/bin/env bash
# СОСТАВ ОБРАЗА — что именно в него едет. Одно объявление на зону, и читают его ДВОЕ.
#
#   ./deploy/sostav.sh --obrazy            ключи всех образов, по строке
#   ./deploy/sostav.sh --door              перечень путей образа двери
#   ./deploy/sostav.sh --control --pult    путь, из которого собирается пульт
#
# ЗАЧЕМ ЭТОТ ФАЙЛ ВООБЩЕ ЕСТЬ. Неподвижный тег отвечает на один вопрос — «из чего это
# собрано» (`sha-<7>`, довод в `release.sh`). Раньше он выводился из `HEAD` репозитория, то
# есть отвечал на другой вопрос: «когда это собрано». Разница молчит ровно до того дня,
# когда правят одну зону, а выпускают другую: тег двери сдвигался от правки в `share/`, и
# по нему нельзя было понять, изменилась дверь или нет.
#
# ПОЧЕМУ НЕЛЬЗЯ ВЗЯТЬ «ПАПКУ С ИМЕНЕМ ЗОНЫ» — ловушка, ради которой перечень и заведён.
# В образ КОНТРОЛЛЕРА едет ПУЛЬТ, а пульт живёт в `web/`. Возьми мы «последний коммит по
# `control/`» — выпуск отдал бы контроллер с новой панелью под старым тегом. Тег соврал бы
# МОЛЧА, и поймать это было бы нечем: и тег, и штамп выглядели бы правдой.
#
# ПЕРЕЧЕНЬ ОДИН И ТОТ ЖЕ ДЛЯ СБОРКИ И ДЛЯ ВЕРСИИ, и это главное свойство файла. Заведи мы
# вторую копию — «что собирать» отдельно, «по чему считать версию» отдельно, — они
# разъехались бы, и разъехались бы тихо: ровно тот род дефекта, что уже стоил нам
# `WORLD2-140` и `WORLD2-134`. Поэтому:
#
#   · ВЕРСИЯ (`version.sh`) считает `sha` по перечню образа и по нему же проверяет чистоту;
#   · СБОРКА (`build.sh`) берёт ОТСЮДА путь исходника пульта — тот самый `web/`, из-за
#     которого перечень и написан. То есть убрать `web/` из перечня нельзя «только для
#     версии»: сборке тогда неоткуда взять пульт, и она скажет об этом вслух (`no-pult`).
#
# ЧТО ПОПАДАЕТ В ПЕРЕЧЕНЬ — правило одно: **содержимое, которое оказывается в образе, и
# рецепт ИМЕННО ЭТОГО содержимого**. Отсюда несимметричность, которая иначе выглядит
# случайной: `deploy/build.sh` назван у контроллера и не назван у остальных двух. У двери и
# раздачи рецепт лежит в их же `Dockerfile` и `compose.yaml` — они в перечне и так; а
# ПУЛЬТ изготавливает `build.sh` (шаг 1: чем собирает, какой нодой, какой pnpm), и другого
# рецепта у пульта нет вовсе.
#
# ЧТО В ПЕРЕЧЕНЬ НЕ ВХОДИТ: доки, пробы, скрипты подъёма — они в образ не едут и рецептом
# его содержимого не являются. Правка в `README.md` версию образа не сдвигает, и это верно:
# образ от неё не меняется ни на байт. Гранулярность здесь коммитная и загрублена В
# БЕЗОПАСНУЮ СТОРОНУ — лишний сдвиг версии дёшев, пропущенный стоит вранья в теге.
#
# ЭТОТ ФАЙЛ МОЖНО ПОДКЛЮЧИТЬ (`. sostav.sh`) — тогда он только объявляет и НЕ печатает
# ничего. Так его читает `version.sh`, которому нельзя зависеть ни от одной внешней команды
# (он обязан доходить до ответа `no-git` на машине без `PATH`). Поэтому здесь нет ни одной
# внешней команды тоже: только встроенное в оболочку.
#
# Имена переменных латинские: bash не поддерживает не-ASCII в именах переменных и молча
# превращает `ПУТИ=1` в «команда не найдена». Тексты и комментарии — русские.

# Свой каталог выводим СРЕЗОМ, а не `dirname`: внешних команд в файле нет вовсе — см. выше.
SOSTAV_HERE="${BASH_SOURCE[0]%/*}"
[ "$SOSTAV_HERE" = "${BASH_SOURCE[0]}" ] && SOSTAV_HERE=.
SOSTAV_HERE="$(cd -- "$SOSTAV_HERE" && pwd)"
SOSTAV_ROOT="$(cd -- "$SOSTAV_HERE/.." && pwd)"

# ┌──────────────────────────────────────────────────────────────────────────────────────┐
# │ ОБЪЯВЛЕНИЕ. Всё, что ниже этого блока, — чтение и проверка; менять состав образа       │
# │ надо ЗДЕСЬ и только здесь.                                                            │
# └──────────────────────────────────────────────────────────────────────────────────────┘

# Ключи образов. Порядок — тот же, в котором они собирались и уезжали, когда выпуск возил их
# пачкой; теперь выпуск возит по одному, и порядок остался только справочным.
SOSTAV_OBRAZY="door share control"

# ДВЕРЬ. Контекст сборки — корень репозитория, но `Dockerfile.dockerignore` пускает внутрь
# ровно два имени (`core/` и `deploy/door-entry.sh`) — их и называем. Рядом рецепт: сам
# сборочный файл, его список исключений и файл запуска, в котором объявлены контекст,
# `dockerfile` и `network: none`.
SOSTAV_door='core
deploy/door-entry.sh
deploy/Dockerfile
deploy/Dockerfile.dockerignore
deploy/compose.yaml'
SOSTAV_ZOVEM_door='дверь'

# РАЗДАЧА. Контекст сборки — сама зона, и в образ не едет ничего чужого: одного пути хватает,
# `Dockerfile` и файл запуска лежат внутри него же.
SOSTAV_share='share'
SOSTAV_ZOVEM_share='раздача'

# КОНТРОЛЛЕР. `control/` — его исходник, `Dockerfile` и файл запуска. `web/` — ПУЛЬТ, он же
# ловушка, ради которой заведён весь файл. Остальные три — чужое содержимое, которое
# `control/Dockerfile` кладёт в образ строками `COPY`; сдвинется оно — сдвинется и образ.
SOSTAV_control='control
web
deploy/build.sh
deploy/remote.sh
deploy/compose.yaml
share/compose.yaml'
SOSTAV_ZOVEM_control='контроллер'

# Откуда берётся ПУЛЬТ. Значение читает сборка (шаг 1) — и оно ОБЯЗАНО быть в перечне образа
# контроллера. Проверку держит `sostav_proverit`, а не договорённость в голове: без неё
# перечень и сборка разъехались бы молча, и тег контроллера соврал бы про панель.
SOSTAV_PULT_IZ='web'

# ────────────────────────────────────────────────────────────── чтение и проверка

# Причина, по которой перечень не отдан. Заполняются обе: код — машине, слова — человеку,
# и человеку слова передают ДОСЛОВНО (`WORLD2` 2.3).
SOSTAV_STATE=
SOSTAV_SLOVAMI=

sostav_net() { SOSTAV_STATE="$1"; SOSTAV_SLOVAMI="$2"; return 1; }

# sostav_obrazy — ключи всех образов, по строке.
sostav_obrazy() { printf '%s\n' $SOSTAV_OBRAZY; }

# sostav_est КЛЮЧ — знаем ли такой образ.
sostav_est() {
    local k
    for k in $SOSTAV_OBRAZY; do [ "$k" = "$1" ] && return 0; done
    return 1
}

# sostav_zovem КЛЮЧ — как образ зовётся по-человечески. Пусто — ключ не наш.
sostav_zovem() {
    local imya="SOSTAV_ZOVEM_$1"
    printf '%s' "${!imya-}"
}

# sostav_puti КЛЮЧ — перечень путей образа, по строке. Ключ не наш — отказ с причиной.
sostav_puti() {
    sostav_est "$1" || sostav_net no-image \
        "образа «$1» зона не знает — есть только: $SOSTAV_OBRAZY" || return 1
    local imya="SOSTAV_$1"
    printf '%s\n' "${!imya}"
}

# sostav_pult — путь, из которого собирается пульт.
sostav_pult() { printf '%s\n' "$SOSTAV_PULT_IZ"; }

# sostav_proverit КЛЮЧ — сходится ли объявление с деревом. Зовётся ПЕРЕД тем, как перечнем
# воспользуются: перечень, разошедшийся с деревом, тише всего врёт именно молча.
#
# Проверяем два вида расхождения, и оба однажды случались бы:
#   · исходник пульта НЕ НАЗВАН в перечне контроллера — то самое, ради чего файл написан.
#     Сборка при этом всё равно возьмёт пульт отсюда, значит в образ он приедет, а в версию
#     не войдёт: тег соврал бы про панель;
#   · названного пути в дереве НЕТ — папку переименовали, а перечень остался. Версия тогда
#     считалась бы по остатку и молча перестала бы замечать целый кусок образа.
#
# ПОРЯДОК ЗНАЧИМ: сперва «перечень сходится САМ С СОБОЙ», потом «сходится с деревом».
# Переименуй кто-нибудь `web/` и поправь половину — обе проверки сработали бы, но первая
# называет причину («пульт выпал из перечня»), а вторая только следствие («такого пути нет»).
# Отказ обязан называть то, что чинят.
sostav_proverit() {
    local key="$1" p imya

    sostav_est "$key" || sostav_net no-image \
        "образа «$key» зона не знает — есть только: $SOSTAV_OBRAZY" || return 1

    imya="SOSTAV_$key"

    # Пульт спрашивается только у того образа, в который он едет. У двери и раздачи его нет
    # вовсе, и требовать там `web/` значило бы стеречь пустоту (`WORLD2` 4.2).
    if [ "$key" = control ]; then
        local est=
        while IFS= read -r p; do
            [ "$p" = "$SOSTAV_PULT_IZ" ] && est=1
        done <<< "${!imya}"
        [ -n "$est" ] || sostav_net no-pult \
            "пульт собирается из $SOSTAV_PULT_IZ, а в перечне образа «$(sostav_zovem control)» этого пути нет: он приехал бы в образ, но не вошёл бы в версию — тег соврал бы про панель" || return 1
    fi

    while IFS= read -r p; do
        [ -n "$p" ] || continue
        [ -e "$SOSTAV_ROOT/$p" ] || sostav_net no-path \
            "в перечне образа «$(sostav_zovem "$key")» назван путь $p, а в дереве его нет" || return 1
    done <<< "${!imya}"

    return 0
}

# ────────────────────────────────────────────────────────────── запуск отдельной командой
# Подключён (`. sostav.sh`) — здесь всё и кончается: файл только объявил. Запущен — отвечает
# на вопрос из ключей. Различаем ровно этим сравнением, а не переменной окружения: у неё
# нашёлся бы способ соврать.
[ "${BASH_SOURCE[0]}" = "${0}" ] || return 0

usage() {
    cat <<'USAGE'
Состав образа: ./deploy/sostav.sh --obrazy | <образ> [--pult]

  --obrazy       ключи всех образов, по строке
  --door         перечень путей, которые едут в образ ДВЕРИ
  --share        то же для образа РАЗДАЧИ
  --control      то же для образа КОНТРОЛЛЕРА
  --pult         вместо перечня напечатать путь, из которого собирается пульт
  -h, --help     эта подсказка

Перечень ОДИН и тот же для сборки и для версии: по нему `version.sh` считает
sha-<7> и проверяет чистоту, из него же `build.sh` берёт исходник пульта.

Выход:
  stdout   пути (или ключи), по строке
  stderr   SOSTAV-STATE: <код>   для машины, следом причина словами
  код      0 — перечень отдан · 1 — нет · 2 — непонятный ключ

Коды состояния:
  no-image     такого образа зона не знает
  no-path      в перечне назван путь, которого в дереве нет
  no-pult      исходник пульта не назван в перечне образа контроллера
USAGE
}

klyuch=
pult=
while [ $# -gt 0 ]; do
    case "$1" in
        --obrazy)   sostav_obrazy; exit 0 ;;
        --door|--share|--control) klyuch="${1#--}" ;;
        --pult)     pult=1 ;;
        -h|--help)  usage; exit 0 ;;
        *) usage >&2; printf '\nнепонятный ключ: %s\n' "$1" >&2; exit 2 ;;
    esac
    shift
done

net() {
    printf 'SOSTAV-STATE: %s\n' "$1" >&2
    printf '%s\n' "$2" >&2
    exit 1
}

[ -n "$klyuch" ] || net no-image \
    "образ не назван — перечень принадлежит образу, а не зоне: ./deploy/sostav.sh --door|--share|--control"

sostav_proverit "$klyuch" || net "$SOSTAV_STATE" "$SOSTAV_SLOVAMI"

if [ -n "$pult" ]; then
    # Пульт есть ровно у одного образа. Спросили у другого — это не пустой ответ, а вопрос
    # не по адресу: молчание тут читалось бы как «пульта нет», и сборка пошла бы собирать
    # его из пустоты.
    [ "$klyuch" = control ] || net no-pult \
        "пульт едет только в образ «$(sostav_zovem control)», а спросили у образа «$(sostav_zovem "$klyuch")»"
    sostav_pult
    exit 0
fi

sostav_puti "$klyuch"

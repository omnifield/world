#!/usr/bin/env bash
# ВЫПУСК — собрать у себя ОДИН образ и опубликовать его в реестре.
#
#   ./deploy/release.sh --door             выпуск двери
#   ./deploy/release.sh --share            выпуск раздачи скоупа
#   ./deploy/release.sh --control          выпуск контроллера
#   ./deploy/release.sh --door --dry-run   показать, что и куда поедет; не собирать и не публиковать
#
# ОДИН ОБРАЗ ЗА ВЫЗОВ, и три образа — это три вызова (`WORLD2-146`). Раньше выпуск возил
# тройку одной сборки, помеченную одним `sha`, и выборочного выпуска не было намеренно.
# Решение отменено user'ом 2026-08-18: у каждого образа СВОЯ версия, и «раз я такой сборки,
# то и вещи такой же» больше не действует — стык держит форма (канон `3.4`), а не общий тег.
#
# ЧТО ЭТО МЕНЯЕТ ПО СУЩЕСТВУ, а не в ключах. Тег отвечает на вопрос «из чего это собрано», и
# отвечать он обязан про СВОЙ образ. Пока `sha` брался у `HEAD`, тег двери сдвигался от
# правки в `share/` — то есть по нему нельзя было понять, менялась дверь или нет. Теперь
# версия выводится по ПЕРЕЧНЮ ОБРАЗА (`deploy/sostav.sh`, счёт — `deploy/version.sh`), и
# чистое дерево спрашивается тоже по перечню: правка в чужой зоне не обязана мешать выпуску.
#
# УМОЛЧАНИЯ У КЛЮЧА НЕТ, и это не строгость ради строгости. Публикация необратима: угадай мы
# образ за человека — он узнал бы о догадке из реестра. Назвать надо ровно один; два ключа
# в одной строке — отказ, потому что «за вызов уезжает один образ» это свойство, за которым
# следит проба, а не памятка в подсказке.
#
# ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ, а не ключ к `build.sh`. Сборка складывает вещь у себя; выпуск
# ОТДАЁТ её наружу — необратимо и всем сразу. Это разные поступки, и путать их нельзя:
# случайный ключ в чужой команде публикует, случайный файл — нет. Обратное направление
# безобидно и потому разрешено: выпуск сам зовёт сборку, а сборка публиковать не умеет
# вовсе — этого в ней нет ни ключом, ни переменной.
#
# ЗАЧЕМ ВООБЩЕ ВЫПУСК. Юзер не собирает ничего — он получает готовое (`WORLD2-110`). Собрать
# значит иметь у себя клон репозитория, ноду и терпение на три сборки; получить — одна
# команда `docker run`. Ради этого выпуск и существует.
#
# ПОЛЕ ВЫПУСКУ БОЛЬШЕ НЕ НУЖНО. Раньше было нужно: собрать контроллер значило собрать
# пульт, а пакеты пульта лежали на складе локации `probe-web` и наружу не торчали
# (`kb:FUND-5`) — то есть выпускать можно было только там, где поле поднято. Панель
# отвязана от продуктов мира (`WORLD2-127`), и это требование ушло вместе с причиной.
# Выпуску теперь нужен обычный выход наружу — как и всякой сборке.
#
# ЧТО ЗДЕСЬ НЕ ЖИВЁТ:
#
#   · имена образов. Каждое принадлежит СВОЕЙ зоне и берётся из ЕЁ файла запуска — так же,
#     как это делает `build.sh`. Держи мы вторую копию, выпуск однажды опубликовал бы не
#     тот образ, который поднимают, и разъехались бы они молча;
#   · СПИСОК ПЕРЕМЕННЫХ, которыми зоны крутят свои имена. Он был бы такой же второй копией,
#     только чужого устройства: заведи соседняя зона четвёртую переменную — и выпуск узнал
#     бы об этом, опубликовав не туда. Какие подстановки есть в файле запуска, спрашиваем у
#     САМОГО ФАЙЛА (см. «умолчание зоны» ниже);
#   · ПЕРЕЧЕНЬ ПУТЕЙ ОБРАЗА. Он объявлен в `deploy/sostav.sh` — одним экземпляром на зону,
#     потому что тем же перечнем пользуется сборка. Вторая копия здесь разъехалась бы с ним
#     молча, и тег соврал бы ровно в том случае, ради которого перечень и заведён;
#   · креды. Ни ключа, ни переменной с токеном: в реестр ходит `docker`, а он берёт вход
#     там, где его оставил человек (`docker login`). Токен в аргументе команды — это токен
#     в истории оболочки и в списке процессов. Ключи принадлежат человеку (`WORLD2` 3.0).
#
# ЧЕГО ЗДЕСЬ БОЛЬШЕ НЕТ И ПОЧЕМУ — сверка имён образов между собой. Пока выпуск возил тройку,
# он сравнивал все пары: два образа под одним именем это один образ, и второй `push` лёг бы
# поверх первого. Свойство было про НАБОР, а набора больше нет. Вернуть проверку значило бы
# читать файлы запуска двух чужих зон ради сравнения — и тогда нечитаемый сосед мешал бы
# выпуску двери ровно так же, как мешала грязь в его папке. Риск при этом не исчез, он
# сменил владельца: «имена трёх образов не совпадают» — это cross-zone контракт, и держать
# его должен тот, кто владеет всеми тремя именами, а не одна зона в момент отдачи.
#
# ПОСТАВКА КОПИЕЙ НЕ ОТМЕНЯЕТСЯ — и тем более теперь, когда дверь ещё и выпускается.
# `docker save | docker load` остаётся для машин без выхода в реестр: им возит образ
# `deploy/remote.sh`. Это два способа доставки одной вещи (`WORLD2` 1.5), а не выбор
# навсегда: появление второго не делает первый лишним — ресурс без реестра никуда не делся.
#
# Имена переменных ЛАТИНСКИЕ: bash не поддерживает не-ASCII в именах переменных и молча
# превращает `ТЕГ=latest` в «команда не найдена». Тексты и комментарии — русские.
set -euo pipefail

# Реестр — значение, а не зашитое слово. Умолчание `ghcr.io` выбрано user'ом 2026-08-15
# (`WORLD2-110`): организация `omnifield` там уже есть, репозиторий публичный, и `docker
# pull` с него идёт без входа — то есть юзеру не нужно ничего, кроме докера.
REGISTRY="${WORLD_REGISTRY:-ghcr.io}"

HERE="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd -- "$HERE/.." && pwd)"

# Перечень путей образа объявлен один раз на зону — подключаем его, а не пересказываем.
# Отсюда берутся человеческие имена образов и то, по чему выведена версия: человеку надо
# показать не только «какой тег», но и «почему такой».
. "$HERE/sostav.sh"

dry=
obraz=
usage() {
    cat <<'USAGE'
Выпуск образа мира: ./deploy/release.sh <образ> [--dry-run]

  --door         выпустить образ ДВЕРИ
  --share        выпустить образ РАЗДАЧИ скоупа
  --control      выпустить образ КОНТРОЛЛЕРА
  --dry-run      показать, что и куда поедет. Ничего не собирается и не
                 публикуется — ни одного изменения ни здесь, ни в реестре.
                 Работает и на ГРЯЗНОМ дереве: он ничего не меняет, а нужен
                 как раз посреди работы — про грязь он скажет вслух
  -h, --help     эта подсказка

ЗА ВЫЗОВ УЕЗЖАЕТ ОДИН ОБРАЗ, и у каждого СВОЯ версия. Три образа — три вызова.
Умолчания у ключа нет: публикация необратима, и угадывать за человека, что он
хотел отдать наружу, нельзя.

ЧЕМ МЕТИМ. Неподвижный тег — sha-<7 знаков коммита>, и коммит берётся не у HEAD, а у
последнего, тронувшего то, что в ЭТОТ образ едет. Перечень объявлен в deploy/sostav.sh
(посмотреть: ./deploy/sostav.sh --control). Подвижный тег latest уезжает следом.

ЧТО НУЖНО ТОМУ, КТО ВЫПУСКАЕТ (юзеру не нужно ничего из этого):
  · ВЫХОД НАРУЖУ — обычный. ПОЛЯ НЕ НУЖНО: сеть omnifield-gateway для выпуска не
    создаётся и не спрашивается ни на одном шаге;
  · ВХОД В РЕЕСТР — заранее и не нашей командой:
      echo $TOKEN | docker login ghcr.io -u <логин> --password-stdin
    токен — PAT с правом write:packages (сверено с докой GitHub 2026-08-15);
  · ЧИСТЫЙ ПЕРЕЧЕНЬ ЭТОГО ОБРАЗА — неподвижный тег называет коммит, и называть он обязан
    правду. Чистота спрашивается по перечню, а не по всему репозиторию: правка в чужой
    зоне не делает утверждение об этом образе ложным. Нужно только НАСТОЯЩЕМУ выпуску;
  · ОКРУЖЕНИЕ БЕЗ ПОДСТАНОВОК ЗОН. Имя образа выпуск берёт из файла запуска, а не из
    окружения; назови ты имя переменной (её зона завела для ПОДЪЁМА названного
    выпуска) — выпуск откажет и покажет обе стороны, а не выберет за тебя.

КУДА ПУБЛИКУЕМ — решает имя образа, а имена принадлежат зонам. Разбор один:
  · имя БЕЗ реестра (организация/образ) — реестр приписывает WORLD_REGISTRY;
  · имя С реестром (ghcr.io/организация/образ) — публикуем ровно туда: это
    адрес, по которому образ потом ТЯНУТ;
  · названы оба и они разные — отказ. Выбирать за человека, куда отдать вещь
    наружу, нельзя.

Переменные:
  WORLD_REGISTRY=ghcr.io   куда публикуем, если имя реестра не несёт (умолчание ghcr.io)
USAGE
}

while [ $# -gt 0 ]; do
    case "$1" in
        --dry-run)  dry=1 ;;
        --door|--share|--control)
            # Два образа в одной строке — не «понял и то и другое», а несогласие с правилом
            # вызова. Молча взять последний значило бы отдать наружу не то, что назвали.
            if [ -n "$obraz" ] && [ "$obraz" != "${1#--}" ]; then
                usage >&2
                printf '\nназваны два образа: %s и %s — за вызов уезжает ОДИН\n' "$obraz" "${1#--}" >&2
                exit 2
            fi
            obraz="${1#--}" ;;
        -h|--help)  usage; exit 0 ;;
        *)  usage >&2; printf '\nнепонятный ключ: %s\n' "$1" >&2; exit 2 ;;
    esac
    shift
done

step() { printf '\n\033[1m→ %s\033[0m\n' "$*" >&2; }
ok()   { printf '  ✓ %s\n' "$*" >&2; }
warn() { printf '  \033[33m!\033[0m %s\n' "$*" >&2; }

# fail ПРИЧИНА ВЫХОД… — единственный способ выйти с ошибкой. Выход обязателен: отказ без
# следующего действия это диагноз, а не отказ (`kb:WORLD-31`).
fail() {
    local why="$1"; shift
    printf '\n\033[1;31m✗ не выпущено: %s\033[0m\n' "$why" >&2
    local line
    for line in "$@"; do printf '  выход: %s\n' "$line" >&2; done
    exit 1
}

[ -n "$obraz" ] || { usage >&2; printf '\nобраз не назван — за вызов уезжает ОДИН, и назвать его надо явно\n' >&2; exit 2; }

# docker_noconv … — вызов докера, в аргументах которого НЕТ путей хоста. Правило зоны и
# довод целиком — в `build.sh` рядом с таким же помощником.
docker_noconv() { MSYS_NO_PATHCONV=1 MSYS2_ARG_CONV_EXCL='*' docker "$@"; }

# Куда компоуз пишет своё «не читается». Отдельным файлом, а не в общий поток: причина
# отказа обязана быть НАЗВАНА ЕГО СЛОВАМИ, а смешай мы потоки — в имя образа попала бы
# первая строка предупреждения, и выпуск опубликовал бы её.
OSHIBKA="$(mktemp)"
trap 'rm -f "$OSHIBKA"' EXIT

# ЗОНА, ФАЙЛ ЗАПУСКА И КЛЮЧ СБОРКИ — три вещи, которые выпуск знает про образ помимо его
# состава. Образ складывается и называется СВОИМ файлом запуска; имя спрашиваем у него же —
# и у чужих зон, и у своей. Своя тут не исключение: копия имени в выпуске разъехалась бы с
# файлом запуска ровно так же, только тише, потому что чинить её было бы «у себя».
#
# Чем чаще всего кончается неудача сборки — тоже здесь, и по образу оно разное: общий совет
# отправил бы человека чинить не то (`kb:WORLD-31`).
zovem="$(sostav_zovem "$obraz")"
case "$obraz" in
    door)
        zona=deploy
        fayl="$HERE/compose.yaml"
        klyuch=""                       # у двери его нет — она умолчание сборки
        pochemu="сети этому шагу не нужно вовсе — он компилирует Go без зависимостей" ;;
    share)
        zona=share
        fayl="$ROOT/share/compose.yaml"
        klyuch="--share"
        pochemu="зависимостей у зоны нет: чаще всего это базовый образ, который не притянулся" ;;
    control)
        zona=control
        fayl="$ROOT/control/compose.yaml"
        klyuch="--control"
        pochemu="чаще всего это выход наружу: шаг 1 ставит зависимости пульта из реестра" ;;
esac

# ------------------------------------------------------------------ 1. чем выпускаем
step "чем выпускаем — образ «$zovem» (зона $zona)"

command -v docker >/dev/null 2>&1 || fail "докера на машине нет" \
    "поставь Docker Engine: https://docs.docker.com/engine/install/"
command -v git >/dev/null 2>&1 || fail \
    "на машине нет git, а неподвижный тег выводится из коммита" \
    "поставь git — либо выпускай там, где репозиторий полон"
docker info >/dev/null 2>&1 || fail "докер есть, а демон не отвечает" \
    "запусти его: systemctl start docker (либо открой Docker Desktop)"

ok "докер и git на месте"
ok "за этот вызов уедет ОДИН образ — «$zovem», и никакой другой"

# ------------------------------------------------------------------ 2. чем метим
# НЕПОДВИЖНЫЙ ТЕГ — `sha-<7 знаков коммита>`, и вот почему именно он.
#
# Версии у продукта пока нет, значит `1.4.2` писать нечем. Из того, что есть, тег обязан
# отвечать на один вопрос: «из чего это собрано». Дата (`2026-08-15`) на него не отвечает —
# два выпуска в один день сольются, а вернуться к исходнику по ней нельзя. Коммит отвечает
# точно: по тегу видно, что именно поехало, и это можно прочитать в репозитории.
# Тот же выбор делает рынок: тег с коммитом кладут в дополнение к остальным (сверено с
# `docker/metadata-action` и обзорами практик тегирования 2026-08-15).
#
# КОММИТ БЕРЁТСЯ НЕ У `HEAD`, А У ПЕРЕЧНЯ ЭТОГО ОБРАЗА (`WORLD2-146`). Довод целиком — в
# `deploy/sostav.sh`; короткий: в образ контроллера едет пульт из `web/`, и «последний коммит
# по `control/`» выпустил бы контроллер с новой панелью под старым тегом — молча.
#
# ПЕРЕЧЕНЬ ОБЯЗАН БЫТЬ ЧИСТЫМ — но только там, где что-то УЕЗЖАЕТ. Тег `sha-abc1234` это
# утверждение «собрано из abc1234»; собери мы из дерева с правками, утверждение станет ложью,
# которую уже не отличить: образ уехал, а по тегу человек прочитает не тот исходник. Чистота
# спрашивается ПО ПЕРЕЧНЮ: правка в `share/` не делает утверждение о двери ложным.
#
# ХОЛОСТОЙ ХОД — ДРУГОЕ ДЕЛО, и раньше он отказывал зря. Он не меняет ничего ни здесь, ни в
# реестре, значит чистое дерево ему не нужно; а нужен он чаще всего именно тогда, когда
# дерево грязное — человек в работе и смотрит, что поедет. Отказ на нём вдобавок советовал
# выходом сам себя: холостой ход, который отказал, предлагал сделать холостой ход. Отказ,
# ведущий в себя, — это диагноз, а не отказ (`kb:WORLD-31`). Поэтому здесь грязь только
# НАЗЫВАЕТСЯ вслух, а отказ стоит на настоящем выпуске — ниже развилки.
#
# ВЕРСИЮ ВЫПУСК НЕ СЧИТАЕТ САМ — он спрашивает её у `deploy/version.sh`, и это не лишний
# файл. Ту же версию сборка ВПИСЫВАЕТ ВНУТРЬ образа штампом (`WORLD2-130`). Считай её два
# разных куска кода — они разъедутся, и образ станет утверждать одно, а тег означать другое;
# снаружи это не отличить. Поэтому вычисление одно, а здесь — только чтение его ответа.
# Ниже, после сборки, штамп и тег ещё и СВЕРЯЮТСЯ: единственный источник это хорошо, но
# проверять надо то, что получилось.
step "чем метим"

versiya="$("$HERE/version.sh" "--$obraz" 2>"$OSHIBKA")" || versiya=""
sostoyanie="$(sed -n 's/^VERSION-STATE: //p' "$OSHIBKA" 2>/dev/null || true)"
slovami="$(grep -v '^VERSION-STATE:' "$OSHIBKA" 2>/dev/null || true)"

# Грязный перечень — единственное состояние, при котором версия ЕСТЬ, но она не честна:
# коммит на месте, а собрано будет не из него. Настоящему выпуску это отказ (ниже развилки),
# а холостому ходу нужен план — поэтому спрашивается отдельно и НАЗВАННЫМ ключом, чтобы такое
# значение нельзя было получить случайно.
derevo_gryaznoe=
gryazno=
if [ -z "$versiya" ]; then
    case "$sostoyanie" in
        dirty)
            derevo_gryaznoe=1
            versiya="$("$HERE/version.sh" "--$obraz" --plan 2>/dev/null || true)"
            # Показываем ТОЛЬКО грязь этого образа: перечисли мы весь репозиторий, человек
            # чинил бы чужие правки, которые выпуску двери не мешают вовсе.
            puti=(); while IFS= read -r p; do [ -n "$p" ] && puti+=("$p"); done < <(sostav_puti "$obraz")
            gryazno="$(git -C "$ROOT" status --porcelain -- "${puti[@]}" 2>/dev/null | head -n 10 || true)"
            ;;
        no-git)
            fail "$slovami" \
                "поставь git — либо выпускай там, где репозиторий полон" ;;
        not-a-repo)
            fail "$slovami" \
                "неподвижный тег выводится из коммита, а взять его неоткуда" \
                "выпускай из клона репозитория, а не из распакованного архива" ;;
        no-commit|not-in-history)
            fail "$slovami" \
                "сделай коммит и повтори выпуск" \
                "что входит в версию этого образа: ./deploy/sostav.sh --$obraz" ;;
        no-path|no-pult)

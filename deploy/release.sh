#!/usr/bin/env bash
# ВЫПУСК — собрать у себя ОБА образа и опубликовать их в реестр.
#
#   ./deploy/release.sh            выпуск: собрать дверь и контроллер, отдать оба
#   ./deploy/release.sh --dry-run  показать, что и куда поедет; не собирать и не публиковать
#
# ОБРАЗОВ ДВА, И ВЫПУСК ВОЗИТ ИХ ВМЕСТЕ — дверь (зона `deploy`, её файл запуска) и
# контроллер (зона `control`, его файл запуска). Раньше уезжал один контроллер, а дверь
# собиралась из репозитория — то есть шаг «ставлю дверь» требовал клона, которого в потоке
# юзера нет вовсе (`WORLD2`, роадмап «Итерация 1 — поток юзера», ступень 1). Пока оба образа
# не выпускаются, «поставил докер — и поднялось» не складывается ни в каком порядке.
#
# ВЫБОРОЧНОГО ВЫПУСКА НЕТ — ни ключа, ни переменной, и это решение, а не недоделка. Предмет
# выпуска — ПАРА одной сборки: оба образа собраны из одного коммита и помечены одним
# `sha-<7>`, и по тегу видно, что они друг другу ровня. Заведись ключ «только дверь» — в
# реестре появлялись бы пары, которых никто не собирал вместе, а узнавал бы об этом юзер, у
# которого пульт раскладывает дверь не той сборки. Обрыв чинится повтором: выпуск отдаёт то
# же самое ещё раз, и это дёшево.
#
# ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ, а не ключ к `build.sh`. Сборка складывает вещь у себя; выпуск
# ОТДАЁТ её наружу — необратимо и всем сразу. Это разные поступки, и путать их нельзя:
# случайный ключ в чужой команде публикует, случайный файл — нет. Обратное направление
# безобидно и потому разрешено: выпуск сам зовёт сборку (`build.sh` и `build.sh --control`),
# а сборка публиковать не умеет вовсе — этого в ней нет ни ключом, ни переменной.
#
# ЗАЧЕМ ВООБЩЕ ВЫПУСК. Юзер не собирает ни контроллер, ни дверь — он их получает
# (`WORLD2-110`). Собрать контроллер значит собрать пульт, а пульту нужно ПОЛЕ: пакеты
# `@omnifield/probe-web-*` лежат на складе локации `probe-web` и наружу не торчат
# (`kb:FUND-5`). Поле есть у нас, и оно остаётся здесь — но перестаёт стоять на пути юзера:
# он тянет готовые образы. Двери поле не нужно и так (`build.sh`, шаг 2) — ей мешал не склад,
# а необходимость клона.
#
# ЧТО ЗДЕСЬ НЕ ЖИВЁТ:
#
#   · имена образов. Каждое принадлежит СВОЕЙ зоне и берётся из ЕЁ файла запуска — так же,
#     как это делает `build.sh`. Держи мы вторую копию, выпуск однажды опубликовал бы не
#     тот образ, который поднимают, и разъехались бы они молча;
#   · креды. Ни ключа, ни переменной с токеном: в реестр ходит `docker`, а он берёт вход
#     там, где его оставил человек (`docker login`). Токен в аргументе команды — это токен
#     в истории оболочки и в списке процессов. Ключи принадлежат человеку (`WORLD2` 3.0).
#
# ПОСТАВКА КОПИЕЙ НЕ ОТМЕНЯЕТСЯ — и тем более теперь, когда дверь ещё и выпускается.
# `docker save | docker load` остаётся для машин без выхода в реестр: им возит образ двери
# `deploy/remote.sh`. Это два способа доставки одной вещи (`WORLD2` 1.5), а не выбор
# навсегда: появление второго не делает первый лишним — ресурс без реестра никуда не делся.
#
# Имена переменных ЛАТИНСКИЕ: bash не поддерживает не-ASCII в именах переменных и молча
# превращает `ТЕГ=latest` в «команда не найдена». Тексты и комментарии — русские.
set -euo pipefail

# Реестр — значение, а не зашитое слово. Умолчание `ghcr.io` выбрано user'ом 2026-08-15
# (`WORLD2-110`): организация `omnifield` там уже есть, репозиторий публичный, и `docker
# pull` с него идёт без входа — то есть юзеру не нужно ничего, кроме докера.
REGISTRY="${WORLD_REGISTRY:-ghcr.io}"

HERE="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd -- "$HERE/.." && pwd)"
# Каждый образ складывается и называется СВОИМ файлом запуска. Имена спрашиваем у них же —
# и у чужой зоны, и у своей. Своя тут не исключение: копия имени в выпуске разъехалась бы с
# файлом запуска ровно так же, только тише, потому что чинить её было бы «у себя».
WORLD_COMPOSE="$HERE/compose.yaml"
CONTROL_COMPOSE="$ROOT/control/compose.yaml"

dry=

usage() {
    cat <<'USAGE'
Выпуск образов мира и контроллера: ./deploy/release.sh [--dry-run]

  (без ключей)   собрать ОБА образа (deploy/build.sh и deploy/build.sh --control)
                 и опубликовать каждый двумя тегами: latest и sha-<7 знаков коммита>
  --dry-run      показать, что и куда поедет. Ничего не собирается и не
                 публикуется — ни одного изменения ни здесь, ни в реестре.
                 Работает и на ГРЯЗНОМ дереве: он ничего не меняет, а нужен
                 как раз посреди работы — про грязь он скажет вслух
  -h, --help     эта подсказка

ОБРАЗА ДВА, И ВЫПУСКАЮТСЯ ОНИ ВМЕСТЕ. Ключа «только дверь» или «только контроллер»
нет намеренно: предмет выпуска — пара одной сборки, помеченная одним sha-<7>.
Порознь в реестре завелись бы пары, которых никто не собирал вместе.

ЧТО НУЖНО ТОМУ, КТО ВЫПУСКАЕТ (юзеру не нужно ничего из этого):
  · ПОЛЕ — сеть omnifield-gateway со складом probe-web: без него не собрать пульт.
    Нужно оно образу КОНТРОЛЛЕРА; образ мира собирается и без поля, но выпуск
    отдаёт оба сразу — значит поле нужно выпуску целиком;
  · ВХОД В РЕЕСТР — заранее и не нашей командой:
      echo $TOKEN | docker login ghcr.io -u <логин> --password-stdin
    токен — PAT с правом write:packages (сверено с докой GitHub 2026-08-15);
  · ЧИСТОЕ ДЕРЕВО — неподвижный тег называет коммит, и называть он обязан правду.
    Нужно только НАСТОЯЩЕМУ выпуску, не холостому ходу.

КУДА ПУБЛИКУЕМ — решает имя образа, а имена принадлежат зонам (двери — файлу
запуска мира, контроллера — файлу запуска контроллера). Разбор у обоих один:
  · имя БЕЗ реестра (организация/образ) — реестр приписывает WORLD_REGISTRY;
  · имя С реестром (ghcr.io/организация/образ) — публикуем ровно туда: это
    адрес, по которому образ потом ТЯНУТ;
  · названы оба и они разные — отказ. Выбирать за человека, куда отдать вещь
    наружу, нельзя.

Переменные:
  WORLD_REGISTRY=ghcr.io   куда публикуем, если имя реестра не несёт (умолчание ghcr.io)
USAGE
}

while [ $# -gt 0 ]; do
    case "$1" in
        --dry-run)  dry=1 ;;
        -h|--help)  usage; exit 0 ;;
        *)  usage >&2; printf '\nнепонятный ключ: %s\n' "$1" >&2; exit 2 ;;
    esac
    shift
done

step() { printf '\n\033[1m→ %s\033[0m\n' "$*" >&2; }
ok()   { printf '  ✓ %s\n' "$*" >&2; }
warn() { printf '  \033[33m!\033[0m %s\n' "$*" >&2; }

# fail ПРИЧИНА ВЫХОД… — единственный способ выйти с ошибкой. Выход обязателен: отказ без
# следующего действия это диагноз, а не отказ (`kb:WORLD-31`).
fail() {
    local why="$1"; shift
    printf '\n\033[1;31m✗ не выпущено: %s\033[0m\n' "$why" >&2
    local line
    for line in "$@"; do printf '  выход: %s\n' "$line" >&2; done
    exit 1
}

# docker_noconv … — вызов докера, в аргументах которого НЕТ путей хоста. Правило зоны и
# довод целиком — в `build.sh` рядом с таким же помощником.
docker_noconv() { MSYS_NO_PATHCONV=1 MSYS2_ARG_CONV_EXCL='*' docker "$@"; }

# ------------------------------------------------------------------ 1. чем выпускаем
step "чем выпускаем"

command -v docker >/dev/null 2>&1 || fail "докера на машине нет" \
    "поставь Docker Engine: https://docs.docker.com/engine/install/"
command -v git >/dev/null 2>&1 || fail \
    "на машине нет git, а неподвижный тег выводится из коммита" \
    "поставь git — либо выпускай там, где репозиторий полон"
docker info >/dev/null 2>&1 || fail "докер есть, а демон не отвечает" \
    "запусти его: systemctl start docker (либо открой Docker Desktop)"

ok "докер и git на месте"

# ------------------------------------------------------------------ 2. чем метим
# НЕПОДВИЖНЫЙ ТЕГ — `sha-<7 знаков коммита>`, и вот почему именно он.
#
# Версии у продукта пока нет, значит `1.4.2` писать нечем. Из того, что есть, тег обязан
# отвечать на один вопрос: «из чего это собрано». Дата (`2026-08-15`) на него не отвечает —
# два выпуска в один день сольются, а вернуться к исходнику по ней нельзя. Коммит отвечает
# точно: по тегу видно, что именно поехало, и это можно прочитать в репозитории.
# Тот же выбор делает рынок: тег с коммитом кладут в дополнение к остальным (сверено с
# `docker/metadata-action` и обзорами практик тегирования 2026-08-15).
#
# ДЕРЕВО ОБЯЗАНО БЫТЬ ЧИСТЫМ — но только там, где что-то УЕЗЖАЕТ. Тег `sha-abc1234` это
# утверждение «собрано из abc1234»; собери мы из дерева с правками, утверждение станет ложью,
# которую уже не отличить: образ уехал, а по тегу человек прочитает не тот исходник.
#
# ХОЛОСТОЙ ХОД — ДРУГОЕ ДЕЛО, и раньше он отказывал зря. Он не меняет ничего ни здесь, ни в
# реестре, значит чистое дерево ему не нужно; а нужен он чаще всего именно тогда, когда
# дерево грязное — человек в работе и смотрит, что поедет. Отказ на нём вдобавок советовал
# выходом сам себя: холостой ход, который отказал, предлагал сделать холостой ход. Отказ,
# ведущий в себя, — это диагноз, а не отказ (`kb:WORLD-31`). Поэтому здесь грязь только
# НАЗЫВАЕТСЯ вслух, а отказ стоит на настоящем выпуске — ниже развилки.
step "чем метим"

git -C "$ROOT" rev-parse --git-dir >/dev/null 2>&1 || fail \
    "выпуск идёт не из репозитория: в $ROOT нет гита" \
    "неподвижный тег выводится из коммита, а взять его неоткуда" \
    "выпускай из клона репозитория, а не из распакованного архива"

sha="$(git -C "$ROOT" rev-parse --short=7 HEAD 2>/dev/null || true)"
[ -n "$sha" ] || fail \
    "в репозитории нет ни одного коммита — метить нечем" \
    "сделай коммит и повтори выпуск"

dirty="$(git -C "$ROOT" status --porcelain 2>/dev/null || true)"
[ -n "$dirty" ] || ok "дерево чисто, коммит $sha"

# ------------------------------------------------------------------ 3. что и куда
# Имена берём у ЗОН — одним источником с тем, что потом поднимают. У контроллера это чужой
# файл запуска, у двери свой; спрашиваем оба одинаково, и своя зона тут не исключение.
#
# Записать имя сюда «для наглядности» нельзя даже комментарием — и это не придирка: проба
# зоны ищет ЛЮБОЕ его вхождение (сценарии 26e и 29m). Иначе однажды копия окажется не в
# комментарии, а в коде, и разъедется с оригиналом молча.
#
# РАЗБИРАЕМ ИМЯ ЧЕСТНО, а не «приписываем реестр». Прежняя правка приписывала его всегда,
# полагая, что имя реестра не несёт. Допущение живёт до соседней задачи той же истории
# (`WORLD2-112`): контроллеру, который ТЯНЕТ готовое, в `image:` нужен полный адрес — и
# тогда выпуск отдал бы образ в `ghcr.io/ghcr.io/…`. Молча: докер такое имя принимает.
#
# РАЗБОР ОДИН НА ОБА ОБРАЗА — функцией, а не второй копией правил. Развилок в нём три
# (реестр в имени · реестр в переменной · названы оба и разные), и разъезжались бы они по
# одной: у двери починили, у контроллера забыли. Заметил бы это реестр, приняв вещь не туда.
step "что и куда"

# strip_tag — отрезать тег, и только тег. `%%:*` рубило по ПЕРВОМУ двоеточию, а первым
# бывает порт реестра (`registry.local:5000/…`) — от имени оставался огрызок. Тег живёт в
# ПОСЛЕДНЕМ сегменте пути, поэтому и смотрим только на него; двоеточия левее — порт.
strip_tag() {
    local name="$1" last="${1##*/}"
    case "$last" in
        *:*) printf '%s' "${name%:*}" ;;
        *)   printf '%s' "$name" ;;
    esac
}

# has_registry — несёт ли имя адрес реестра. Правило не наше, а докера: первый сегмент
# считается хостом реестра, если это `localhost` либо в нём есть точка или двоеточие;
# иначе он часть пути, и реестр подразумевается (сверено с докой docker/distribution
# 2026-08-15). Своё правило здесь было бы вторым мнением о чужом формате.
has_registry() {
    local head="${1%%/*}"
    [ "$head" = "$1" ] && return 1          # слэша нет вовсе — пути нет, реестра тем более
    case "$head" in
        localhost|*.*|*:*) return 0 ;;
        *)                 return 1 ;;
    esac
}

# razobrat ЗОНА ФАЙЛ-ЗАПУСКА ВЫХОД… — спросить у зоны имя её образа и решить, куда он едет.
#
# Ответ кладётся в `img_local` (что лежит на машине) и `img_published` (что отдаём), а
# словами он назван в `img_naming`. Три значения через глобальные, а не одной строкой с
# разделителем: любой разделитель здесь однажды встретится внутри имени — в нём законны и
# двоеточие (порт реестра), и слэш, — и разбор ответа стал бы четвёртым местом, где имя
# можно испортить.
razobrat() {
    local zone="$1" compose_file="$2"; shift 2
    img_local="$(docker compose -f "$compose_file" config --images 2>/dev/null | head -n1 || true)"
    [ -n "$img_local" ] || fail \
        "у зоны $zone не спросить имя образа: $compose_file не читается" "$@"

    local repo; repo="$(strip_tag "$img_local")"
    if has_registry "$repo"; then
        # Имя уже названо целиком — это адрес, по которому образ будут ТЯНУТЬ. Он и есть
        # истина: публиковать надо ровно туда, откуда потом возьмут.
        img_published="$repo"
        img_naming="реестр взят из имени зоны $zone"
        # Но если реестр назвали ЕЩЁ И нам — молчать нельзя: два источника называют разные
        # места, и любой выбор был бы нашей догадкой о чужом намерении. `${WORLD_REGISTRY+…}`
        # без двоеточия: важно, ЗАДАНА ли переменная, а не пуста ли она.
        if [ -n "${WORLD_REGISTRY+zadano}" ] && [ "${repo%%/*}" != "$REGISTRY" ]; then
            fail "два разных реестра: в имени от зоны $zone — ${repo%%/*}, в WORLD_REGISTRY — $REGISTRY" \
                "выбрать за тебя нельзя: выпуск отдал бы образ не туда, откуда его потом тянут" \
                "либо убери WORLD_REGISTRY и выпускай туда, что названо в $compose_file" \
                "либо назови там имя без реестра — тогда WORLD_REGISTRY решает один"
        fi
    else
        img_published="$REGISTRY/$repo"
        img_naming="реестр приписан: имя от зоны $zone его не несёт"
    fi
}

# Дверь спрашиваем первой — в этом же порядке она потом и уезжает.
razobrat "deploy" "$WORLD_COMPOSE" \
    "проверь, что файл запуска мира на месте: ls $WORLD_COMPOSE" \
    "копии имени в выпуске нет намеренно — оно живёт в файле запуска, и источник один"
world_local="$img_local"; world_published="$img_published"
ok "локально $world_local — дверь"
ok "$img_naming"

razobrat "control" "$CONTROL_COMPOSE" \
    "проверь, что репозиторий полон: ls $ROOT/control" \
    "копии этого имени в зоне deploy нет намеренно — источник один, и он там"
control_local="$img_local"; control_published="$img_published"
ok "локально $control_local — контроллер"
ok "$img_naming"

# Два образа под одним именем — это один образ: второй push лёг бы поверх первого, и в
# реестре осталась бы дверь под именем контроллера либо наоборот. Случай выглядит
# невозможным ровно до первой правки чужого файла запуска, а цена ему — необратимая отдача.
[ "$world_published" != "$control_published" ] || fail \
    "оба образа названы одинаково: $world_published" \
    "второй отдался бы поверх первого, и в реестре осталась бы одна вещь вместо двух" \
    "имена принадлежат зонам: дверь — $WORLD_COMPOSE, контроллер — $CONTROL_COMPOSE"

world_fixed="$world_published:sha-$sha";     world_moving="$world_published:latest"
control_fixed="$control_published:sha-$sha"; control_moving="$control_published:latest"

# ПОРЯДОК ОТДАЧИ — четыре пуша, и идут они не «по одному образу целиком».
#
# Правило прежнее и не изменилось: НЕПОДВИЖНЫЕ УЕЗЖАЮТ ПЕРВЫМИ. Просто теперь их два, и
# оборванный выпуск обязан оставлять в реестре не половину, а пару, на которую можно
# сослаться целиком — `sha-<7>` двери и `sha-<7>` контроллера одной сборки.
#
# ПОДВИЖНЫЕ — ПОСЛЕДНИМИ И ПОДРЯД. `latest` это то, что юзер тянет, ничего не выбирая. Два
# тега реестр одним движением не переставляет, значит пара `latest`-ов неизбежно расходится
# на время, и распоряжаемся мы только ДЛИНОЙ этого окна. Здесь оно в один push; гони мы
# образы по очереди целиком — в окно попала бы ещё и сборка с отдачей неподвижного тега.
#
# А ВНУТРИ ПАРЫ ПЕРВОЙ ИДЁТ ДВЕРЬ. Что хуже: в реестре новый пульт при старой двери или
# новая дверь при старом пульте? Хуже первое, и не поровну. Пульт РАСКЛАДЫВАЕТ двери
# (`WORLD2` 3.7) — юзер тянет его и получает руки, которыми ставит дверь; новый пульт,
# ждущий двери, которой в реестре ещё нет, ломается у юзера, а починить это он не может:
# обе вещи наши. Обратная пара безобидна: старый пульт раскладывает новую дверь ровно так
# же, как делал вчера, — это обычное состояние машины, где обновили одно и не обновили
# другое, и оно чинится следующим `docker pull`.
otdaem=("$world_fixed" "$control_fixed" "$world_moving" "$control_moving")

# Реестров может оказаться ДВА: имя каждого образа называет его само, и совпадать они не
# обязаны. Значит и в совете про вход надо назвать оба, иначе человек залогинится наполовину
# и узнает об этом на третьем push'е — когда два тега уже уехали.
registries="${world_published%%/*}"
[ "${control_published%%/*}" = "$registries" ] || registries="$registries и ${control_published%%/*}"

ok "выпускаем $world_fixed"
ok "и $control_fixed — тот же коммит, одна сборка"
ok "потом подвижные: $world_moving, следом $control_moving"

if [ -n "$dry" ]; then
    cat >&2 <<SUHOY

$(printf '\033[1mпрогон вхолостую — не сделано НИЧЕГО\033[0m')

  собралось бы   ./deploy/build.sh            (шаг 2, без сети и без поля)
                 ./deploy/build.sh --control  (шаг 1 в поле, шаг 3 наружу)
  поехало бы     $world_fixed
                 $control_fixed
                 $world_moving
                 $control_moving
                 порядок именно такой: неподвижные первыми, дверь раньше пульта
  вход в реестр  берётся у докера (docker login $registries), здесь его не заводят
SUHOY
    if [ -n "$dirty" ]; then
        printf '%s\n' "$dirty" | head -n 10 >&2
        cat >&2 <<GRYAZNO

$(printf '\033[33m! дерево не чисто — настоящий выпуск на нём ОТКАЖЕТ\033[0m')
  тег выше выведен из HEAD и описывает НЕ то, что лежит в дереве: правки выше в выпуск
  не поехали бы — их сначала коммитят.
GRYAZNO
    fi
    printf '\n  выпустить по-настоящему: ./deploy/release.sh\n' >&2
    exit 0
fi

# Отсюда что-то УЕЗЖАЕТ — и вот теперь грязное дерево это отказ, а не предупреждение.
if [ -n "$dirty" ]; then
    printf '%s\n' "$dirty" | head -n 10 >&2
    fail "дерево не чисто — тег назвал бы коммит, из которого собрано НЕ ЭТО" \
        "закоммить или убери правки, потом повтори: ./deploy/release.sh" \
        "посмотреть целиком: git -C $ROOT status" \
        "поглядеть, что поехало бы, можно и на грязном: ./deploy/release.sh --dry-run"
fi

# ------------------------------------------------------------------ 4. собираем
# Собираем ВСЕГДА и своей же сборкой. Опубликовать то, что лежит, было бы дешевле — и было
# бы ложью: тег называет коммит, а лежать может образ, собранный вчера из другого. Проверить
# это снаружи нечем, значит устранять надо саму возможность, а не предупреждать о ней.
#
# И СОБИРАЕМ ОБА ДО ПЕРВОЙ ОТДАЧИ. Соблазн «собрал дверь — отдал дверь — собрал контроллер»
# экономит минуту и стоит выпуска: сборка контроллера падает чаще всех — ей единственной
# нужно поле, — и упади она после отдачи двери, в реестре осталась бы половина пары,
# отданная молча. Оборванная сборка не оставляет следа снаружи, оборванная отдача оставляет.
#
# Порядок сборки тот же, что порядок отдачи, и второго правила в голове держать не надо:
# до отдачи дело всё равно не доходит, пока не собрано оба.
step "собираю образ мира — deploy/build.sh"
"$HERE/build.sh" >&2 || fail \
    "образ мира не собрался — не отдано ничего" \
    "причина названа выше: её печатает сама сборка" \
    "поля этому шагу не нужно вовсе — он компилирует Go без сети"

step "собираю контроллер — deploy/build.sh --control"
"$HERE/build.sh" --control >&2 || fail \
    "образ контроллера не собрался — не отдано ничего, в том числе дверь" \
    "причина названа выше: её печатает сама сборка" \
    "чаще всего это склад пульта: шагу 1 нужно поле (сеть omnifield-gateway)" \
    "образ мира при этом собран и лежит на машине — но выпуск отдаёт пару, а не половину"

# ------------------------------------------------------------------ 5. метим и отдаём
# Реестр в сообщениях называем ТОТ, куда едем на самом деле, а не значение переменной: имя
# могло прийти с реестром от своей зоны, и совет «залогинься в WORLD_REGISTRY» отправил бы
# человека входить не туда. У каждого тега свой — берём из него же (`${t%%/*}`).
step "метим и отдаю в $registries"

# pometit ЛОКАЛЬНОЕ-ИМЯ ТЕГ… — пометить один образ всеми его тегами.
pometit() {
    local src="$1"; shift
    local t
    for t in "$@"; do
        docker_noconv tag "$src" "$t" || fail \
            "не пометить $src как $t" \
            "имя реестра или образа не годится докеру — посмотри на него целиком выше" \
            "реестр крутится значением: WORLD_REGISTRY=<реестр> ./deploy/release.sh — но если имя от зоны несёт реестр само, решает оно"
    done
}

# Метим ОБА до первого push'а — по той же причине, по которой собираем оба: негодное имя
# должно останавливать выпуск, пока в реестр не ушло ничего.
pometit "$world_local"   "$world_fixed"   "$world_moving"
pometit "$control_local" "$control_fixed" "$control_moving"
ok "метки поставлены — по две на каждый образ"

# Порядок — тот, что собран выше в `otdaem`: неподвижные первыми, дверь раньше пульта.
# Довод целиком — там же, рядом со сборкой списка.
for t in "${otdaem[@]}"; do
    step "отдаю $t"
    docker_noconv push "$t" >&2 || fail \
        "$t не отдался в реестр" \
        "вход в реестр берёт докер, а не мы: echo \$TOKEN | docker login ${t%%/*} -u <логин> --password-stdin" \
        "токену нужно право write:packages (сверено с докой GitHub 2026-08-15)" \
        "denied/403 при верном входе — у логина нет прав на организацию, в которой лежит ${t%:*}" \
        "теги выше уже могли уехать: посмотри, что в реестре, прежде чем повторять" \
        "повторять можно смело: выпуск отдаёт ту же пару целиком, а не половину"
    ok "$t в реестре"
done

# ------------------------------------------------------------------ куда смотреть
# Digest печатаем не для красоты: ТОЛЬКО ОН неизменен по-настоящему. Теги — подвижные
# указатели, и `sha-…` неподвижен нашим уговором, а не запретом реестра (сверено
# 2026-08-15). Кому нужна ссылка, которую нельзя перебить, — берёт отсюда. Спрашиваем у
# обоих образов: пара без второго digest'а — это половина ссылки.
digest_mir="$(docker image inspect --format '{{if .RepoDigests}}{{index .RepoDigests 0}}{{end}}' "$world_fixed" 2>/dev/null || true)"
digest_pult="$(docker image inspect --format '{{if .RepoDigests}}{{index .RepoDigests 0}}{{end}}' "$control_fixed" 2>/dev/null || true)"

cat >&2 <<GOTOVO

$(printf '\033[1;32m✓ выпущено — ОБА образа, один коммит\033[0m')

  дверь         $world_fixed
                $world_moving
  ${digest_mir:+по digest    $digest_mir}
  контроллер    $control_fixed
                $control_moving
  ${digest_pult:+по digest    $digest_pult}

  Неподвижный тег у обоих ОДИН (sha-$sha) — по нему видно, что дверь и пульт одной сборки.

  ЮЗЕР ТЯНЕТ ЭТО БЕЗ ВХОДА В РЕЕСТР — и проверить это надо СВОИМИ РУКАМИ, а не поверить:
    docker logout $registries
    docker pull $control_moving
    docker pull $world_moving

  ПЕРВЫЙ выпуск создаёт ПРИВАТНЫЙ пакет — таково умолчание GitHub (сверено 2026-08-15).
  Пакетов теперь ДВА, и открывать надо оба: пока пакет не открыт в его настройках, у юзера
  pull упрётся в denied, и выглядеть это будет как «образа нет». Открывается один раз,
  руками, хозяином организации.

  поднять у себя: ./control/up.sh   (как он берёт готовый образ — зона control)
GOTOVO

# │ `latest`. Выпуск спрашивает имя у того же файла и правильно делает: своей копии имени │
# │ у него нет. Но подстановка, задуманная для ЧТЕНИЯ («что поднять»), становилась при    │
# │ этом рулём для ЗАПИСИ («куда отдать наружу»): хватало одной переменной, оставшейся в  │
# │ оболочке после отладки подъёма. Публикация НЕОБРАТИМА — опубликованное уже скачали, — │
# │ а ни одна проверка тут не срабатывает: имя валидное, дерево чистое, реестр отвечает.  │
# │                                                                                       │
# │ ЧИНИТСЯ НЕ ПОИМЁННО. Заткни мы переменную одной зоны по имени — то же самое вернулось │
# │ бы через соседнюю, а список имён в этом файле был бы тем же дефектом с другой стороны:│
# │ он молча устаревает, и узнаём мы об этом в реестре. Поэтому спрашиваем у САМОГО ФАЙЛА,│
# │ какие подстановки в нём есть, и читаем его в окружении БЕЗ НИХ.                        │
# └──────────────────────────────────────────────────────────────────────────────────────┘

# СВЕРКА С РЫНКОМ 2026-08-17 — прежде чем делать это руками, спросили у докера.
# Смотрели доку `docker compose config` и дискуссии о подстановках:
#   · `--no-interpolate` — отдал бы файл без подстановок, и это выглядело решением. НЕ БЕРЁМ:
#     с умолчаниями он врёт — `${VAR:-DEFAULT}` печатается обрубком `${VAR` (docker/compose
#     issue 13327). То есть имя образа пришло бы битым;
#   · `--variables` — печатает переменные модели и их умолчания, и по духу это ровно то, что
#     нам нужно: спросить у компоуза, а не разбирать формат самим. НЕ БЕРЁМ ПОКА: состав
#     вывода в доке не описан, с какой версии он есть — тоже, а проверить здесь нечем
#     (докера в девбоксе нет вовсе). Промах разбора дал бы ПУСТОЙ список имён — то есть
#     тихо вернул бы дефект, а не отказ. Появится проверяемый живой докер — это первый
#     кандидат заменить сбор имён ниже;
#   · заставить компоуз не смотреть в окружение нельзя вовсе: оболочка старше `--env-file`
#     и `.env` по его же правилам приоритета.
# Отсюда раскладка: ИМЕНА собираем сами (узкая, проверяемая работа), а ЗНАЧЕНИЯ и умолчания
# по-прежнему разбирает компоуз — своего мнения о его формате мы не держим.
#
# podstanovki ФАЙЛ — имена подстановок, которые в файле встречаются. Не значения и не
# умолчания: разбирать `${VAR:-…}` за компоуз мы не станем — это его формат и его работа,
# а второе мнение о чужом формате однажды разойдётся с первым. Здесь берутся только ИМЕНА,
# и берутся с запасом: попадёт имя из комментария — ну и пусть, лишнее снятое значение имя
# образа изменить не может, а пропущенное — может. Единственное, чем запас может выйти
# наружу, — имена, которыми живёт сам докер (`PATH`, `HOME`): помяни их чужой файл запуска, и
# чтение имени ОТКАЖЕТ вслух, назвав слова компоуза. Это дороже, чем промолчать, но дешевле,
# чем опубликовать не туда.
# `$$` в компоузе означает буквальный `$` и подстановкой не является — потому и стирается.
podstanovki() {
    sed 's/\$\$//g' "$1" 2>/dev/null \
        | grep -oE '\$\{?[A-Za-z_][A-Za-z0-9_]*' \
        | sed 's/^\$[{]\{0,1\}//' \
        | sort -u
}

# obyazatelnye ФАЙЛ — те подстановки, у которых нет умолчания: `${VAR:?…}` и `${VAR?…}`.
# Без значения компоуз такой файл не читает ВОВСЕ — ни `config`, ни `build`, — и это его
# право: так зона `share` требует пароль (`WORLD2-132`). Выпуску пароль не нужен ни для
# чего, но без него он не узнает и имени образа. Поэтому таким подстановкам подставляется
# заведомо непригодное значение: спросить имя оно даёт, а сойти за настоящее не может.
# Ровно так же поступает сосед в своей зоне, когда СНИМАЕТ раздачу (`share/up.sh`).
obyazatelnye() {
    sed 's/\$\$//g' "$1" 2>/dev/null \
        | grep -oE '\$\{[A-Za-z_][A-Za-z0-9_]*:?\?' \
        | sed 's/^\${//; s/:\{0,1\}?$//' \
        | sort -u
}

ZATYCHKA='vypusk-znachenij-ne-nazyvaet'

# umolchanie_zony ФАЙЛ — имя образа, каким его объявляет САМ файл запуска.
# Читается в дочернем окружении, из которого сняты все подстановки этого файла: что бы ни
# лежало в оболочке человека, компоуз ответит умолчанием — тем самым, которое получит юзер.
umolchanie_zony() {
    local file="$1"
    (
        local v
        while read -r v; do [ -n "$v" ] && unset "$v"; done < <(podstanovki "$file")
        while read -r v; do [ -n "$v" ] && export "$v=$ZATYCHKA"; done < <(obyazatelnye "$file")
        docker compose -f "$file" config --images 2>"$OSHIBKA"
    )
}

# kak_v_okruzhenii ФАЙЛ — что тот же файл отвечает СЕЙЧАС, с окружением как есть. Нужно не
# для публикации, а чтобы человек услышал: его окружение уводит выпуск в другое имя.
#
# Заданное человеком здесь не трогается — в том и вопрос, что он задал. Затыкается ровно то
# же, что и в чтении умолчания: подстановки БЕЗ УМОЛЧАНИЯ и только пустые. Иначе зона,
# требующая значение, второго мнения не давала бы вовсе — и увод её переменной проходил бы
# молча ровно там, где у остальных он ловится.
# Не прочиталось — молчим: это не отказ, а отсутствие второго мнения.
kak_v_okruzhenii() {
    local file="$1"
    (
        local v
        while read -r v; do
            [ -n "$v" ] && export "$v=${!v:-$ZATYCHKA}"
        done < <(obyazatelnye "$file")
        docker compose -f "$file" config --images 2>/dev/null
    ) || true
}


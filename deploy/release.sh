    "$HERE/build.sh" ${klyuchi[$i]:+"${klyuchi[$i]}"} >&2 || fail \
        "образ (${zovem[$i]}) не собрался — не отдано ничего" \
        "причина названа выше: её печатает сама сборка" \
        "${pochemu[$i]}" \
        "остальные образы при этом могли собраться — но выпуск отдаёт набор, а не часть"
done

# ------------------------------------------------------------------ 4b. сверяю штамп с тегом
# ОДИН ИСТОЧНИК — ХОРОШО, А ПРОВЕРЯТЬ НАДО ТО, ЧТО ПОЛУЧИЛОСЬ.
#
# Версия живёт в одном месте (`version.sh`), и разъехаться теперь «не должно». Но именно так
# выглядят все дорогие ошибки: обе стороны считают себя правыми. Здесь цена расхождения —
# необратимая публикация и юзер, которому контроллер одной сборки ставит дверь другой, а
# отличить это снаружи нечем: тег `sha-abc1234` и штамп `sha-9999999` оба выглядят правдой.
#
# СПРАШИВАЕМ У ОБРАЗА ТО ЖЕ, ЧТО ПРОЧТЁТ КОНТРОЛЛЕР, — переменную `WORLD_VERSION` из его
# описания. Не метку и не свою запись рядом: контроллер читает СВОЁ ОКРУЖЕНИЕ, и проверять
# надо ровно то значение, по которому он потом будет пинить вещи (`WORLD2-130`).
#
# ПУСТОЙ ШТАМП — ТОЖЕ РАСХОЖДЕНИЕ, и отдельный отказ. Образ без штампа собран не выпуском;
# опубликуй мы его под тегом версии, тег утверждал бы то, чего образ о себе не знает, а
# контроллер, поднятый им, честно сказал бы «версии не знаю» и взял `latest` — то есть
# гарантия тройки одной сборки кончилась бы молча на первом же подъёме.
step "сверяю штамп с тегом"

# shtamp_obraza ИМЯ — что образ говорит о себе САМ. Пусто — не говорит ничего.
shtamp_obraza() {
    local vse mnogo
    vse="$(docker image inspect --format '{{range .Config.Env}}{{println .}}{{end}}' "$1" 2>/dev/null || true)"
    mnogo="$(printf '%s\n' "$vse" | sed -n 's/^WORLD_VERSION=//p')"
    printf '%s' "${mnogo%%$'\n'*}"
}

for i in 0 1 2; do
    shtamp="$(shtamp_obraza "${lokalno[$i]}")"
    [ -n "$shtamp" ] || fail \
        "образ «${zovem[$i]}» (${lokalno[$i]}) не знает своей версии — штампа в нём нет" \
        "тег назвал бы $versiya, а сам образ о себе не знает ничего: опубликованное утверждало бы больше, чем правда" \
        "штамп вписывает сборка (deploy/build.sh); проверь её вывод выше — там сказано, почему версии не было" \
        "посмотреть руками: docker image inspect --format '{{.Config.Env}}' ${lokalno[$i]}"
    [ "$shtamp" = "$versiya" ] || fail \
        "штамп и тег разъехались: образ «${zovem[$i]}» говорит $shtamp, а тег назвал бы $versiya" \
        "это ровно тот случай, ради которого версия считается в одном месте (deploy/version.sh)" \
        "чаще всего это старый образ, оставшийся от прошлой сборки: пересобери и повтори" \
        "не отдано ничего — в реестр не ушло ни одного вызова"
    ok "${zovem[$i]}: штамп $shtamp — тот же, что тег"
done

# ------------------------------------------------------------------ 5. метим и отдаём
# Реестр в сообщениях называем ТОТ, куда едем на самом деле, а не значение переменной: имя
# могло прийти с реестром от своей зоны, и совет «залогинься в WORLD_REGISTRY» отправил бы
# человека входить не туда. У каждого тега свой — берём из него же (`${t%%/*}`).
step "метим и отдаю в $registries"

# pometit ЛОКАЛЬНОЕ-ИМЯ ТЕГ… — пометить один образ всеми его тегами.
pometit() {
    local src="$1"; shift
    local t
    for t in "$@"; do
        docker_noconv tag "$src" "$t" || fail \
            "не пометить $src как $t" \
            "имя реестра или образа не годится докеру — посмотри на него целиком выше" \
            "реестр крутится значением: WORLD_REGISTRY=<реестр> ./deploy/release.sh — но если имя от зоны несёт реестр само, решает оно"
    done
}

# Метим ВСЕ ТРИ до первого push'а — по той же причине, по которой собираем все три: негодное
# имя должно останавливать выпуск, пока в реестр не ушло ничего.
for i in 0 1 2; do
    pometit "${lokalno[$i]}" "${publikuem[$i]}:$versiya" "${publikuem[$i]}:latest"
done
ok "метки поставлены — по две на каждый из трёх образов"

# Порядок — тот, что собран выше в `otdaem`: неподвижные первыми, пульт последним.
# Довод целиком — там же, рядом со сборкой списка.
for t in "${otdaem[@]}"; do
    step "отдаю $t"
    docker_noconv push "$t" >&2 || fail \
        "$t не отдался в реестр" \
        "вход в реестр берёт докер, а не мы: echo \$TOKEN | docker login ${t%%/*} -u <логин> --password-stdin" \
        "токену нужно право write:packages (сверено с докой GitHub 2026-08-15)" \
        "denied/403 при верном входе — у логина нет прав на организацию, в которой лежит ${t%:*}" \
        "теги выше уже могли уехать: посмотри, что в реестре, прежде чем повторять" \
        "повторять можно смело: выпуск отдаёт тот же набор целиком, а не часть"
    ok "$t в реестре"
done

# ------------------------------------------------------------------ куда смотреть
# Digest печатаем не для красоты: ТОЛЬКО ОН неизменен по-настоящему. Теги — подвижные
# указатели, и `sha-…` неподвижен нашим уговором, а не запретом реестра (сверено
# 2026-08-15). Кому нужна ссылка, которую нельзя перебить, — берёт отсюда. Спрашиваем у
# ВСЕХ ТРЁХ: набор без одного digest'а — это часть ссылки.
svodka=""
for i in 0 1 2; do
    d="$(docker image inspect --format '{{if .RepoDigests}}{{index .RepoDigests 0}}{{end}}' "${publikuem[$i]}:$versiya" 2>/dev/null || true)"
    svodka="$svodka  ${zovem[$i]}"$'\n'
    svodka="$svodka    ${publikuem[$i]}:$versiya"$'\n'
    svodka="$svodka    ${publikuem[$i]}:latest"$'\n'
    [ -n "$d" ] && svodka="$svodka    по digest  $d"$'\n'
done

cat >&2 <<GOTOVO

$(printf '\033[1;32m✓ выпущено — ВСЕ ТРИ образа, один коммит\033[0m')

$svodka
  Неподвижный тег у всех трёх ОДИН ($versiya) — по нему видно, что они одной сборки.

  ЮЗЕР ТЯНЕТ ЭТО БЕЗ ВХОДА В РЕЕСТР — и проверить это надо СВОИМИ РУКАМИ, а не поверить:
    docker logout $registries
    docker pull ${otdaem[3]}
    docker pull ${otdaem[4]}
    docker pull ${otdaem[5]}

  ПЕРВЫЙ выпуск создаёт ПРИВАТНЫЙ пакет — таково умолчание GitHub (сверено 2026-08-15).
  Пакетов теперь ТРИ, и открывать надо все: пока пакет не открыт в его настройках, у юзера
  pull упрётся в denied, и выглядеть это будет как «образа нет». Открывается один раз,
  руками, хозяином организации.

  поднять у себя: ./control/up.sh   (как он берёт готовый образ — зона control)
GOTOVO

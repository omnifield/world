    "образ ($zovem) не собрался — не отдано ничего" \
    "причина названа выше: её печатает сама сборка" \
    "$pochemu"

# ------------------------------------------------------------------ 4b. сверяю штамп с тегом
# ОДИН ИСТОЧНИК — ХОРОШО, А ПРОВЕРЯТЬ НАДО ТО, ЧТО ПОЛУЧИЛОСЬ.
#
# Версия живёт в одном месте (`version.sh`) и считается по одному перечню (`sostav.sh`), и
# разъехаться теперь «не должно». Но именно так выглядят все дорогие ошибки: обе стороны
# считают себя правыми. Здесь цена расхождения — необратимая публикация, а отличить это
# снаружи нечем: тег `sha-abc1234` и штамп `sha-9999999` оба выглядят правдой.
#
# СПРАШИВАЕМ У ОБРАЗА ТО ЖЕ, ЧТО ПРОЧТЁТ КОНТРОЛЛЕР, — переменную `WORLD_VERSION` из его
# описания. Не метку и не свою запись рядом: вещь читает СВОЁ ОКРУЖЕНИЕ, и проверять надо
# ровно то значение, которым она потом назовёт себя (`WORLD2-130`).
#
# ПУСТОЙ ШТАМП — ТОЖЕ РАСХОЖДЕНИЕ, и отдельный отказ. Образ без штампа собран не выпуском;
# опубликуй мы его под тегом версии, тег утверждал бы то, чего образ о себе не знает.
#
# СВЕРКА СТОИТ ДО ПЕРВОГО `push` И ОСТАЁТСЯ ЗДЕСЬ (`WORLD2-146` прямо это оговаривает):
# раздельная публикация сняла общий тег, но не сняла вопроса «а тот ли это образ».
step "сверяю штамп с тегом"

# shtamp_obraza ИМЯ — что образ говорит о себе САМ. Пусто — не говорит ничего.
shtamp_obraza() {
    local vse mnogo
    vse="$(docker image inspect --format '{{range .Config.Env}}{{println .}}{{end}}' "$1" 2>/dev/null || true)"
    mnogo="$(printf '%s\n' "$vse" | sed -n 's/^WORLD_VERSION=//p')"
    printf '%s' "${mnogo%%$'\n'*}"
}

shtamp="$(shtamp_obraza "$lokalno")"
[ -n "$shtamp" ] || fail \
    "образ «$zovem» ($lokalno) не знает своей версии — штампа в нём нет" \
    "тег назвал бы $versiya, а сам образ о себе не знает ничего: опубликованное утверждало бы больше, чем правда" \
    "штамп вписывает сборка (deploy/build.sh); проверь её вывод выше — там сказано, почему версии не было" \
    "посмотреть руками: docker image inspect --format '{{.Config.Env}}' $lokalno"
[ "$shtamp" = "$versiya" ] || fail \
    "штамп и тег разъехались: образ «$zovem» говорит $shtamp, а тег назвал бы $versiya" \
    "это ровно тот случай, ради которого версия считается в одном месте (deploy/version.sh) по одному перечню (deploy/sostav.sh)" \
    "чаще всего это старый образ, оставшийся от прошлой сборки: пересобери и повтори" \
    "не отдано ничего — в реестр не ушло ни одного вызова"
ok "$zovem: штамп $shtamp — тот же, что тег"

# ------------------------------------------------------------------ 5. метим и отдаём
# Реестр в сообщениях называем ТОТ, куда едем на самом деле, а не значение переменной: имя
# могло прийти с реестром от своей зоны, и совет «залогинься в WORLD_REGISTRY» отправил бы
# человека входить не туда.
step "метим и отдаю в $registry_addr"

# Метим ОБА тега до первого push'а: негодное имя должно останавливать выпуск, пока в реестр
# не ушло ничего.
for t in "${otdaem[@]}"; do
    docker_noconv tag "$lokalno" "$t" || fail \
        "не пометить $lokalno как $t" \
        "имя реестра или образа не годится докеру — посмотри на него целиком выше" \
        "реестр крутится значением: WORLD_REGISTRY=<реестр> ./deploy/release.sh --$obraz — но если имя от зоны несёт реестр само, решает оно"
done
ok "метки поставлены — две на один образ"

# Порядок — тот, что собран выше в `otdaem`: неподвижный первым.
for t in "${otdaem[@]}"; do
    step "отдаю $t"
    docker_noconv push "$t" >&2 || fail \
        "$t не отдался в реестр" \
        "вход в реестр берёт докер, а не мы: echo \$TOKEN | docker login ${t%%/*} -u <логин> --password-stdin" \
        "токену нужно право write:packages (сверено с докой GitHub 2026-08-15)" \
        "denied/403 при верном входе — у логина нет прав на организацию, в которой лежит ${t%:*}" \
        "неподвижный тег мог уже уехать: посмотри, что в реестре, прежде чем повторять" \
        "повторять можно смело: выпуск отдаёт тот же образ целиком, а не часть"
    ok "$t в реестре"
done

# ------------------------------------------------------------------ куда смотреть
# Digest печатаем не для красоты: ТОЛЬКО ОН неизменен по-настоящему. Теги — подвижные
# указатели, и `sha-…` неподвижен нашим уговором, а не запретом реестра (сверено
# 2026-08-15). Кому нужна ссылка, которую нельзя перебить, — берёт отсюда.
d="$(docker image inspect --format '{{if .RepoDigests}}{{index .RepoDigests 0}}{{end}}' "${otdaem[0]}" 2>/dev/null || true)"

cat >&2 <<GOTOVO

$(printf '\033[1;32m✓ выпущен ОДИН образ — %s\033[0m' "$zovem")

  ${otdaem[0]}
  ${otdaem[1]}$([ -n "$d" ] && printf '\n  по digest  %s' "$d")

  Версия у этого образа СВОЯ и выведена по тому, что в него едет, — не по HEAD репозитория.
  У соседних образов она другая, и это не рассогласование, а устройство (WORLD2-146):
  стык между вещами держит форма, а не общий тег.

  ЮЗЕР ТЯНЕТ ЭТО БЕЗ ВХОДА В РЕЕСТР — и проверить это надо СВОИМИ РУКАМИ, а не поверить:
    docker logout $registry_addr
    docker pull ${otdaem[1]}

  ПЕРВЫЙ выпуск образа создаёт ПРИВАТНЫЙ пакет — таково умолчание GitHub (сверено

# │ Зоны крутят своё имя подстановкой — ею поднимают НАЗВАННЫЙ выпуск вместо подвижного   │
# │ `latest`. Выпуск спрашивает имя у того же файла и правильно делает: своей копии имени │
# │ у него нет. Но подстановка, задуманная для ЧТЕНИЯ («что поднять»), становилась при    │
# │ этом рулём для ЗАПИСИ («куда отдать наружу»): хватало одной переменной, оставшейся в  │
# │ оболочке после отладки подъёма. Публикация НЕОБРАТИМА — опубликованное уже скачали, — │
# │ а ни одна проверка тут не срабатывает: имя валидное, дерево чистое, реестр отвечает.  │
# │                                                                                       │
# │ ЧИНИТСЯ НЕ ПОИМЁННО. Заткни мы переменную зоны `control` по имени — то же самое       │
# │ вернулось бы через `share`, а список имён в этом файле был бы тем же дефектом с       │
# │ другой стороны: он молча устаревает, и узнаём мы об этом в реестре. Поэтому спрашиваем│
# │ у САМОГО ФАЙЛА, какие подстановки в нём есть, и читаем его в окружении БЕЗ НИХ.       │
# └──────────────────────────────────────────────────────────────────────────────────────┘

# СВЕРКА С РЫНКОМ 2026-08-17 — прежде чем делать это руками, спросили у докера.
# Смотрели доку `docker compose config` и дискуссии о подстановках:
#   · `--no-interpolate` — отдал бы файл без подстановок, и это выглядело решением. НЕ БЕРЁМ:
#     с умолчаниями он врёт — `${VAR:-DEFAULT}` печатается обрубком `${VAR` (docker/compose
#     issue 13327). То есть имя образа пришло бы битым;
#   · `--variables` — печатает переменные модели и их умолчания, и по духу это ровно то, что
#     нам нужно: спросить у компоуза, а не разбирать формат самим. НЕ БЕРЁМ ПОКА: состав
#     вывода в доке не описан, с какой версии он есть — тоже, а проверить здесь нечем
#     (докера в девбоксе нет вовсе). Промах разбора дал бы ПУСТОЙ список имён — то есть
#     тихо вернул бы дефект, а не отказ. Появится проверяемый живой докер — это первый
#     кандидат заменить сбор имён ниже;
#   · заставить компоуз не смотреть в окружение нельзя вовсе: оболочка старше `--env-file`
#     и `.env` по его же правилам приоритета.
# Отсюда раскладка: ИМЕНА собираем сами (узкая, проверяемая работа), а ЗНАЧЕНИЯ и умолчания
# по-прежнему разбирает компоуз — своего мнения о его формате мы не держим.
#
# podstanovki ФАЙЛ — имена подстановок, которые в файле встречаются. Не значения и не
# умолчания: разбирать `${VAR:-…}` за компоуз мы не станем — это его формат и его работа,
# а второе мнение о чужом формате однажды разойдётся с первым. Здесь берутся только ИМЕНА,
# и берутся с запасом: попадёт имя из комментария — ну и пусть, лишнее снятое значение имя
# образа изменить не может, а пропущенное — может. Единственное, чем запас может выйти
# наружу, — имена, которыми живёт сам докер (`PATH`, `HOME`): помяни их чужой файл запуска, и
# чтение имени ОТКАЖЕТ вслух, назвав слова компоуза. Это дороже, чем промолчать, но дешевле,
# чем опубликовать не туда.
# `$$` в компоузе означает буквальный `$` и подстановкой не является — потому и стирается.
podstanovki() {
    sed 's/\$\$//g' "$1" 2>/dev/null \
        | grep -oE '\$\{?[A-Za-z_][A-Za-z0-9_]*' \
        | sed 's/^\$[{]\{0,1\}//' \
        | sort -u
}

# obyazatelnye ФАЙЛ — те подстановки, у которых нет умолчания: `${VAR:?…}` и `${VAR?…}`.
# Без значения компоуз такой файл не читает ВОВСЕ — ни `config`, ни `build`, — и это его
# право: так зона `share` требует пароль (`WORLD2-132`). Выпуску пароль не нужен ни для
# чего, но без него он не узнает и имени образа. Поэтому таким подстановкам подставляется
# заведомо непригодное значение: спросить имя оно даёт, а сойти за настоящее не может.
# Ровно так же поступает сосед в своей зоне, когда СНИМАЕТ раздачу (`share/up.sh`).
obyazatelnye() {
    sed 's/\$\$//g' "$1" 2>/dev/null \
        | grep -oE '\$\{[A-Za-z_][A-Za-z0-9_]*:?\?' \
        | sed 's/^\${//; s/:\{0,1\}?$//' \
        | sort -u
}

ZATYCHKA='vypusk-znachenij-ne-nazyvaet'

# umolchanie_zony ФАЙЛ — имя образа, каким его объявляет САМ файл запуска.
# Читается в дочернем окружении, из которого сняты все подстановки этого файла: что бы ни
# лежало в оболочке человека, компоуз ответит умолчанием — тем самым, которое получит юзер.
umolchanie_zony() {
    local file="$1"
    (
        local v
        while read -r v; do [ -n "$v" ] && unset "$v"; done < <(podstanovki "$file")
        while read -r v; do [ -n "$v" ] && export "$v=$ZATYCHKA"; done < <(obyazatelnye "$file")
        docker compose -f "$file" config --images 2>"$OSHIBKA"
    )
}

# kak_v_okruzhenii ФАЙЛ — что тот же файл отвечает СЕЙЧАС, с окружением как есть. Нужно не
# для публикации, а чтобы человек услышал: его окружение уводит выпуск в другое имя.
#
# Заданное человеком здесь не трогается — в том и вопрос, что он задал. Затыкается ровно то
# же, что и в чтении умолчания: подстановки БЕЗ УМОЛЧАНИЯ и только пустые. Иначе зона,
# требующая значение, второго мнения не давала бы вовсе — и увод её переменной проходил бы
# молча ровно там, где у остальных двух он ловится.
# Не прочиталось — молчим: это не отказ, а отсутствие второго мнения.
kak_v_okruzhenii() {
    local file="$1"
    (
        local v
        while read -r v; do
            [ -n "$v" ] && export "$v=${!v:-$ZATYCHKA}"
        done < <(obyazatelnye "$file")
        docker compose -f "$file" config --images 2>/dev/null
    ) || true
}

# razobrat НОМЕР — спросить у зоны имя её образа и решить, куда он едет. Ответ кладётся в
# `lokalno[НОМЕР]` (что лежит на машине) и `publikuem[НОМЕР]` (что отдаём). Массивы, а не
# строка с разделителем: любой разделитель здесь однажды встретится внутри имени — в нём
# законны и двоеточие (порт реестра), и слэш.
lokalno=(); publikuem=(); uvod=()
razobrat() {
    local i="$1" zone="${zony[$i]}" file="${faily[$i]}"
    local vse img

    vse="$(umolchanie_zony "$file")" || vse=
    img="${vse%%$'\n'*}"
    [ -n "$img" ] || fail \
        "у зоны $zone не спросить имя образа: $file не читается" \
        "проверь, что репозиторий полон и файл на месте: ls $file" \
        "копии имени в выпуске нет намеренно — оно живёт в файле запуска зоны, источник один" \
        "компоуз сказал: $(head -n2 "$OSHIBKA" 2>/dev/null | tr '\n' ' ')"

    # Второе мнение — окружение. Разошлось с файлом, значит переменная зоны решает, куда
    # публиковать; отказ (или, на холостом ходу, слово вслух) ждёт ниже, все зоны разом.
    local seychas="$(kak_v_okruzhenii "$file")"
    seychas="${seychas%%$'\n'*}"
    if [ -n "$seychas" ] && [ "$seychas" != "$img" ]; then
        local zadano=""
        local v
        while read -r v; do
            [ -n "$v" ] && [ -n "${!v+zadano}" ] && zadano="${zadano:+$zadano }$v"
        done < <(podstanovki "$file")
        uvod+=("зона $zone: файл называет $img, окружение — $seychas${zadano:+ (задано у тебя: $zadano)}")
    fi

    local repo; repo="$(strip_tag "$img")"
    if has_registry "$repo"; then
        # Имя уже названо целиком — это адрес, по которому образ будут ТЯНУТЬ. Он и есть
        # истина: публиковать надо ровно туда, откуда потом возьмут.
        publikuem[$i]="$repo"
        ok "локально $img — ${zovem[$i]}"
        ok "реестр взят из имени зоны $zone"
        # Но если реестр назвали ЕЩЁ И нам — молчать нельзя: два источника называют разные
        # места, и любой выбор был бы нашей догадкой о чужом намерении. `${WORLD_REGISTRY+…}`
        # без двоеточия: важно, ЗАДАНА ли переменная, а не пуста ли она.
        if [ -n "${WORLD_REGISTRY+zadano}" ] && [ "${repo%%/*}" != "$REGISTRY" ]; then
            fail "два разных реестра: в имени от зоны $zone — ${repo%%/*}, в WORLD_REGISTRY — $REGISTRY" \
                "выбрать за тебя нельзя: выпуск отдал бы образ не туда, откуда его потом тянут" \
                "либо убери WORLD_REGISTRY и выпускай туда, что названо в $file" \
                "либо назови там имя без реестра — тогда WORLD_REGISTRY решает один"
        fi
    else
        publikuem[$i]="$REGISTRY/$repo"
        ok "локально $img — ${zovem[$i]}"
        ok "реестр приписан: имя от зоны $zone его не несёт"
    fi
    lokalno[$i]="$img"
}

for i in 0 1 2; do razobrat "$i"; done

# Два образа под одним именем — это один образ: второй push лёг бы поверх первого, и в
# реестре осталась бы дверь под именем контроллера либо наоборот. Случай выглядит
# невозможным ровно до первой правки чужого файла запуска, а цена ему — необратимая отдача.
# Сравниваем ВСЕ ПАРЫ, а не соседей по списку: совпасть могут любые двое из трёх.
for i in 0 1 2; do
    for j in 0 1 2; do
        [ "$i" -lt "$j" ] || continue
        [ "${publikuem[$i]}" != "${publikuem[$j]}" ] || fail \
            "образы ${zovem[$i]} и ${zovem[$j]} названы одинаково: ${publikuem[$i]}" \
            "второй отдался бы поверх первого, и в реестре осталась бы одна вещь вместо двух" \
            "имена принадлежат зонам: ${zovem[$i]} — ${faily[$i]}, ${zovem[$j]} — ${faily[$j]}"
    done
done

# ПОРЯДОК ОТДАЧИ — шесть push'ей, и идут они не «по одному образу целиком».
#
# Правило прежнее и не изменилось: НЕПОДВИЖНЫЕ УЕЗЖАЮТ ПЕРВЫМИ. Просто теперь их три, и
# оборванный выпуск обязан оставлять в реестре не часть, а набор, на который можно
# сослаться целиком — `sha-<7>` у всех трёх одной сборки.
#
# ПОДВИЖНЫЕ — ПОСЛЕДНИМИ И ПОДРЯД. `latest` это то, что юзер тянет, ничего не выбирая. Два
# тега реестр одним движением не переставляет, значит `latest`-ы неизбежно расходятся на
# время, и распоряжаемся мы только ДЛИНОЙ этого окна. Здесь оно в два push'а; гони мы
# образы по очереди целиком — в окно попали бы ещё и сборки с отдачей неподвижных тегов.
#
# А ВНУТРИ НАБОРА КОНТРОЛЛЕР ИДЁТ ПОСЛЕДНИМ, и это то же правило, что было у пары, только
# теперь у него два предмета. Пульт РАСКЛАДЫВАЕТ и дверь, и раздачу (`WORLD2` 3.7,
# `WORLD2-132`): юзер тянет его и получает руки, которыми ставит остальное. Новый пульт,
# ждущий двери или раздачи, которых в реестре ещё нет, ломается У ЮЗЕРА, и починить это он
# не может: все три вещи наши. Обратный порядок безобиден — старый пульт раскладывает новую
# дверь ровно так же, как делал вчера, и чинится следующим `docker pull`.
otdaem=()
for i in 0 1 2; do otdaem+=("${publikuem[$i]}:$versiya"); done
for i in 0 1 2; do otdaem+=("${publikuem[$i]}:latest"); done

# Реестров может оказаться до трёх: имя каждого образа называет его само, и совпадать они не
# обязаны. Значит и в совете про вход надо назвать все, иначе человек залогинится наполовину
# и узнает об этом посреди отдачи — когда часть тегов уже уехала.
registries=""
for i in 0 1 2; do
    r="${publikuem[$i]%%/*}"
    case " $registries " in *" $r "*) ;; *) registries="${registries:+$registries и }$r" ;; esac
done

for i in 0 1 2; do
    ok "выпускаем ${otdaem[$i]} — ${zovem[$i]}"
done
ok "тот же коммит у всех трёх — одна сборка"
ok "потом подвижные, тем же порядком: ${otdaem[3]}, ${otdaem[4]}, ${otdaem[5]}"

if [ -n "$dry" ]; then
    # Ярлык у списка один, а строк шесть: столбец тот же, что у соседних строк плана.
    plan=""
    for i in 0 1 2 3 4 5; do
        if [ "$i" = 0 ]; then plan="$plan  поехало бы     ${otdaem[$i]}"$'\n'
        else                  plan="$plan                 ${otdaem[$i]}"$'\n'; fi
    done
    cat >&2 <<SUHOY

$(printf '\033[1mпрогон вхолостую — не сделано НИЧЕГО\033[0m')

  собралось бы   ./deploy/build.sh            (образ мира, без сети вовсе)
                 ./deploy/build.sh --share    (образ раздачи)
                 ./deploy/build.sh --control  (пульт и образ контроллера)
$plan                порядок именно такой: неподвижные первыми, пульт последним
  вход в реестр  берётся у докера (docker login $registries), здесь его не заводят
SUHOY
    if [ -n "$derevo_gryaznoe" ]; then
        printf '%s\n' "$gryazno" >&2
        cat >&2 <<GRYAZNO

$(printf '\033[33m! дерево не чисто — настоящий выпуск на нём ОТКАЖЕТ\033[0m')
  тег выше выведен из HEAD и описывает НЕ то, что лежит в дереве: правки выше в выпуск
  не поехали бы — их сначала коммитят.
GRYAZNO
    fi
    # Увод окружением на холостом ходу — тоже слово вслух, а не отказ, и по той же причине,
    # что и грязь. Холостой ход ничего не отдаёт, а нужен человеку как раз тогда, когда
    # переменная у него в оболочке: он смотрит, что поедет. Отказать здесь значило бы
    # отправить его выходом в тот же холостой ход (`kb:WORLD-31`). Разница с «двумя разными
    # реестрами», где отказ стоит и на холостом ходу: там развилка неразрешима — печатать в
    # плане нечего; здесь умолчание зоны известно, и план выше показан ТОЧНО.
    if [ ${#uvod[@]} -gt 0 ]; then
        cat >&2 <<UVEL

$(printf '\033[33m! окружение уводит имя образа — настоящий выпуск на нём ОТКАЖЕТ\033[0m')
UVEL
        for line in "${uvod[@]}"; do printf '  %s\n' "$line" >&2; done
        printf '  план выше показан по ФАЙЛАМ ЗАПУСКА — то есть по тому, что получит юзер.\n' >&2
    fi
    printf '\n  выпустить по-настоящему: ./deploy/release.sh\n' >&2
    exit 0
fi

# Отсюда что-то УЕЗЖАЕТ — и вот теперь окружение, спорящее с файлом запуска, это отказ.
# Публиковать по умолчанию, промолчав, было бы «правильно и молча»: человек так и не узнал
# бы, что его оболочка чуть не увела выпуск в чужое имя, и в следующий раз узнал бы об этом
# из реестра. Выбирать за него, что он имел в виду, тоже нельзя — публикация необратима.
if [ ${#uvod[@]} -gt 0 ]; then
    for line in "${uvod[@]}"; do printf '  %s\n' "$line" >&2; done
    fail "имя образа у тебя в окружении и в файле запуска — разные" \
        "имя, которым зона ЗОВЁТСЯ, живёт в её файле запуска; переменная там для ПОДЪЁМА названного выпуска, а не для отдачи наружу" \
        "убери подстановку из окружения (она названа выше) и повтори: ./deploy/release.sh" \
        "посмотреть, что поедет, можно и не убирая: ./deploy/release.sh --dry-run"
fi

if [ -n "$derevo_gryaznoe" ]; then
    printf '%s\n' "$gryazno" >&2
    fail "дерево не чисто — тег назвал бы коммит, из которого собрано НЕ ЭТО" \
        "закоммить или убери правки, потом повтори: ./deploy/release.sh" \
        "посмотреть целиком: git -C $ROOT status" \
        "поглядеть, что поехало бы, можно и на грязном: ./deploy/release.sh --dry-run"
fi

# ------------------------------------------------------------------ 4. собираем
# Собираем ВСЕГДА и своей же сборкой. Опубликовать то, что лежит, было бы дешевле — и было
# бы ложью: тег называет коммит, а лежать может образ, собранный вчера из другого. Проверить
# это снаружи нечем, значит устранять надо саму возможность, а не предупреждать о ней.
#
# И СОБИРАЕМ ВСЕ ТРИ ДО ПЕРВОЙ ОТДАЧИ. Соблазн «собрал дверь — отдал дверь — собрал
# остальное» экономит минуту и стоит выпуска: сборка контроллера падает чаще всех — ей
# единственной нужны сеть, нода и чужая зона, — и упади она после отдачи двери, в реестре
# осталась бы часть набора, отданная молча. Оборванная сборка не оставляет следа снаружи,
# оборванная отдача оставляет.
#
# Порядок сборки тот же, что порядок отдачи, и второго правила в голове держать не надо:
# до отдачи дело всё равно не доходит, пока не собраны все три.

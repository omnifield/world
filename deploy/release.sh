# на месте, а собрано будет не из него. Настоящему выпуску это отказ (ниже развилки), а
# холостому ходу нужен план — поэтому у HEAD спрашивается отдельно и НАЗВАННЫМ ключом, чтобы
# такое значение нельзя было получить случайно.
derevo_gryaznoe=
gryazno=
if [ -z "$versiya" ]; then
    case "$sostoyanie" in
        dirty)
            derevo_gryaznoe=1
            versiya="$("$HERE/version.sh" --head 2>/dev/null || true)"
            gryazno="$(git -C "$ROOT" status --porcelain 2>/dev/null | head -n 10 || true)"
            ;;
        no-git)
            fail "$slovami" \
                "поставь git — либо выпускай там, где репозиторий полон" ;;
        not-a-repo)
            fail "$slovami" \
                "неподвижный тег выводится из коммита, а взять его неоткуда" \
                "выпускай из клона репозитория, а не из распакованного архива" ;;
        no-commit)
            fail "$slovami" \
                "сделай коммит и повтори выпуск" ;;
        *)
            fail "версию сборки не спросить: ${slovami:-deploy/version.sh не ответил}" \
                "проверь руками: ./deploy/version.sh" ;;
    esac
fi

[ -n "$versiya" ] || fail \
    "версии сборки нет, а метить надо ею" \

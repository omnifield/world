#
# РАЗБИРАЕМ ИМЯ ЧЕСТНО, а не «приписываем реестр». Прежняя правка приписывала его всегда,
# полагая, что имя реестра не несёт. Допущение живёт до соседней задачи той же истории
# (`WORLD2-112`): контроллеру, который ТЯНЕТ готовое, в `image:` нужен полный адрес — и
# тогда выпуск отдал бы образ в `ghcr.io/ghcr.io/…`. Молча: докер такое имя принимает.
#
# РАЗБОР ОДИН НА ВСЕ ТРИ ОБРАЗА — функцией, а не тремя копиями правил. Развилок в нём три
# (реестр в имени · реестр в переменной · названы оба и разные), и разъезжались бы они по
# одной: у двери починили, у раздачи забыли. Заметил бы это реестр, приняв вещь не туда.

#!/usr/bin/env bash
# ВЫПУСК — собрать у себя ВСЕ ТРИ образа и опубликовать их в реестре.
#
#   ./deploy/release.sh            выпуск: собрать дверь, раздачу и контроллер, отдать все три
#   ./deploy/release.sh --dry-run  показать, что и куда поедет; не собирать и не публиковать
#
# ОБРАЗОВ ТРИ, И ВЫПУСК ВОЗИТ ИХ ВМЕСТЕ — дверь (зона `deploy`, её файл запуска), раздача
# скоупа (зона `share`) и контроллер (зона `control`). Раньше уезжал один контроллер, а
# дверь собиралась из репозитория — то есть шаг «ставлю дверь» требовал клона, которого в
# потоке юзера нет вовсе (`WORLD2`, роадмап «Итерация 1 — поток юзера», ступень 1). Потом
# ступень 2 завела раздачу (`WORLD2-132`): контроллер поднимает её НА МАШИНЕ ЮЗЕРА, и образа
# ей неоткуда взять, кроме реестра, — без него шаг «создать скоуп» не проходит вовсе
# (`WORLD2-138`). Пока все три не выпускаются, «поставил докер — и поднялось» не складывается
# ни в каком порядке.
#
# ВЫБОРОЧНОГО ВЫПУСКА НЕТ — ни ключа, ни переменной, и это решение, а не недоделка. Предмет
# выпуска — ТРОЙКА одной сборки: все три образа собраны из одного коммита и помечены одним
# `sha-<7>`, и по тегу видно, что они друг другу ровня. Заведись ключ «только дверь» — в
# реестре появлялись бы наборы, которых никто не собирал вместе, а узнавал бы об этом юзер, у
# которого пульт раскладывает дверь не той сборки. Обрыв чинится повтором: выпуск отдаёт то
# же самое ещё раз, и это дёшево.
#
# ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ, а не ключ к `build.sh`. Сборка складывает вещь у себя; выпуск
# ОТДАЁТ её наружу — необратимо и всем сразу. Это разные поступки, и путать их нельзя:
# случайный ключ в чужой команде публикует, случайный файл — нет. Обратное направление
# безобидно и потому разрешено: выпуск сам зовёт сборку (по разу на каждый образ), а сборка
# публиковать не умеет вовсе — этого в ней нет ни ключом, ни переменной.
#
# ЗАЧЕМ ВООБЩЕ ВЫПУСК. Юзер не собирает ничего — он получает готовое (`WORLD2-110`). Собрать
# значит иметь у себя клон репозитория, ноду и терпение на три сборки; получить — одна
# команда `docker run`. Ради этого выпуск и существует.
#
# ПОЛЕ ВЫПУСКУ БОЛЬШЕ НЕ НУЖНО. Раньше было нужно: собрать контроллер значило собрать
# пульт, а пакеты пульта лежали на складе локации `probe-web` и наружу не торчали
# (`kb:FUND-5`) — то есть выпускать можно было только там, где поле поднято. Панель
# отвязана от продуктов мира (`WORLD2-127`), и это требование ушло вместе с причиной.
# Выпуску теперь нужен обычный выход наружу — как и всякой сборке.
#
# ЧТО ЗДЕСЬ НЕ ЖИВЁТ:
#
#   · имена образов. Каждое принадлежит СВОЕЙ зоне и берётся из ЕЁ файла запуска — так же,
#     как это делает `build.sh`. Держи мы вторую копию, выпуск однажды опубликовал бы не
#     тот образ, который поднимают, и разъехались бы они молча;
#   · СПИСОК ПЕРЕМЕННЫХ, которыми зоны крутят свои имена. Он был бы такой же второй копией,
#     только чужого устройства: заведи соседняя зона четвёртую переменную — и выпуск узнал
#     бы об этом, опубликовав не туда. Какие подстановки есть в файле запуска, спрашиваем у
#     САМОГО ФАЙЛА (см. «умолчание зоны» ниже);
#   · креды. Ни ключа, ни переменной с токеном: в реестр ходит `docker`, а он берёт вход
#     там, где его оставил человек (`docker login`). Токен в аргументе команды — это токен
#     в истории оболочки и в списке процессов. Ключи принадлежат человеку (`WORLD2` 3.0).
#
# ПОСТАВКА КОПИЕЙ НЕ ОТМЕНЯЕТСЯ — и тем более теперь, когда дверь ещё и выпускается.
# `docker save | docker load` остаётся для машин без выхода в реестр: им возит образ
# `deploy/remote.sh`. Это два способа доставки одной вещи (`WORLD2` 1.5), а не выбор
# навсегда: появление второго не делает первый лишним — ресурс без реестра никуда не делся.
#
# Имена переменных ЛАТИНСКИЕ: bash не поддерживает не-ASCII в именах переменных и молча
# превращает `ТЕГ=latest` в «команда не найдена». Тексты и комментарии — русские.
set -euo pipefail

# Реестр — значение, а не зашитое слово. Умолчание `ghcr.io` выбрано user'ом 2026-08-15
# (`WORLD2-110`): организация `omnifield` там уже есть, репозиторий публичный, и `docker

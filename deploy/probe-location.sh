total=0; failed=0
part()   { printf '\n\033[1m%s\033[0m\n' "$*" >&2; }
detail() { printf '      %s\n' "$*" >&2; }

green() {
    local name="$1"; shift
    total=$((total + 1))
    if "$@"; then printf '  \033[32m✔\033[0m %s\n' "$name" >&2; return 0; fi
    printf '  \033[31m✘\033[0m %s\n' "$name" >&2
    failed=$((failed + 1)); return 1
}

# red <имя> <проверка…> — проверка ОБЯЗАНА упасть: мы сломали вход нарочно.
red() {
    local name="$1"; shift
    total=$((total + 1))
    if "$@"; then
        printf '  \033[31m✘\033[0m %s — проба ЗЕЛЕНЕЕТ на сломанном входе\n' "$name" >&2
        failed=$((failed + 1)); return 1
    fi
    printf '  \033[32m✔\033[0m %s — покраснела, как и должна\n' "$name" >&2; return 0
}

fail() {
    printf '\n\033[1;31m✗ пробу не выполнить: %s\033[0m\n' "$1" >&2
    shift; local line; for line in "$@"; do printf '  выход: %s\n' "$line" >&2; done
    exit 1
}

# Правило зоны: путь хоста в аргументе — обычный `docker`; путей хоста нет, а контейнерные
# есть — `docker_noconv`. Довод целиком — в `build.sh`.
docker_noconv() { MSYS_NO_PATHCONV=1 MSYS2_ARG_CONV_EXCL='*' docker "$@"; }

command -v docker >/dev/null 2>&1 || fail "докера на машине нет" \
    "поставь Docker Engine: https://docs.docker.com/engine/install/"
command -v curl >/dev/null 2>&1 || fail "на машине нет curl, а проба смотрит в поле снаружи" \
    "поставь curl (самим изделиям он не нужен — только пробе)"

# ------------------------------------------------------------------ конфиг пробной локации
# Тот же конфиг, что заполняет человек, — и поднимаем мы им же, штатной командой. Проба,
# которая поднимает локацию своим особым способом, проверяет свой особый способ.
CFG="$(mktemp)"

# write_cfg [адрес застройки] — тот же конфиг, что заполняет человек. Функцией, а не одной
# записью: у места ДВА законных состояния — пустое и с заявленной застройкой, — и проба
# обязана пройти оба тем же способом, каким их проходит человек: правкой конфига и подъёмом.
write_cfg() {
    cat > "$CFG" <<CFGEOF
WORLD_NAME=$LOC
WORLD_GIVES=$GIVES
WORLD_DOOR=$ALIAS:8080
WORLD_NET=$NET
CFGEOF
    [ -z "${1:-}" ] || printf 'WORLD_BUILD_ADDR=%s\n' "$1" >> "$CFG"
    [ -z "${2:-}" ] || printf 'WORLD_SECRETS=%s\n' "$2" >> "$CFG"
}
write_cfg

KEEP=
cleanup() {
    rm -f "$CFG"
    # СВОЙ склад проба стирает за собой: том завела она, значит ей и убирать — иначе он
    # переживёт прогон и следующий увидит вчерашнее построенное. Улику НЕ трогаем: провал
    # разбирают по тому, что осталось, а не по чистому месту (`kb:WORLD-31`).
    # Снос молчаливый: контейнер может быть ещё жив, и тогда докер тома не отдаст — это не
    # отказ прогона, а нормальный исход уборки.
    [ -n "$KEEP" ] || docker volume rm "world-loc-${LOC}_place" >/dev/null 2>&1 || true
    # Своя связка — тоже её артефакт: завела проба, ей и убирать. Настоящей связки юзера
    # проба не касается вовсе.
    [ -n "$KEEP" ] || docker volume rm "$SECRETS_VOL" >/dev/null 2>&1 || true
    [ -z "$KEEP" ] || printf '\n  улики оставлены нарочно: %s\n  убрать: ./deploy/location-down.sh --config <свой конфиг> либо docker rm -f world-loc-%s\n' \
        "$KEEP" "$LOC" >&2
    return 0
}
trap cleanup EXIT


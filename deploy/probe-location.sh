cat >&2 <<BANNER

$(printf '\033[1;33m! проба разрушительна для живого мира\033[0m')
  прогон идёт на ШТАТНОМ порту $PORT и в ЖИВОМ поле: мир будет поднят штатным up.sh,
  а в поле появится и уйдёт пробная локация $LOC. Тома и чужие локации не трогаются.
  подробности: $0 -h
BANNER

case "$mode" in
    --green) run_green ;;
    --red)   run_red ;;
    --both)  run_green; run_red ;;
esac

part "── итог"
if [ "$failed" = 0 ]; then
    printf '  \033[1;32m✔ проверок %s, провалов нет\033[0m\n' "$total" >&2
    exit 0
fi
printf '  \033[1;31m✘ проверок %s, провалено %s\033[0m\n' "$total" "$failed" >&2
printf '    журнал локации: docker logs world-loc-%s\n' "$LOC" >&2
printf '    журнал двери:   docker compose -f %s logs --tail=60\n' "$HERE/compose.yaml" >&2
exit 1

GIVES='проба входа в поле (образ локации)'
# Куда проба поднимет СВОЮ вещь внутри места и что та ответит. Порт внутренний: наружу
# локация не публикуется вовсе, и снаружи в застройку заходят по маршруту места за дверью.
BUILD_ADDR=127.0.0.1:3000
# СВОЯ связка ключей на один прогон. Настоящую (`omnifield-secrets`) проба не трогает вовсе:
# это состояние пространства юзера, и пробе в нём делать нечего — она проверяет МЕХАНИЗМ, а
# не чужое содержимое. Свой том заводит сама и сама сносит.
SECRETS_VOL=world-probe-secrets
SECRETS_MARK='проба связки: ключ юзера виден в месте'
BUILD_MARK='проба застройки: на месте стоит моя вещь'

HERE="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"


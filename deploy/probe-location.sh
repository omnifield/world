# ------------------------------------------------------------------ сами проверки
# Всё, что можно, спрашивается СНАРУЖИ — через хост-порт двери: это тот же взгляд, каким на
# поле смотрит человек. Изнутри сети проверяется только то, чего снаружи не видно.

# в поле ли локация — по реестру за дверью
check_in_field() {
    local body
    body=$(curl -sS -m 10 "$base/api/locations" 2>&1) || { detail "реестр не ответил: $body"; return 1; }
    case "$body" in
        *"\"$LOC\""*) return 0 ;;
        *) detail "локации $LOC в поле нет: $body"; return 1 ;;
    esac
}

# маршрут в локацию работает, и отвечает по нему СТОРОЖ, а не сама дверь. Проверяется именно
# `mode":"guard"`: код 200 сам по себе не говорит, КТО ответил, — а спрашиваем мы здесь
# присутствие места в поле, а не живость двери.
#
# Раньше довод был другим: дверь на неизвестном имени отдавала страницу мира, тоже с кодом
# 200. Раздачи у двери больше нет (`WORLD2-107`), промах теперь честный отказ — но проверка
# от этого не ослабла и остаётся на месте: она стережёт ответившего, а не код.
check_route_guard() {
    local answer code body
    answer=$(curl -sS -m 10 -w $'\n%{http_code}' "$base/$LOC/" 2>&1) \
        || { detail "маршрут не ответил: $answer"; return 1; }
    code=${answer##*$'\n'}; body=${answer%$'\n'*}
    [ "$code" = 200 ] || { detail "маршрут /$LOC/ ответил $code: $body"; return 1; }
    case "$body" in
        *'"mode":"guard"'*) ;;
        *) detail "по маршруту ответил не сторож локации: $body"; return 1 ;;
    esac
    case "$body" in
        *'я здесь'*) return 0 ;;
        *) detail "сторож ответил, но не сказал «я здесь»: $body"; return 1 ;;
    esac
}

# локации в поле НЕТ — отдельной функцией, а не отрицанием на месте: `green` зовёт проверку
# по имени, и `!` перед ней не команда, а синтаксис оболочки, который туда не доедет.
check_not_in_field() {
    local body
    body=$(curl -sS -m 10 "$base/api/locations" 2>&1) || { detail "реестр не ответил: $body"; return 1; }
    case "$body" in
        *"\"$LOC\""*) detail "локация $LOC всё ещё в поле: $body"; return 1 ;;
        *) return 0 ;;
    esac
}

# наружу локация не торчит: снаружи машины к ней ходят ТОЛЬКО через дверь (`kb:FUND-5`).
# Смотрим не в файл запуска, а в ЖИВОЙ контейнер: публикацию можно добавить и мимо файла.
#
# Сначала убеждаемся, что контейнер вообще есть. Без этого проверка была бы ложно-зелёной
# на снесённом контейнере: `docker port` по несуществующему имени отвечает ошибкой и пустой
# строкой, а пустая строка здесь читается как «портов нет».
check_no_host_port() {
    local ports
    [ -n "$(container_id)" ] || { detail "контейнера локации нет — проверять публикацию не на чем"; return 1; }
    ports=$(docker port "world-loc-$LOC" 2>/dev/null || true)
    [ -z "$ports" ] || { detail "локация публикует порт наружу: $ports"; return 1; }
    return 0
}

# container_id — id живого контейнера пробной локации (пусто, если его нет).
container_id() { docker ps -q --filter "name=^world-loc-$LOC$" 2>/dev/null | head -n1; }

# вход был подтверждением, а не первым: повторный подъём тем же адресом — не ошибка
check_said_confirmed() { grep -qF 'подтвердила присутствие' "$1" || {
        detail "повторный подъём не назвал вход подтверждением — вот что он сказал:"
        tail -n 15 "$1" >&2; return 1; }; }

# отказ ДОЕХАЛ до человека целиком: код отказа виден в выводе команды
check_refusal_says() {   # <файл вывода> <код отказа>
    grep -qF "$2" "$1" && return 0
    detail "в выводе нет отказа «$2» — вот последние строки:"
    tail -n 15 "$1" >&2
    return 1
}

# ------------------------------------------------------------------ ландшафт места
# То, что есть на месте ИЗНАЧАЛЬНО (`tasker:WORLD-102`). Спрашивается ИЗНУТРИ контейнера и
# тем же способом, каким этим будет пользоваться стройка: не «лежит ли файл», а отвечает ли
# команда. Пакет, приехавший наполовину, лежит на диске и не работает.
#
# Все четыре в ОДНОЙ проверке, но каждая недостача названа поимённо: «ландшафта нет» без
# имени — это диагноз, а не отказ (`kb:WORLD-31`).
LANDSCAPE_MARK='проба ландшафта: место пишет в свой склад'

check_landscape() {
    local cid missing='' pair name cmd out
    cid=$(container_id)
    [ -n "$cid" ] || { detail "контейнера локации нет — смотреть ландшафт не в чем"; return 1; }
    for pair in 'git:git --version' 'node:node -v' 'npm:npm -v' 'curl:curl --version'; do
        name=${pair%%:*}; cmd=${pair#*:}
        # shellcheck disable=SC2086
        if out=$(docker_noconv exec "$cid" $cmd 2>&1); then
            detail "$name — $(printf '%s' "$out" | head -n1)"
        else
            missing="$missing $name"
        fi
    done
    [ -z "$missing" ] || { detail "на месте нет:$missing (это ландшафт, он кладётся в образ локации)"; return 1; }
    return 0
}

# склад под застройку: каталог стройки существует и в него ПИШЕТ тот пользователь, под
# которым бежит сторож. Проверяется записью, а не правами в листинге: право писать — это
# то, что запись прошла, а не то, что в `ls` красивые буквы.
check_build_dir_writable() {
    local cid out
    cid=$(container_id)
    [ -n "$cid" ] || { detail "контейнера локации нет — писать некуда"; return 1; }
    out=$(docker_noconv exec "$cid" sh -c 'printf "%s\n" "$1" > "$WORLD_BUILD_DIR"/probe-place.txt && cat "$WORLD_BUILD_DIR"/probe-place.txt' _ "$LANDSCAPE_MARK" 2>&1) \
        || { detail "в каталог стройки не пишется: $out"; return 1; }
    case "$out" in
        *"$LANDSCAPE_MARK"*) return 0 ;;
        *) detail "записалось не то: $out"; return 1 ;;
    esac
}

# склад — ТОМ, а не слой контейнера. Спрашиваем у докера, куда смонтирован том, и сверяем
# с `WORLD_BUILD_DIR` самого контейнера: разъедься они — постройка легла бы в слой, а
# проверка «пишется» осталась бы зелёной.
check_build_dir_on_volume() {
    local cid dir mounts
    cid=$(container_id)
    [ -n "$cid" ] || { detail "контейнера локации нет — смотреть монтирования не у чего"; return 1; }
    dir=$(docker_noconv exec "$cid" sh -c 'printf "%s" "$WORLD_BUILD_DIR"' 2>/dev/null)
    [ -n "$dir" ] || { detail "WORLD_BUILD_DIR внутри места не задан — сторож поднят без каталога стройки"; return 1; }
    mounts=$(docker inspect "$cid" --format '{{range .Mounts}}{{.Type}}:{{.Destination}} {{end}}' 2>/dev/null || true)
    case "$mounts" in
        *"volume:$dir"*) return 0 ;;
        *) detail "на $dir тома нет — вот что смонтировано: ${mounts:-ничего}"; return 1 ;;
    esac
}

# построенное пережило снятие и подъём. Метку кладём ДО снятия, ищем ПОСЛЕ подъёма — то же
# место всей пробы, что пересоздание у мира (`kb:WORLD-32`): рестарт сохранил бы её и без
# тома, а снятие с подъёмом — только с томом.
check_build_survived() {
    local cid out
    cid=$(container_id)
    [ -n "$cid" ] || { detail "контейнера локации нет — искать построенное негде"; return 1; }
    out=$(docker_noconv exec "$cid" sh -c 'cat "$WORLD_BUILD_DIR"/probe-place.txt' 2>&1) \
        || { detail "после подъёма файла в каталоге стройки нет: $out"; return 1; }
    case "$out" in
        *"$LANDSCAPE_MARK"*) return 0 ;;
        *) detail "в каталоге стройки лежит не то: $out"; return 1 ;;
    esac
}

# ------------------------------------------------------------------ место жилое
# «Человек может работать», а не «файл лежит». Проверяется тем же способом, каким в место
# входит юзер: `docker exec` без `-u`, то есть ПОД ТЕМ пользователем, который объявлен в
# образе. Зайди мы от root — проверка зеленела бы ровно на том месте, где живой вход
# упирался (`tasker:WORLD-106`).
HOME_MARK='проба входа: дом пишется'
PLACE_MARK='проба входа: человек создал вещь в месте'

# 1. вход не от root, и оболочка СТАРТУЕТ. Обе половины разом: `sh -c` не выполнится вовсе,
#    если оболочка у пользователя `/sbin/nologin`, — а `id` скажет, кем мы вошли.
check_enter_as_world() {
    local cid who
    cid=$(container_id)
    [ -n "$cid" ] || { detail "контейнера локации нет — входить некуда"; return 1; }
    who=$(docker_noconv exec "$cid" sh -c 'id -un' 2>&1) \
        || { detail "оболочка в месте не стартовала: $who"; return 1; }
    case "$who" in
        root) detail "вошли от root — а место обязано пускать своего пользователя"; return 1 ;;
        world) return 0 ;;
        *) detail "вошли кем-то третьим: $who"; return 1 ;;
    esac
}

# 2. дом существует и ПИШЕТСЯ — именно на этом падал редактор.
check_home_writable() {
    local cid out
    cid=$(container_id)
    [ -n "$cid" ] || { detail "контейнера локации нет — дома искать негде"; return 1; }
    out=$(docker_noconv exec "$cid" sh -c 'cd "$HOME" && printf "%s\n" "$1" > .probe-home && cat .probe-home && pwd' _ "$HOME_MARK" 2>&1) \
        || { detail "в дом не зайти либо не записать: $out"; return 1; }
    case "$out" in
        *"$HOME_MARK"*/home/world) return 0 ;;
        *"$HOME_MARK"*) detail "дом пишется, но лежит не там, где объявлен: $out"; return 1 ;;
        *) detail "в доме записалось не то: $out"; return 1 ;;
    esac
}

# 3. вещь, созданная человеком в `/place`, видна СНАРУЖИ места — то есть лежит на томе, а
#    не в слое контейнера. Смотрим тем же образом локации, но другим контейнером: том
#    подключается к нему напрямую, мимо места.
check_place_seen_outside() {
    local cid out
    cid=$(container_id)
    [ -n "$cid" ] || { detail "контейнера локации нет — создавать вещь не в чем"; return 1; }
    docker_noconv exec "$cid" sh -c 'printf "%s\n" "$1" > "$WORLD_BUILD_DIR"/probe-human.txt' _ "$PLACE_MARK" 2>&1 \
        || { detail "человек не смог создать вещь в месте — писать в /place не выходит"; return 1; }
    out=$(docker_noconv run --rm -v "world-loc-${LOC}_place:/snaruzhi" --entrypoint sh "$IMAGE_LOC" \
            -c 'cat /snaruzhi/probe-human.txt' 2>&1) \
        || { detail "снаружи места вещи не видно: $out"; return 1; }
    case "$out" in
        *"$PLACE_MARK"*) return 0 ;;
        *) detail "снаружи лежит не то: $out"; return 1 ;;
    esac
}

# ------------------------------------------------------------------ место-мастерская
# Жилое место — ещё не мастерская: в нём надо чем-то РАБОТАТЬ. Инструменты приносит юзер
# (`WORLD2` 0.1), связка ключей приходит с ним из его пространства (`3.0`).

# 1. инструмент СТАВИТСЯ без root. Ставим свой пакет из каталога внутри места, а не из сети:
#    проверяется право писать в префикс и запуск поставленного, а не наличие интернета.
#    Тянись проба в реестр — красный прогон на машине без сети означал бы «npm сломан».
check_npm_global() {
    local cid out
    cid=$(container_id)
    [ -n "$cid" ] || { detail "контейнера локации нет — ставить инструмент некуда"; return 1; }
    out=$(docker_noconv exec "$cid" sh -c '
        set -e
        d=$(mktemp -d)
        mkdir -p "$d/bin"
        printf "%s" "{\"name\":\"probe-tool\",\"version\":\"1.0.0\",\"bin\":{\"probe-tool\":\"bin/probe-tool.js\"}}" > "$d/package.json"
        printf "#!/usr/bin/env node\nconsole.log(\"probe-tool ok\")\n" > "$d/bin/probe-tool.js"
        chmod +x "$d/bin/probe-tool.js"
        npm i -g "$d" >/dev/null 2>&1
        probe-tool
    ' 2>&1) || { detail "инструмент от world не поставился либо не запустился: $out"; return 1; }
    case "$out" in
        *'probe-tool ok'*) return 0 ;;
        *) detail "поставленное ответило не тем: $out"; return 1 ;;
    esac
}

# 2. связка ключей ВИДНА в месте — то самое «состояние старшего скоупа доступно вложенным».
check_secrets_seen() {
    local cid out
    cid=$(container_id)
    [ -n "$cid" ] || { detail "контейнера локации нет — связку смотреть негде"; return 1; }
    out=$(docker_noconv exec "$cid" sh -c 'cat "$HOME"/.secrets/probe-key.txt' 2>&1) \
        || { detail "связки ключей в месте не видно: $out"; return 1; }
    case "$out" in
        *"$SECRETS_MARK"*) return 0 ;;
        *) detail "в связке лежит не то: $out"; return 1 ;;
    esac
}

# 3. и она ТОЛЬКО ДЛЯ ЧТЕНИЯ: доступность не равна владению (`WORLD2` 3.0). Проверяется
#    попыткой записи — она ОБЯЗАНА не пройти; отдельной функцией, потому что `green` зовёт
#    проверку по имени, и отрицание на месте туда не доедет.
check_secrets_read_only() {
    local cid out
    cid=$(container_id)
    [ -n "$cid" ] || { detail "контейнера локации нет — писать некуда"; return 1; }
    if out=$(docker_noconv exec "$cid" sh -c 'printf x > "$HOME"/.secrets/probe-write.txt' 2>&1); then
        detail "в связку ЗАПИСАЛОСЬ — место начало владеть состоянием юзера"
        docker_noconv exec "$cid" sh -c 'rm -f "$HOME"/.secrets/probe-write.txt' >/dev/null 2>&1 || true
        return 1
    fi
    case "$out" in
        *'ead-only'*|*'ermission denied'*) return 0 ;;
        *) detail "запись не прошла, но причина не про «только чтение»: $out"; return 1 ;;
    esac
}

# ------------------------------------------------------------------ застройка на месте
# Мир застройку НЕ поднимает и не следит, что она такое: он доводит до заявленного адреса
# (`core/README.md`). Поэтому здесь пробa делает работу ЧЕЛОВЕКА — поднимает внутри места
# свою вещь и заявляет её адрес настройкой; проверяется же не она, а то, куда после этого
# ведёт маршрут места.
#
# Вещь поднимается тем, что на месте УЖЕ лежит, — `node` из базового ландшафта
# (`tasker:WORLD-102`). Тянуть внутрь чужой образ или пакет значило бы проверять доступ в
# сеть вместо маршрута.
stand_up() {
    local cid js _
    cid=$(container_id)
    [ -n "$cid" ] || { detail "контейнера локации нет — поднимать вещь не в чем"; return 1; }
    js="require('http').createServer(function(q,s){s.writeHead(200,{'Content-Type':'text/plain; charset=utf-8'});s.end('$BUILD_MARK')}).listen(${BUILD_ADDR##*:},'${BUILD_ADDR%%:*}')"
    docker_noconv exec -d "$cid" node -e "$js" || {
        detail "вещь внутри места не запустилась — node из ландшафта не отработал"; return 1; }
    # «Запущен» и «отвечает» — разные вещи и здесь тоже: стучимся изнутри места тем же
    # `curl`, который лежит в ландшафте.
    for _ in {1..15}; do
        docker_noconv exec "$cid" curl -fsS -m 2 "http://$BUILD_ADDR/" >/dev/null 2>&1 && return 0
        sleep 1
    done
    detail "вещь внутри места не ответила за 15 секунд по $BUILD_ADDR"
    return 1
}

# маршрут места ведёт В ЗАСТРОЙКУ: снаружи, через дверь, по имени места — то есть тем же
# путём, каким на место смотрит человек. Ответ обязан быть ВЕЩИ, а не сторожа: страница
# сторожа тоже отдаётся с кодом 200, и без сверки тела проверка зеленела бы на пустом месте.
check_route_build() {
    local answer code body
    answer=$(curl -sS -m 10 -w $'\n%{http_code}' "$base/$LOC/" 2>&1) \
        || { detail "маршрут не ответил: $answer"; return 1; }
    code=${answer##*$'\n'}; body=${answer%$'\n'*}
    [ "$code" = 200 ] || { detail "маршрут /$LOC/ ответил $code: $body"; return 1; }
    case "$body" in
        *"$BUILD_MARK"*) return 0 ;;
        *'"mode":"guard"'*) detail "по маршруту ответил СТОРОЖ, а не застройка: $body"; return 1 ;;
        *) detail "по маршруту ответило что-то третье: $body"; return 1 ;;
    esac
}

# ================================================================== ЗЕЛЁНЫЙ ПРОГОН
run_green() {
    part "── зелёный прогон: локация поднимается одной командой и входит в поле сама"

    # Адрес передаём подъёму явно, как и порт: проверять дверь он обязан там же, где её
    # проверяем мы, — иначе один из двоих объявит живую дверь мёртвой.
    part "мир (deploy/up.sh) — локации нужно, куда входить"
    WORLD_PORT="$PORT" WORLD_HOST="$HOST" "$HERE/up.sh" ${want_build:+--build} >&2 \
        || fail "мир не поднялся — причина названа выше" "локации без двери входить некуда"

    local out; out="$(mktemp)"

    part "подъём локации: ./deploy/location-up.sh (конфиг: имя $LOC, дверь $ALIAS:8080)"
    if ! up_location "$out"; then
        cat "$out" >&2
        KEEP="world-loc-$LOC"
        fail "локация не поднялась либо не вошла в поле" \
            "полный вывод — прямо выше, причина названа там" \
            "контейнер оставлен уликой: docker logs world-loc-$LOC"
    fi
    detail "поднялась и вошла — вывод команды ниже проверяется по частям"

    green "1. локация в поле (реестр за дверью)"          check_in_field || true
    green "2. маршрут /$LOC/ отвечает «я здесь» (сторож)" check_route_guard || true
    green "3. наружу локация не торчит — только через дверь" check_no_host_port || true

    part "ландшафт места — то, чем оно располагает изначально"
    green "4. на месте есть git · node · npm · curl"       check_landscape || true
    green "5. склад под застройку пишется сторожем"        check_build_dir_writable || true
    green "6. склад лежит на ТОМЕ, а не в слое контейнера" check_build_dir_on_volume || true

    part "повторный подъём — обязан быть подтверждением, а не отказом"
    if up_location "$out"; then
        green "7. повторный подъём назвал вход подтверждением" check_said_confirmed "$out" || true
    else
        cat "$out" >&2
        total=$((total + 1)); failed=$((failed + 1))
        printf '  \033[31m✘\033[0m 7. повторный подъём ОТКАЗАЛ — переобъявление должно проходить\n' >&2
    fi

    part "снятие: ./deploy/location-down.sh — из поля, потом контейнер"
    if down_location; then
        green "8. снятая локация ушла из поля"  check_not_in_field || true
    else
        total=$((total + 1)); failed=$((failed + 1))
        printf '  \033[31m✘\033[0m 8. снятие не отработало\n' >&2
        KEEP="world-loc-$LOC"
    fi

    part "подъём после снятия — место возвращается тем же способом"
    if up_location "$out"; then
        green "9. поднятая заново локация снова в поле" check_in_field || true
        # Метка легла в склад ДО снятия. Снятие сносит контейнер целиком, подъём делает
        # новый — и построенное обязано оказаться на месте: оно на томе, а не в слое.
        green "10. построенное пережило снятие и подъём"  check_build_survived || true
    else
        cat "$out" >&2
        total=$((total + 1)); failed=$((failed + 1))
        printf '  \033[31m✘\033[0m 9. повторный подъём после снятия не отработал\n' >&2
        KEEP="world-loc-$LOC"
    fi

    part "место жилое — человек входит и работает в нём сам"
    green "11. вход в место не от root, оболочка стартует"   check_enter_as_world || true
    green "12. дом пользователя существует и пишется"        check_home_writable || true
    green "13. вещь человека в /place видна снаружи места"   check_place_seen_outside || true

    green "14. инструмент ставится от world и запускается"    check_npm_global || true

    part "связка ключей юзера — состояние его пространства, месту доступное"
    docker volume create "$SECRETS_VOL" >/dev/null 2>&1 || true
    docker_noconv run --rm -v "$SECRETS_VOL:/svyazka" --user root --entrypoint sh "$IMAGE_LOC" \
        -c "printf '%s\n' '$SECRETS_MARK' > /svyazka/probe-key.txt" >/dev/null 2>&1 \
        || detail "свою связку завести не вышло — проверки ниже это и покажут"
    write_cfg "" "$SECRETS_VOL"
    if up_location "$out"; then
        detail "место поднято заново, связка названа: $SECRETS_VOL"
        green "15. связка ключей видна в месте"                check_secrets_seen || true
        green "16. связка только для чтения — место ею не владеет" check_secrets_read_only || true
    else
        cat "$out" >&2
        total=$((total + 2)); failed=$((failed + 2))
        printf '  \033[31m✘\033[0m 15-16. подъём с названной связкой не отработал\n' >&2
        KEEP="world-loc-$LOC"
    fi

    part "застройка на месте — маршрут ведёт к ней, а не к сторожу"
    detail "без заявленного адреса маршрут отвечал сторожем — это проверка 2 выше"
    write_cfg "$BUILD_ADDR"
    if up_location "$out"; then
        detail "место поднято заново, адрес застройки заявлен: $BUILD_ADDR"
        if stand_up; then
            green "17. маршрут /$LOC/ отдаёт ЗАСТРОЙКУ, а не сторожа" check_route_build || true
        else
            total=$((total + 1)); failed=$((failed + 1))
            printf '  \033[31m✘\033[0m 17. вещь внутри места не поднялась — проверять маршрут нечем\n' >&2
            KEEP="world-loc-$LOC"
        fi
    else
        cat "$out" >&2
        total=$((total + 1)); failed=$((failed + 1))
        printf '  \033[31m✘\033[0m 17. подъём с заявленным адресом застройки не отработал\n' >&2
        KEEP="world-loc-$LOC"
    fi
    # Конфиг возвращаем в прежнее состояние: красный прогон идёт по нему же, и место с
    # заявленной, но не поднятой застройкой ломало бы ему не то, что он ломает нарочно.
    write_cfg

    part "убираю за собой"
    if [ "$failed" = 0 ]; then
        down_location || detail "снятие не отработало — убрать: docker rm -f world-loc-$LOC"
        detail "пробная локация снята, поле вернулось в прежнее состояние; мир оставлен поднятым на $base"
    else
        KEEP="world-loc-$LOC"
        detail "локация ОСТАВЛЕНА уликой вместе с журналом — разбирать провал по снесённому контейнеру нечем"
    fi
    rm -f "$out"
}

# ================================================================== КРАСНЫЙ ПРОГОН
# Три поломки — ровно те, что названы в приёмке. Каждая ломает ОДНУ вещь, и проверяется не
# только падение, но и то, что отказ ДОЕХАЛ до человека своими словами: отказ, потерявший
# по дороге причину и выход, — это диагноз, а не отказ (`kb:WORLD-31`).
run_red() {
    part "── красный прогон: ломаем вход нарочно, отказ обязан доехать целиком"

    docker image inspect "$IMAGE_LOC" >/dev/null 2>&1 || {
        [ -n "$want_build" ] || fail \
            "образа локации $IMAGE_LOC на машине нет — ломать нечего" \
            "собрать: ./deploy/probe-location.sh --red --build (сборке образа локации поле не нужно)" \
            "либо перенести готовый: docker save $IMAGE_LOC | docker load"
        part "образа локации нет, просили --build — собираю"
        "$HERE/location-up.sh" --config "$CFG" --build >&2 \
            || fail "образ локации не собрался — причина названа выше"
        down_location || true
    }

    part "мир — красный прогон тоже смотрит на настоящую дверь"
    WORLD_PORT="$PORT" WORLD_HOST="$HOST" "$HERE/up.sh" >&2 || fail "мир не поднялся — причина названа выше"

    local out; out="$(mktemp)"

    # ---------- поломка 1: вход бежит раньше сторожа ----------
    # Ровно тот случай, ради которого порядок «сначала сторож, потом вход» и записан. Зовём
    # `join` в контейнере, в котором сторож не поднят ВООБЩЕ: по объявленному адресу нет
    # никого, и локация обязана сказать это про СЕБЯ, а не переложить на дверь.
    part "поломка 1 — по объявленному адресу никого нет (сторож не поднят)"
    set +e
    docker_noconv run --rm --network "$NET" \
        -e WORLD_NAME=probe-nikogo -e WORLD_GIVES="$GIVES" -e WORLD_DOOR="$ALIAS:8080" \
        "$IMAGE_LOC" join >"$out" 2>&1
    local status_join=$?
    set -e
    if [ "$status_join" = 0 ]; then
        total=$((total + 1)); failed=$((failed + 1))
        printf '  \033[31m✘\033[0m вход БЕЗ сторожа прошёл — в поле легла запись в никуда\n' >&2
        curl -sS -m 10 -X DELETE "$base/api/locations/probe-nikogo" >/dev/null 2>&1 || true
    else
        printf '  \033[32m✔\033[0m вход без сторожа отказал, как и должен\n' >&2
        total=$((total + 1))
    fi
    green "и отказ назвал СЕБЯ (self-unreachable), а не дверь" check_refusal_says "$out" self-unreachable || true

    # ---------- поломка 2: имя занято другой локацией ----------
    # Занимаем имя ЧУЖИМ адресом — берём заведомо достижимый адрес самой двери: дверь
    # проверяет достижимость, и адрес, по которому никого нет, она бы просто не приняла.
    part "поломка 2 — имя $LOC занято другой локацией"
    curl -sS -m 10 -X POST "$base/api/locations" -H 'Content-Type: application/json' \
        -d "{\"name\":\"$LOC\",\"addr\":\"$ALIAS:8080\",\"gives\":\"занятое имя, проба\"}" >/dev/null 2>&1 \
        || fail "имя занять не вышло — дверь не приняла регистрацию" \
                "поле цело; посмотри: curl $base/api/locations"
    if up_location "$out"; then
        total=$((total + 1)); failed=$((failed + 1))
        printf '  \033[31m✘\033[0m подъём на ЗАНЯТОЕ имя прошёл — переобъявление чужого адреса не отказ\n' >&2
    else
        printf '  \033[32m✔\033[0m подъём на занятое имя отказал, как и должен\n' >&2
        total=$((total + 1))
    fi
    green "и отказ приехал СЛОВАМИ ДВЕРИ (name-taken)" check_refusal_says "$out" name-taken || true
    down_location >/dev/null 2>&1 || true
    curl -sS -m 10 -X DELETE "$base/api/locations/$LOC" >/dev/null 2>&1 || true

    # ---------- поломка 3: двери не видно ----------
    # Здесь сторож ПОДНЯТ и локация про себя знает, что достижима, — значит отказ обязан
    # указывать на дверь, а не на себя. Пара к нему зелёная: тот же вызов с настоящей
    # дверью проходит. Краснели бы оба — сломали бы не то.
    part "поломка 3 — двери по адресу нет"
    up_location "$out" || { cat "$out" >&2; KEEP="world-loc-$LOC"
        fail "локация не поднялась — ломать поломку 3 не на чем" \
             "вывод выше; контейнер оставлен: docker logs world-loc-$LOC"; }
    local cid
    cid=$(container_id)
    [ -n "$cid" ] || fail "контейнер локации не найден" "посмотри: docker ps -a --filter name=world-loc-$LOC"

    set +e
    docker_noconv exec "$cid" /app/world join -door nikakoj-dveri:8080 >"$out" 2>&1
    local status_door=$?
    set -e
    if [ "$status_door" = 0 ]; then
        total=$((total + 1)); failed=$((failed + 1))
        printf '  \033[31m✘\033[0m вход в НЕСУЩЕСТВУЮЩУЮ дверь прошёл\n' >&2
    else
        printf '  \033[32m✔\033[0m вход в несуществующую дверь отказал, как и должен\n' >&2
        total=$((total + 1))
    fi
    green "и отказ назвал ДВЕРЬ (door-unreachable), а не себя" check_refusal_says "$out" door-unreachable || true

    set +e
    docker_noconv exec "$cid" /app/world join >"$out" 2>&1
    local status_ok=$?
    set -e
    if [ "$status_ok" = 0 ]; then
        printf '  \033[32m✔\033[0m а с настоящей дверью тот же вход проходит (сломано именно её отсутствие)\n' >&2
        total=$((total + 1))
    else
        total=$((total + 1)); failed=$((failed + 1))
        printf '  \033[31m✘\033[0m с настоящей дверью вход тоже не прошёл — сломали не то\n' >&2
        tail -n 15 "$out" >&2
    fi

    part "убираю за собой"
    down_location >/dev/null 2>&1 || KEEP="world-loc-$LOC"
    detail "пробная локация снята; мир оставлен поднятым на $base"
    rm -f "$out"
}


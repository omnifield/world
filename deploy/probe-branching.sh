skip()   { skipped=$((skipped+1)); printf '  \033[33m∅\033[0m %s\n' "$*" >&2; }

# ------------------------------------------------------------------ подставной докер
# Отдельным файлом в PATH, а не функцией: `up.sh` зовёт `build.sh` отдельным процессом,
# и функция до него не доехала бы. Файл рождается на прогон и умирает вместе с ним —
# храниться ему негде и незачем.
STUB_DIR="$(mktemp -d)"
DOOR_PID=

cleanup() {
    [ -n "$DOOR_PID" ] && kill "$DOOR_PID" 2>/dev/null
    rm -rf "$STUB_DIR"
    rm -rf "$OUT"
    [ -d "$OUT.saved" ] && mv "$OUT.saved" "$OUT"
    return 0
}
trap cleanup EXIT

[ -d "$OUT" ] && { rm -rf "$OUT.saved"; mv "$OUT" "$OUT.saved"; }

cat > "$STUB_DIR/docker" <<'STUB'
#!/usr/bin/env bash
# ПОДСТАВНОЙ докер: пишет журнал вызовов и отвечает по сценарию. Контейнеров не запускает.
printf '%s\n' "$*" >> "${STUB_LOG:-/dev/null}"
ALL="$*"   # вызов целиком — по нему отличается мир от локации после того, как ключи сдвинуты

emit_tar() {   # отдать в stdout настоящий tar с названными файлами
    d=$(mktemp -d)
    for f in "$@"; do mkdir -p "$d/$(dirname "$f")"; printf 'подстава\n' > "$d/$f"; done
    tar -C "$d" -cf - .
    rm -rf "$d"
}

case "$1" in
    info) exit 0 ;;
    network) exit 0 ;;
    pull) [ -n "${STUB_PULL_OK:-}" ] && exit 0 || exit 1 ;;
    image)
        # `image inspect --format …{{range .Config.Env}}…` — вопрос выпуска и подъёма: что
        # образ говорит о себе САМ (`WORLD_VERSION`, `WORLD2-130`). Умолчание сценария —
        # штатный ход: штамп совпадает с версией подставного гита. Крутится он `STUB_STAMP`:
        # пусто — штампа в образе нет вовсе, другое значение — штамп разъехался с тегом.
        # Двоеточия в `${STUB_STAMP-…}` нет намеренно: пустое значение это состояние, а не
        # просьба взять умолчание.
        case "$ALL" in
            *Config.Env*)
                if [ -n "${STUB_STAMP-sha-abc1234}" ]; then
                    printf 'WORLD_ADDR=:8080\n'
                    printf 'WORLD_VERSION=%s\n' "${STUB_STAMP-sha-abc1234}"
                fi
                exit 0 ;;
        esac
        # `image inspect --format …{{RepoDigests}}…` — вопрос выпуска: под каким digest'ом
        # образ лёг в реестр. Отвечаем подставным: проверяется, что его СПРАШИВАЮТ и
        # печатают, а не то, чему он равен.
        #
        # Отвечаем ИМЕНЕМ ТОГО ЖЕ образа, а не одной зашитой строкой: образов теперь два, и
        # с общим ответом «спросили у обоих» было бы не отличить от «спросили дважды у
        # одного» — а в выводе выпуска это ровно та ошибка, ради которой digest и печатают.
        case "$ALL" in
            *RepoDigests*) last="${!#}"; printf '%s@sha256:podstava\n' "${last%:*}"; exit 0 ;;
        esac
        case "$3" in
            ghcr.io/omnifield/world:latest) [ -n "${STUB_HAVE_IMAGE:-}" ] && exit 0 || exit 1 ;;
            omnifield/location:dev) [ -n "${STUB_HAVE_LOC_IMAGE:-}" ] && exit 0 || exit 1 ;;
            *)                      [ -n "${STUB_HAVE_PROBE:-}" ]     && exit 0 || exit 1 ;;
        esac ;;
    tag) exit 0 ;;
    push)
        # Реестр отвечает по сценарию. `denied` — это и «не залогинен», и «нет прав на
        # организацию»: докер их не различает, и отказ выпуска обязан назвать оба.
        case "${STUB_PUSH:-ok}" in
            ok) exit 0 ;;
            *)  echo 'denied: requested access to the resource is denied' >&2; exit 1 ;;
        esac ;;
    exec)
        # `docker exec` в живой локации: стук в сторожа и команды входа в поле. Тем же
        # бинарём, что стоит внутри, — и заглушка отвечает за него по сценарию.
        case "$ALL" in
            *"/app/world join"*)  [ -n "${STUB_JOIN_OK:-}" ] \
                                      && { echo 'локация "podstava" вошла в поле'; exit 0; } \
                                      || { echo 'world join: подстава отказала' >&2; exit 1; } ;;
            *"/app/world leave"*) [ "${STUB_LEAVE_OK:-1}" = 1 ] \
                                      && { echo 'локация "podstava" снята с поля'; exit 0; } \
                                      || exit 1 ;;
            *wget*)               [ -n "${STUB_GUARD_READY:-}" ] && exit 0 || exit 1 ;;
            *)                    exit 0 ;;
        esac ;;
    compose)
        # Ключи до подкоманды: у мира это `-f ФАЙЛ`, у локации ещё `-p ИМЯ` и
        # `--env-file ФАЙЛ`. Сдвигаем парами, а не на фиксированное число: иначе заглушка
        # знала бы ровно один вызов из двух и молча отвечала бы не на ту подкоманду.
        shift
        while [ $# -gt 0 ]; do
            case "$1" in -*) shift 2 ;; *) break ;; esac
        done
        # ФАЙЛ РАЗДАЧИ БЕЗ ЗНАЧЕНИЯ НЕ ЧИТАЕТСЯ ВОВСЕ — ни `config`, ни `build`: у него есть
        # подстановка без умолчания (`${SHARE_PASSWORD:?…}`, зона `share`). Заглушка ведёт
        # себя так же, и это не придирка: выпуск и сборка, забывшие заткнуть обязательную
        # подстановку чужой зоны, зеленели бы здесь и падали бы на живой машине — там, где
        # чинить дороже всего.
        case "$ALL" in
            *share/compose.yaml*)
                [ -n "${SHARE_PASSWORD:-}" ] || {
                    echo 'required variable SHARE_PASSWORD is missing a value' >&2; exit 1; } ;;
        esac
        case "$1" in
            config)
                # ЗАГЛУШКА ПОДСТАВЛЯЕТ ПЕРЕМЕННЫЕ ТАК ЖЕ, КАК КОМПОУЗ: имя образа берётся из
                # ОКРУЖЕНИЯ, а нет его — из умолчания файла запуска. Без этого проверить
                # `WORLD2-114` было бы нечем: заглушка отвечала бы одно и то же при любом
                # окружении, и порча «увести публикацию переменной» проходила бы молча —
                # причём именно на том шве, где её и нашли.
                case "$ALL" in
                    *location-compose.yaml*)  echo "omnifield/location:dev" ;;
                    # Имя образа контроллера принадлежит зоне `control`, и спрашивают его
                    # у неё же — так делают и сборка, и выпуск. Отвечаем за неё.
                    #
                    # Умолчание ЗАДАЁТСЯ СЦЕНАРИЕМ: соседняя задача той же истории
                    # (`WORLD2-112`) прописала туда полный адрес с реестром, а бывают и
                    # адреса с портом. Проверять выпуск только на сегодняшнем имени значит
                    # проверять его на том единственном случае, где он и так работает.
                    *control/compose.yaml*)   echo "${CONTROL_IMAGE:-${STUB_CONTROL_IMAGE:-omnifield/world-control:dev}}" ;;
                    # Имя образа РАЗДАЧИ принадлежит зоне `share` (`WORLD2-132`) — третий
                    # выпускаемый образ, и спрашивается он там же, где два первых.
                    *share/compose.yaml*)     echo "${SHARE_IMAGE:-${STUB_SHARE_IMAGE:-ghcr.io/omnifield/world-share:latest}}" ;;
                    # Имя образа МИРА принадлежит зоне `deploy` и живёт в её файле запуска.
                    # Выпуск спрашивает его там же, где чужое, — и сценарием оно так же
                    # крутится: у двери те же три случая разбора, что и у соседей.
                    *deploy/compose.yaml*)    echo "${WORLD_IMAGE:-${STUB_WORLD_IMAGE:-ghcr.io/omnifield/world:latest}}" ;;
                    *)                        echo "ghcr.io/omnifield/world:latest" ;;
                esac
                exit 0 ;;
            ps) echo "podstavnoy-kontejner-id"; exit 0 ;;
            up)
                # Значения, с которыми компоуз подставит имя двери в сети и настройку
                # локации, видны только в окружении процесса — в аргументах их нет. Пишем в
                # журнал отдельной строкой: иначе проверить, что настройка ДОЕХАЛА, нечем.
                printf 'ENV WORLD_DOOR_ALIAS=%s\n' "${WORLD_DOOR_ALIAS:-<нет>}" >> "${STUB_LOG:-/dev/null}"
                printf 'ENV WORLD_NAME=%s WORLD_GIVES=%s WORLD_DOOR=%s WORLD_NET=%s\n' \
                    "${WORLD_NAME:-<нет>}" "${WORLD_GIVES:-<нет>}" \
                    "${WORLD_DOOR:-<нет>}" "${WORLD_NET:-<нет>}" >> "${STUB_LOG:-/dev/null}"
                # Адрес застройки отдельной строкой: он необязателен, и «не заявлено» —
                # такой же проверяемый исход, как заявленный адрес.
                printf 'ENV WORLD_BUILD_ADDR=%s\n' \
                    "${WORLD_BUILD_ADDR:-<не заявлено>}" >> "${STUB_LOG:-/dev/null}"
                exit 0 ;;
            *)  exit 0 ;;
        esac ;;
    build)
        # ШТАМП ВЕРСИИ ставится поверх готового образа: `docker build -f -`, сборочный файл
        # приходит ПОТОКОМ. В аргументах значения штампа нет вовсе — оно в потоке; поэтому
        # заглушка поток вычитывает и кладёт в журнал построчно. Иначе проверить, ЧТО именно
        # вписано в образ, было бы нечем — а это и есть предмет проверки.
        while IFS= read -r stroka; do
            printf 'STDIN %s\n' "$stroka" >> "${STUB_LOG:-/dev/null}"
        done
        exit "${STUB_STAMP_FAIL:-0}" ;;
    run)
        case "$*" in
            *"${STUB_NODE_IMAGE:?}"*)
                # сборщик пульта. Поток исходника обычно выпивается (`cat`), но случай
                # `deaf` — нарочно НЕ выпивает: так ведёт себя упавший сборщик, и хостовый
                # tar получает SIGPIPE. Проверяем, что отказ назовёт сборщик, а не подачу.
                case "${STUB_BUILDER:-ok}" in
                    deaf)      exit 1 ;;
                    ok)        cat >/dev/null; emit_tar index.html assets/main.js; exit 0 ;;
                    nowebpage) cat >/dev/null; emit_tar assets/main.js;            exit 0 ;;
                    empty)     cat >/dev/null; exit 0 ;;
                    *)         cat >/dev/null; exit 1 ;;
                esac ;;
            "run -d"*)
                # фоновый контейнер (заглушка-локация, держатель порта, сломанные двери
                # красного прогона) — считаем, что запустился
                exit 0 ;;
            *probe-loc*)
                # стук в заглушку-локацию: отвечает она или нет
                [ -n "${STUB_LOC_READY:-}" ] && exit 0 || exit 1 ;;
            *) exit 0 ;;
        esac ;;
    *) exit 0 ;;
esac
STUB
chmod +x "$STUB_DIR/docker"

# ------------------------------------------------------------------ подставной git
# Выпуск (`release.sh`) метит образ КОММИТОМ и отказывается выпускать из грязного дерева.
# Проверить оба исхода настоящим гитом нельзя, не пачкая настоящее дерево, — а проба,
# которая ради своего сценария правит рабочую копию, однажды съест чужую работу. Поэтому
# гит здесь подставной, ровно как докер: он отвечает по сценарию и ничего не трогает.
#
# Знает он четыре вопроса и больше ничему не учится: репозиторий ли это, есть ли коммиты,
# какой коммит тронул НАЗВАННЫЕ ПУТИ и чисто ли по НАЗВАННЫМ ПУТЯМ. Ровно те, что задаёт
# версия образа.
#
# ПУТИ ЗДЕСЬ — НЕ ФОРМАЛЬНОСТЬ. С `WORLD2-146` версия принадлежит образу: `sha` берётся у
# последнего коммита, тронувшего перечень ИМЕННО ЭТОГО образа, и чистота спрашивается по нему
# же. Отвечай заглушка одинаково на любой список путей — проверить главное свойство («правка
# только в `web/` двигает версию контроллера и не двигает дверь») было бы нечем вовсе:
# зелёный прогон означал бы ровно то же, что и до задачи.
#
#   STUB_GIT_TOUCHED=<путь>:<sha>   этот путь тронут ОТДЕЛЬНЫМ коммитом; спросили список,
#                                   в котором он есть, — ответ его, иначе общий
#   STUB_GIT_DIRTY_PATH=<путь>      грязен только он: спросили без него — чисто
#   STUB_GIT_DIRTY=1                грязно по любому списку (прежнее поведение)
cat > "$STUB_DIR/git" <<'STUBGIT'
#!/usr/bin/env bash
# ПОДСТАВНОЙ git: отвечает по сценарию, рабочей копии не касается.
printf 'git %s\n' "$*" >> "${STUB_LOG:-/dev/null}"
while [ $# -gt 0 ]; do case "$1" in -C) shift 2 ;; *) break ;; esac; done

# sprosili ПУТЬ — назван ли этот путь среди аргументов вызова. Смотрим ПОСЛЕ `--`: слева от
# него ключи, справа пути, и путать их нельзя.
sprosili() {
    local hochu="$1"; shift
    local posle= a
    for a in "$@"; do
        [ "$a" = "--" ] && { posle=1; continue; }
        [ -n "$posle" ] && [ "$a" = "$hochu" ] && return 0
    done
    return 1
}

case "$1" in
    rev-parse)
        case "$*" in
            *--git-dir*) [ -n "${STUB_GIT_REPO-1}" ] && { echo .git; exit 0; }; exit 128 ;;
            # `${STUB_GIT_SHA-abc1234}` БЕЗ двоеточия: пустое значение сценария означает
            # «коммитов нет вовсе», а не «возьми умолчание». Это отдельное состояние, и
            # `version.sh` отвечает на него своим кодом (`no-commit`).
            *HEAD*)      printf '%s\n' "${STUB_GIT_SHA-abc1234}"; exit 0 ;;
        esac ;;
    log)
        # Коммитов нет вовсе — молчим и здесь: иначе версия нашлась бы там, где её нет.
        [ -n "${STUB_GIT_SHA-abc1234}" ] || exit 0

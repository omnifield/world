#!/usr/bin/env bash
# Проба подъёма мира — поднимает образ и проверяет, что вход в поле работает.
#
#   ./deploy/probe.sh          зелёный прогон: подняли и проверили
#   ./deploy/probe.sh --red    красный прогон: ломаем нарочно и убеждаемся, что проба падает
#   ./deploy/probe.sh --both   сначала зелёный, потом красный
#
# ┌─────────────────────────────────────────────────────────────────────────────────────┐
# │ ПРОБА РАЗРУШИТЕЛЬНА ДЛЯ ЖИВОГО МИРА. Это не побочный эффект, а условие: проверять    │
# │ надо на том, на чём поедет, — на штатном порту, штатным файлом запуска, в живом      │
# │ поле. Но знать об этом надо ДО прогона, а не после.                                  │
# │                                                                                      │
# │ Что она делает с работающим миром:                                                   │
# │   · пересоздаёт контейнер двери (down + up) — перерыв в обслуживании;                │
# │   · регистрирует в поле заглушку `probe-loc` — своим же образом — и снимает её в    │
# │     конце; при провале ОСТАВЛЯЕТ её уликой и говорит, чем убрать;                   │
# │   · красный прогон ЗАНИМАЕТ штатный хост-порт и оставляет мир СНЯТЫМ.                │
# │                                                                                      │
# │ Чего она не делает: тома не трогает — `down` идёт без `-v`, поле переживает прогон.  │
# │ Не на боевом поле — прогоняй, для того и написана. На боевом — сначала предупреди.   │
# └─────────────────────────────────────────────────────────────────────────────────────┘
#
# Что проверяет зелёный прогон — ровно то, чем принимают зону:
#
#   1. /healthz отвечает                     дверь жива
#   2. регистрация проходит                  локация попадает в поле
#   3. маршрут работает                      к локации ходят через дверь по её имени
#   4. пересоздание сохраняет поле           реестр лежит на томе, а не в слое контейнера
#   5. в образе двери нет лица               ни пульта, ни каталога под него
#   6. сосед видит дверь по имени            в поле можно войти изнутри общей сети
#
# ПУЛЬТ ЗДЕСЬ БОЛЬШЕ НЕ ПРОВЕРЯЕТСЯ, и это не пропуск. Дверь перестала раздавать веб
# (`WORLD2-107`): на корне она отвечает `410 face-elsewhere` и называет адрес контроллера.
# Проверка «пульт открывается» стерегла бы то, чего дверь не отдаёт, — а снятая проверка,
# оставленная на всякий случай, это зелёная ложь (`WORLD2` 4.2). Лицо проверяют там, где
# оно живёт, — при контроллере (зона `control`). Взамен пятая проверка стережёт ОБРАТНОЕ:
# что раздача не вернулась в образ двери тихо, слоем или каталогом.
#
# Всё — СНАРУЖИ контейнера, по опубликованному хост-порту. Изнутри проверять
# опубликованный порт бессмысленно: он там не участвует, и проба зеленела бы даже тогда,
# когда наружу не торчит ничего.
#
# Четвёртый пункт делает ПЕРЕСОЗДАНИЕ, а не рестарт, и это главное место всей пробы:
# рестарт сохраняет реестр и БЕЗ тома — слой контейнера при рестарте никуда не девается.
# Проба на рестарте зеленела бы на несмонтированном томе, то есть не была бы пробой
# (`kb:WORLD-32`).
#
# Красный прогон — не приложение к зелёному, а его подтверждение. Он ломает подъём четырьмя
# способами (том не смонтирован · порт занят · маршрут ведёт обратно в дверь · дверь без
# имени в сети) и требует, чтобы проба ПОКРАСНЕЛА. Зелёная проба, которую ни разу не
# заставили упасть, пробой не является.
#
# Заглушка-локация поднимается НАШИМ ЖЕ образом, а не чужим: чужой образ приносит чужие
# предположения, и на этом мы уже обожглись — апплет `httpd` уехал из базового busybox в
# отдельный пакет, и прежняя заглушка (`alpine:3` + `httpd`) перестала подниматься. Лишних
# образов проба не тянет вовсе, а в поле встаёт настоящая локация, а не бутафория.
#
# УБОРКА НЕ СЪЕДАЕТ УЛИКУ. Контейнер, в котором лежит причина отказа, проба оставляет жить,
# а его состояние и хвост журнала печатает прямо в отказ. Иначе выход «посмотри журнал»
# исполнить нечем: раньше его съедал наш же `trap cleanup EXIT` (`kb:WORLD-31`).
#
# Имена переменных ЛАТИНСКИЕ намеренно: bash не поддерживает не-ASCII в именах переменных
# и молча превращает `ПОРТ=8080` в «команда не найдена». Тексты и комментарии — русские.
#
# Проверки ниже зовутся косвенно — через `green`/`red`, по имени в аргументе; линтер
# читает это как «функция не вызвана». Глушим, чтобы его прогон был чистым и настоящая
# находка не потерялась среди шума.
# shellcheck disable=SC2329
set -euo pipefail

NET=omnifield-gateway
PORT="${WORLD_PORT:-8080}"
# Адрес, по которому машина видит свой же опубликованный порт (умолчание `127.0.0.1`, довод
# целиком — в `up.sh`). Проба обязана проверять то, что ЕСТЬ: на машине, где хост-петля до
# докера не доходит, зашитый адрес называл живую дверь мёртвой (`tasker:WORLD-97`).
#
# Здесь у значения ДВЕ работы, и это одна и та же работа: по нему проба стучится и на нём же
# ПУБЛИКУЕТ сломанные двери красного прогона. Публиковать в одном месте, а стучаться в другое
# — значит краснеть по посторонней причине.
HOST="${WORLD_HOST:-127.0.0.1}"
RED_PORT="${WORLD_PROBE_RED_PORT:-8099}"
LOC=probe-loc
# Заглушка бежит нашим образом, а он слушает 8080 внутри контейнера — как и дверь. Реестр
# принимает любой адрес, менять там нечего.
LOC_PORT=8080
# Контрактное имя двери в сети — то же умолчание, что в `up.sh` и `compose.yaml`. Проба
# обязана проверять адрес, которым пользуется сосед, а не тот, что удобен ей.
ALIAS="${WORLD_DOOR_ALIAS:-door}"

HERE="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
COMPOSE=("docker" "compose" "-f" "$HERE/compose.yaml")

# Имя образа берём из файла запуска, а не держим вторую копию здесь: разъедутся — проба
# начнёт проверять не тот образ, который поднимает `up.sh`.
IMAGE="$("${COMPOSE[@]}" config --images 2>/dev/null | head -n1 || true)"
[ -n "$IMAGE" ] || IMAGE=ghcr.io/omnifield/world:latest

mode=--green
want_build=


#!/usr/bin/env bash
# Проба подъёма мира — поднимает образ и проверяет, что вход в поле работает.
#
#   ./deploy/probe.sh          зелёный прогон: подняли и проверили
#   ./deploy/probe.sh --red    красный прогон: ломаем нарочно и убеждаемся, что проба падает
#   ./deploy/probe.sh --both   сначала зелёный, потом красный
#
# ┌─────────────────────────────────────────────────────────────────────────────────────┐
# │ ПРОБА РАЗРУШИТЕЛЬНА ДЛЯ ЖИВОГО МИРА. Это не побочный эффект, а условие: проверять    │
# │ надо на том, на чём поедет, — на штатном порту, штатным файлом запуска, в живом      │
# │ поле. Но знать об этом надо ДО прогона, а не после.                                  │
# │                                                                                      │
# │ Что она делает с работающим миром:                                                   │
# │   · пересоздаёт контейнер двери (down + up) — перерыв в обслуживании;                │
# │   · регистрирует в поле заглушку `probe-loc` — своим же образом — и снимает её в    │
# │     конце; при провале ОСТАВЛЯЕТ её уликой и говорит, чем убрать;                   │
# │   · красный прогон ЗАНИМАЕТ штатный хост-порт и оставляет мир СНЯТЫМ.                │
# │                                                                                      │
# │ Чего она не делает: тома не трогает — `down` идёт без `-v`, поле переживает прогон.  │
# │ Не на боевом поле — прогоняй, для того и написана. На боевом — сначала предупреди.   │
# └─────────────────────────────────────────────────────────────────────────────────────┘
#
# Что проверяет зелёный прогон — ровно то, чем принимают зону:
#
#   1. /healthz отвечает                     дверь жива
#   2. пульт открывается                     и это СБОРКА, а не исходник
#   3. регистрация проходит                  локация попадает в поле
#   4. маршрут работает                      к локации ходят через дверь по её имени
#   5. пересоздание сохраняет поле           реестр лежит на томе, а не в слое контейнера
#   6. в образе только собранное             исходников внутрь не уехало
#   7. сосед видит дверь по имени            в поле можно войти изнутри общей сети
#
# Всё — СНАРУЖИ контейнера, по опубликованному хост-порту. Изнутри проверять
# опубликованный порт бессмысленно: он там не участвует, и проба зеленела бы даже тогда,
# когда наружу не торчит ничего.
#
# Пятый пункт делает ПЕРЕСОЗДАНИЕ, а не рестарт, и это главное место всей пробы: рестарт
# сохраняет реестр и БЕЗ тома — слой контейнера при рестарте никуда не девается. Проба на
# рестарте зеленела бы на несмонтированном томе, то есть не была бы пробой (`kb:WORLD-32`).
#
# Красный прогон — не приложение к зелёному, а его подтверждение. Он ломает подъём четырьмя
# способами (том не смонтирован · порт занят · фронт не собран · дверь без имени в сети) и
# требует, чтобы проба ПОКРАСНЕЛА. Зелёная проба, которую ни разу не заставили упасть,
# пробой не является.
#
# Заглушка-локация поднимается НАШИМ ЖЕ образом, а не чужим: чужой образ приносит чужие
# предположения, и на этом мы уже обожглись — апплет `httpd` уехал из базового busybox в
# отдельный пакет, и прежняя заглушка (`alpine:3` + `httpd`) перестала подниматься. Лишних
# образов проба не тянет вовсе, а в поле встаёт настоящая локация, а не бутафория.
#
# УБОРКА НЕ СЪЕДАЕТ УЛИКУ. Контейнер, в котором лежит причина отказа, проба оставляет жить,
# а его состояние и хвост журнала печатает прямо в отказ. Иначе выход «посмотри журнал»
# исполнить нечем: раньше его съедал наш же `trap cleanup EXIT` (`kb:WORLD-31`).
#
# Имена переменных ЛАТИНСКИЕ намеренно: bash не поддерживает не-ASCII в именах переменных
# и молча превращает `ПОРТ=8080` в «команда не найдена». Тексты и комментарии — русские.
#
# Проверки ниже зовутся косвенно — через `green`/`red`, по имени в аргументе; линтер
# читает это как «функция не вызвана». Глушим, чтобы его прогон был чистым и настоящая
# находка не потерялась среди шума.
# shellcheck disable=SC2329
set -euo pipefail

NET=omnifield-gateway
PORT="${WORLD_PORT:-8080}"
RED_PORT="${WORLD_PROBE_RED_PORT:-8099}"
LOC=probe-loc
# Заглушка бежит нашим образом, а он слушает 8080 внутри контейнера — как и дверь. Реестр
# принимает любой адрес, менять там нечего.
LOC_PORT=8080
# Контрактное имя двери в сети — то же умолчание, что в `up.sh` и `compose.yaml`. Проба
# обязана проверять адрес, которым пользуется сосед, а не тот, что удобен ей.
ALIAS="${WORLD_DOOR_ALIAS:-door}"
MARK='проба подъёма: локация отвечает'

HERE="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
COMPOSE=("docker" "compose" "-f" "$HERE/compose.yaml")

# Имя образа берём из файла запуска, а не держим вторую копию здесь: разъедутся — проба
# начнёт проверять не тот образ, который поднимает `up.sh`.
IMAGE="$("${COMPOSE[@]}" config --images 2>/dev/null | head -n1 || true)"
[ -n "$IMAGE" ] || IMAGE=omnifield/world:dev

mode=--green
want_build=

usage() {
    cat <<'USAGE'
Проба подъёма мира: ./deploy/probe.sh [--green|--red|--both] [--build]

  --green    (умолчание) поднять и проверить: healthz · пульт · регистрация ·
             маршрут · пересоздание сохраняет поле · в образе только собранное ·
             сосед видит дверь по имени в общей сети
  --red      сломать подъём нарочно (том не смонтирован · порт занят · фронт не
             собран · дверь без имени в сети) и убедиться, что проба КРАСНЕЕТ
  --both     сначала зелёный, потом красный
  --build    пересобрать образ перед подъёмом (deploy/build.sh, нужно поле).
             Без ключа проба проверяет тот образ, который уже лежит, — то
             есть ровно то, что поедет
  -h --help  эта подсказка

  ВНИМАНИЕ: ПРОБА РАЗРУШИТЕЛЬНА ДЛЯ ЖИВОГО МИРА. Она работает на ШТАТНОМ порту и
  в ЖИВОМ поле — иначе проверяла бы не то, что поедет. На работающем мире это:
    · пересоздание контейнера двери — перерыв в обслуживании;
    · заглушка probe-loc, зарегистрированная в поле (снимается в конце,
      а при провале остаётся уликой — команда на уборку в отказе);
    · красный прогон занимает штатный порт и ОСТАВЛЯЕТ МИР СНЯТЫМ.
  Тома не трогаются: down идёт без -v, поле прогон переживает.

  Заглушка-локация поднимается нашим же образом omnifield/world:dev — чужих
  образов проба не тянет. Провалилась проверка — контейнер ОСТАЁТСЯ уликой
  вместе с журналом; команда, которой его убрать, названа в самом отказе.

Переменные:
  WORLD_PORT=8090            штатный хост-порт, на котором идёт прогон
  WORLD_DOOR_ALIAS=door      имя двери в общей сети — то, по чему входит сосед
  WORLD_PROBE_RED_PORT=8099  порт для сломанных контейнеров красного прогона
USAGE
}

# Ключи разбираем ДО всего остального: `--help` обязан работать и там, где докера нет.
while [ $# -gt 0 ]; do
    case "$1" in
        --green|--red|--both) mode="$1" ;;
        --build)              want_build=1 ;;
        -h|--help)            usage; exit 0 ;;
        *)  usage >&2; printf '\nнепонятный ключ: %s\n' "$1" >&2; exit 2 ;;
    esac
    shift
done

total=0; failed=0

part()   { printf '\n\033[1m%s\033[0m\n' "$*" >&2; }
detail() { printf '      %s\n' "$*" >&2; }

# green <имя> <проверка…> — проверка ОБЯЗАНА пройти.
green() {
    local name="$1"; shift
    total=$((total + 1))
    if "$@"; then printf '  \033[32m✔\033[0m %s\n' "$name" >&2; return 0; fi
    printf '  \033[31m✘\033[0m %s\n' "$name" >&2
    failed=$((failed + 1)); return 1
}

# red <имя> <проверка…> — проверка ОБЯЗАНА упасть. Мы сломали подъём нарочно; если после
# этого она зеленеет, чинить надо пробу, а не подъём.
red() {
    local name="$1"; shift
    total=$((total + 1))
    if "$@"; then
        printf '  \033[31m✘\033[0m %s — проба ЗЕЛЕНЕЕТ на сломанном подъёме\n' "$name" >&2
        failed=$((failed + 1)); return 1
    fi
    printf '  \033[32m✔\033[0m %s — покраснела, как и должна\n' "$name" >&2; return 0
}

fail() {
    printf '\n\033[1;31m✗ пробу не выполнить: %s\033[0m\n' "$1" >&2
    shift; local line; for line in "$@"; do printf '  выход: %s\n' "$line" >&2; done
    exit 1
}

# docker_noconv … — вызов докера, в аргументах которого нет путей ХОСТА, но есть
# контейнерные (`-e WORLD_WEB_DIR=/app/…`, `wget -O …`). Git Bash (MSYS) переписал бы их в
# виндовые, и проба проверяла бы не то, что думает. Правило зоны и довод целиком — в
# `build.sh` рядом с таким же помощником; глушить перевод глобально нельзя, потому что
# `docker compose -f "$HERE/compose.yaml"` подаёт путь хоста, и его переводить обязаны.
docker_noconv() { MSYS_NO_PATHCONV=1 MSYS2_ARG_CONV_EXCL='*' docker "$@"; }

# ------------------------------------------------------------------ разговор с дверью
# curl нужен ПРОБЕ, а не подъёму: мир поднимается одним докером, а вот стучаться в него
# чем-то надо. Отсутствие curl — отказ пробы, и он назван, а не выглядит как «мир не встал».
body_and_code() { curl -sS -m 10 -w $'\n%{http_code}' "$@" 2>&1; }
http_code()     { curl -s  -m 10 -o /dev/null -w '%{http_code}' "$@" 2>/dev/null || echo 000; }

# wait_door <база> — «контейнер запущен» и «дверь отвечает» не одно и то же.
wait_door() {
    local _
    for _ in {1..30}; do
        [ "$(http_code "$1/healthz")" = 200 ] && return 0
        sleep 1
    done
    return 1
}

# ------------------------------------------------------------------ сами проверки
# Функции ниже — единственное место, где написано, что считается работающим входом в поле.
# Зелёный и красный прогоны зовут ИХ ЖЕ: иначе красный проверял бы не то, что зелёный.

# 1. дверь жива
check_alive() {
    local answer code body
    answer=$(body_and_code "$1/healthz") || { detail "дверь не ответила: $answer"; return 1; }
    code=${answer##*$'\n'}; body=${answer%$'\n'*}
    [ "$code" = 200 ] || { detail "healthz ответил $code, а не 200: $body"; return 1; }
    case "$body" in
        *'"status":"ok"'*) return 0 ;;
        *) detail "healthz ответил не ok: $body"; return 1 ;;
    esac
}

# 2. пульт открывается — и это СБОРКА, а не исходник
#
# Три вопроса, а не один «ответило ли 200». Дверь отдаёт 503 web-not-built, когда пульт не
# собран (`core/README.md`), и на этом проверка обязана краснеть. А ещё она обязана
# краснеть на ИСХОДНИКЕ пульта: у него свой index.html, он тоже отдаётся с кодом 200, и
# снаружи это выглядит как рабочая страница, которая ничего не показывает.
check_panel() {
    local answer code body bundle bundle_code
    answer=$(body_and_code "$1/") || { detail "пульт не ответил: $answer"; return 1; }
    code=${answer##*$'\n'}; body=${answer%$'\n'*}
    [ "$code" = 200 ] || { detail "корень ответил $code, а не 200: $body"; return 1; }

    case "$body" in
        *'/src/main.tsx'*)
            detail "отдаётся ИСХОДНИК пульта, а не сборка (в теле ссылка на /src/main.tsx)"
            detail "выход: WORLD_WEB_DIR обязан смотреть на каталог сборки, в образе это /app/web"
            return 1 ;;
    esac

    bundle=$(printf '%s' "$body" | grep -o '/assets/[A-Za-z0-9._-]*\.js' | head -n1)
    [ -n "$bundle" ] || { detail "в странице нет ссылки на собранный бандл /assets/*.js"; return 1; }

    # Сам бандл тоже спрашиваем: index.html мог доехать в одиночку, и пульт открылся бы
    # белым экраном — снаружи это неотличимо от рабочего.
    bundle_code=$(http_code "$1$bundle")
    [ "$bundle_code" = 200 ] || { detail "бандл $bundle отдаётся с кодом $bundle_code"; return 1; }
    return 0
}

# 3. регистрация проходит
check_register() {
    local answer code body
    answer=$(body_and_code -X POST "$1/api/locations" \
        -H 'Content-Type: application/json' \
        -d "{\"name\":\"$2\",\"addr\":\"$3\",\"gives\":\"проба подъёма мира\"}") \
        || { detail "дверь не ответила на регистрацию: $answer"; return 1; }
    code=${answer##*$'\n'}; body=${answer%$'\n'*}
    case "$code" in
        201|200) return 0 ;;
        *) detail "регистрация ответила $code: $body"; return 1 ;;
    esac
}

# 4. маршрут работает — к локации ходят снаружи по её имени
check_route() {
    local answer code body
    answer=$(body_and_code "$1/$2/probe.txt") || { detail "маршрут не ответил: $answer"; return 1; }
    code=${answer##*$'\n'}; body=${answer%$'\n'*}
    [ "$code" = 200 ] || { detail "маршрут /$2/ ответил $code: $body"; return 1; }
    case "$body" in
        *"$MARK"*) return 0 ;;
        *) detail "по маршруту ответила не наша заглушка: $body"; return 1 ;;
    esac
}

# 5. поле на месте — локация видна в реестре
check_in_field() {
    local body
    body=$(curl -sS -m 10 "$1/api/locations" 2>&1) || { detail "реестр не ответил: $body"; return 1; }
    case "$body" in
        *"\"$2\""*) return 0 ;;
        *) detail "локации $2 в поле нет: $body"; return 1 ;;
    esac
}

# 6. в образе только собранное — исходников там нет
#
# Свойство держится построением: пульт собирается ДО образа, отдельным шагом, и внутрь
# копируется каталог сборки, а не зона `web` (`deploy/build.sh`). Но «держится построением»
# это ровно тот случай, когда через полгода кто-то поправит COPY и никто не заметит.
# Единственная проверка, которая смотрит в САМ ОБРАЗ, а не в поднятую дверь.
check_image_clean() {
    local listing
    listing=$(docker_noconv run --rm --entrypoint sh "$1" -c 'ls -Ra /app' 2>&1) \
        || { detail "в образ не заглянуть: $listing"; return 1; }
    case "$listing" in
        *node_modules*|*.tsx*|*package.json*|*pnpm-lock*|*tsconfig*|*vite.config*)
            detail "в образе нашлись исходники или оснастка сборки — туда должно ехать только собранное:"
            # `|| true` не для красоты: `head -5` закрывает трубу, `grep` получает SIGPIPE,
            # и при `set -euo pipefail` проба падала бы целиком ровно там, где нашла находку.
            printf '%s\n' "$listing" | grep -E 'node_modules|\.tsx|package\.json|pnpm-lock|tsconfig|vite\.config' | head -5 >&2 || true
            return 1 ;;
    esac
    case "$listing" in
        *index.html*) ;;
        *) detail "в образе нет собранной страницы (/app/web/index.html):"
           printf '%s\n' "$listing" | head -10 >&2 || true   # SIGPIPE от head — см. выше
           return 1 ;;
    esac
    return 0
}

# 7. сосед видит дверь по объявленному имени — то есть в поле можно войти
#
# Единственная проверка, которая смотрит на дверь ИЗНУТРИ общей сети, а не через хост-порт,
# и потому единственная, которая подтверждает контракт соседа (`door:8080`). Через хост её
# не подменить: сосед хост-публикацией не пользуется вовсе, и дверь без объявленного имени
# выглядела бы снаружи совершенно рабочей.
#
# Стучимся из ЧУЖОГО контейнера, а не из самой двери: изнутри себя имя резолвится всегда, и
# проверка зеленела бы даже тогда, когда алиаса в сети нет.
check_neighbour_sees_door() {
    local out
    out=$(docker_noconv run --rm --network "$NET" --entrypoint wget "$IMAGE" \
        -q -T 5 -O- "http://$1:8080/healthz" 2>&1) || {
        detail "по имени $1:8080 из сети $NET дверь не ответила: $out"
        detail "выход: проверь имя — docker inspect world-door --format '{{json .NetworkSettings.Networks}}'"
        return 1
    }
    case "$out" in
        *'"status":"ok"'*) return 0 ;;
        *) detail "по имени $1:8080 ответило что-то не то: $out"; return 1 ;;
    esac
}

# ------------------------------------------------------------------ заглушка-локация
# Сосед, который отвечает по имени в общей сети. Дверь на регистрации больше ничего и не
# проверяет (`core/README.md`): одно TCP-соединение.
#
# Поднимается НАШИМ ЖЕ образом, а не чужим. Три довода, и первый — живой:
#
# 1. чужой образ приносит чужие предположения. Прежняя заглушка была `alpine:3` + `httpd`,
#    и она перестала подниматься: апплет `httpd` вынесен из базового busybox в отдельный
#    пакет `busybox-extras`. Вызов был верен для того alpine, который помнили, и тихо
#    перестал быть верным для того, который приезжает сегодня (живой прогон,
#    `tasker:WORLD-37`). Ставить пакет на прогоне нельзя: проба стала бы зависеть от
#    выхода наружу, и «нет интернета» читалось бы как «заглушка не поднялась»;
# 2. лишних образов не тянем вообще: `omnifield/world:dev` к этому моменту на машине
#    заведомо есть — без него прогона нет вовсе;
# 3. заглушка перестаёт быть бутафорией: в поле встаёт НАСТОЯЩАЯ локация, и маршрут
#    проверяется на том, что реально поедет.
#
# Метку кладём в витрину образа перед стартом двери — она и есть то, по чему проверка
# маршрута отличает соседа от самой двери. Без метки проверка была бы ложно-зелёной:
# обе стороны — один образ, и ответ двери на свой же `/healthz` выглядел бы как ответ
# соседа. Из-под root ровно ради этой записи: /app/web владеет root, а мир бежит не из-под
# него. Это стенд на один прогон, а не мир.
stub_up() {
    docker rm -f "world-$LOC" >/dev/null 2>&1 || true
    docker_noconv run -d --name "world-$LOC" \
        --network "$NET" --network-alias "$LOC" \
        --user root --entrypoint sh "$IMAGE" \
        -c "printf '%s\n' '$MARK' > /app/web/probe.txt && exec /app/world" \
        >/dev/null
    local _
    for _ in {1..15}; do
        # Стучимся тоже своим образом — busybox `wget` в нём есть, и это тот самый wget,
        # которым стучится HEALTHCHECK. `-O-`, а не `-O /dev/null`: одиночный аргумент со
        # слэша Git Bash переписал бы в виндовый путь, wget упал бы на записи, и заглушка
        # выглядела бы неподнявшейся.
        docker_noconv run --rm --network "$NET" --entrypoint wget "$IMAGE" \
            -q -T 2 -O- "http://$LOC:$LOC_PORT/probe.txt" >/dev/null 2>&1 && return 0
        sleep 1
    done
    # Улику снимаем ДО отказа и контейнер оставляем: иначе выход «посмотри журнал»
    # исполнить нечем — его съела бы наша же уборка.
    evidence "world-$LOC"
    fail "заглушка-локация не поднялась" \
        "её состояние и журнал — прямо выше, контейнер оставлен" \
        "полный журнал: docker logs world-$LOC" \
        "убрать, когда разберёшься: docker rm -f world-$LOC"
}

# ------------------------------------------------------------------ уборка и улики
# Прервали пробу на полпути — мусор убираем: иначе следующий прогон упрётся в занятое имя
# контейнера, и причина будет выглядеть посторонней.
#
# НО УБОРКА НЕ ВПРАВЕ СЪЕДАТЬ УЛИКУ. Отказ, который отправляет смотреть журнал контейнера,
# а сам этот контейнер сносит, выхода не даёт — он даёт диагноз (`kb:WORLD-31`). Живой
# случай: «заглушка не поднялась → посмотри `docker logs world-probe-loc`» → `No such
# container`, потому что его снёс этот самый trap. Причину пришлось добывать руками.
#
# Поэтому: контейнер, в котором лежит причина, ОСТАЁТСЯ ЖИТЬ, а его состояние и хвост
# журнала печатаются сразу — в вывод прогона, который переживёт и сам контейнер.
KEEP=' '   # имена контейнеров-улик: их уборка не трогает

# evidence <контейнер> — снять улику, пока контейнер жив, и оставить его.
evidence() {
    local name="$1"
    KEEP="$KEEP$name "
    printf '\n  ── улика: %s ──\n' "$name" >&2
    docker ps -a --filter "name=^${name}$" \
        --format '  состояние: {{.Status}}  ·  образ: {{.Image}}' >&2 2>/dev/null || true
    if docker logs --tail=30 "$name" >/dev/null 2>&1; then
        { docker logs --tail=30 "$name" 2>&1 | sed 's/^/  │ /' >&2; } || true
    else
        printf '  журнал не читается — контейнера может не быть вовсе\n' >&2
    fi
    printf '  контейнер ОСТАВЛЕН нарочно. Смотреть: docker logs %s · убрать: docker rm -f %s\n' \
        "$name" "$name" >&2
}

# block / blockdone <контейнер…> — рамка вокруг куска прогона. Если внутри что-то
# провалилось, контейнеры куска остаются уликой, а не сносятся: разбирать провал по
# снесённому контейнеру нечем, и это тот же дефект, только отложенный.
block_from=0
block()     { block_from=$failed; }
blockdone() {
    local name
    for name in "$@"; do
        if [ "$failed" != "$block_from" ]; then evidence "$name"
        else docker rm -f "$name" >/dev/null 2>&1 || true; fi
    done
}

cleanup() {
    local name
    for name in "world-$LOC" world-red-vol world-red-port world-red-web world-red-alias; do
        case "$KEEP" in *" $name "*) continue ;; esac
        docker rm -f "$name" >/dev/null 2>&1 || true
    done
    [ "$KEEP" = ' ' ] || printf '\n  улики оставлены нарочно:%s\n  убрать всё разом: docker rm -f%s\n' \
        "$KEEP" "$KEEP" >&2
    return 0
}
trap cleanup EXIT

command -v docker >/dev/null 2>&1 || fail "докера на машине нет" \
    "поставь Docker Engine: https://docs.docker.com/engine/install/"
command -v curl >/dev/null 2>&1 || fail "на машине нет curl, а проба стучится в дверь снаружи" \
    "поставь curl (сам мир для подъёма его не требует — он нужен только пробе)"

# ================================================================== ЗЕЛЁНЫЙ ПРОГОН
run_green() {
    local base="http://127.0.0.1:$PORT"

    part "── зелёный прогон: поднимаем мир и проверяем вход в поле"

    part "подъём (deploy/up.sh)"
    if [ -n "$want_build" ]; then
        WORLD_PORT="$PORT" "$HERE/up.sh" --build >&2 || fail "мир не поднялся — причина названа выше"
    else
        # Без `--build` — намеренно: проба проверяет ТОТ образ, который поедет, а не свежий.
        WORLD_PORT="$PORT" "$HERE/up.sh" >&2 || fail "мир не поднялся — причина названа выше"
    fi

    part "заглушка-локация $LOC в сети $NET"
    stub_up
    detail "поднята"

    block
    part "проверки — все снаружи контейнера, через хост-порт $PORT"
    green "1. /healthz отвечает"                          check_alive "$base" || true
    green "2. пульт открывается (сборка, не исходник)"    check_panel "$base" || true
    green "3. регистрация проходит"                       check_register "$base" "$LOC" "$LOC:$LOC_PORT" || true
    green "4. маршрут /$LOC/ работает"                    check_route "$base" "$LOC" || true

    # ПЕРЕСОЗДАНИЕ, а не рестарт: см. шапку файла. `down` без `-v` сносит контейнер и
    # оставляет тома — ровно то, чем принимают зону.
    part "пересоздаю контейнер (down + up, тома остаются)"
    "${COMPOSE[@]}" down >/dev/null 2>&1 || true
    WORLD_PORT="$PORT" "${COMPOSE[@]}" up -d >/dev/null 2>&1 \
        || fail "контейнер не встал обратно" "журнал: docker compose -f $HERE/compose.yaml logs"
    wait_door "$base" || fail "после пересоздания дверь не ответила" \
        "журнал: docker compose -f $HERE/compose.yaml logs --tail=40"
    green "5. поле пережило пересоздание (том живой)"     check_in_field "$base" "$LOC" || true
    green "6. в образе только собранное"                  check_image_clean "$IMAGE" || true
    green "7. сосед видит дверь по имени $ALIAS:8080"     check_neighbour_sees_door "$ALIAS" || true

    part "убираю за собой"
    curl -sS -m 10 -X DELETE "$base/api/locations/$LOC" >/dev/null 2>&1 || true
    # Провалилась хоть одна проверка — заглушка остаётся уликой вместе с журналом: по
    # снесённому контейнеру разбирать нечего, а «повтори прогон» выходом не является.
    blockdone "world-$LOC"
    if [ "$failed" = "$block_from" ]; then
        detail "заглушка снята, локация из поля убрана; мир оставлен поднятым на $base"
    else
        detail "локация из поля убрана; мир оставлен поднятым на $base"
    fi
}

# ================================================================== КРАСНЫЙ ПРОГОН
# Три поломки, названные в приёмке. Каждая ломает ОДНУ вещь и требует, чтобы покраснела
# ровно та проверка, которая за неё отвечает, — а соседние остались зелёными. Проверка,
# которая краснеет от всего подряд, не показывает причину и потому бесполезна.
run_red() {
    local red_base="http://127.0.0.1:$RED_PORT"

    part "── красный прогон: ломаем подъём нарочно, проба обязана падать"

    # Молча собирать нельзя: сборка требует поля, а красный прогон — нет. Образа нет —
    # это отказ с выходом, а не тихая двухминутная стройка (`kb:WORLD-54`).
    if ! docker image inspect "$IMAGE" >/dev/null 2>&1; then
        [ -n "$want_build" ] || fail \
            "образа $IMAGE на машине нет — красному прогону нечего ломать" \
            "перенеси готовый образ: docker load < world.tar — поля для этого не нужно" \
            "либо собери здесь: ./deploy/probe.sh --red --build (вот для сборки поле нужно)"
        part "образа нет, просили --build — собираю"
        "$HERE/build.sh" >&2 || fail "образ не собрался" "причина названа выше"
    fi

    # ---------- поломка 1: том не смонтирован ----------
    # Реестр ложится в слой контейнера. Рестарт этого не покажет — покажет пересоздание.
    part "поломка 1 — том под реестр не смонтирован"
    block
    docker rm -f world-red-vol >/dev/null 2>&1 || true
    stub_up
    docker run -d --name world-red-vol --network "$NET" \
        -p "127.0.0.1:$RED_PORT:8080" "$IMAGE" >/dev/null
    wait_door "$red_base" || { evidence world-red-vol; fail \
        "контейнер без тома не поднялся" \
        "состояние и журнал — прямо выше, контейнер оставлен" \
        "убрать, когда разберёшься: docker rm -f world-red-vol"; }
    green "дверь жива и без тома (ломали не её)"  check_alive "$red_base" || true
    green "локация зарегистрировалась"            check_register "$red_base" "$LOC" "$LOC:$LOC_PORT" || true
    docker rm -f world-red-vol >/dev/null 2>&1
    docker run -d --name world-red-vol --network "$NET" \
        -p "127.0.0.1:$RED_PORT:8080" "$IMAGE" >/dev/null
    wait_door "$red_base" || { evidence world-red-vol; fail \
        "пересозданный контейнер без тома не поднялся" \
        "состояние и журнал — прямо выше, контейнер оставлен" \
        "убрать, когда разберёшься: docker rm -f world-red-vol"; }
    red   "5. поле пережило пересоздание"         check_in_field "$red_base" "$LOC" || true
    blockdone world-red-vol "world-$LOC"

    # ---------- поломка 2: хост-порт занят ----------
    # Подъём обязан не просто упасть, а НАЗВАТЬ порт и следующее действие (`kb:WORLD-31`).
    # Проверка здесь ЗЕЛЁНАЯ, хотя путь красный: спрашивается качество отказа, а исходов
    # три, и два из них провал — подъём зазеленел на занятом порту (значит публикации
    # наружу не случилось) либо упал молча, не назвав ни порта, ни выхода.
    part "поломка 2 — хост-порт $PORT занят"
    "${COMPOSE[@]}" down >/dev/null 2>&1 || true
    docker rm -f world-red-port >/dev/null 2>&1 || true
    # Порт держим СВОИМ образом, а не чужим: лишних образов проба не тянет, а `sleep` в
    # busybox есть всегда — в отличие от `httpd`, на котором мы уже обожглись.
    docker_noconv run -d --name world-red-port -p "$PORT:8080" \
        --entrypoint sleep "$IMAGE" 600 >/dev/null
    sleep 1
    check_busy_port_named() {
        local out status
        out=$(WORLD_PORT="$PORT" "$HERE/up.sh" 2>&1) && status=0 || status=$?
        if [ "$status" = 0 ]; then
            detail "up.sh завершился УСПЕХОМ на занятом порту — публикации наружу не случилось"
            return 1
        fi
        case "$out" in
            *"порт $PORT"*) return 0 ;;
        esac
        detail "up.sh упал, но порта $PORT в отказе не назвал — это диагноз без выхода:"
        printf '%s\n' "$out" | tail -n 12 >&2
        return 1
    }
    green "подъём на занятом порту падает и называет порт" check_busy_port_named || true
    # Держателя порта сносим ВСЕГДА, даже если проверка провалилась, и это исключение из
    # правила об уликах — названное, а не молчаливое: он занимает ШТАТНЫЙ порт, и оставить
    # его значит сломать следующий подъём чужой причиной. Улика по этой поломке не в нём:
    # она в выводе `up.sh`, который проверка печатает прямо в отказ.
    docker rm -f world-red-port >/dev/null 2>&1 || true

    # ---------- поломка 3: фронт не собран ----------
    # Дверь при этом обязана работать: несобранная витрина не повод не пускать в поле
    # (`core/README.md`). Поэтому здесь пара — одна проверка краснеет, соседняя зеленеет.
    part "поломка 3 — пульта нет там, куда смотрит WORLD_WEB_DIR"
    block
    docker rm -f world-red-web >/dev/null 2>&1 || true
    # Через `docker_noconv`: `-e WORLD_WEB_DIR=/app/…` — контейнерный путь, и Git Bash
    # переписал бы его в виндовый. Поломка осталась бы поломкой, но НЕ ТОЙ, которую назвали:
    # проба краснела бы по посторонней причине, а выглядело бы это как проверенное свойство.
    docker_noconv run -d --name world-red-web \
        -p "127.0.0.1:$RED_PORT:8080" \
        -e WORLD_WEB_DIR=/app/net-takogo-kataloga "$IMAGE" >/dev/null
    wait_door "$red_base" || { evidence world-red-web; fail \
        "контейнер без пульта не поднялся" \
        "состояние и журнал — прямо выше, контейнер оставлен" \
        "убрать, когда разберёшься: docker rm -f world-red-web"; }
    red   "2. пульт открывается"                               check_panel "$red_base" || true
    green "1. /healthz отвечает (дверь работает без пульта)"   check_alive "$red_base" || true
    blockdone world-red-web

    # ---------- поломка 4: дверь поднята БЕЗ объявленного имени ----------
    # Свойство «сосед входит по имени» держится одной строкой в файле запуска, и снаружи
    # машины его не видно вовсе: дверь на хост-порту работает точно так же. Значит проверка
    # обязана уметь покраснеть именно на пропавшем имени — иначе она стережёт воздух.
    #
    # Пара, как и в поломке 3: контрактное имя не отвечает, а имя контейнера отвечает. Так
    # видно, что сломано ИМЕНОВАНИЕ, а не дверь: краснела бы обе — сломали бы не то.
    #
    # Штатной двери здесь уже нет: её сняла поломка 2 и обратно не поднимала. Иначе она
    # держала бы имя `$ALIAS` сама, и проверка зеленела бы на сломанном.
    part "поломка 4 — дверь в сети без объявленного имени $ALIAS"
    block
    docker rm -f world-red-alias >/dev/null 2>&1 || true
    docker_noconv run -d --name world-red-alias --network "$NET" "$IMAGE" >/dev/null
    local _
    for _ in {1..15}; do
        check_neighbour_sees_door world-red-alias >/dev/null 2>&1 && break
        sleep 1
    done
    red   "7. сосед видит дверь по имени $ALIAS:8080"        check_neighbour_sees_door "$ALIAS" || true
    green "но по имени контейнера она отвечает (жива, безымянна)" \
                                                             check_neighbour_sees_door world-red-alias || true
    blockdone world-red-alias

    # Поломка 2 сняла штатный контейнер и обратно его не поднимала: красный прогон не
    # обязан оставлять мир стоящим, но обязан сказать, в каком состоянии его оставил.
    detail "мир снят поломкой 2; поднять обратно — ./deploy/up.sh (поле на томе, не потерялось)"
}

# ================================================================== запуск
# Разрушительность называется ДО первого действия, а не в отчёте после него. Третье место,
# где она названа, — `deploy/README.md`; первое — шапка этого файла.
cat >&2 <<BANNER

$(printf '\033[1;33m! проба разрушительна для живого мира\033[0m')
  прогон идёт на ШТАТНОМ порту $PORT и в ЖИВОМ поле — иначе проверял бы не то, что поедет.
  дверь будет пересоздана (перерыв в обслуживании), в поле появится и уйдёт заглушка $LOC.
BANNER
case "$mode" in
    --red|--both) printf '  красный прогон ЗАЙМЁТ порт %s и оставит мир СНЯТЫМ — поднять обратно: ./deploy/up.sh\n' "$PORT" >&2 ;;
esac
printf '  тома не трогаются: down идёт без -v, поле прогон переживает. Подробности: %s -h\n' "$0" >&2

case "$mode" in
    --green) run_green ;;
    --red)   run_red ;;
    --both)  run_green; run_red ;;
esac

part "── итог"
if [ "$failed" = 0 ]; then
    printf '  \033[1;32m✔ проверок %s, провалов нет\033[0m\n' "$total" >&2
    exit 0
fi
printf '  \033[1;31m✘ проверок %s, провалено %s\033[0m\n' "$total" "$failed" >&2
printf '    журнал двери: docker compose -f %s logs --tail=60\n' "$HERE/compose.yaml" >&2
exit 1

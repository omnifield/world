}

# ------------------------------------------------------------------ разговор
step() { printf '\n\033[1m→ %s\033[0m\n' "$*" >&2; }
ok()   { printf '  ✓ %s\n' "$*" >&2; }
warn() { printf '  \033[33m!\033[0m %s\n' "$*" >&2; }
say()  { printf '%s\n' "$*" >&2; }
detail() { printf '      %s\n' "$*" >&2; }

# refuse <код> <причина> <выход…> — единственный способ выйти с ошибкой. Причина и выход
# обязательны оба: «нельзя» без выхода — провал самого мира, юзеру нечего чинить
# (`WORLD2` 2.3). Код печатается в stdout и предназначен машине; проба стережёт КОД, а не
# формулировку — проба, привязанная к тексту, зеленеет на верной правке (`WORLD2` 4.2).
refuse() {
    local code="$1" why="$2"; shift 2
    printf 'REMOTE-REFUSAL: %s\n' "$code"
    printf '\n\033[1;31m✗ отказ:\033[0m %s\n' "$why" >&2
    local line; for line in "$@"; do printf '  выход: %s\n' "$line" >&2; done
    exit 1
}

# path_say <путь> — КАКИМ ПУТЁМ ПОШЛИ, сказанное машине. Печатается ДО самого пути, а не
# после: копия образа и установка докера — шаги на минуты, и тот, кто ждёт, вправе знать,
# чего он ждёт, пока это ещё ожидание, а не пересказ (`WORLD2-150` B2).
#
# В stdout и рядом с `REMOTE-REFUSAL`, по той же причине: человеку — слова в stderr, машине —
# метка. Контроллер и так читает этот поток, и своего второго канала для того же знания не
# надо (`WORLD2` 2.3: причина довозится дословно, а не пересказом).
path_say() { printf 'REMOTE-PATH: %s\n' "$1"; }

# thing_say <имя> — КАК ЗОВЁТСЯ ВЕЩЬ, сказанное машине. Имя принадлежит рецепту, и знает
# его тот, кто рецепт прочитал, — то есть мы. Зовущему оно нужно затем, что на одной машине
# законно стоят вещи РАЗНЫХ юзеров (`WORLD2` 3.4): спросив её «что на тебе стоит», он
# получит их все, и отличить своё сможет, только если помнит, что сам поднимал.
thing_say() { printf 'REMOTE-THING: %s\n' "$1"; }

# ------------------------------------------------------------------ имя и адрес
NAME=""; ADDR=""; CTX=""
USER_AT=""; HOST=""; SSH_PORT=22
# Ставил ли докер мир в этом прогоне. Нужно в конце: отчёт обязан назвать всё, что на машине
# появилось, а не половину (`WORLD2` 4.2).
DOCKER_PUT=""

# ctx_name — ЕДИНСТВЕННОЕ место, где имя ресурса превращается в имя контекста. Разъедутся
# две таких формулы — `add` заведёт один контекст, а `drop` пойдёт снимать другой, и дверь
# останется висеть на чужой машине, о которой человек уже думает, что убрал её.
ctx_name() { printf '%s%s' "$PREFIX" "$1"; }

# need_name — имя ресурса называет человек. Умолчания нет намеренно: угаданное имя однажды
# укажет на чужой ресурс, и мы снесём дверь не там.
need_name() {
    local cmd="$1"
    [ -n "$NAME" ] || refuse no-name \
        "имя ресурса не названо" \
        "назови его: ./deploy/remote.sh $cmd <имя>" \
        "имя своё и короткое — по нему потом искать: vps, home, work"

    # Годность имени проверяем СВОИМ правилом, а не отдаём докеру. Докер про своё имя
    # контекста скажет «invalid reference format» — про контекст, которого человек не
    # называл вовсе; отказ указывал бы на вещь, которой в его команде нет.
    case "$NAME" in
        *[!a-z0-9-]*|-*|*-|"")
            refuse bad-name \
                "имя ресурса «$NAME» не годится" \
                "буквы латиницей в нижнем регистре, цифры и дефис внутри: vps-1, home" \
                "имя едет в имя контекста докера ($(ctx_name '<имя>')), и там оно ограничено не нами" ;;
    esac
    CTX="$(ctx_name "$NAME")"
}

# parse_addr — разбор адреса ОДИН раз и в одном месте: разъедутся разборы — проверка
# доступа пойдёт на один порт, а контекст докера на другой, и отказ назовёт ступень,
# которой на самом деле нет.
parse_addr() {
    local rest="$ADDR"
    case "$rest" in
        *@*) USER_AT="${rest%@*}"; rest="${rest##*@}" ;;
        *)   USER_AT="" ;;
    esac
    # Больше одного двоеточия — это IPv6, и в этой форме он неразличим с портом. Отказываем
    # вслух, а не разбираем как попало: молчаливый разбор увёл бы и стук, и контекст на
    # выдуманный порт. Тот же довод и тот же отказ, что у зоны `gate`.
    case "${rest//[!:]/}" in
        ::*) refuse bad-address \
                "адрес «$ADDR» похож на IPv6 — эта форма не разбирается" \
                "назови имя или адрес IPv4: --addr world@10.8.0.5" \
                "нужен именно IPv6 — это отдельная работа, скажи владельцу зоны deploy" ;;
    esac
    case "$rest" in
        *:*) HOST="${rest%:*}"; SSH_PORT="${rest##*:}" ;;
        *)   HOST="$rest"; SSH_PORT=22 ;;
    esac
    [ -n "$HOST" ] || refuse bad-address \
        "в адресе «$ADDR» нет хоста" \
        "форма адреса: --addr user@хост или user@хост:порт"
    case "$SSH_PORT" in
        ""|*[!0-9]*) refuse bad-address \
                "порт «$SSH_PORT» в адресе «$ADDR» — не число" \
                "форма адреса: --addr user@хост:2222" ;;
    esac
}

ssh_target() { [ -n "$USER_AT" ] && printf '%s@%s' "$USER_AT" "$HOST" || printf '%s' "$HOST"; }
# Адрес докера — то, что ложится в контекст. Собирается из тех же кусков, что и цель ssh:
# один разбор, две сборки, разъехаться нечему.
docker_endpoint() { printf 'ssh://%s:%s' "$(ssh_target)" "$SSH_PORT"; }

# ------------------------------------------------------------------ чем поднимаем
# have_local_tools — что нужно на ЭТОЙ машине. Демон здесь НЕ проверяется: он нужен только
# поставке образа, и спрашивается ровно там (`need_local_daemon`). Ресурсу, где образ уже
# лежит, наш демон не нужен вовсе — и требовать его значило бы отказывать без причины.
have_local_tools() {
    command -v docker >/dev/null 2>&1 || refuse no-docker \
        "докера на ЭТОЙ машине нет — управлять чужим демоном нечем" \
        "поставь Docker Engine либо Docker Desktop: https://docs.docker.com/engine/install/" \
        "докер нужен здесь как клиент: на тот ресурс он ходит сам, по ssh"

    docker compose version >/dev/null 2>&1 || refuse no-compose \
        "у докера нет compose v2 (плагина docker-compose-plugin)" \
        "поставь плагин: https://docs.docker.com/compose/install/" \
        "compose работает ЗДЕСЬ и говорит с чужим демоном — на том ресурсе он не нужен"

    # Клиент ssh — не наша прихоть: транспорт `ssh://` докер делает системным `ssh`, своего
    # у него нет. Без него `docker --context` упал бы ответом про exec, а человек искал бы
    # поломку в ресурсе.
    command -v ssh >/dev/null 2>&1 || refuse no-ssh \
        "клиента ssh на этой машине нет" \
        "поставь openssh-client — докер ходит на чужой демон системным ssh, своего у него нет" \
        "на Windows он есть в Git Bash и в самой системе (OpenSSH Client)"
}

need_local_daemon() {
    docker info >/dev/null 2>&1 || refuse no-daemon \
        "докер есть, а свой демон не отвечает — узнать, лежит ли образ здесь, нечем" \
        "запусти его: systemctl start docker (либо открой Docker Desktop)" \
        "демон работает — дело в правах: usermod -aG docker \$USER и перезайти" \
        "свой демон нужен, чтобы ВЫБРАТЬ путь доставки: есть образ здесь — везём копией, нет — тянет та машина" \
        "выбирать не нужно — вели тянуть из реестра, и свой демон не понадобится: ./deploy/remote.sh add $NAME --pull"
}

# ------------------------------------------------------------------ ресурс
ctx_exists() { docker context inspect "$CTX" >/dev/null 2>&1; }

# ctx_endpoint — адрес, записанный в контексте. Это и есть наш реестр ресурсов: своего
# файла зона не заводит, потому что второй список того же самого рано или поздно разъедется
# с первым, и `drop` пойдёт не туда.
ctx_endpoint() {
    docker context inspect "$CTX" --format '{{.Endpoints.docker.Host}}' 2>/dev/null || true
}

# check_access — принимает ли ресурс креды юзера. Отдельной ступенью ДО докера: «ключ не
# принят» и «на той стороне нет докера» чинят разные вещи, и схлопывать их в одно «не
# получилось» нельзя (`WORLD2` 2.3).
#
# BatchMode=yes обязателен: без него ssh спросит пароль и проверка повиснет вместо того,
# чтобы покраснеть. Пароль докеру всё равно не годится — по SSH он умеет только ключ
# (`TECH` 3), — так что спрашивать его не за чем.
check_access() {
    local out rc
    set +e
    out=$(ssh -o BatchMode=yes -o StrictHostKeyChecking=accept-new \
              -o "ConnectTimeout=$TIMEOUT" -p "$SSH_PORT" "$(ssh_target)" true 2>&1); rc=$?
    set -e
    [ "$rc" -eq 0 ] && return 0

    detail "${out:-(ssh промолчал)}"
    refuse access-denied \
        "ресурс $ADDR не пустил: креды не приняты либо до него не дойти" \
        "положи открытый ключ юзера на тот ресурс: ssh-copy-id -p $SSH_PORT $(ssh_target)" \
        "ключ есть — добавь его в агент (ssh-add ~/.ssh/id_ed25519) или назови в ~/.ssh/config для этого хоста: докер берёт ключ ОТТУДА, своим значением его не задать" \
        "имя юзера в адресе — часть кред, а не украшение: проверь его" \
        "ресурс вообще не отвечает — ступени «дорога · ответ · доступ» разбирает ./gate/gate.sh check"
}

# ------------------------------------------------------------------ докер на той стороне
# ЕДИНСТВЕННОЕ МЕСТО, ГДЕ МИР ВЫПОЛНЯЕТ ЧТО-ЛИБО НА ЧУЖОЙ МАШИНЕ. Всё, что ниже, — про
# докер и только про докер: спросить, есть ли он, и поставить, если его нет (`WORLD2` 3.5
# п. 7). Появится здесь команда о чём-то ещё — это уже не условие мира, а распоряжение
# чужой машиной, и проба на такую команду краснеет.

# remote_said — ответ той машины на последний вопрос. Отдельной переменной, а не возвратом:
# разбирать надо и ответ, и код возврата, и оба нужны на месте разбора.
REMOTE_SAID=""

# remote_run <команда> — выполнить на той машине ОДНУ названную команду. Через тот же ssh и
# с теми же ключами, что проверка доступа: BatchMode обязателен — без него ssh спросит пароль
# и подготовка повиснет вместо того, чтобы покраснеть.
remote_run() {
    local out rc
    set +e
    out=$(ssh -o BatchMode=yes -o StrictHostKeyChecking=accept-new \
              -o "ConnectTimeout=$TIMEOUT" -p "$SSH_PORT" "$(ssh_target)" "$1" 2>&1); rc=$?
    set -e
    REMOTE_SAID="$out"
    return "$rc"
}

# remote_run_declared <команда> — ЕДИНСТВЕННЫЙ способ выполнить на чужой машине команду,
# которая эту машину МЕНЯЕТ. Он её печатает и он же её выполняет — одно значение, а не два
# похожих, построенных рядом.
#
# Почему функцией, а не двумя строками подряд. «Строится в одном месте» — это обещание, и
# держится оно ровно до следующей правки: показать `install_cmd` без прав, а выполнить с
# `sudo` можно, ничего не сломав, и человек согласится на одно, а получит другое, с правами
# root. Здесь показанному и ушедшему разойтись НЕЧЕМ: это один и тот же аргумент.
#
# «Говорим ДО» тоже становится свойством, а не порядком строк в вызывающем коде: печать
# стоит перед `remote_run` внутри самой функции, и переставить их местами снаружи нельзя.
remote_run_declared() {
    local cmd="$1" line
    say ""
    detail "на машине $ADDR будет выполнено ровно это:"
    while IFS= read -r line; do [ -n "$line" ] && detail "    $line"; done <<< "$cmd"
    say ""
    remote_run "$cmd"
}

# Вопрос «есть ли докер вообще». Задаётся ТОЛЬКО когда докер не ответил: на машине, где он
# отвечает, мир не выполняет ничего сверх проверки доступа, и это проверяемое свойство, а не
# обещание. Ответ помечен словом, а не кодом возврата: молчащий ssh и «докера нет» — разные
# состояния, и различить их можно только по метке.
PROBE_DOCKER='if command -v docker >/dev/null 2>&1; then echo "WORLD-PROBE docker=yes"; else echo "WORLD-PROBE docker=no"; fi'

# probe_ready_cmd — ОДИН вопрос вместо трёх: чем ставить (root или sudo), чем скачать и
# достаёт ли машина до установщика. Одним заходом потому, что каждый заход — это команда на
# чужой машине, а их должно быть столько, сколько нужно, и ни одной сверх.
probe_ready_cmd() {
    cat <<CMD
root=no; su_ok=no; fetch=none; net=no
[ "\$(id -u)" = 0 ] && root=yes
[ "\$root" = no ] && sudo -n true >/dev/null 2>&1 && su_ok=yes
if command -v curl >/dev/null 2>&1; then fetch=curl
elif command -v wget >/dev/null 2>&1; then fetch=wget; fi
case "\$fetch" in
  curl) curl -fsS -m $TIMEOUT -o /dev/null $DOCKER_INSTALL_URL >/dev/null 2>&1 && net=yes ;;
  wget) wget -q -T $TIMEOUT -O /dev/null $DOCKER_INSTALL_URL >/dev/null 2>&1 && net=yes ;;
esac
echo "WORLD-PROBE root=\$root sudo=\$su_ok fetch=\$fetch net=\$net"
CMD
}

# probe_field <ответ> <ключ> — значение из ответа машины. Разбор в одном месте: разъедутся
# два разбора — отказ назовёт не ту причину, чем и живут схлопнутые ступени.
probe_field() {
    printf '%s\n' "$1" | tr ' ' '\n' | sed -n "s/^$2=//p" | head -n1
}

# install_cmd <curl|wget> <приставка прав> — ТА САМАЯ команда, которая пойдёт на машину. Она
# же печатается юзеру ДО запуска: «что именно там запускается, юзер обязан узнать словами, а
# не из журнала после» (`WORLD2` 3.5). Строится в одном месте — иначе показанное и
# выполненное однажды разойдутся, и обещание станет ложью.
#
# Скачанное идёт в `sh` ПОТОКОМ: на чужой машине не появляется даже файла установщика.
#
# Скачивание и запуск РАЗВЕДЕНЫ, и это не украшение. Привычное `curl … | sh` берёт код
# возврата у последнего в конвейере, то есть у `sh`: не скачавшись, установщик отдал бы `sh`
# пустоту, тот бы успешно ничего не сделал — и мир записал бы «поставили», а потом отказал
# «докер молчит», отправив чинить не то. `pipefail` тут не годится: оболочка на той машине
# чужая, и в `dash` его нет вовсе. Отдельным присваиванием отказ скачивания остаётся отказом
# скачивания, и на машине по-прежнему не появляется файла — установщик живёт в переменной.
install_cmd() {
    local get
    case "$1" in
        curl) get="curl -fsSL $DOCKER_INSTALL_URL" ;;
        wget) get="wget -qO- $DOCKER_INSTALL_URL" ;;
    esac
    printf 'set -e\ndocker_installer=$(%s)\nprintf %s "$docker_installer" | %ssh\n' \
        "$get" "'%s\n'" "$2"
    # Право говорить с демоном — часть установки, а не отдельная вещь: докер, с которым
    # нашему юзеру не дают разговаривать, машину в мир не вводит. Под root'ом не нужно.
    [ -z "$2" ] || printf '%susermod -aG docker "$(id -un)"\n' "$2"
}

# ensure_remote_docker — докер на той стороне: есть — не трогаем, нет — ставим, не вышло —
# отказ с причиной и выходом. Спрашиваем через контекст, то есть ровно тем путём, которым
# потом пойдёт подъём: спроси мы иначе (своим `ssh docker version`), проверка зеленела бы
# там, где настоящий путь ломается.
ensure_remote_docker() {
    local out rc
    set +e
    out=$(docker --context "$CTX" version --format '{{.Server.Version}}' 2>&1); rc=$?
    set -e
    if [ "$rc" -eq 0 ]; then
        ok "докер на ресурсе есть: версия $out"
        detail "мир его не трогает — ни обновления, ни замены, ни починки: чужая версия не его дело, пока отвечает"
        return 0
    fi
    detail "${out:-(докер промолчал)}"

    # ПОЧЕМУ не отвечает — спрашиваем машину, а не догадываемся. Три состояния, и чинят их
    # трое разных: докера нет вовсе (ставит мир) · докер стоит, а прав говорить с ним нет
    # (хозяин машины) · докер стоит, а демон молчит (хозяин машины). Схлопнуть их в одно
    # «докер не отвечает» значит отправить чинить не туда (`WORLD2` 2.3).
    local probe_rc=0
    remote_run "$PROBE_DOCKER" || probe_rc=$?
    case "$REMOTE_SAID" in
        *"WORLD-PROBE docker=yes"*)
            # ДОКЕР ЕСТЬ — и мир его не трогает. Ни ставит поверх, ни чинит, ни заменяет.
            case "$out" in
                *"permission denied"*|*"Permission denied"*)
                    refuse remote-docker-denied \
                        "на ресурсе $ADDR докер СТОИТ, а юзеру ${USER_AT:-<юзер>} не дают говорить с его демоном" \
                        "дай это право на той машине: sudo usermod -aG docker ${USER_AT:-<юзер>} — и перезайди по ssh" \
                        "право уже дано — старое ssh-соединение могло остаться открытым: ssh -O exit -p $SSH_PORT $(ssh_target)" \
                        "это НЕ «докера нет»: он там есть, и мир его не ставит поверх и не чинит — чужой докер не его дело" ;;
            esac
            refuse no-remote-docker \
                "на ресурсе $ADDR докер СТОИТ, а его демон не отвечает" \
                "запусти его на той машине: sudo systemctl start docker" \
                "мир стоящий докер не трогает — ни обновления, ни замены, ни починки (WORLD2 3.5): это машина хозяина" \
                "проверить руками: ssh -p $SSH_PORT $(ssh_target) docker version" ;;
        *"WORLD-PROBE docker=no"*)
            install_remote_docker ;;
        *)
            # Ни «да», ни «нет». Здесь два РАЗНЫХ состояния, и валить их в одно нельзя:
            # машина не ответила вовсе (связь) — и машина ответила, но не тем, о чём
            # спрашивали. Второе — не поломка связи: так отвечает машина, у которой оболочка
            # юзера не понимает обычных слов (`fish`, `csh` и подобные). Гадать между ними
            # значило бы полезть ставить докер вслепую на машину, где он, может быть, есть.
            detail "${REMOTE_SAID:-(ssh промолчал)}"
            [ "$probe_rc" -eq 0 ] && refuse bad-remote-answer \
                "ресурс $ADDR ответил, но не о докере — понять, есть он там или нет, нечем" \
                "чаще всего это оболочка юзера на той машине: она не разбирает обычные слова (fish, csh)" \
                "назови в адресе юзера с обычной оболочкой: --addr <другой>@$HOST" \
                "либо поставь докер сам — мир его не тронет: https://docs.docker.com/engine/install/" \
                "это НЕ «докера нет» и НЕ «машина молчит»: она ответила, и ответ не про то"
            refuse access-denied \
                "ресурс $ADDR перестал отвечать по ssh — спросить его про докер не вышло" \
                "проверь связь: ssh -p $SSH_PORT $(ssh_target) true" \
                "ступени «дорога · ответ · доступ» разбирает ./gate/gate.sh check" \
                "это НЕ «докера нет»: машина не ответила вовсе, а гадать о ней мы не станем" ;;
    esac
}

# install_remote_docker — мир ставит докер на чужую машину. Законно это потому, что докер не
# вещь В мире, а то, ЧЕМ мир на машине бывает: без него мира на ней нет вовсе (`WORLD2` 3.5
# п. 7 и раздел «Докер ставит мир», 2026-08-18). Цена настоящая — на чужой машине выполняется
# то, что мир туда принёс, — и потому называется вслух и ДО, а не после.
install_remote_docker() {
    path_say docker-install
    step "докера на ресурсе $NAME нет — мир ставит его сам"

    # ГОВОРИМ ДО, А НЕ ПОСЛЕ. Эти строки печатаются раньше первой команды установки — не
    # ради вежливости: юзер узнаёт, что на его машине появится докер, ДО того как он там
    # появится, как и с ключом (`WORLD2` 3.4). Порядок здесь и есть свойство, и проба
    # стережёт именно его — что слова сказаны раньше, а не что они где-то есть.
    warn "на машине $ADDR появится ДОКЕР — и это единственное, что мир туда ставит"
    detail "без докера мира на машине нет вовсе: ни двери, ни раздачи, ни в возможности (WORLD2 3.5 п. 7)"
    detail "ставит его официальный установщик докера, а не мир: готовое и общее, а не своё"
    detail "стоял бы докер — мир бы его не тронул: ни обновления, ни замены, ни починки"
    detail "не хочешь этого на своей машине — поставь докер сам и повтори команду: второй раз мир его не поставит"

    # Чем ставить — спрашиваем машину ОДНИМ вопросом. Каждая непригодность отказывает своим
    # кодом: «нет прав» и «не достала до сети» — разные состояния, и второе законно.
    local probe_rc=0
    remote_run "$(probe_ready_cmd)" || probe_rc=$?
    local answer; answer="$(printf '%s\n' "$REMOTE_SAID" | sed -n 's/.*WORLD-PROBE //p' | head -n1)"
    if [ -z "$answer" ]; then
        detail "${REMOTE_SAID:-(ssh промолчал)}"
        [ "$probe_rc" -eq 0 ] && refuse bad-remote-answer \
            "ресурс $ADDR ответил, но не о том, чем ставить докер" \
            "чаще всего это оболочка юзера на той машине: она не разбирает обычные слова (fish, csh)" \
            "назови в адресе юзера с обычной оболочкой: --addr <другой>@$HOST" \
            "либо поставь докер сам — мир его не тронет: https://docs.docker.com/engine/install/"
        refuse access-denied \
            "ресурс $ADDR перестал отвечать по ssh — спросить его, чем ставить докер, не вышло" \
            "проверь связь: ssh -p $SSH_PORT $(ssh_target) true" \
            "ступени «дорога · ответ · доступ» разбирает ./gate/gate.sh check"
    fi

    local root su_ok fetch net runner
    root="$(probe_field "$answer" root)"
    su_ok="$(probe_field "$answer" sudo)"
    fetch="$(probe_field "$answer" fetch)"
    net="$(probe_field "$answer" net)"

    # 1. ПРАВА. Ставить докер — работа хозяина машины, и без его прав она не начинается.
    if [ "$root" = yes ]; then
        runner=""
        ok "юзер на той машине — root: докер ставится напрямую"
    elif [ "$su_ok" = yes ]; then
        runner="sudo -n "
        ok "юзер не root, но sudo без пароля есть: докер ставится через sudo"
    else
        refuse docker-install-denied \
            "докера на ресурсе $ADDR нет, а поставить его нечем: юзер ${USER_AT:-<юзер>} не root, и sudo без пароля ему не дают" \
            "дай ему это право на той машине, одной строкой в sudoers: ${USER_AT:-<юзер>} ALL=(ALL) NOPASSWD: ALL" \
            "либо назови в адресе юзера, которому оно уже есть: --addr root@$HOST" \
            "либо поставь докер сам, и мир его не тронет: ssh -p $SSH_PORT $(ssh_target) 'curl -fsSL $DOCKER_INSTALL_URL | sudo sh'" \
            "это НЕ «машина не достала до сети»: она ответила, дело в правах"
    fi

    # 2. ЧЕМ СКАЧАТЬ. Отдельно от сети: «нечем качать» чинится установкой curl, а «не достала
    # до сети» — выходом наружу либо зеркалом. Общий отказ отправлял бы чинить не то.
    case "$fetch" in
        curl|wget) ok "установщик машина возьмёт через $fetch" ;;
        *)  refuse docker-install-no-fetch \
                "на ресурсе $ADDR нет ни curl, ни wget — взять установщик докера нечем" \
                "поставь на той машине любой из них: apt install curl (либо dnf, apk — чем она ставит пакеты)" \
                "либо поставь докер сам, и мир его не тронет: https://docs.docker.com/engine/install/" \
                "это НЕ «нет прав» и НЕ «нет сети»: качать нечем" ;;
    esac

    # 3. СЕТЬ. Машина без выхода наружу — законное состояние, а не поломка, и отказ говорит
    # это прямым текстом: чинить тут нечего, тут выбирают другой путь.
    if [ "$net" != yes ]; then
        refuse docker-install-no-net \
            "ресурс $ADDR не достал до $DOCKER_INSTALL_URL — взять установщик докера неоткуда" \
            "машина без выхода наружу — законное состояние, а не поломка: поставь докер её же средствами (пакетом из её зеркала), и мир его не тронет" \
            "зеркало установщика есть — назови его: WORLD_DOCKER_INSTALL_URL=https://<зеркало> ./deploy/remote.sh add $NAME" \
            "выход наружу через прокси — назови его той машине (http_proxy/https_proxy в её окружении)" \
            "это НЕ «нет прав»: права у нас есть ($([ "$root" = yes ] && printf root || printf sudo)), не дошла сеть"
    fi
    ok "машина достаёт до установщика: $DOCKER_INSTALL_URL"

    # 4. САМА УСТАНОВКА. Команда печатается ЦЕЛИКОМ и до запуска — не «той же строкой, которая
    # уедет», а ТОЙ САМОЙ: печатает и выполняет её одна функция, одно значение
    # (`remote_run_declared`). Обещание «показанное и выполненное строятся в одном месте»
    # здесь заменено на свойство: разойтись им нечем.
    step "ставлю докер на $NAME — это минуты, а не секунды"
    if ! remote_run_declared "$(install_cmd "$fetch" "$runner")"; then
        printf '%s\n' "$REMOTE_SAID" >&2
        refuse docker-install-failed \
            "докер на ресурс $ADDR не встал — ответ машины напечатан выше, он же первая причина" \
            "дистрибутив, которого установщик не знает, — поставь докер по инструкции и повтори: https://docs.docker.com/engine/install/" \
            "на диске той машины нет места: ssh -p $SSH_PORT $(ssh_target) df -h" \
            "поставь докер сам — мир не станет ставить его второй раз и не тронет стоящий"
    fi
    ok "установщик докера отработал"

    # 5. ПОДТВЕРЖДАЕМ ТЕМ ЖЕ ПУТЁМ, которым пойдёт подъём. «Установщик сказал ок» и «докер
    # отвечает» — разные вещи, и записывать надо второе (`WORLD2` 4.2).
    local out rc
    set +e
    out=$(docker --context "$CTX" version --format '{{.Server.Version}}' 2>&1); rc=$?
    set -e
    if [ "$rc" -ne 0 ]; then
        detail "${out:-(докер промолчал)}"
        refuse docker-install-silent \
            "докер на ресурс $ADDR поставлен, а по нашему пути так и не отвечает" \
            "право говорить с демоном применяется при НОВОМ входе — повтори команду: ./deploy/remote.sh add $NAME" \
            "старое ssh-соединение держит прежний вход — закрой его: ssh -O exit -p $SSH_PORT $(ssh_target)" \
            "демон не запустился сам: ssh -p $SSH_PORT $(ssh_target) 'sudo systemctl start docker'" \
            "мир поставил докер и второй раз его ставить не станет: дальше это машина с докером"
    fi
    DOCKER_PUT=1
    ok "докер на ресурсе есть: версия $out — его поставил мир"
    detail "на машине теперь есть докер, и он остаётся: снятие вещи его не убирает — он не наша вещь"
}

# ------------------------------------------------------------------ рецепт
# THING — имя вещи, IMAGE — её образ. Оба ЧИТАЮТСЯ из рецепта, а не задаются здесь: список
# вещей мира не является механикой (`WORLD2` 3.7), и всё, что механика о вещи знает, она
# узнаёт в этой одной функции.
THING=""; IMAGE=""

# read_recipe — прочитать рецепт и отказать ВНЯТНО, если читать нечего. Три разных отказа, а
# не один «плохой рецепт»: файла нет · файл не разбирается · в разобранном нет образа — чинят
# их разными действиями, и общий код отправлял бы чинить не туда (`WORLD2` 2.3).
#
# Спрашиваем сам компоуз (`config`), а не читаем YAML своими глазами: рецепт может тянуть
# подстановки, `extends` и второй файл, и наш разбор разошёлся бы с тем, что реально
# поднимется. Разъехавшийся разбор хуже отсутствующего — он выглядит знанием (`WORLD2` 4.2).
read_recipe() {
    [ -n "$RECIPE" ] || refuse no-recipe \
        "рецепт не назван" \
        "назови файл запуска: --recipe deploy/compose.yaml" \
        "без ключа берётся рецепт двери — deploy/compose.yaml"

    [ -f "$RECIPE" ] || refuse no-recipe \
        "рецепта «$RECIPE» нет — поднимать нечего" \
        "проверь путь: ls -l $RECIPE" \
        "путь считается от того места, где ты стоишь, а не от deploy/" \
        "какие рецепты лежат рядом: ls $HERE/*.yaml"

    local conf rc=0
    set +e
    conf=$(docker compose -f "$RECIPE" config 2>&1); rc=$?
    set -e
    if [ "$rc" -ne 0 ]; then
        detail "${conf:-(компоуз промолчал)}"
        refuse bad-recipe \
            "рецепт «$RECIPE» компоуз не разбирает — ответ его напечатан выше" \
            "проверь руками: docker compose -f $RECIPE config" \
            "чаще всего это отступы, неизвестное поле либо подстановка, которой нечем стать"
    fi

    # Имя вещи — имя проекта компоуза: он же и есть то, чем на той стороне помечены её
    # контейнеры, тома и сети. Берём его у компоуза, а не из имени файла: рецепт вправе
    # назвать проект сам (`name:`), и тогда наше имя разошлось бы с настоящим.
    THING="$(printf '%s\n' "$conf" | sed -n 's/^name: *//p' | head -n1)"
    [ -n "$THING" ] || THING="$(basename -- "${RECIPE%.*}")"

    # ИМЯ ВЕЩИ НАЗЫВАЕТСЯ МАШИНЕ — той же формой, что путь и отказ. Знает его тот, кто
    # поднимает: имя принадлежит рецепту, и разбирать рецепт второй раз у себя тому, кто
    # нас позвал, незачем — второй разбор разъехался бы с этим на первой правке компоуза.
    #
    # Зачем это зовущему: на одной машине законно стоят вещи РАЗНЫХ юзеров (`WORLD2` 3.4,
    # «Копий нет — есть адреса»). Спросив машину «что на тебе стоит», он получит их все, и
    # отличить своё сможет, только если помнит, что сам поднимал.
    thing_say "$THING"

    IMAGE="$(docker compose -f "$RECIPE" config --images 2>/dev/null | head -n1 || true)"
    [ -n "$IMAGE" ] || refuse recipe-no-image \
        "в рецепте «$RECIPE» не названо имя образа — везти на ресурс нечего" \
        "назови его у службы: image: ghcr.io/<кто>/<что>:<тег>" \
        "имя нужно ПОЛНОЕ, с реестром: короткое докер достроит своим умолчанием (Docker Hub), а это чужое пространство имён" \
        "посмотреть, что компоуз видит в рецепте: docker compose -f $RECIPE config --images"
}

# ------------------------------------------------------------------ что стоит на той стороне
# thing_ids — контейнеры ЭТОГО рецепта на том ресурсе. Спрашиваем компоуз, а не сверяем имена
# со своей константой: имя контейнера принадлежит рецепту, и знать его механике неоткуда.
thing_ids() {
    docker --context "$CTX" compose -f "$RECIPE" ps -aq 2>/dev/null || true
}

# health_of — здоровье одного контейнера словами. `none` значит «у образа нет HEALTHCHECK», и
# это НЕ то же самое, что «здоров»: приблизительная запись хуже отсутствующей (`WORLD2` 4.2).
health_of() {
    docker --context "$CTX" inspect --format \
        '{{if .State.Health}}{{.State.Health.Status}}{{else}}none{{end}}' "$1" 2>/dev/null || true
}

# thing_volumes — тома ЭТОЙ вещи на том ресурсе. Ищем по метке проекта, которую компоуз
# ставит на всё, что заводит сам: имена томов принадлежат рецепту, и держать их копию здесь
# значило бы завести второй список того же самого.
thing_volumes() {
    docker --context "$CTX" volume ls \
        --filter "label=com.docker.compose.project=$THING" --format '{{.Name}}' 2>/dev/null \
        | tr '\n' ' ' | sed 's/ *$//' || true
}

# published_of — куда опубликованы порты контейнера. Читается ФАКТОМ у чужого демона: какие
# порты у вещи есть, знает её рецепт, а какие из них легли наружу — только сам докер.
published_of() { docker --context "$CTX" port "$1" 2>/dev/null || true; }

# host_port — первый хост-порт из публикации, чтобы было куда стучаться снаружи.
host_port() { printf '%s\n' "$1" | sed -n 's/.*-> *[^:]*:\([0-9]\+\).*/\1/p' | head -n1; }

# ------------------------------------------------------------------ add
cmd_add() {
    need_name add
    have_local_tools
    # Рецепт читается ДО того, как мы тронули ресурс: непригодный рецепт обязан отказать, не
    # заводя ни контекста, ни соединения. Отказ не вправе ничего оставлять за собой
    # (`WORLD2` 2.3, пункт 4).
    read_recipe

    # Адрес обязателен, пока ресурс не заведён. Заведённому он не нужен: адрес лежит в
    # контексте, и повторный `add` — это законный способ поднять дверь заново, не повторяя
    # адрес. Названный заново — адрес меняется, и об этом говорится вслух.
    if [ -z "$ADDR" ]; then
        ctx_exists || refuse no-address \
            "адрес ресурса «$NAME» не назван, а сам ресурс ещё не заведён" \
            "назови адрес: ./deploy/remote.sh add $NAME --addr user@10.8.0.5" \
            "адрес угадывать нечем — умолчания у него нет намеренно: угаданный однажды укажет на чужую машину" \
            "какие ресурсы уже заведены: ./deploy/remote.sh list"
        local ep; ep="$(ctx_endpoint)"
        ADDR="${ep#ssh://}"
    fi
    parse_addr

    step "ресурс $NAME → $ADDR (контекст $CTX)"
    ok "вещь «$THING» по рецепту $RECIPE"

    # ---------------------------------------------------------- 1. доступ
    step "проверяю доступ: ssh на $(ssh_target):$SSH_PORT"
    check_access
    ok "ресурс пускает — креды приняты"

    # ---------------------------------------------------------- 2. контекст
    step "контекст докера $CTX"
    local endpoint; endpoint="$(docker_endpoint)"
    if ctx_exists; then
        local was; was="$(ctx_endpoint)"
        if [ "$was" = "$endpoint" ]; then
            ok "контекст уже есть и смотрит туда же"
        else
            docker context update "$CTX" --docker "host=$endpoint" >/dev/null 2>&1 || refuse context-failed \
                "контекст $CTX не переставить на $endpoint" \
                "посмотри, что мешает: docker context update $CTX --docker host=$endpoint" \
                "снести и завести заново: ./deploy/remote.sh drop $NAME, затем add"
            warn "адрес ресурса сменился: было $was, стало $endpoint"
        fi
    else
        docker context create "$CTX" \
            --description "мир: ресурс $NAME" \
            --docker "host=$endpoint" >/dev/null 2>&1 || refuse context-failed \
            "контекст $CTX не создать" \
            "посмотри, что мешает: docker context create $CTX --docker host=$endpoint" \
            "имя занято чем-то чужим — возьми другое имя ресурса: ./deploy/remote.sh add <другое> --addr $ADDR"
        ok "контекст создан — дальше докер ходит на ресурс сам"
    fi

    # ---------------------------------------------------------- 3. докер на той стороне
    # Машина без докера — не отказ, а состояние, которое мир умеет привести в годное:
    # докер не вещь В мире, а то, ЧЕМ мир на машине бывает (`WORLD2` 3.5 п. 7).
    step "докер на ресурсе"
    ensure_remote_docker

    # ---------------------------------------------------------- 4. образ
    # ДВА ПУТИ ДОСТАВКИ ОДНОЙ ВЕЩИ (`WORLD2` 1.5), И ВЫБИРАЕТ МЕЖДУ НИМИ НАЛИЧИЕ, А НЕ
    # ЧЕЛОВЕК (слова user, `WORLD2-150` B2: «скачивает раздачу, или передаёт её по ssh, если
    # у контроллера она рядом»):
    #
    #   образ есть здесь    везём КОПИЕЙ: `docker save | docker load` через ssh. Реестр той
    #                       машине не нужен вовсе, и приезжает РОВНО ТО, что у нас на руках;
    #   образа здесь нет    та машина тянет его ИЗ РЕЕСТРА сама. Наш канал не задействован,
    #                       но приезжает ОПУБЛИКОВАННОЕ, а не собранное здесь.
    #
    # Спрашивать об этом человека незачем: ответ уже лежит на машине, и он не вопрос вкуса.
    # Прежнее умолчание («всегда копия») отказывало там, где машина прекрасно взяла бы образ
    # сама, а выбор ключом делал обязательным знание, которого у юзера нет: лежит ли у
    # контроллера этот образ прямо сейчас. `--pull` остался — им человек велит взять
    # ОПУБЛИКОВАННОЕ, даже когда своё под рукой; обратного ключа нет намеренно: «вези копией
    # то, чего у тебя нет» — не команда, а пожелание.
    #
    # КАКИМ ПУТЁМ ПОШЛИ — говорится вслух и ДО, а не после: оба пути идут минутами, и тот,
    # кто ждёт, вправе знать, чего он ждёт.
    #
    # Тянуть стало ВОЗМОЖНО только теперь: имя образа полное, с реестром (`WORLD2-121`).
    # Пока оно было коротким, `docker pull` на той стороне пошёл бы в Docker Hub — то есть
    # не туда, куда мы публикуем.
    local image="$IMAGE"
    step "образ $image на ресурсе"
    local have_remote=
    docker --context "$CTX" image inspect "$image" >/dev/null 2>&1 && have_remote=1

    if [ -n "$have_remote" ] && [ -z "$RESEND" ]; then
        path_say image-present
        ok "образ на ресурсе уже есть — не везём (перевезти заново: --resend-image)"
    else
        [ -n "$have_remote" ] && warn "образ там есть, но велено взять заново (--resend-image)"

        # ВЫБОР ПУТИ. Человек назвал его ключом — идём названным; не назвал — смотрим, есть
        # ли образ у нас. Чтобы посмотреть, нужен свой демон: без него мы не знаем ответа, а
        # угадывать нельзя — «наверное, нет, потянем из реестра» подменило бы собранное
        # здесь опубликованным молча (`WORLD2` 4.2).
        local way=""
        if [ -n "$PULL" ]; then
            way=pull
        else
            need_local_daemon
            if docker image inspect "$image" >/dev/null 2>&1; then way=copy; else way=pull; fi
        fi

        if [ "$way" = copy ]; then
            path_say image-copy
            warn "образ есть у контроллера — везу его КОПИЕЙ через ssh"
            detail "это самый долгий шаг: минуты, а не секунды — сколько весит образ, столько и едет"
            detail "приедет РОВНО ТО, что лежит здесь, а не то, что опубликовано"
            # Поток идёт через ssh целиком: ни временного файла на той стороне, ни `scp`. На
            # чужой машине не появляется даже tar-архива — только слои в её докере.
            local rc=0
            docker save "$image" | docker --context "$CTX" load >/dev/null || rc=$?
            [ "$rc" -eq 0 ] || refuse image-send-failed \
                "образ $image не доехал на ресурс $NAME" \
                "проверь, что на той стороне есть место: ssh -p $SSH_PORT $(ssh_target) df -h" \
                "связь рвётся на длинной передаче — повтори: ./deploy/remote.sh add $NAME --resend-image" \
                "образ большой, а канал узкий — это цена копии; вели взять опубликованный: ./deploy/remote.sh add $NAME --pull"
            ok "образ приехал копией"
        else
            path_say image-pull
            if [ -n "$PULL" ]; then
                warn "велено взять образ ИЗ РЕЕСТРА (--pull) — ресурс тянет его сам"
            else
                warn "образа $image у контроллера нет — ресурс тянет его ИЗ РЕЕСТРА сам"
            fi
            detail "наш канал не задействован; приедет ОПУБЛИКОВАННОЕ, а не собранное здесь"
            docker --context "$CTX" pull "$image" >&2 || refuse image-pull-failed \
                "ресурс $NAME не смог притянуть $image из реестра" \
                "у той машины может не быть выхода наружу — тогда положи образ у себя, и он поедет копией: ./deploy/build.sh (либо docker pull $image здесь)" \
                "пакет ещё приватный (первый выпуск создаёт приватный) — открой его в настройках пакета" \
                "имя не опубликовано вовсе — выпусти ЭТОТ образ и повтори: ./deploy/release.sh --door|--share|--control (за вызов уезжает один, рецепт здесь может быть любой)" \
                "реестр требует входа — залогинься на ТОЙ машине: ssh -p $SSH_PORT $(ssh_target) docker login ${image%%/*}" \
                "имя образа взято из рецепта $RECIPE и здесь не выдумывается: назови в рецепте то имя, которое у тебя есть"
            ok "образ приехал из реестра"
        fi
    fi

    # ---------------------------------------------------------- 5. общая сеть
    # Идемпотентно, ровно как у себя (`up.sh`): сеть уже есть — не сделано ничего. Компоуз
    # её не создаёт (`external: true`), а войти в несуществующую сеть докер не даёт.
    step "общая сеть $NET на ресурсе"
    if docker --context "$CTX" network inspect "$NET" >/dev/null 2>&1; then
        ok "сеть уже есть"
    else
        docker --context "$CTX" network create "$NET" >/dev/null 2>&1 || refuse no-network \
            "общую сеть $NET на ресурсе $NAME не создать" \
            "посмотри, что мешает: docker --context $CTX network create $NET" \
            "подсети кончились — почисти неиспользуемые: docker --context $CTX network prune"
        ok "сеть создана"
    fi

    # ---------------------------------------------------------- 6. контейнер
    # Файл запуска ЛЕЖИТ ЗДЕСЬ и остаётся здесь: компоуз читает его на этой машине и говорит
    # с чужим демоном. На тот ресурс не уезжает ни файла — в этом весь смысл контекста.
    step "поднимаю «$THING» на $NAME по рецепту $RECIPE"
    local out rc=0
    set +e
    out=$(docker --context "$CTX" compose -f "$RECIPE" \
              up -d --no-build --remove-orphans 2>&1); rc=$?
    set -e
    if [ "$rc" -ne 0 ]; then
        printf '%s\n' "$out" >&2
        # Занятый порт — отдельная ступень, а не «не встало»: чинит его хозяин того ресурса,
        # и чинится он другим действием. Схлопнуть его в общий отказ значит отправить
        # человека читать журнал там, где ответ уже известен.
        #
        # Номер порта берём ИЗ ОТВЕТА ДОКЕРА, а не из своего значения: какой порт вещь просит
        # наружу, знает её рецепт, и наш пересказ назвал бы не тот (`WORLD2` 2.3).
        case "$out" in
            *"port is already allocated"*|*"address already in use"*|*"Ports are not available"*|*"bind: address already in use"*)
                local busy; busy="$(printf '%s\n' "$out" | sed -n 's/.*[Bb]ind for [^:]*:\([0-9]\+\).*/\1/p' | head -n1)"
                refuse port-busy \
                    "порт ${busy:-из рецепта} на ресурсе $NAME занят кем-то ещё" \
                    "порт вещь просит рецептом — назови другой в $RECIPE либо значением, которое этот рецепт читает" \
                    "кто держит порт: ssh -p $SSH_PORT $(ssh_target) ss -lntp${busy:+ | grep :$busy}" \
                    "наружу торчит ровно одна дверь на ресурс (kb:FUND-5) — второй мир на той же машине поднимают на другом хост-порту" ;;
        esac
        refuse up-failed \
            "вещь «$THING» на ресурсе $NAME не встала" \
            "ответ докера напечатан выше — он же первая причина" \
            "журнал: docker --context $CTX compose -f $RECIPE logs --tail=40" \
            "снять недоделанное и начать заново: ./deploy/remote.sh drop $NAME --recipe $RECIPE"
    fi
    ok "контейнеры запущены"

    # ---------------------------------------------------------- 7. дверь отвечает
    # «Запущен» и «отвечает» — разные вещи, и подтверждать надо второе. Спрашиваем ЗДОРОВЬЕ у
    # чужого демона, а не стучимся сюда curl-ом: опубликованный порт того ресурса может быть
    # закрыт для нас фаерволом, и живая дверь выглядела бы мёртвой. HEALTHCHECK стучится
    # изнутри контейнера — это ровно тот вопрос, на который тут надо ответить.
    step "жду, пока «$THING» на $NAME станет здоровой (до ${WAIT}с)"
    local ids; ids="$(thing_ids)"
    [ -n "$ids" ] || refuse up-failed \
        "компоуз отчитался о подъёме, а контейнеров рецепта $RECIPE на ресурсе $NAME не видно" \
        "спроси сам: docker --context $CTX compose -f $RECIPE ps -a" \
        "рецепт мог не объявить ни одной службы — проверь: docker compose -f $RECIPE config --services"

    # Ждём ВСЕ контейнеры рецепта, а не один: сколько их и какие — знает рецепт. Считать
    # здоровой вещь по первому попавшемуся контейнеру значило бы выдать часть за целое.
    local verdict="" waited=0 id h pending checked
    while :; do
        pending=0; checked=0
        for id in $ids; do
            h="$(health_of "$id")"
            case "$h" in
                healthy)     checked=$((checked + 1)) ;;
                # `none` — у образа нет HEALTHCHECK: этот контейнер не ждём вовсе, потому что
                # ждать нечего. Пустой ответ — контейнера уже нет; это тоже не ожидание.
                none|"")     ;;
                *)           pending=$((pending + 1)) ;;
            esac
        done
        if [ "$pending" -eq 0 ]; then
            [ "$checked" -gt 0 ] && verdict=healthy || verdict=none
            break
        fi
        if [ "$waited" -ge "$WAIT" ]; then verdict=timeout; break; fi
        sleep 2; waited=$((waited + 2))
    done

    case "$verdict" in
        healthy) ok "вещь отвечает: все проверяемые контейнеры «$THING» здоровы на $NAME" ;;
        # Ни одного HEALTHCHECK — сказать это вслух, а не выдать «встало» за «отвечает».
        # Приблизительная запись хуже отсутствующей: она выглядит знанием (`WORLD2` 4.2).
        none)    warn "ни у одного образа рецепта нет HEALTHCHECK — «отвечает ли вещь» этой командой не проверить" ;;
        *)
            printf '\n--- последние строки журнала ---\n' >&2
            docker --context "$CTX" compose -f "$RECIPE" logs --tail=40 >&2 || true
            refuse thing-silent \
                "вещь «$THING» на $NAME запущена, но за ${WAIT}с здоровой не стала" \
                "журнал выше — если вещь падает, она называет причину сама, первой же строкой" \
                "состояние с прошлого раза могло остаться от другой редакции: ./deploy/remote.sh drop $NAME --recipe $RECIPE --with-state, затем add" \
                "медленный ресурс — дай больше времени: WORLD_REMOTE_WAIT=180 ./deploy/remote.sh add $NAME --recipe $RECIPE" ;;
    esac

    # ---------------------------------------------------------- 8. виден ли порт отсюда
    # Стук с ЭТОЙ машины — не проверка двери, а проверка ДОСТУПА снаружи, и это разные
    # вещи. Не дошло — не отказ: дверь здорова у себя, а порт может быть закрыт фаерволом
    # или NAT-ом, и чинит это хозяин ресурса.
    # Какой порт спрашивать — говорит ФАКТ публикации, а не наше значение: что вещь кладёт
    # наружу, знает её рецепт. И спрашиваем мы ВИДИМОСТЬ порта, а не здоровье: здоровье уже
    # спрошено у демона, а какой путь у этой вещи «живой», механике знать неоткуда — потому
    # годится ЛЮБОЙ ответ HTTP, хоть 404, хоть 410.
    local ports=""; ports="$(published_of "$(printf '%s\n' "$ids" | head -n1)")"
    local hport; hport="$(host_port "$ports")"
    if [ "$verdict" = healthy ] && [ -n "$hport" ]; then
        local knocked=
        if command -v curl >/dev/null 2>&1; then
            local code
            code="$(curl -sS -o /dev/null -m 3 -w '%{http_code}' "http://$HOST:$hport/" 2>/dev/null || true)"
            case "$code" in ""|000) ;; *) knocked=1 ;; esac
        elif command -v wget >/dev/null 2>&1; then
            wget -q -S --spider -T 3 -O /dev/null "http://$HOST:$hport/" 2>&1 | grep -q 'HTTP/' && knocked=1 || true
        else
            warn "ни curl, ни wget здесь нет — снаружи порт не проверить (изнутри вещь здорова)"
            knocked=skip
        fi
        if [ "$knocked" = 1 ]; then
            ok "порт виден и с этой машины: http://$HOST:$hport/ отвечает"
        elif [ -z "$knocked" ]; then
            warn "с этой машины http://$HOST:$hport/ не отвечает, хотя вещь здорова"
            detail "это не поломка вещи: снаружи порт может быть закрыт фаерволом или NAT-ом"
            detail "открыть его — дело хозяина ресурса; изнутри ресурса вещь работает"
        fi
    fi

    cat >&2 <<GOTOVO

$(printf '\033[1;32m✓ вещь «%s» стоит на ресурсе %s\033[0m' "$THING" "$NAME")

  рецепт            $RECIPE
  публикация        ${ports:-наружу ничего не опубликовано}
  что там сейчас    ./deploy/remote.sh status $NAME --recipe $RECIPE
  журнал            docker --context $CTX compose -f $RECIPE logs -f
  снять             ./deploy/remote.sh drop $NAME --recipe $RECIPE

  на ресурсе появилось то, что назвал рецепт: контейнеры «$THING», её тома, сеть $NET и
  образ $image. Ничего сверх этого туда не клали — ни файлов, ни пакетов, ни самого рецепта.
GOTOVO

    # Докер, если его ставил мир, — часть того, что на машине появилось, и отчёт обязан его
    # назвать: перечень, из которого выпало главное изменение чужой машины, врёт (`WORLD2` 4.2).
    [ -z "$DOCKER_PUT" ] || cat >&2 <<'DOCKER_PUT_SKAZANO'
  а ещё там появился ДОКЕР — его поставил мир, потому что без него машина не могла принять
  мир вовсе (WORLD2 3.5 п. 7). Сказано это было ДО установки, а не сейчас. Он остаётся и
  снятием вещи не убирается: это уже не наша вещь, а то, чем машина держит мир.
DOCKER_PUT_SKAZANO
}

# ------------------------------------------------------------------ drop
cmd_drop() {
    need_name drop
    have_local_tools
    # Снимаем ТО ЖЕ, что ставили, — а чем ставили, помнит человек и называет рецептом. Своего
    # реестра вещей зона не заводит намеренно: второй список того же самого разъехался бы с
    # первым, и `drop` начал бы снимать не то, о чём думает человек.
    read_recipe

    ctx_exists || refuse no-such-resource \
        "ресурса «$NAME» с этой машины не заводили — контекста $CTX нет" \
        "посмотри, какие есть: ./deploy/remote.sh list" \
        "ресурс заводили с ДРУГОЙ машины — снимай оттуда: контекст живёт там, где его создали"

    ADDR="$(ctx_endpoint)"; ADDR="${ADDR#ssh://}"
    parse_addr

    step "снимаю «$THING» с ресурса $NAME ($ADDR) — рецепт $RECIPE"

    # Ресурс мог умереть, уехать или сменить ключ — а контекст на этой машине остался. Снять
    # его мы обязаны в любом случае: иначе `list` будет врать про ресурсы, которых нет.
    # Поэтому сначала пробуем снять на той стороне, а свой контекст убираем всегда.
    local reachable=1 vols=""
    docker --context "$CTX" version >/dev/null 2>&1 || reachable=

    if [ -n "$reachable" ]; then
        # Тома спрашиваем ДО снятия и у самого докера: какие они у этой вещи, знает её
        # рецепт, и назвать их мы вправе только по факту — своего списка у нас нет.
        vols="$(thing_volumes)"

        local out rc=0
        local -a args=(compose -f "$RECIPE" down --remove-orphans)
        [ -n "$WITH_STATE" ] && args+=(-v)
        set +e
        out=$(docker --context "$CTX" "${args[@]}" 2>&1); rc=$?
        set -e
        if [ "$rc" -ne 0 ]; then
            printf '%s\n' "$out" >&2
            refuse down-failed \
                "вещь «$THING» на ресурсе $NAME не снялась" \
                "ответ докера напечатан выше" \
                "снять руками: docker --context $CTX compose -f $RECIPE down" \
                "контекст на этой машине НЕ снят — повтори команду, когда ресурс ответит" \
                "ресурса больше нет вовсе — снеси только контекст: docker context rm $CTX"
        fi
        ok "контейнеры сняты"
        [ -n "$WITH_STATE" ] && ok "тома сняты: состояние «$THING» стёрто${vols:+ ($vols)}"

        # Сеть снимаем, если в ней больше никого нет. Занята — оставляем и говорим об этом:
        # снести общую сеть, в которой стоят соседи, значило бы сломать чужое ради своей
        # чистоты. `network rm` сам откажет на занятой сети, и это ровно та проверка,
        # которая нужна, — спрашивать состав отдельно значило бы гадать между двумя вызовами.
        if docker --context "$CTX" network inspect "$NET" >/dev/null 2>&1; then
            if docker --context "$CTX" network rm "$NET" >/dev/null 2>&1; then
                ok "общая сеть $NET снята"
            else
                warn "сеть $NET осталась — в ней стоит кто-то ещё"
                detail "это соседи по полю, а не наш след: снести её значит сломать их связь"
            fi
        fi

        if [ -n "$WITH_IMAGE" ]; then
            local image="$IMAGE"
            if docker --context "$CTX" image rm "$image" >/dev/null 2>&1; then
                ok "образ $image снят с ресурса"
            else
                warn "образ $image снять не вышло — возможно, его держит другой контейнер"
            fi
        fi
    else
        warn "ресурс $ADDR не отвечает — на той стороне снять нечего этой командой"
        detail "контекст с этой машины всё равно убираем: иначе list будет врать про живой ресурс"
        detail "ресурс вернётся — заведи заново: ./deploy/remote.sh add $NAME --addr $ADDR"
    fi

    docker context rm "$CTX" >/dev/null 2>&1 || refuse context-failed \
        "контекст $CTX с этой машины не убрать" \
        "посмотри, что мешает: docker context rm $CTX" \
        "контекст выбран текущим — переключись и повтори: docker context use default"
    ok "контекст $CTX убран — на этой машине следов ресурса не осталось"

    say ""
    if [ -n "$reachable" ]; then
        printf '\033[1;32m✓ вещь «%s» снята с ресурса %s\033[0m\n' "$THING" "$NAME" >&2
        say ""
        say "  что осталось на той машине:"
        if [ -n "$WITH_STATE" ]; then
            say "    состояние вещи — стёрто (--with-state)"
        else
            say "    тома вещи — её состояние, оно переживает снятие${vols:+: $vols}"
            say "      стереть: ./deploy/remote.sh add $NAME --addr $ADDR --recipe $RECIPE,"
            say "               затем drop $NAME --recipe $RECIPE --with-state"
            say "      состояние переживает снятие НАРОЧНО: поднятая заново вещь находит своё,"
            say "      а не пустоту. Молча стирать его снятие не вправе"
        fi
        if [ -n "$WITH_IMAGE" ]; then
            say "    образ $IMAGE — снят (--with-image)"
        else
            say "    образ $IMAGE — остался: он тяжёлый, и второй подъём с ним мгновенный"
        fi
        say "    больше НИЧЕГО из нашего: ни файлов, ни пакетов, ни клона репозитория — их туда и не клали"
        say "    докер — если его ставил мир, он ОСТАЁТСЯ: снести чужой докер значит распорядиться"
        say "      машиной, а этого мир не делает. Убрать его — дело хозяина машины"
    else
        printf '\033[1;33m! ресурс %s убран только с этой машины\033[0m\n' "$NAME" >&2
        say "  на самой машине контейнеры, тома и образ могли остаться — снять их можно, когда она ответит"
    fi
}

# ------------------------------------------------------------------ list
cmd_list() {
    have_local_tools
    local rows
    rows="$(docker context ls --format '{{.Name}}	{{.DockerEndpoint}}' 2>/dev/null | grep "^$PREFIX" || true)"
    say ""
    if [ -z "$rows" ]; then
        say "ресурсов с этой машины не заводили"
        say ""
        say "  завести: ./deploy/remote.sh add <имя> --addr user@10.8.0.5"
        return 0
    fi
    printf '%-16s %-32s %s\n' "РЕСУРС" "АДРЕС" "КОНТЕКСТ" >&2
    local name endpoint
    while IFS="	" read -r name endpoint; do
        [ -n "$name" ] || continue
        printf '%-16s %-32s %s\n' "${name#$PREFIX}" "${endpoint#ssh://}" "$name" >&2
    done <<< "$rows"
    say ""
    say "  что на ресурсе сейчас: ./deploy/remote.sh status <имя>"
    say "  список — это контексты докера, своего реестра зона не заводит: второй список"
    say "  того же самого однажды разъехался бы с первым"
}

# ------------------------------------------------------------------ status
cmd_status() {
    need_name status
    have_local_tools
    ctx_exists || refuse no-such-resource \
        "ресурса «$NAME» с этой машины не заводили — контекста $CTX нет" \
        "посмотри, какие есть: ./deploy/remote.sh list" \
        "завести: ./deploy/remote.sh add $NAME --addr user@10.8.0.5"

    ADDR="$(ctx_endpoint)"; ADDR="${ADDR#ssh://}"
    parse_addr
    read_recipe
    local image="$IMAGE"

    say ""
    say "ресурс     : $NAME"
    say "адрес      : $ADDR"
    say "контекст   : $CTX"

    say "рецепт     : $RECIPE (вещь «$THING»)"

    # Каждая строка ниже — ОТДЕЛЬНЫЙ вопрос отдельному демону, и ни одна не выводится из
    # другой. «Докер отвечает» не значит «вещь стоит», «контейнер есть» не значит «вещь
    # отвечает»: состояние, выведенное вместо измеренного, врёт ровно тогда, когда на него
    # смотрят (`WORLD2` 4.2).
    if ! docker --context "$CTX" version >/dev/null 2>&1; then
        say "докер там  : не отвечает"
        say ""
        say "  ресурс молчит: он выключен, сменил адрес или не пускает креды"
        say "  разобрать по ступеням: ./gate/gate.sh check (GATE_ADDR=$ADDR)"
        return 0
    fi
    say "докер там  : отвечает"

    # ЧТО ВООБЩЕ СТОИТ НА РЕСУРСЕ — вопрос к ресурсу, а не к нашему рецепту. Ресурс это
    # машина, до которой дотянулись; какие вещи на ней подняты — отдельное знание, и оно
    # читается у чужого демона по метке проекта, которую компоуз ставит сам. Своего реестра
    # вещей зона по-прежнему не заводит.
    local things
    things="$(docker --context "$CTX" ps -a --format '{{.Label "com.docker.compose.project"}}' 2>/dev/null \
              | grep -v '^$' | sort -u | tr '\n' ' ' | sed 's/ *$//' || true)"
    say "вещи там   : ${things:-ни одной}"

    if docker --context "$CTX" image inspect "$image" >/dev/null 2>&1; then
        say "образ      : $image есть"
    else
        say "образ      : $image НЕТ — «$THING» поднять нечем"
    fi

    # Дальше — про ВЕЩЬ ЭТОГО РЕЦЕПТА, и контейнеры её называет компоуз, а не мы.
    local ids id name state health published
    ids="$(thing_ids)"
    if [ -z "$ids" ]; then
        say "контейнеры : нет"
    else
        for id in $ids; do
            name="$(docker --context "$CTX" inspect --format '{{.Name}}' "$id" 2>/dev/null | sed 's|^/||' || true)"
            state="$(docker --context "$CTX" ps -a --filter "id=$id" --format '{{.Status}}' 2>/dev/null | head -n1 || true)"
            health="$(health_of "$id")"
            published="$(published_of "$id" | tr '\n' ' ' | sed 's/ *$//')"
            say "контейнер  : ${name:-$id} — ${state:-состояние неизвестно}"
            case "$health" in
                none|"") say "  здоровье : HEALTHCHECK-а нет — «отвечает ли» этим не проверить" ;;
                *)       say "  здоровье : $health" ;;
            esac
            say "  порт     : ${published:-публикации не видно}"
        done
    fi

    if docker --context "$CTX" network inspect "$NET" >/dev/null 2>&1; then
        say "сеть       : $NET есть"
    else
        say "сеть       : $NET нет"
    fi

    local vols; vols="$(thing_volumes)"
    say "состояние  : ${vols:-томов нет}"

    say ""
    say "  поднять заново : ./deploy/remote.sh add $NAME --recipe $RECIPE"
    say "  снять          : ./deploy/remote.sh drop $NAME --recipe $RECIPE"
}

# ------------------------------------------------------------------ разбор ключей
# Ключи разбираем ДО всего: `--help` обязан работать и там, где нет ни докера, ни ssh, ни
# заведённых ресурсов.
RESEND=""; WITH_STATE=""; WITH_IMAGE=""; PULL=""
CMD="${1:-}"
[ $# -gt 0 ] && shift || true

case "$CMD" in
    -h|--help) usage; exit 0 ;;
    "")        usage >&2; printf '\nкоманда не названа\n' >&2; exit 2 ;;
    add|drop|status|list) ;;
    *)         usage >&2; printf '\nнепонятная команда: %s\n' "$CMD" >&2; exit 2 ;;
esac

while [ $# -gt 0 ]; do
    case "$1" in
        --addr)  shift; [ $# -gt 0 ] || { printf 'у --addr нет значения: --addr user@10.8.0.5\n' >&2; exit 2; }
                 ADDR="$1" ;;
        --addr=*)       ADDR="${1#--addr=}" ;;
        # Рецепт — не украшение команды, а то, ЧТО она поднимает: без значения ключ
        # молчаливо вернул бы дверь, и человек поднял бы не ту вещь.
        --recipe) shift; [ $# -gt 0 ] || { printf 'у --recipe нет значения: --recipe deploy/compose.yaml\n' >&2; exit 2; }
                 RECIPE="$1" ;;
        --recipe=*)     RECIPE="${1#--recipe=}" ;;
        --resend-image) RESEND=1 ;;
        --pull)         PULL=1 ;;
        --with-state)   WITH_STATE=1 ;;
        --with-image)   WITH_IMAGE=1 ;;
        -h|--help)      usage; exit 0 ;;
        -*)             usage >&2; printf '\nнепонятный ключ: %s\n' "$1" >&2; exit 2 ;;
        *)              [ -z "$NAME" ] || { usage >&2; printf '\nимя ресурса названо дважды: %s и %s\n' "$NAME" "$1" >&2; exit 2; }
                        NAME="$1" ;;
    esac
    shift
done

case "$CMD" in
    add)    cmd_add ;;
    drop)   cmd_drop ;;
    list)   cmd_list ;;
    status) cmd_status ;;
esac

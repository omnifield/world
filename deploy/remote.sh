#!/usr/bin/env bash
# Вещь на НАЗВАННОМ ресурсе: назвал адрес и рецепт — вещь появилась там сама.
#
#   ./deploy/remote.sh add <имя> --addr user@host[:порт] [--recipe <путь>]   поставить
#   ./deploy/remote.sh drop <имя> [--recipe <путь>]        снять её оттуда
#   ./deploy/remote.sh list                                какие ресурсы заведены
#   ./deploy/remote.sh status <имя> [--recipe <путь>]      что сейчас на том ресурсе
#
# ┌─────────────────────────────────────────────────────────────────────────────────────┐
# │ ЧТО ИМЕННО ПОДНИМАЕТСЯ — ЗНАЕТ РЕЦЕПТ, А НЕ ЭТОТ СКРИПТ (`WORLD2` 3.7).              │
# │                                                                                      │
# │ Рецепт — файл запуска (compose). Из него берётся ВСЁ про вещь: имя, образ, имена     │
# │ контейнеров, порты, тома, имя в сети. Своих констант про конкретную вещь у механики  │
# │ нет: положил второй рецепт — поднимается вторая вещь, и ни строки здесь править не   │
# │ надо. Потребовала бы правки — значит вещь была зашита, а не описана, и это дефект.   │
# │                                                                                      │
# │ Дверь — ОДИН ИЗ РЕЦЕПТОВ (`deploy/compose.yaml`), а не встроенная вещь. Она осталась │
# │ умолчанием КОМАНДЫ (не назвал рецепт — ставится дверь), и это единственное место,    │
# │ где механика вообще про неё слышит.                                                  │
# └─────────────────────────────────────────────────────────────────────────────────────┘
#
# ┌─────────────────────────────────────────────────────────────────────────────────────┐
# │ ЧЕЛОВЕК НА ТОТ РЕСУРС НЕ ЗАХОДИТ. Ни консоли, ни `git clone`, ни положенных туда     │
# │ скриптов: всё, чем мир пользуется, приезжает образом (`TECH` 2, решение user         │
# │ 2026-08-14, рамочное).                                                               │
# │                                                                                      │
# │ ЕДИНСТВЕННОЕ, ЧТО МИР НА ТОЙ МАШИНЕ ДЕЛАЕТ САМ, — ДОКЕР. Это не послабление, а       │
# │ условие: докер не вещь В мире, а то, ЧЕМ мир на машине бывает (`WORLD2` 3.5 п. 7 и   │
# │ раздел «Докер ставит мир, и это не нарушение п. 6», 2026-08-18). Машина без него     │
# │ принять мир не может вовсе — ни двери, ни раздачи на ней не существует даже в        │
# │ возможности, — поэтому мир ставит его сам. Границы жёсткие, и стережёт их проба:     │
# │                                                                                      │
# │   докер — единственное     список не открывается: ставится он, и ничего сверх        │
# │   есть докер — не трогаем  ни обновления, ни замены, ни починки чужой версии         │
# │   говорим ДО, а не после   юзер узнаёт, что на машине появится докер, до того как он │
# │                            там появится, и слышит саму команду, а не журнал после    │
# │   не вышло — отказ         причина и выход, и «не достала до сети» ≠ «нет прав»      │
# │                                                                                      │
# │ Ставит его ОФИЦИАЛЬНЫЙ установщик докера, а не наш скрипт: мир ставит готовое и      │
# │ общее, а не своё (`3.5`, таблица «кто изготовитель»). Сверка с рынком — ниже, у      │
# │ DOCKER_INSTALL_URL.                                                                  │
# │                                                                                      │
# │ Своего подъёма мы для этого НЕ ПИШЕМ. Докер умеет управлять чужим демоном по SSH из  │
# │ коробки — контекст (`docker context`), и это встроенный механизм, а не находка       │
# │ (сверка с рынком `TECH` 3, 2026-08-14: класс 1, «агента нет вообще»). Здесь только   │
# │ то, чего у контекста нет: производное имя, поставка образа, порядок шагов и отказ с  │
# │ причиной и выходом (`WORLD2` 2.3).                                                   │
# └─────────────────────────────────────────────────────────────────────────────────────┘
#
# ЧТО ПОЯВЛЯЕТСЯ НА ТОЙ СТОРОНЕ — и ничего сверх этого:
#
#   контейнеры рецепта          снимаются `drop`
#   сеть `omnifield-gateway`    снимается `drop`, если в ней больше никого нет
#   тома рецепта                состояние — остаётся, снимается `drop --with-state`
#   образ, названный рецептом   остаётся, снимается `drop --with-image`
#   докер, если его там не было  ОСТАЁТСЯ и `drop`-ом не снимается: он не наша вещь, а то,
#                                чем машина вообще способна принять мир. Сносить чужой
#                                докер — распоряжаться машиной, а этого мир не делает
#
# Имён контейнеров, томов и образа тут не перечислено намеренно: они принадлежат рецепту, и
# у механики их знать неоткуда. Что появилось на самом деле — говорит `status`, спрашивая
# чужой демон, а не наш список.
#
# На ЭТОЙ машине появляется ровно одна вещь — контекст докера `world-<имя>`. Он же и есть
# всё наше состояние: адрес ресурса хранится в нём, своего файла реестра зона не заводит.
# Снимается тем же `drop`. Двух списков одного и того же не бывает: разъедутся — `drop`
# начнёт снимать не тот ресурс, о котором думает человек.
#
# КРЕДЫ МИР НЕ ЗАВОДИТ И НЕ ХРАНИТ. Докер по SSH ходит системным `ssh` и берёт ключ там, где
# его берёт ssh: агент либо `~/.ssh/config`. Ключом-значением это подменить нельзя — у
# `docker context` нет такого поля вовсе, и наш ключ докер бы молча проигнорировал. Поэтому
# ключа-ключа здесь нет: креды принадлежат юзеру и его связке (`WORLD2` 3.0), а отказ
# `access-denied` называет, куда именно ключ кладут.
#
# Имена переменных ЛАТИНСКИЕ, хотя репозиторий говорит по-русски: bash не поддерживает
# не-ASCII в именах и молча превращает `ИМЯ=x` в «команда не найдена». Тексты — русские.
set -euo pipefail
# Ступени «нет докера на той стороне» и «ключ не принят» различаются по тексту ответа
# системы, а он переводится. Без этого на локализованной машине два разных отказа
# схлопнулись бы в один — и человека отправляло бы чинить не то (`WORLD2` 2.3).
export LC_ALL=C

HERE="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"

# РЕЦЕПТ — единственный источник знания о поднимаемой вещи. Умолчание — рецепт двери, и это
# умолчание КОМАНДЫ, а не знание механики: прежний путь («поставь дверь на ресурс») остаётся
# одной командой без ключей, а всё, что механика делает дальше, читается из названного файла.
RECIPE="$HERE/compose.yaml"

# Общая сеть — ЛАНДШАФТ машины, а не свойство вещи: в ней стоят соседи по полю, и она старше
# любого рецепта. Компоуз её не создаёт (`external: true`), поэтому создаём мы — так же, как
# это делает `up.sh` у себя, и по той же причине: войти в несуществующую сеть докер не даёт,
# и первый подъём на чистой машине без этого не встаёт.
NET=omnifield-gateway
# Сколько ждём ответа ssh. Меньше — быстрее краснеет, больше — терпимее к медленной связи.
TIMEOUT="${WORLD_REMOTE_TIMEOUT:-10}"
# Сколько ждём, пока вещь на той стороне станет здоровой. Дольше, чем у `up.sh`: там образ
# уже лежит и запуск местный, здесь между нами сеть.
WAIT="${WORLD_REMOTE_WAIT:-60}"

# Приставка контекста. Имя контекста ПРОИЗВОДНО от имени ресурса (`world-<имя>`), а не
# выдумывается заново: производное имя разбирается в обе стороны — по ресурсу находится
# контекст, по контексту виден ресурс. Выдуманное имя пришлось бы где-то записать, и это
# был бы второй список того же самого.
PREFIX=world-

# ОТКУДА БЕРЁТСЯ ДОКЕР, КОГДА ЕГО НА МАШИНЕ НЕТ.
#
# Сверка с рынком 2026-08-19 (правило рамки: новая механика — сверяемся и оставляем след).
# Смотрели три класса:
#   1. официальный установщик докера — `get.docker.com` (репозиторий `docker/docker-install`):
#      сам определяет дистрибутив, подключает НАСТОЯЩИЕ репозитории докера и ставит движок,
#      CLI, compose и containerd. Изготовитель — докер, а не мы;
#   2. свой разбор дистрибутивов (apt/dnf/apk своими руками) — это уже НАШ установщик докера,
#      со своим списком дистрибутивов, который нам же чинить. Ровно то, чего канон не велит:
#      мир ставит готовое и общее, а не своё (`WORLD2` 3.5, таблица «кто изготовитель»);
#   3. чужой инструмент доставки целиком (Kamal `server bootstrap`, ansible-роли) — он делает
#      ТО ЖЕ САМОЕ (проверяет докер и ставит его через `get.docker.com`), но тянет за собой
#      рантайм и зависимость в поставку, а зависимость — решение architect, не зоны.
# Взят первый. Оговорку докера «не для продакшена» знаем: она про то, что скрипт не даёт
# настроить установку и ставит рекомендованное без спроса, — а нам нужен ровно докер по
# умолчанию, и настраивать в нём нечего. Машине, где докер уже есть, всё это не касается:
# её мир не трогает вовсе.
DOCKER_INSTALL_URL="${WORLD_DOCKER_INSTALL_URL:-https://get.docker.com}"

usage() {
    cat <<'USAGE'
Вещь на названном ресурсе: ./deploy/remote.sh <команда>

  add <имя> --addr user@host[:порт]   поставить вещь на том ресурсе одной командой
  drop <имя> [--with-state] [--with-image]   снять её оттуда
  list                                какие ресурсы заведены с этой машины
  status <имя>                        что сейчас на том ресурсе
  -h --help                           эта подсказка

Имя ресурса — своё, короткое: буквы, цифры и дефис. Имя контекста докера производно от
него (`world-<имя>`) и отдельно не называется.

ЧТО ПОДНИМАЕТСЯ — говорит РЕЦЕПТ (файл запуска), а не эта команда. Не назвал рецепт —
берётся рецепт двери (deploy/compose.yaml); назвал — поднимается названная им вещь, и
механике для этого нечего знать заранее.

  ./deploy/remote.sh add vps --addr world@10.8.0.5                    дверь (умолчание)
  ./deploy/remote.sh add vps --recipe deploy/весы.yaml                 другая вещь
  ./deploy/remote.sh add vps --addr world@10.8.0.5:2222   порт ssh, если он не 22
  WORLD_PORT=8090 ./deploy/remote.sh add vps --addr …     значение, которое читает рецепт

Ключи `add`:
  --addr АДРЕС      адрес ресурса. Обязателен, пока ресурс не заведён; заведённому не
                    нужен — адрес лежит в контексте. Названный заново — адрес меняется
  --recipe ПУТЬ     файл запуска поднимаемой вещи. Умолчание — deploy/compose.yaml,
                    рецепт двери. Тот же ключ нужен `drop` и `status`: своего реестра
                    вещей зона не заводит, и «что мы там поднимали» она не помнит
  --resend-image    везти образ, даже если на той стороне он уже есть
  --pull            велеть ресурсу взять образ ИЗ РЕЕСТРА, даже если он есть здесь.
                    БЕЗ ЭТОГО КЛЮЧА ПУТЬ ВЫБИРАЕТ НАЛИЧИЕ, а не человек: образ лежит у
                    нас — везём копией по ssh; не лежит — ту машину просим притянуть его
                    самой. Каким путём пошли, команда говорит вслух ДО того, как путь
                    занял минуты

Ключи `drop` — по умолчанию снимаются контейнеры, сеть и контекст:
  --with-state      снять и ТОМА рецепта: состояние стирается
  --with-image      снять и образ, названный рецептом, с того ресурса

Переменные:
  WORLD_PORT=8080              значение для рецепта двери — её хост-порт на том ресурсе.
                               Рецепт, который его не читает, о нём и не узнает
  WORLD_REMOTE_TIMEOUT=10      сколько секунд ждём ответа ssh
  WORLD_REMOTE_WAIT=60         сколько секунд ждём, пока вещь станет здоровой
  WORLD_DOCKER_INSTALL_URL=…   откуда та машина берёт установщик докера. Умолчание —
                               официальный get.docker.com; своё зеркало нужно машине,
                               которой наружу не выйти

ЧТО НУЖНО НА ТОМ РЕСУРСЕ: ssh с ключом. Докера может не быть — мир поставит его сам и
скажет об этом ДО, а не после; есть докер — не трогает его вовсе. Больше на ту машину не
кладётся ничего: ни пакетов, ни клона репозитория, ни наших скриптов (WORLD2 3.5 п. 7).
Ключ берётся оттуда же, откуда его берёт ssh: агент (`ssh-add`) либо `~/.ssh/config`;
своего хранилища ключей мир не заводит (WORLD2 3.0).

Каким путём команда пошла, она говорит и машине — строкой `REMOTE-PATH: <путь>` в stdout,
ДО самого пути: docker-install · image-present · image-copy · image-pull.

Отказ печатается двумя строками: причина и выход — человеку, `REMOTE-REFUSAL: <код>` —
машине. Коды: no-name · bad-name · no-address · bad-address · no-recipe · bad-recipe ·
recipe-no-image · no-docker · no-daemon · no-compose · no-ssh · access-denied ·
no-remote-docker · remote-docker-denied · bad-remote-answer · docker-install-denied ·
docker-install-no-fetch ·
docker-install-no-net · docker-install-failed · docker-install-silent · image-send-failed ·
image-pull-failed · no-network · port-busy · up-failed · thing-silent · no-such-resource ·
down-failed · context-failed.

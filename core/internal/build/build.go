// Package build — ПОСТРОЙКА НА МЕСТЕ: что встаёт внутрь локации и чем место
// отвечает на вопрос «что на тебе стоит».
//
// # Зачем пакет существует
//
// Локации находятся ВНУТРИ мира, значит доступ до них у мира есть по
// построению, и отдавать его инструменту стройки нельзя: «если доступ к
// локациям даёт не мир, а инструмент стройки, — вот это дыра» (`kb:WORLD-56`).
// Дыра была открыта: до места дотягивались `docker exec`'ом и работали руками —
// мир в этом не участвовал, хотя место его.
//
// Здесь закрыта третья часть правила — ДОСТУП. Остальные две не наши:
//
//	место ничего не «принимает» — оно место (`kb:WORLD-27`), на нём стоит вахта;
//	строит ЮЗЕР — руками, которые дал мир (`kb:WORLD-61`, `kb:WORLD-57`);
//	мир ДАЁТ доступ до места и внутрь него — маршрут за дверью плюс эта ручка.
//
// Пакет исполняет установку, но не решает, что ставить, и не отвечает за
// результат: «мир поставил постройку» — оборот, которого в мире нет.
//
// # Форма доставки — репозиторий
//
// Форма доставки задаёт потолок ступени (`kb:WORLD-27`): постройка приезжает
// РЕПОЗИТОРИЕМ. В гите одна истина есть СХЕМА, клон в локации есть сама
// ПОСТРОЙКА. Поэтому «поставить постройку» здесь буквально `git clone` схемы
// внутрь места, а не распаковка пакета и не копирование файлов снаружи.
//
// # Исходы — три, и повтор назван своим
//
//	built     — место было пустым, постройка встала;
//	confirmed — та же схема уже стоит: повтор не ошибка и не перезапись;
//	replaced  — стояла другая схема, и её снесли ПО ЯВНОЙ просьбе (replace).
//
// Та же логика, что у входа в поле (`tasker:WORLD-81`), своими словами. Тихой
// перезаписи нет: без `replace` чужая схема получает названный отказ с выходом,
// а не молча затирает то, что стоит.
//
// # Чего пакет НЕ делает сознательно
//
//   - не собирает участок из НЕСКОЛЬКИХ схем: это уровень `tasker:WORLD-43`
//     целиком, форма там не назначена. Здесь ОДНА постройка на место;
//   - не обновляет постройку (`git pull`): «уже стоит» — это исход, а не повод
//     молча подтянуть чужие коммиты. Обновление — отдельное решение с отдельным
//     владельцем;
//   - не запускает поставленное и не раздаёт его наружу: клон лежит на диске
//     места, а кто его поднимает — вопрос следующей ступени, не сторожа;
//   - не заводит допуск: кто вправе строить, разбирается в ветке юзера
//     (`tasker:WORLD-49`). Поле сегодня доверенное, и это сказано вслух.

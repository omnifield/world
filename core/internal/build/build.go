const (
	// Path — ручка постройки внутри места: доступ, который даёт мир. Путь один
	// на чтение и на стройку («что стоит» и «пусть встанет» это одна вещь с двух
	// сторон), и живёт он ЗДЕСЬ, а не у сторожа с клиентом порознь: две копии
	// одного пути разъезжаются молча.
	Path = "/api/build"

	// MaxBody — потолок тела стройки. Схема это одна строка адреса: содержимое
	// постройки приезжает гитом, а не этим запросом.
	MaxBody = 8 << 10

	// CloneTimeout — сколько ждём приезда схемы. Клон это сеть и диск, и
	// секундами тут не обойтись; но ждать вечно тоже нельзя — молчащий git
	// держал бы ручку места открытой, и снаружи это выглядит как зависшее место.
	CloneTimeout = 4 * time.Minute

	// MeasureTimeout — сколько ждём измерения уже приехавшего клона. Локальная
	// операция: дольше секунд это не «медленно», а «git не отвечает».
	MeasureTimeout = 30 * time.Second

	// MaxSchemaLen — потолок адреса схемы. Адрес репозитория длиннее килобайта
	// адресом не является.
	MaxSchemaLen = 2048

	// Раскладка на диске места. Клон и паспорт лежат РЯДОМ, а не паспорт внутри
	// клона: паспорт — наша запись, а клон целиком принадлежит схеме, и класть
	// в него своё значит пачкать чужую постройку.
	деревоИмя  = "build"
	паспортИмя = "build.json"
	времянка   = ".build-tmp"
	снесённое  = ".build-old"
)

// Outcome — чем кончилось обращение стройки. Слово уезжает в ответ ручки,
// поэтому это строка, а не число: ответ читают глазами.
type Outcome string

const (
	// OutcomeBuilt — место было пустым, постройка встала.
	OutcomeBuilt Outcome = "built"
	// OutcomeConfirmed — та же схема уже стоит: ничего не делали и не трогали.
	OutcomeConfirmed Outcome = "confirmed"
	// OutcomeReplaced — прежнюю постройку снесли по явной просьбе и поставили эту.
	OutcomeReplaced Outcome = "replaced"
)

// Build — паспорт постройки: что стоит на месте и чем это подтверждено.
//
// Поля отвечают ровно на те вопросы, которые задают месту: ЧТО это (schema),
// что именно приехало (commit), КУДА встало (tree) и КОГДА (since). Больше
// здесь не появляется: чего не измерили — того не пишем (`kb:WORLD-32`).
type Build struct {
	// Schema — откуда приехала постройка: адрес репозитория-схемы.
	Schema string `json:"schema"`
	// Commit — что именно приехало: SHA HEAD, измеренный сразу после клона.
	// Пусто — измерить было нечем (схема без единого коммита), и тогда так и
	// сказано, а не проставлено правдоподобное.
	Commit string `json:"commit,omitempty"`
	// Tree — куда встало: путь внутри места.
	Tree string `json:"tree"`
	// Since — когда встало, RFC3339. Повтор той же схемы это время не двигает:
	// подтверждение присутствия — не новая стройка.
	Since string `json:"since"`
}

// Refusal — отказ, названный по `kb:WORLD-31`: причина И выход. Форма та же,
// что у двери и у клиента поля, — снаружи не должно быть видно, кто из троих
// сказал «нет», важно, что делать дальше.
type Refusal struct {
	// Status — код HTTP, которым отказ уедет наружу.
	Status int    `json:"-"`
	Code   string `json:"error"`
	Detail string `json:"detail"`
}

func (r *Refusal) Error() string { return r.Code + ": " + r.Detail }

func refuse(status int, code, format string, args ...any) *Refusal {
	return &Refusal{Status: status, Code: code, Detail: fmt.Sprintf(format, args...)}
}

// Site — место, на котором стоит (или не стоит) постройка.
//
// Замок один на всё место и держится на весь клон: две стройки, приехавшие
// одновременно, поделили бы один каталог, и на диске оказалась бы половина
// одной схемы поверх половины другой.
type Site struct {
	dir  string
	logf func(string, ...any)
	now  func() time.Time

	// изъян — почему стройка на этом месте невозможна (каталог не создаётся или
	// не пишется). Не ошибка старта: локация вправе стоять пустой (`kb:WORLD-54`),
	// и место обязано подняться даже тогда, когда строить в нём нечем.
	изъян error

	mu sync.Mutex
}

// Open готовит место под стройку: создаёт каталог и проверяет, что в него
// действительно можно писать.
//
// Ошибки НЕ возвращает намеренно. Скоуп не вправе зависеть от того, идёт ли в
// нём стройка (`kb:WORLD-54`): непишущийся каталог обязан остановить стройку, а
// не место. Причина запоминается и называется в отказе на первой же попытке —
// вместе с выходом.
func Open(dir string, logf func(string, ...any), now func() time.Time) *Site {
	if logf == nil {
		logf = log.Printf
	}
	if now == nil {
		now = time.Now
	}
	s := &Site{dir: dir, logf: logf, now: now}

	abs, err := filepath.Abs(dir)
	if err != nil {
		s.изъян = fmt.Errorf("путь каталога стройки %q не разрешается: %w", dir, err)
	} else {
		s.dir = abs
		s.изъян = проверитьКаталог(abs)
	}
	if s.изъян != nil {
		// Молчать нельзя: снаружи «место стоит, а строить в нём нельзя» выглядит
		// как поломка мира, хотя сломана раскладка одного каталога.
		s.logf("guard: ПРЕДУПРЕЖДЕНИЕ: стройка на этом месте невозможна: %v", s.изъян)
	}
	return s
}

// проверитьКаталог — можно ли сюда положить постройку. Проверяем ЗАПИСЬЮ, а не
// правами в inode: права читаются по-разному под разными пользователями и
// файловыми системами, а запись отвечает на вопрос ровно так, как он стоит.
func проверитьКаталог(dir string) error {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return fmt.Errorf("каталог стройки %s не создаётся: %w; задай WORLD_BUILD_DIR каталогом, куда место может писать", dir, err)
	}
	f, err := os.CreateTemp(dir, ".world-write-probe.*")
	if err != nil {
		return fmt.Errorf("в каталог стройки %s нельзя писать: %w; том смонтирован только на чтение либо принадлежит другому пользователю", dir, err)
	}
	name := f.Name()
	f.Close()
	return os.Remove(name)
}

// Dir — где на месте живёт постройка. Нужен стартовой строке: «постройка
// переживает рестарт» проверяется взглядом на каталог, а не на слово.
func (s *Site) Dir() string { return s.dir }

func (s *Site) дерево() string  { return filepath.Join(s.dir, деревоИмя) }
func (s *Site) паспорт() string { return filepath.Join(s.dir, паспортИмя) }

// Standing — что стоит на месте. nil, nil значит «пусто», и это ЗАКОННОЕ
// состояние (`kb:WORLD-54`), а не сбой: стройка идёт после входа в поле, а
// может не идти вовсе.
func (s *Site) Standing() (*Build, *Refusal) {
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.стоит()
}

// стоит читает паспорт и сверяет его с землёй. Зовётся ТОЛЬКО под s.mu.
//
// Паспорт — запись ИЗМЕРЕНИЯ в момент стройки, а не мнение: коммит в нём снят
// с приехавшего клона. Живьём при чтении он не перемеряется, и граница названа
// вслух в core/README.md: залезли внутрь места руками и поменяли клон — паспорт
// этого не увидит. Что проверяется всегда — что клон вообще на месте.
func (s *Site) стоит() (*Build, *Refusal) {
	raw, err := os.ReadFile(s.паспорт())
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, refuse(http.StatusInternalServerError, "passport-unreadable",
			"паспорт постройки %s не читается: %v; место стоит, а что на нём — сказать нечем. "+
				"Выход: поставить постройку заново (world build -schema <адрес>) — паспорт перепишется", s.паспорт(), err)
	}

	var b Build
	if err := json.Unmarshal(raw, &b); err != nil {
		return nil, refuse(http.StatusInternalServerError, "passport-invalid",
			"паспорт постройки %s не разбирается как JSON: %v; выход: поставить постройку заново (world build -schema <адрес>) "+
				"либо удалить паспорт — место скажет «пусто», и это законно", s.паспорт(), err)
	}
	if _, err := os.Stat(s.дерево()); err != nil {
		// Паспорт есть, а клона нет — это не «пусто»: пустое место паспорта не
		// имеет. Сказать «пусто» здесь значило бы спрятать пропажу.
		return nil, refuse(http.StatusInternalServerError, "build-lost",
			"паспорт постройки есть (схема %s, встала %s), а самой постройки по пути %s нет: %v. "+
				"Клон живёт на диске места: он переживает рестарт контейнера, но не его пересоздание, пока у локации нет тома под стройку. "+
				"Выход: поставить заново — world build -schema %s", b.Schema, b.Since, s.дерево(), err, b.Schema)
	}
	return &b, nil
}

// Raise — поставить постройку на место. Возвращает то, что теперь на нём стоит,
// и ИСХОД: повтор обязан быть назван своим словом, а не тихой перезаписью.
//
// replace — явная просьба снести стоящую постройку. Без неё чужая схема
// получает отказ с выходом: снос — это потеря того, что на месте уже сделано, и
// случаться молча он не вправе.
func (s *Site) Raise(schema string, replace bool) (*Build, Outcome, *Refusal) {
	schema = strings.TrimSpace(schema)
	if r := validSchema(schema); r != nil {
		return nil, "", r
	}

	s.mu.Lock()
	defer s.mu.Unlock()

	if s.изъян != nil {
		return nil, "", refuse(http.StatusServiceUnavailable, "build-dir-unusable",
			"стройка на этом месте невозможна: %v. Место при этом стоит и в поле остаётся: скоуп не зависит от стройки (kb:WORLD-54)", s.изъян)
	}
	git, r := путьGit()
	if r != nil {
		return nil, "", r
	}

	прежняя, отказ := s.стоит()
	switch {
	case отказ != nil && отказ.Code == "build-lost":
		// Паспорт остался от пропавшего клона. По земле место ПУСТО, и строить
		// в него — ровно тот выход, который назван в отказе. Паспорт перепишется.
		прежняя = nil
	case отказ != nil:
		return nil, "", отказ
	case прежняя != nil && прежняя.Schema == schema && !replace:
		// Повтор той же схемы — не ошибка и не повод переклонировать: место
		// подтверждает, что на нём стоит, и не трогает уже стоящее.
		return прежняя, OutcomeConfirmed, nil
	case прежняя != nil && !replace:
		return nil, "", refuse(http.StatusConflict, "build-present",
			"на месте уже стоит постройка по схеме %s (встала %s), а место держит ОДНУ постройку: "+
				"сборка участка из нескольких схем — отдельный уровень (tasker:WORLD-43), и форма там ещё не назначена. "+
				"Выход: сноси прежнюю явно и ставь эту — world build -schema %s -replace (клон прежней удаляется целиком, вместе с тем, что в нём наработано), "+
				"либо возьми другое место",
			прежняя.Schema, прежняя.Since, schema)
	}

	работа := filepath.Join(s.dir, времянка)
	// Остаток прошлой неудачи. Не ошибка: клон могло оборвать рестартом места.
	if err := os.RemoveAll(работа); err != nil {
		return nil, "", refuse(http.StatusInternalServerError, "write-failed",
			"остаток прошлой стройки %s не убирается: %v; убери его руками либо задай другой WORLD_BUILD_DIR", работа, err)
	}

	начали := s.now()
	if r := s.клонировать(git, schema, работа); r != nil {
		os.RemoveAll(работа)
		return nil, "", r
	}
	коммит := s.head(git, работа)

	if r := s.въехать(работа, прежняя != nil); r != nil {
		os.RemoveAll(работа)
		return nil, "", r
	}

	готово := &Build{
		Schema: schema,
		Commit: коммит,
		Tree:   s.дерево(),
		Since:  s.now().UTC().Format(time.RFC3339),
	}
	if r := s.записатьПаспорт(готово); r != nil {
		return nil, "", r
	}

	исход := OutcomeBuilt
	if прежняя != nil {
		исход = OutcomeReplaced
		// Снос — единственное место, где стройка ТЕРЯЕТ сделанное, и назвать
		// его надо отдельной строкой: без неё «заменили» остаётся словом.
		s.logf("guard: постройка ЗАМЕНЕНА: снесена схема %s (коммит %s, стояла с %s), встала %s",
			прежняя.Schema, короткий(прежняя.Commit), прежняя.Since, schema)
	}
	s.logf("guard: постройка %s: схема=%s commit=%s встала в %s за %s",
		исход, schema, короткий(коммит), готово.Tree, s.now().Sub(начали).Round(time.Millisecond))
	return готово, исход, nil
}

// въехать вводит свежий клон на место прежнего переименованием: читатель видит
// либо старую постройку целиком, либо новую, но не половину (тот же приём, что
// у записи реестра двери). Прежнее сносится ПОСЛЕ того, как новое встало, —
// иначе неудача въезда оставила бы место пустым.
func (s *Site) въехать(работа string, естьПрежняя bool) *Refusal {
	старое := filepath.Join(s.dir, снесённое)
	if естьПрежняя {
		if err := os.RemoveAll(старое); err != nil {
			return refuse(http.StatusInternalServerError, "write-failed",
				"остаток прошлого сноса %s не убирается: %v; постройка на месте не изменилась", старое, err)
		}
		if err := os.Rename(s.дерево(), старое); err != nil {
			return refuse(http.StatusInternalServerError, "write-failed",
				"прежняя постройка %s не отодвигается: %v; она осталась на месте, ничего не потеряно — повтори, когда каталог освободится",
				s.дерево(), err)
		}
	}
	if err := os.Rename(работа, s.дерево()); err != nil {
		if естьПрежняя {
			// Вернуть прежнюю обязаны: иначе место осталось бы без постройки
			// из-за неудавшегося въезда.
			if e := os.Rename(старое, s.дерево()); e != nil {
				return refuse(http.StatusInternalServerError, "write-failed",
					"новая постройка не встала (%v) И прежняя не вернулась на место (%v): по пути %s сейчас пусто, "+
						"прежний клон лежит в %s. Выход: поставить заново — world build -schema <адрес>",
					err, e, s.дерево(), старое)
			}
		}
		return refuse(http.StatusInternalServerError, "write-failed",
			"постройка не въезжает в %s: %v; место осталось таким, каким было — повтори", s.дерево(), err)
	}
	if естьПрежняя {
		if err := os.RemoveAll(старое); err != nil {
			// Новая постройка уже стоит — это не отказ. Но сказать надо: каталог
			// занимает место и однажды удивит того, кто в него заглянет.
			s.logf("guard: ПРЕДУПРЕЖДЕНИЕ: снесённая постройка не удалилась из %s: %v; убери каталог руками", старое, err)
		}
	}
	return nil
}

// записатьПаспорт кладёт паспорт через временный файл и rename — по той же
// причине, что и реестр двери: читатель видит либо старый паспорт целиком, либо
// новый, но не половину.
func (s *Site) записатьПаспорт(b *Build) *Refusal {
	body, err := json.MarshalIndent(b, "", "  ")
	if err != nil {
		return refuse(http.StatusInternalServerError, "write-failed", "паспорт постройки не сериализуется: %v", err)
	}
	body = append(body, '\n')

	tmp, err := os.CreateTemp(s.dir, "."+паспортИмя+".*")
	if err == nil {
		_, err = tmp.Write(body)
		if cerr := tmp.Close(); err == nil {
			err = cerr
		}
		if err == nil {
			err = os.Chmod(tmp.Name(), 0o644)
		}
		if err == nil {
			err = os.Rename(tmp.Name(), s.паспорт())
		}
		if err != nil {
			os.Remove(tmp.Name())
		}
	}
	if err != nil {
		// Клон УЖЕ стоит, а паспорта нет — и место будет говорить «пусто»,
		// хотя постройка лежит. Врать про это нельзя: называем ровно то, что есть.
		return refuse(http.StatusInternalServerError, "write-failed",
			"постройка встала в %s, но паспорт %s не записан: %v. Пока паспорта нет, место отвечает «пусто», хотя клон на диске лежит. "+
				"Выход: освободи место на диске и повтори стройку (world build -schema %s -replace) — клон переедет заново",
			s.дерево(), s.паспорт(), err, b.Schema)
	}
	return nil
}

// ── git ──────────────────────────────────────────────────────────────────────

// путьGit — чем ехать схеме. Инструмент стройки внутри места — НЕ наша зона:
// класть его в образ локации это `deploy` (`tasker:WORLD-95`). Наше здесь —
// назвать отсутствие вслух вместе с выходом, а не отвечать «не получилось».
func путьGit() (string, *Refusal) {
	git, err := exec.LookPath("git")
	if err != nil {
		return "", refuse(http.StatusServiceUnavailable, "git-missing",
			"внутри места нет git (%v), а постройка приезжает СХЕМОЙ — репозиторием (kb:WORLD-27): клонировать нечем. "+
				"Место при этом стоит и в поле остаётся. Выход: положить git в образ локации — это зона deploy, задача tasker:WORLD-95", err)
	}
	return git, nil
}

// окружениеGit — среда клона. GIT_TERMINAL_PROMPT и BatchMode здесь не
// украшение: без них закрытая схема заставляет git СПРАШИВАТЬ логин, а спросить
// его некого — ручка виснет до таймаута, и снаружи это выглядит как зависшее
// место. Пусть лучше откажет сразу и словами.
func окружениеGit() []string {
	return append(os.Environ(),
		"GIT_TERMINAL_PROMPT=0",
		"GIT_SSH_COMMAND=ssh -oBatchMode=yes",
		"GIT_CONFIG_NOSYSTEM=1",
	)
}

// клонировать — приезд схемы. Отдельная функция, потому что отказ здесь самый
// частый и самый непонятный без слов самого git: его вывод уезжает в detail
// целиком (обрезанный по длине), а не заменяется нашим «не удалось».
func (s *Site) клонировать(git, schema, dst string) *Refusal {
	ctx, cancel := context.WithTimeout(context.Background(), CloneTimeout)
	defer cancel()

	// `--` отделяет адрес от флагов: без него схема, начинающаяся с дефиса,
	// прочиталась бы гитом как опция. Форму адреса мы проверили и сами
	// (validSchema), но защита от подстановки флага обязана стоять в обоих
	// местах — одна проверка однажды меняется, и вторая остаётся.
	cmd := exec.CommandContext(ctx, git, "clone", "--quiet", "--", schema, dst)
	cmd.Env = окружениеGit()
	out, err := cmd.CombinedOutput()

	if errors.Is(ctx.Err(), context.DeadlineExceeded) {
		return refuse(http.StatusGatewayTimeout, "schema-timeout",
			"схема %s не приехала за %s и клон оборван: %s. Выход: проверь размер схемы и сеть места, "+
				"потом повтори — место осталось таким, каким было", schema, CloneTimeout, вывод(out))
	}
	if err != nil {
		return refuse(http.StatusBadGateway, "schema-unreachable",
			"схема %s не приехала (%v): такой схемы нет, доступа к ней нет либо сети из места не видно. git сказал: %s. "+
				"Выход: проверь адрес схемы (git ls-remote %s там, где он точно работает) и повтори; место осталось таким, каким было",
			schema, err, вывод(out), schema)
	}
	return nil
}

// head — что именно приехало. Измеряется сразу после клона и попадает в
// паспорт: без коммита «постройка встала» подтверждается только нашим словом.
//
// Не измерилось — пишем пусто, а не правдоподобное (`kb:WORLD-32`). Такое
// бывает честно: у схемы без единого коммита HEAD не существует.
func (s *Site) head(git, dir string) string {
	ctx, cancel := context.WithTimeout(context.Background(), MeasureTimeout)
	defer cancel()

	cmd := exec.CommandContext(ctx, git, "-C", dir, "rev-parse", "HEAD")
	cmd.Env = окружениеGit()
	out, err := cmd.Output()
	if err != nil {
		s.logf("guard: коммит приехавшей схемы не измерен (%v) — у схемы нет ни одного коммита либо git отказал; "+
			"в паспорт он не пишется: чего не измерили, того не пишем (kb:WORLD-32)", err)
		return ""
	}
	return strings.TrimSpace(string(out))
}

// ── форма адреса схемы ───────────────────────────────────────────────────────

// scpПодобный — форма `user@host:path`, которой git пользуется для ssh без
// схемы. Отдельным выражением, потому что двоеточие в ней значит не порт.
var scpПодобный = regexp.MustCompile(`^[A-Za-z0-9._~-]+@[A-Za-z0-9._-]+:.+$`)

// схемыАдреса — с чего может начинаться адрес репозитория. Список закрытый:
// открытый пропустил бы внутрь места всё, что git согласится счесть адресом.
var схемыАдреса = []string{"https://", "http://", "ssh://", "git://", "file://"}

// validSchema проверяет АДРЕС схемы, а не саму схему: что там действительно
// постройка, место знать не может и притворяться не будет (та же граница, что у
// пробы адреса на двери).
func validSchema(schema string) *Refusal {
	if schema == "" {
		return refuse(http.StatusBadRequest, "field-missing",
			"поле «schema» обязательно: постройка приезжает СХЕМОЙ — репозиторием (kb:WORLD-27), и без адреса ехать нечему. "+
				"Задай адрес: world build -schema https://… (переменная WORLD_SCHEMA)")
	}
	if len(schema) > MaxSchemaLen {
		return refuse(http.StatusBadRequest, "schema-invalid",
			"адрес схемы длиннее %d символов — это не адрес репозитория; проверь, что в поле «schema» уехал адрес, а не содержимое", MaxSchemaLen)
	}
	if strings.ContainsAny(schema, "\x00\n\r\t") {
		return refuse(http.StatusBadRequest, "schema-invalid",
			"в адресе схемы есть перевод строки либо управляющий символ — адрес репозитория пишется одной строкой")
	}
	if strings.HasPrefix(schema, "-") {
		return refuse(http.StatusBadRequest, "schema-invalid",
			"адрес схемы %q начинается с дефиса — git прочитал бы его как свою опцию, а не как репозиторий; "+
				"дай адрес целиком (https://…, ssh://…, user@host:path) либо путь от корня места", schema)
	}
	for _, п := range схемыАдреса {
		if strings.HasPrefix(schema, п) {
			return nil
		}
	}
	if scpПодобный.MatchString(schema) {
		return nil
	}
	if strings.HasPrefix(schema, "/") {
		// Путь от корня — законная схема: репозиторий может лежать на диске,
		// который место видит. Относительный путь не берём (см. отказ ниже).
		return nil
	}
	return refuse(http.StatusBadRequest, "schema-invalid",
		"адрес схемы %q не похож на репозиторий. Берутся: https:// · http:// · ssh:// · git:// · file:// · user@host:path · путь от корня (/…). "+
			"Относительный путь не берём сознательно: он считался бы ОТ МЕСТА, а не от твоей машины, и молча уехал бы не туда", schema)
}

// ── мелочи вывода ────────────────────────────────────────────────────────────

// короткий — коммит в том виде, в каком его читают глазами. Пустой называется
// словом, а не пустотой в середине строки журнала.
func короткий(commit string) string {
	switch {
	case commit == "":
		return "не измерен"
	case len(commit) > 12:
		return commit[:12]
	default:
		return commit
	}
}

// вывод — что сказал git, обрезанное до читаемого. Целиком его тащить в отказ
// нельзя: клон умеет говорить абзацами, а отказ читают в терминале.
func вывод(out []byte) string {
	s := strings.TrimSpace(string(out))
	if s == "" {
		return "(молча)"
	}
	s = strings.Join(strings.Fields(s), " ")
	if len(s) > 400 {
		s = s[:400] + "…"
	}
	return s
}

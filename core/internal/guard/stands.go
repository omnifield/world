// ЗАСТРОЙКА МЕСТА — то, что на месте стоит, и куда из-за этого ведёт маршрут.
//
// # Зачем это здесь
//
// Локация — это адрес и свойства, а ЗАСТРОЙКА есть её состояние: то, что на ней
// стоит (канон `WORLD2`, узел `2.0`). Вид идёт по приближению (`1.8`): подошёл к
// месту — видишь место, зашёл внутрь — видишь, что на нём стоит. Пользование
// стоящей вещью — это связь, и происходит она ТАМ, ГДЕ ВЕЩЬ СТОИТ (`1.6`):
// ничего никуда не копируется.
//
// Отсюда правило маршрута: по маршруту места открывается ЗАСТРОЙКА, а не рассказ
// сторожа о себе. Пусто — сторож отвечает «я здесь» ровно как раньше: пустая
// локация законна (`1.0`), и это не отказ.
//
// # Адрес застройки ЗАЯВЛЯЕТСЯ, а не угадывается
//
// Мир не ходит проверять и не сканирует место: «не заявлено — не видно»
// (`0.8`), «заявить можно только достижимое» (`1.8`). Где внутри места стоит
// застройка — свойство локации, приезжающее её настройкой (`WORLD_BUILD_ADDR`,
// флаг `-build-addr`), как и всё остальное в режиме сторожа.
//
// Не заявлено — застройки для мира нет, и маршрут отвечает присутствием.
// Заявлено — маршрут уезжает туда целиком, всеми методами.
//
// # Чего здесь НЕТ сознательно
//
//   - мир НЕ разворачивает застройку. Развернуть — это доставить И выполнить
//     цепочку (`2.4`), и делает это юзер своими руками либо своим инструментом.
//     Здесь только показ того, что уже поднято;
//   - мир НЕ публикует порт локации наружу (`kb:FUND-5`): наружу торчит одна
//     дверь, застройка достижима по маршруту места через неё. Сторож остаётся
//     хозяином порта — он же и ведёт к застройке;
//   - мир НЕ раздаёт содержимое застройки с диска. Лежащие на складе файлы —
//     это доставленное, а не поднятое: показывать их как работающую вещь значит
//     выдавать доставку за разворачивание.
const (
	// DialTimeout — сколько ждём соединения с застройкой. Она стоит внутри того
	// же места, соседним процессом: ждать дольше нечего, а «мертва» надо назвать
	// быстро и словами, а не держать пришедшего в тишине.
	DialTimeout = 2 * time.Second

	// AddrVar и AddrFlag — где заявляется адрес застройки. Названы константами,
	// потому что уезжают в отказы: выход в тексте отказа обязан совпадать с тем,
	// чем это чинится на самом деле.
	AddrVar  = "WORLD_BUILD_ADDR"
	AddrFlag = "-build-addr"
)

// Stands — заявленная застройка места: адрес, маршрут к нему и причина, по
// которой маршрута может не быть.
//
// nil значит «застройка не заявлена»: место пустое, и маршрут отвечает
// присутствием сторожа. Это ЗАКОННОЕ состояние (`1.0`), а не недонастройка.
type Stands struct {
	addr string
	// изъян — адрес заявлен, но маршрута из него не выходит (форма адреса не та
	// либо он указывает на самого сторожа). Не ошибка старта: место обязано
	// встать и остаться в поле, а изъян называется в отказе на маршруте —
	// вместе с выходом (`2.3`).
	изъян *отказ
	rp    *httputil.ReverseProxy
}

// отказ — форма ответа «нет» на маршруте: причина И выход (`2.3`). Своя, а не
// общая с internal/build: застройка про стройку ничего не знает, и связывать их
// значило бы завести зависимость там, где её нет.
type отказ struct {
	Status int    `json:"-"`
	Code   string `json:"error"`
	Detail string `json:"detail"`
}

func отказать(status int, code, format string, args ...any) *отказ {
	return &отказ{Status: status, Code: code, Detail: fmt.Sprintf(format, args...)}
}

// OpenStands читает заявленный адрес застройки и строит маршрут к ней.
//
// addr — что заявлено настройкой места («хост:порт» внутри места); listen — что
// слушает сам сторож, и нужен он ровно для одного: поймать петлю, когда
// застройку заявили по адресу самого сторожа.
//
// Пустой адрес даёт nil — застройки нет, маршрут остаётся сторожу. Дурной адрес
// НЕ роняет место: возвращается Stands с изъяном, и он называется на маршруте.
func OpenStands(addr, listen string, logf func(string, ...any)) *Stands {
	addr = strings.TrimSpace(addr)
	if addr == "" {
		return nil
	}
	if logf == nil {
		logf = func(string, ...any) {}
	}
	s := &Stands{addr: addr}

	if изъян := провериться(addr, listen); изъян != nil {
		s.изъян = изъян
		// Молчать нельзя: снаружи это выглядит как «место сломано», хотя
		// сломана одна строка конфига, и починить её можно за секунду.
		logf("guard: ПРЕДУПРЕЖДЕНИЕ: застройка заявлена по адресу %q, но маршрута из него не выходит: %s", addr, изъян.Detail)
		return s
	}

	// Адрес берётся как заявлен. Пустой хост («:3000») — это «внутри места»:
	// стандартная библиотека читает адрес без хоста как локальную машину
	// (документировано у net.Dial), и подставлять сюда 127.0.0.1 своей рукой
	// значило бы завести вторую копию того же правила.
	target := &url.URL{Scheme: "http", Host: addr}
	s.rp = &httputil.ReverseProxy{
		// Rewrite, а не устаревший Director — тем же приёмом, что у двери
		// (internal/door/proxy.go). Путь НЕ трогаем: имя места срезала дверь, и
		// застройка живёт у себя в корне — знать о маршруте за дверью ей нечем.
		Rewrite: func(pr *httputil.ProxyRequest) {
			pr.SetURL(target)
			pr.SetXForwarded()
		},
		// Транспорт свой ради ОДНОГО таймаута: застройка стоит соседним
		// процессом, и «не отвечает» обязано называться сразу, а не через
		// полминуты умолчания.
		Transport: транспорт(),
		// Застройка не ответила — это отказ МЕСТА, и он называет причину и
		// выход (`2.3`). Молчаливый 502 от прокси читается как «мир сломался»,
		// хотя не поднята одна вещь внутри одного места.
		ErrorHandler: func(w http.ResponseWriter, _ *http.Request, err error) {
			писать(w, отказать(http.StatusBadGateway, "build-unreachable",
				"застройка места по адресу %s не отвечает: %v. Место при этом СТОИТ и в поле остаётся — пустое место законно. "+
					"Выход: подними застройку внутри места (развернуть — это доставить И выполнить цепочку, делает это юзер) "+
					"либо убери адрес (%s / %s), и маршрут снова ответит присутствием сторожа",
				addr, err, AddrVar, AddrFlag))
		},
	}
	return s
}

// провериться — годится ли заявленный адрес в маршрут. Проверяется ФОРМА и
// петля, а не то, что там действительно застройка: чем она является, место
// знать не может и притворяться не будет (та же граница, что у пробы адреса на
// двери).
func провериться(addr, listen string) *отказ {
	for _, схема := range []string{"http://", "https://", "//"} {
		if strings.HasPrefix(addr, схема) {
			return отказать(http.StatusServiceUnavailable, "build-addr-invalid",
				"адрес застройки %q задан со схемой, а нужен «хост:порт» без неё: до застройки место ходит по HTTP внутри себя. "+
					"Выход: убери %q из %s (например 127.0.0.1:3000)", addr, схема, AddrVar)
		}
	}
	хост, порт, err := net.SplitHostPort(addr)
	if err != nil {
		return отказать(http.StatusServiceUnavailable, "build-addr-invalid",
			"адрес застройки %q не разбирается как «хост:порт» (%v): без порта до застройки не дойти — она стоит внутри места отдельным процессом. "+
				"Выход: задай %s в форме «хост:порт», например 127.0.0.1:3000 (%s)", addr, err, AddrVar, AddrFlag)
	}
	н, err := strconv.Atoi(порт)
	if err != nil || н < 1 || н > 65535 {
		return отказать(http.StatusServiceUnavailable, "build-addr-invalid",
			"в адресе застройки %q порт %q не число от 1 до 65535: %v. Выход: задай %s в форме «хост:порт», например 127.0.0.1:3000",
			addr, порт, err, AddrVar)
	}
	if сторожСам(хост, порт, listen) {
		// Петля: сторож ходил бы сам к себе, и каждый запрос множился бы до
		// исчерпания соединений. Ловим ДО первого запроса, а не в момент, когда
		// место уже легло.
		return отказать(http.StatusServiceUnavailable, "build-addr-is-guard",
			"адрес застройки %q — это адрес самого сторожа (он слушает %q): маршрут замкнулся бы на себя, и место легло бы на первом же запросе. "+
				"Выход: застройка стоит внутри места СВОИМ процессом на своём порту — задай %s её портом (например 127.0.0.1:3000), а не портом сторожа",
			addr, listen, AddrVar)
	}
	return nil
}

// сторожСам — заявленный адрес указывает на самого сторожа? Мерка честная и
// узкая: совпал порт, а хост либо тот же, либо сторож слушает все интерфейсы.
// Чужой контейнер с тем же портом под неё не попадает — у него другой хост.
func сторожСам(хост, порт, listen string) bool {
	свойХост, свойПорт, err := net.SplitHostPort(strings.TrimSpace(listen))
	if err != nil || свойПорт != порт {
		return false
	}
	// Пустой хост в «:8080» — это все интерфейсы: на них попадает и петля, и
	// собственное имя места.
	if свойХост == "" || свойХост == "0.0.0.0" || свойХост == "::" {
		return true
	}
	return свойХост == хост
}

// транспорт — умолчание стандартной библиотеки с одним изменённым сроком:
// соединение до соседнего процесса либо есть сразу, либо его нет.
func транспорт() *http.Transport {
	t := http.DefaultTransport.(*http.Transport).Clone()
	t.DialContext = (&net.Dialer{Timeout: DialTimeout}).DialContext
	return t
}

// Addr — куда ведёт маршрут места. Пусто, если застройка не заявлена.
func (s *Stands) Addr() string {
	if s == nil {
		return ""
	}
	return s.addr
}

// Изъян — почему маршрута к заявленной застройке не выходит. nil значит, что с
// адресом всё в порядке; отвечает ли по нему кто-нибудь — вопрос запроса, а не
// настройки, и он выясняется на маршруте.
func (s *Stands) Изъян() error {
	if s == nil || s.изъян == nil {
		return nil
	}
	return fmt.Errorf("%s: %s", s.изъян.Code, s.изъян.Detail)
}

// ServeHTTP уводит запрос в застройку — целиком, всеми методами: по маршруту
// места ею ПОЛЬЗУЮТСЯ там, где она стоит (`1.6`), а не смотрят на её снимок.
func (s *Stands) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	if s.изъян != nil {
		писать(w, s.изъян)
		return
	}
	s.rp.ServeHTTP(w, r)
}

// писать — отказ в том же виде, в каком его пишут остальные ручки сторожа.
func писать(w http.ResponseWriter, о *отказ) { writeJSON(w, о.Status, о) }

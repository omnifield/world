#!/usr/bin/env node
// index.mjs — генератор INDEX.md по шапкам выписок.
//
// Указатель никто не ведёт руками: ведомый руками он расходится с фондом на
// первой же выписке, и расхождение не видно, пока не станет дорогим. Прошлый
// заход вёл такую таблицу вручную — она разошлась с фактом на 63 записи.
//
//   node tools/index.mjs [путь-к-папке-фонда]

import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join, dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(process.argv[2] || join(dirname(fileURLToPath(import.meta.url)), '..'))
const ГОД = 365 * 24 * 60 * 60 * 1000

function шапка(текст) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---/.exec(текст)
  if (!m) return null
  const поля = {}
  let текущий = null
  for (const строка of m[1].split(/\r?\n/)) {
    const элемент = /^\s*-\s+(.*)$/.exec(строка)
    if (элемент && текущий) { поля[текущий] = [].concat(поля[текущий] || [], значение(элемент[1])); continue }
    const пара = /^([^:#\s][^:]*?):(.*)$/.exec(строка)
    if (!пара) continue
    const ключ = пара[1].trim(), сырое = пара[2].trim()
    текущий = ключ
    if (сырое === '') { поля[ключ] = []; continue }
    поля[ключ] = значение(сырое)
    текущий = null
  }
  return поля
}

function значение(сырое) {
  const s = сырое.trim()
  if (/^\[.*\]$/.test(s)) return s.slice(1, -1).split(',').map(x => чисто(x)).filter(Boolean)
  return чисто(s)
}
const чисто = s => s.trim().replace(/^["'](.*)["']$/s, '$1').trim()
const экран = s => String(s ?? '').replace(/\|/g, '\\|')

const каталог = join(ROOT, 'sources')
if (!existsSync(каталог)) {
  console.error(`✗ нет папки sources/ в ${ROOT}`)
  process.exit(1)
}

// README.md — пояснение к папке, `_*.md` — бланки. Ни то, ни другое не выписка.
const записи = readdirSync(каталог)
  .filter(f => f.endsWith('.md') && !f.startsWith('_') && f !== 'README.md')
  .sort()
  .map(f => ({ файл: f, поля: шапка(readFileSync(join(каталог, f), 'utf8')) || {} }))

const сегодня = new Date()

// Сроков годности ДВА, и следить надо за обоими: жив ли документ (`статус_сверен`)
// и совпадает ли наша цитата с его действующим текстом (`сверено`). Второй тише
// первого: запись с верным статусом и несверенной цитатой выглядит здоровой.
const протух = (з, поле) => {
  const d = з.поля[поле] && new Date(з.поля[поле] + 'T00:00:00Z')
  return d && !Number.isNaN(d.getTime()) && сегодня.getTime() - d.getTime() > ГОД
}
const требуетВнимания = з => з.поля.статус !== 'действует'
  || протух(з, 'статус_сверен') || протух(з, 'сверено')
  || з.поля.цитаты === 'вторичный' || з.поля.цитаты === 'нет'

// темы → выписки
const темы = new Map()
for (const з of записи) {
  for (const т of [].concat(з.поля.темы || ['без темы'])) {
    темы.set(т, [...(темы.get(т) || []), з])
  }
}

const строки = []
строки.push('# Указатель фонда')
строки.push('')
строки.push('> **СГЕНЕРИРОВАНО** `tools/index.mjs` по шапкам выписок. Руками не править — правка уедет при следующей генерации. Менять надо шапку выписки.')
строки.push('')
строки.push(`Выписок: **${записи.length}** · тем: **${темы.size}** · собрано на ${сегодня.toISOString().slice(0, 10)}.`)
строки.push('')

const внимание = записи.filter(требуетВнимания)
if (внимание.length) {
  строки.push('## Требует внимания')
  строки.push('')
  строки.push('| источник | что не так | файл |')
  строки.push('|---|---|---|')
  for (const з of внимание) {
    const причины = []
    if (з.поля.статус === 'заменён') причины.push(`заменён${з.поля.замещён ? ` → ${з.поля.замещён}` : ''}`)
    if (з.поля.статус === 'не установлен') причины.push('статус не установлен — это не «устарело», это «не проверено»')
    if (протух(з, 'статус_сверен')) причины.push(`статус сверен ${з.поля.статус_сверен}, больше года назад`)
    if (протух(з, 'сверено')) причины.push(`цитаты сверены ${з.поля.сверено}, больше года назад`)
    if (з.поля.цитаты === 'вторичный') причины.push('цитаты вторичные')
    if (з.поля.цитаты === 'нет') причины.push('дословных цитат нет')
    строки.push(`| ${экран(з.поля.источник)} | ${экран(причины.join(' · '))} | \`${з.файл}\` |`)
  }
  строки.push('')
}

строки.push('## По темам')
строки.push('')
for (const тема of [...темы.keys()].sort()) {
  строки.push(`### ${тема}`)
  строки.push('')
  строки.push('| источник | редакция | статус | сверен | цитаты | файл |')
  строки.push('|---|---|---|---|---|---|')
  for (const з of темы.get(тема)) {
    строки.push([
      экран(з.поля.источник), экран(з.поля.редакция), экран(з.поля.статус),
      экран(з.поля.статус_сверен), экран(з.поля.цитаты), `\`${з.файл}\``,
    ].map(c => ` ${c} `).join('|').replace(/^/, '|') + '|')
  }
  строки.push('')
}

строки.push('---')
строки.push('')
строки.push('**Зелёный указатель не означает верных цитат.** Здесь видно, жив ли документ и когда это проверяли; совпадает ли наша формулировка с действующим текстом — отдельная работа, и машина её не делает.')
строки.push('')

writeFileSync(join(ROOT, 'INDEX.md'), строки.join('\n'), 'utf8')
console.log(`INDEX.md перегенерирован: ${записи.length} выписок, ${темы.size} тем, ${внимание.length} требуют внимания.`)

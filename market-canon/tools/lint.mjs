#!/usr/bin/env node
// lint.mjs — гейт формы фонда рыночных канонов.
//
// Проверяет ровно то, что описано в template/FORM.md, и ничего сверх. Форма без машины
// держится на памяти собирающего; собирающих много, память у всех разная.
//
// Зависимостей нет намеренно: папка копируется в любой продукт как есть, и
// тянуть за собой установку пакетов она не должна.
//
//   node tools/lint.mjs [путь-к-папке-фонда]
//
// Выход: 0 — форма соблюдена, 1 — есть красное. Жёлтое не роняет.

import { readdirSync, readFileSync, existsSync, statSync } from 'node:fs'
import { join, basename, dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(process.argv[2] || join(dirname(fileURLToPath(import.meta.url)), '..'))

// ── что считается формой ─────────────────────────────────────────────────────

const ПОЛЯ_ОБЯЗАТЕЛЬНЫЕ = ['источник', 'издатель', 'редакция', 'статус', 'статус_сверен', 'цитаты', 'темы', 'адрес', 'сверено']
const СТАТУСЫ = ['действует', 'заменён', 'не установлен']
const ЦИТАТЫ = ['первичный', 'предпросмотр', 'вторичный', 'нет']
const ДАТЫ = ['статус_сверен', 'сверено']

const РАЗДЕЛЫ_ОБЯЗАТЕЛЬНЫЕ = [
  'Какой вопрос закрывает',
  'Как устроено',
  'Дословно',
  'Что предотвращает',
  'Чего НЕ покрывает',
]

// Наш вывод в выписке. Правило «только чужое» — первое и самое нарушаемое.
const НАШ_ВЫВОД = [
  { re: /^#{1,6}\s*К чему у нас/im, чем: 'раздел «К чему у нас относится»' },
  { re: /\bзначит,? нам\b/i, чем: 'оборот «значит нам»' },
  { re: /\bнам (?:надо|нужно|следует)\b/i, чем: 'оборот «нам надо»' },
  { re: /отсюда следует,? что (?:нам|нужно|надо)/i, чем: 'оборот «отсюда следует, что нужно»' },
  { re: /\bу нас это (?:значит|означает)\b/i, чем: 'оборот «у нас это значит»' },
]

// Ссылки на наши узлы. Список продуктовый — правь под свои сервисы при переносе.
const НАШИ_УЗЛЫ = [
  { re: /\b(?:kb|tasker|knowledger):[A-ZА-Я][A-ZА-Я0-9]*-\d+/, чем: 'ключ нашего узла (kb:/tasker:)' },
  { re: /\[→\s*\d+\]/, чем: 'номер узла в квадратных скобках ([→NN])' },
]

const ГОД = 365 * 24 * 60 * 60 * 1000

// ── разбор ───────────────────────────────────────────────────────────────────

/** Минимальный YAML: `ключ: значение`, `ключ: [a, b]`, `ключ:` + строки `- item`. */
function шапка(текст) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/.exec(текст)
  if (!m) return null
  const поля = {}, строки = {}
  const тело = m[1].split(/\r?\n/)
  let текущий = null
  тело.forEach((строка, i) => {
    const номер = i + 2 // +1 за `---`, +1 за счёт с единицы
    const элемент = /^\s*-\s+(.*)$/.exec(строка)
    if (элемент && текущий) {
      поля[текущий] = [].concat(поля[текущий] || [], разобратьЗначение(элемент[1]))
      return
    }
    const пара = /^([^:#\s][^:]*?):(.*)$/.exec(строка)
    if (!пара) return
    const ключ = пара[1].trim()
    const сырое = пара[2].trim()
    строки[ключ] = номер
    текущий = ключ
    if (сырое === '') { поля[ключ] = []; return }
    поля[ключ] = разобратьЗначение(сырое)
    текущий = null
  })
  return { поля, строки, конец: текст.slice(0, m[0].length).split(/\r?\n/).length }
}

function разобратьЗначение(сырое) {
  const s = сырое.trim()
  if (/^\[.*\]$/.test(s)) {
    return s.slice(1, -1).split(',').map(x => снятьКавычки(x.trim())).filter(Boolean)
  }
  return снятьКавычки(s)
}

const снятьКавычки = s => s.replace(/^["'](.*)["']$/s, '$1').trim()

/** Разделы тела: заголовок → { строка, содержимое }. */
function разделы(текст, смещение) {
  const строки = текст.split(/\r?\n/)
  const найдено = []
  строки.forEach((строка, i) => {
    const m = /^##\s+(.+?)\s*$/.exec(строка)
    if (m) найдено.push({ имя: m[1], строка: i + смещение, начало: i + 1 })
  })
  return найдено.map((р, i) => ({
    ...р,
    содержимое: строки.slice(р.начало, i + 1 < найдено.length ? найдено[i + 1].начало - 1 : строки.length).join('\n').trim(),
  }))
}

const номерСтроки = (текст, индекс) => текст.slice(0, индекс).split(/\r?\n/).length

// ── проверка одного файла ────────────────────────────────────────────────────

function проверитьВыписку(путь, текст, общее) {
  const красное = [], жёлтое = []
  const имя = basename(путь)
  const бей = (строка, что) => красное.push({ строка, что })
  const жёлт = (строка, что) => жёлтое.push({ строка, что })

  // имя файла
  if (!/^[a-z0-9][a-z0-9.\-]*\.md$/.test(имя)) {
    бей(1, `имя файла «${имя}» — только строчная латиница, цифры, точка и дефис`)
  }
  if (/^\d+[-_]/.test(имя)) {
    бей(1, `имя файла начинается с порядкового номера — единица хранения это источник, а не заход сбора`)
  }

  const ш = шапка(текст)
  if (!ш) {
    бей(1, 'нет YAML-шапки — файл не является выпиской (форма: template/FORM.md)')
    return { красное, жёлтое }
  }
  const { поля, строки, конец } = ш

  // обязательные поля
  for (const поле of ПОЛЯ_ОБЯЗАТЕЛЬНЫЕ) {
    const v = поля[поле]
    if (v === undefined || v === '' || (Array.isArray(v) && v.length === 0)) {
      бей(строки[поле] || 1, `нет обязательного поля шапки «${поле}»`)
    }
  }

  // перечисления
  if (поля.статус && !СТАТУСЫ.includes(поля.статус)) {
    бей(строки.статус, `статус «${поля.статус}» — допустимы: ${СТАТУСЫ.join(' · ')}`)
  }
  if (поля.цитаты && !ЦИТАТЫ.includes(поля.цитаты)) {
    бей(строки.цитаты, `цитаты «${поля.цитаты}» — допустимы: ${ЦИТАТЫ.join(' · ')}`)
  }

  // условные поля
  if (поля.статус === 'заменён' && !поля.замещён) {
    бей(строки.статус, 'статус «заменён» без поля «замещён» — чем именно и когда')
  }
  if (поля.статус === 'не установлен' && !поля.причина_неустановления) {
    бей(строки.статус, 'статус «не установлен» без поля «причина_неустановления» — «не проверено» это не «устарело»')
  }

  // даты
  const сегодня = new Date()
  for (const поле of ДАТЫ) {
    const v = поля[поле]
    if (!v) continue
    if (!/^\d{4}-\d{2}-\d{2}$/.test(v)) { бей(строки[поле], `«${поле}»: дата в форме ГГГГ-ММ-ДД, а не «${v}»`); continue }
    const д = new Date(v + 'T00:00:00Z')
    if (Number.isNaN(д.getTime())) { бей(строки[поле], `«${поле}»: несуществующая дата «${v}»`); continue }
    if (д.getTime() > сегодня.getTime() + 24 * 60 * 60 * 1000) бей(строки[поле], `«${поле}»: дата в будущем «${v}»`)
    else if (сегодня.getTime() - д.getTime() > ГОД) {
      жёлт(строки[поле], `«${поле}» сверено больше года назад (${v}) — у выписки два срока годности`)
    }
  }

  // уникальность источника
  if (поля.источник) {
    const прежний = общее.источники.get(поля.источник)
    if (прежний) бей(строки.источник, `источник «${поля.источник}» уже выписан в ${прежний} — одна норма, один файл`)
    else общее.источники.set(поля.источник, имя)
  }

  // темы
  for (const тема of [].concat(поля.темы || [])) {
    общее.темы.set(тема, (общее.темы.get(тема) || 0) + 1)
    общее.темаГде.set(тема, [...(общее.темаГде.get(тема) || []), имя])
  }

  const тело = текст.slice(текст.indexOf('---', 3) + 3)
  const рр = разделы(тело, конец)
  const поИмени = new Map(рр.map(р => [р.имя.trim(), р]))

  // H1 и лид
  if (!/^#\s+\S/m.test(тело)) бей(конец, 'нет заголовка H1 — что именно этот источник решает')
  const лид = /^#\s+.+\r?\n+(.*)$/m.exec(тело)
  if (!лид || !/^\*\*.+/.test(лид[1].trim())) {
    жёлт(конец + 1, 'после заголовка нет жирного лида — прочитал абзац, знаешь суть')
  }

  // обязательные разделы
  for (const имяР of РАЗДЕЛЫ_ОБЯЗАТЕЛЬНЫЕ) {
    const р = поИмени.get(имяР)
    if (!р) { бей(конец, `нет обязательного раздела «## ${имяР}»`); continue }
    if (!р.содержимое) бей(р.строка, `раздел «${имяР}» пустой`)
  }

  const непокрыто = поИмени.get('Чего НЕ покрывает')
  if (непокрыто && /^(—|-|нет|н\/д|tbd|—\.)$/i.test(непокрыто.содержимое.trim())) {
    бей(непокрыто.строка, 'раздел «Чего НЕ покрывает» — отписка. Это самое ценное поле выписки: ни один стандарт не пишет, чего в нём нет')
  }

  // цитаты
  const дословно = поИмени.get('Дословно')
  if (дословно) {
    const естьЦитата = /^>\s*\S/m.test(дословно.содержимое)
    if (поля.цитаты !== 'нет' && !естьЦитата) {
      бей(дословно.строка, `цитаты объявлены как «${поля.цитаты}», но в разделе «Дословно» нет ни одной цитаты (строка с «>»)`)
    }
    if (поля.цитаты === 'нет' && естьЦитата) {
      бей(дословно.строка, 'цитаты объявлены как «нет», а цитаты в разделе есть — поправь шапку')
    }
    if (естьЦитата && !/\(\s*\d+(\.\d+)*[^)]*\)|§|\bразд(ел|\.)|\bп\.\s*\d/.test(дословно.содержимое)) {
      жёлт(дословно.строка, 'у цитат не видно номера раздела или пункта — несущее цитируется с адресом внутри документа')
    }
    if (поля.цитаты === 'вторичный' && !дословно.содержимое.includes('[вторичный]')) {
      бей(дословно.строка, 'цитаты вторичные, но пометки [вторичный] у цитат нет — оговорка на файл не годится, метится каждая')
    }
  }
  if (поля.цитаты && поля.цитаты !== 'первичный' && !поИмени.has('Оговорка об источнике')) {
    бей(конец, `цитаты «${поля.цитаты}» требуют раздела «## Оговорка об источнике» — что из открытого фрагмента, а что из пересказа`)
  }

  // только чужое
  for (const { re, чем } of НАШ_ВЫВОД) {
    const m = re.exec(тело)
    if (m) бей(номерСтроки(тело, m.index) + конец - 1, `в выписке наш вывод: ${чем}. Выписка отвечает, что решил рынок, и молчит о том, что из этого следует нам`)
  }
  for (const { re, чем } of НАШИ_УЗЛЫ) {
    const m = re.exec(тело)
    if (m) бей(номерСтроки(тело, m.index) + конец - 1, `в выписке ${чем} — «${m[0]}». Связь держится со стороны решения, а не со стороны выписки: номера узлов однажды уже соврали`)
  }

  return { красное, жёлтое }
}

// ── проход по папке ──────────────────────────────────────────────────────────

// README.md — пояснение к папке, `_*.md` — бланки. Ни то, ни другое не выписка.
const мдФайлы = (папка) => existsSync(папка)
  ? readdirSync(папка).filter(f => f.endsWith('.md') && !f.startsWith('_') && f !== 'README.md').sort()
  : null

/**
 * Словарь тем: строки списка `- тема` ПОСЛЕ заголовка «## Темы».
 *
 * Читается только этот раздел, и внутри него пропускается содержимое блоков
 * кода. Оба ограничения — от одной и той же мины: пример разметки выглядит
 * ровно как запись словаря, и словарь включается сам собой на образцах. Первый
 * раз это поймалось на примерах в пояснении сверху; страховка от кода нужна
 * потому, что «## Темы последний раздел» — соглашение, а не свойство файла.
 *
 * Нет файла, нет раздела или нет ни одной темы → null (словарь выключен).
 */
function прочитатьСловарь(путь) {
  if (!existsSync(путь)) return null
  const строки = readFileSync(путь, 'utf8').split(/\r?\n/)
  const начало = строки.findIndex(с => /^##\s+Темы\s*$/.test(с))
  if (начало < 0) return null
  const темы = new Set()
  let вКоде = false
  for (const строка of строки.slice(начало + 1)) {
    if (/^\s*(```|~~~)/.test(строка)) { вКоде = !вКоде; continue }
    if (вКоде) continue
    if (/^#{1,6}\s/.test(строка)) break
    const m = /^\s*-\s+`?([^`\s][^`—]*?)`?\s*(?:—.*)?$/.exec(строка)
    if (m) темы.add(m[1].trim())
  }
  return темы.size ? темы : null
}

function main() {
  const общее = { источники: new Map(), темы: new Map(), темаГде: new Map() }
  let красных = 0, жёлтых = 0, выписок = 0
  const вывод = []

  const каталогИсточников = join(ROOT, 'sources')
  const файлы = мдФайлы(каталогИсточников)
  if (файлы === null) {
    console.error(`✗ нет папки sources/ в ${ROOT} — это не фонд канонов`)
    process.exit(1)
  }

  for (const f of файлы) {
    const путь = join(каталогИсточников, f)
    if (!statSync(путь).isFile()) continue
    выписок++
    const { красное, жёлтое } = проверитьВыписку(путь, readFileSync(путь, 'utf8'), общее)
    красных += красное.length
    жёлтых += жёлтое.length
    if (красное.length || жёлтое.length) {
      вывод.push(`\nsources/${f}`)
      for (const { строка, что } of красное) вывод.push(`  ✗ :${строка}  ${что}`)
      for (const { строка, что } of жёлтое) вывод.push(`  ⚠ :${строка}  ${что}`)
    }
  }

  // сведения — не цитаты, и происхождение обязано быть названо
  const сведения = мдФайлы(join(ROOT, 'digests')) || []
  for (const f of сведения) {
    const текст = readFileSync(join(ROOT, 'digests', f), 'utf8')
    if (!/оговорка о происхождении|## Происхождение/i.test(текст)) {
      красных++
      вывод.push(`\ndigests/${f}`)
      вывод.push('  ✗ :1  сведение без оговорки о происхождении — читатель обязан видеть, что это не цитаты, а сборка')
    }
  }

  // Словарь тем — необязательный и включается заведением template/topics.md.
  // Заведён — тема вне словаря красная: свободные слова расходятся молча
  // («отгрузка» и «поставка» станут двумя темами, и указатель развалится надвое).
  // Не заведён — только жёлтое на одиночек.
  const словарь = прочитатьСловарь(join(ROOT, 'template', 'topics.md'))
  for (const [тема, сколько] of общее.темы) {
    const где = общее.темаГде.get(тема).join(', ')
    if (словарь && !словарь.has(тема)) {
      красных++
      вывод.push(`\nтема «${тема}»`)
      вывод.push(`  ✗ нет в словаре template/topics.md (${где}) — заведи тему в словаре или возьми существующую`)
    } else if (!словарь && сколько === 1 && общее.темы.size > 3) {
      жёлтых++
      вывод.push(`\nтема «${тема}»`)
      вывод.push(`  ⚠ встречается один раз (${где}) — опечатка или новая тема?`)
    }
  }

  console.log(вывод.join('\n') || '')
  console.log(`\nвыписок: ${выписок} · сведений: ${сведения.length} · ✗ ${красных} · ⚠ ${жёлтых}`)

  if (выписок === 0) console.log('\nsources/ пуст — форма проверена не на чем. Это не ошибка, это пустой фонд.')
  if (красных) {
    console.log('\nКрасное — не заливаем и не сдаём. Форма целиком: template/FORM.md')
    process.exit(1)
  }
  console.log('Форма соблюдена. Совпадают ли цитаты с действующим текстом — гейт не знает и знать не может.')
}

main()

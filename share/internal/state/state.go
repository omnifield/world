// Пакет state — файл состояния юзера: отдать целиком и принять целиком.
//
// ┌─────────────────────────────────────────────────────────────────────────────────────┐
// │ ГЛАВНОЕ ПРАВИЛО ЭТОГО ПАКЕТА: МЫ НЕ СМОТРИМ ВНУТРЬ (`WORLD2` 3.4).                   │
// │                                                                                      │
// │ Ни разбора JSON, ни проверки разделов, ни версии формата, ни «а имя территории       │
// │ точно не повторяется». За тем, что внутри, следит тот, кто пишет, — контроллер.       │
// │ Раздача знает про файл ровно две вещи: сколько в нём байт и целиком ли он лёг.        │
// │                                                                                      │
// │ Разбор здесь был бы не строгостью, а второй правдой о формате: наша проверка         │
// │ разъехалась бы с канонической на первой же правке `3.4`, и юзер получал бы отказ на  │
// │ законном файле — от вилки, которая вообще не вправе иметь мнение о его содержимом.   │
// └─────────────────────────────────────────────────────────────────────────────────────┘
//
// Пустые списки внутри законны (`WORLD2` 3.4, «Почему так», п. 5): свежесозданный скоуп —
// это личность и пустота. Отсюда же и то, чего здесь НЕ проверяется: «слишком мало полей»
// не бывает.
package state

import (
	"errors"
	"fmt"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"sync"

	"github.com/omnifield/world/share/internal/refusal"
)

// DefaultLimit — сколько байт мы готовы принять за одну запись. Это НЕ мнение о
// содержимом (внутрь мы не смотрим), а граница памяти и диска: без неё одна оборванная
// запись затягивается на весь том, и раздача умирает вместе с личностью, которую держит.
//
// Мегабайт — с запасом на порядки: связка ключей, десяток территорий и список полей это
// килобайты. Не хватило — значение поднимается ключом, а не правкой кода.
const DefaultLimit int64 = 1 << 20

// Store — состояние по адресу файла. Своего кэша нет намеренно: каждое чтение идёт до
// диска. Кэш завёл бы вторую истину о личности юзера, а вторая истина о личности — это
// два разных юзера, обнаруживаемых по факту.
type Store struct {
	Path  string
	Limit int64

	// mu держит ЗАПИСЬ, а не чтение. Чтение обходится без него: смена файла делается
	// переименованием, а открытый читатель видит старый файл целиком до конца — рваного
	// состояния он не увидит никогда. Двух одновременных записей мьютекс не смешивает:
	// иначе две времянки уехали бы в одно имя.
	mu sync.Mutex
}

func New(path string, limit int64) *Store {
	if limit <= 0 {
		limit = DefaultLimit
	}
	return &Store{Path: path, Limit: limit}
}

// Read отдаёт файл целиком. Файла нет — это НЕ поломка и не пустой ответ: раздача поднята,
// состояние в неё ещё не записали. Различать эти два случая обязан клиент, поэтому и
// приходят они разными кодами, а не одним «пусто».
func (s *Store) Read() ([]byte, *refusal.Refusal) {
	data, err := os.ReadFile(s.Path)
	switch {
	case err == nil:
		return data, nil
	case errors.Is(err, os.ErrNotExist):
		return nil, refusal.New(http.StatusNotFound, "no-state",
			"раздача поднята, а состояния по этому адресу ещё нет — файл не записывали",
			"запиши его целиком: PUT по этому же адресу",
			"если состояние должно было тут лежать — проверь, тот ли том отдан раздаче")
	default:
		return nil, refusal.New(http.StatusInternalServerError, "state-unreadable",
			fmt.Sprintf("состояние по адресу %s не прочиталось: %v", s.Path, err),
			"проверь права на файл и том, отданный раздаче",
			"журнал раздачи называет тот же путь — сверь его с тем, что смонтировано")
	}
}

// Write принимает файл целиком и кладёт его на место одним движением.
//
// Цена названа в каноне вслух и здесь не лечится: пишущий затирает предыдущего целиком
// (`WORLD2` 3.4). Ни слияния, ни «а вдруг там новее» — раздача принимает то, что ей дали.
func (s *Store) Write(r io.Reader) (int64, *refusal.Refusal) {
	// Читаем на один байт больше предела: иначе «ровно предел» и «предел с хвостом»
	// неразличимы, и человек получал бы отказ на файле, который влезает.
	data, err := io.ReadAll(io.LimitReader(r, s.Limit+1))
	if err != nil {
		return 0, refusal.New(http.StatusBadRequest, "state-not-received",
			fmt.Sprintf("состояние не доехало целиком: %v", err),
			"повтори запись — старое состояние не тронуто",
			"если рвётся каждый раз — смотри связь до раздачи, файл на диске не менялся")
	}
	if int64(len(data)) > s.Limit {
		return 0, refusal.New(http.StatusRequestEntityTooLarge, "state-too-big",
			fmt.Sprintf("состояние больше предела в %d байт, и раздача его не берёт", s.Limit),
			fmt.Sprintf("подними предел ключом: SHARE_LIMIT=%d", s.Limit*4),
			"или посмотри, не попало ли в файл лишнее: в скоупе лежат ссылки и ключи, а не потроха вещей")
	}
	// Ноль байт — не состояние. Внутрь мы не смотрим, но пустой файл это не «личность без
	// полей», а стёртая личность: приняв его молча, раздача отдала бы юзеру пустоту вместо
	// отказа — и он узнал бы об этом при следующем входе, когда чинить уже нечего.
	if len(data) == 0 {
		return 0, refusal.New(http.StatusBadRequest, "empty-state",
			"пришло ноль байт — это стёртое состояние, а не состояние юзера",
			"пришли файл целиком телом запроса",
			"пустые списки внутри законны, пустой ФАЙЛ — нет: свежий скоуп это личность и пустые разделы")
	}

	s.mu.Lock()
	defer s.mu.Unlock()

	dir := filepath.Dir(s.Path)
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return 0, refusal.New(http.StatusInternalServerError, "state-unwritable",
			fmt.Sprintf("каталог состояния %s не завёлся: %v", dir, err),
			"проверь, что том смонтирован и права на нём есть")
	}

	// Времянка рядом и переименование: оборванная запись не должна оставлять покалеченную
	// личность. Личность у юзера одна, второй попытки прочитать её «как было» у него нет.
	// Времянка заводится в ТОМ ЖЕ каталоге — переименование через границу файловых систем
	// перестаёт быть одним движением и превращается в копирование.
	tmp, err := os.CreateTemp(dir, "."+filepath.Base(s.Path)+".*")
	if err != nil {
		return 0, refusal.New(http.StatusInternalServerError, "state-unwritable",
			fmt.Sprintf("времянка рядом с %s не завелась: %v", s.Path, err),
			"проверь права на каталог и место на томе")
	}
	// Уборка на любом раннем выходе. Прошло всё — удалять уже нечего, и промах Remove
	// здесь законен.
	defer func() { _ = os.Remove(tmp.Name()) }()

	if _, err := tmp.Write(data); err != nil {
		_ = tmp.Close()
		return 0, refusal.New(http.StatusInternalServerError, "state-unwritable",
			fmt.Sprintf("состояние не записалось: %v", err),
			"проверь место на томе, отданном раздаче")
	}
	// Sync до переименования — иначе имя встанет на место раньше содержимого, и внезапная
	// потеря питания оставит юзеру файл нужного имени и нулевой длины.
	if err := tmp.Sync(); err != nil {
		_ = tmp.Close()
		return 0, refusal.New(http.StatusInternalServerError, "state-unwritable",
			fmt.Sprintf("состояние не легло на диск: %v", err),
			"проверь том, отданный раздаче: место и права")
	}
	if err := tmp.Close(); err != nil {
		return 0, refusal.New(http.StatusInternalServerError, "state-unwritable",
			fmt.Sprintf("времянка не закрылась: %v", err),
			"проверь том, отданный раздаче")
	}
	// Права на файл личности: только тому, кто его раздаёт. `CreateTemp` заводит файл с
	// 0600, но umask и чужая файловая система на это не влияют — ставим явно.
	if err := os.Chmod(tmp.Name(), 0o600); err != nil {
		return 0, refusal.New(http.StatusInternalServerError, "state-unwritable",
			fmt.Sprintf("права на состояние не встали: %v", err),
			"проверь том, отданный раздаче")
	}
	if err := os.Rename(tmp.Name(), s.Path); err != nil {
		return 0, refusal.New(http.StatusInternalServerError, "state-unwritable",
			fmt.Sprintf("состояние не встало на место: %v", err),
			"проверь права на каталог, отданный раздаче")
	}
	// Каталог тоже синхронизируем: без этого переименование может не пережить потерю
	// питания, и юзер получит прошлое состояние при живом новом файле.
	syncDir(dir)
	return int64(len(data)), nil
}

// syncDir — «имя точно на месте». Промах здесь не отказ: файл уже переименован и юзеру
// отдан правильный ответ; не пережить эту секунду может только внезапно погасшая машина,
// и говорить ей «нет» задним числом нечем.
func syncDir(dir string) {
	d, err := os.Open(dir)
	if err != nil {
		return
	}
	defer func() { _ = d.Close() }()
	_ = d.Sync()
}

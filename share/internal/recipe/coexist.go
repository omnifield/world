// Сторож сосуществования — стережёт, что две раздачи на одной машине не столкнутся.
//
// ┌─────────────────────────────────────────────────────────────────────────────────────┐
// │ ПОЧЕМУ ОН ОТДЕЛЬНЫЙ ОТ `Check`. Тот стережёт ФОРМУ ЗАПИСИ: прочитает ли файл YAML.    │
// │ Этот стережёт СВОЙСТВО: разведёт ли рецепт две раздачи, стоящие рядом. Файл может     │
// │ быть безупречен по форме и при этом сажать вторую раздачу поверх первой — читается,   │
// │ поднимается, и личность одного юзера ложится в том другого.                          │
// │                                                                                      │
// │ Смешать их в одну функцию значило бы получить сторожа, который краснеет по двум       │
// │ разным причинам одинаково, и человека, который не знает, что именно он сломал.        │
// └─────────────────────────────────────────────────────────────────────────────────────┘
//
// ЧТО ЗДЕСЬ СТЕРЕЖЁТСЯ, ОДНОЙ СТРОКОЙ: всё, чем две раздачи на одной машине различаются,
// приходит СНАРУЖИ — именем (`SHARE_NAME`) и портом (`SHARE_PORT`), а не умолчанием
// внутри файла. Канон — `WORLD2` 3.4, «Копий нет — есть адреса»: машина не единица
// личности, единица — адрес, и две раздачи на одной машине это два скоупа, оба законных.
//
// Зашитое имя ловится ЗДЕСЬ, без докера, и потому всегда: живая проба «поднять две рядом»
// требует докера, а докера на машине разработчика зоны может не быть — ровно та дыра,
// из-за которой файл запуска однажды не читал ни один сторож (`WORLD2-140`).
//
// ИМЕНА ЗНАЧЕНИЙ ЗДЕСЬ ЗАКРЕПЛЕНЫ НАРОЧНО (`SHARE_NAME`, `SHARE_PORT`). Это не украшение
// и не вкус: ими рецепт разговаривает с тем, кто раздачу поднимает, — контроллер называет
// именно их. Переименуй значение молча — рецепт останется зелёным по форме и перестанет
// принимать то, что ему передают.
package recipe

import "strings"

const (
	varName = "${SHARE_NAME"
	varPort = "${SHARE_PORT"
)

// Coexist разбирает файл запуска и возвращает всё, из-за чего вторая раздача встанет
// поверх первой. Пустой ответ — «этим рецептом две раздачи на одной машине разводятся».
//
// Правил ровно четыре, и каждое стоит на своём столкновении:
//
//  1. имя проекта названо и приходит подстановкой — иначе компоуз возьмёт имя папки,
//     и вторая раздача окажется в том же проекте, что первая;
//  2. имя контейнера, если названо поимённо, — подстановкой (докер их не повторяет);
//  3. имя тома, если названо поимённо, — подстановкой (иначе одна личность поверх другой);
//  4. публикация названа, и хостовый порт — подстановкой: порт раздачи это адрес, который
//     юзер уже назвал, а не наше умолчание.
//
// Больше не заводим по той же причине, что и в `Check`: сторож, краснеющий на законном
// файле, учит не смотреть на его красноту.
func Coexist(data []byte) []Finding {
	var out []Finding
	lines := strings.Split(strings.ReplaceAll(string(data), "\r\n", "\n"), "\n")

	top := ""         // раздел нулевого отступа, внутри которого мы сейчас
	portsIndent := -1 // отступ ключа `ports:`, пока идёт его список; -1 — мы вне списка
	project := false  // имя проекта встретилось
	publish := false  // публикация наружу встретилась

	for i, line := range lines {
		n := i + 1
		if strings.TrimSpace(line) == "" {
			continue
		}
		indent := len(line) - len(strings.TrimLeft(line, " \t"))
		trimmed := strings.TrimLeft(line, " \t")
		if strings.HasPrefix(trimmed, "#") {
			continue
		}
		if portsIndent >= 0 && indent <= portsIndent {
			portsIndent = -1 // список портов кончился — вышли на его уровень или выше
		}

		key, value := pair(trimmed)
		if indent == 0 && key != "" {
			top = key
		}

		switch {
		// ── правило 4: публикация ───────────────────────────────────────────
		case portsIndent >= 0:
			if f, bad := publication(n, line, trimmed, &publish); bad {
				out = append(out, f)
			}

		case key == "ports" && value == "":
			portsIndent = indent

		// ── правило 1: имя проекта ──────────────────────────────────────────
		case indent == 0 && key == "name":
			project = true
			if !strings.Contains(value, varName) {
				out = append(out, Finding{Line: n, Text: line,
					Why: "имя проекта зашито — вторая раздача встанет в тот же проект компоуза, что первая, и снимет её собой",
					Way: "верни подстановку: name: \"${SHARE_NAME:-world-share}\" — имя приходит от того, кто поднимает"})
			}

		// ── правило 2: имя контейнера ───────────────────────────────────────
		case key == "container_name":
			if !strings.Contains(value, varName) {
				out = append(out, Finding{Line: n, Text: line,
					Why: "имя контейнера зашито — докер не повторяет имён, и вторая раздача не поднимется вовсе",
					Way: "верни подстановку: container_name: \"${SHARE_NAME:-world-share}\""})
			}

		// ── правило 3: имя тома ─────────────────────────────────────────────
		case top == "volumes" && indent > 0 && key == "name":
			if !strings.Contains(value, varName) {
				out = append(out, Finding{Line: n, Text: line,
					Why: "имя тома зашито — обе раздачи возьмут ОДИН том, и личность одного юзера ляжет поверх личности другого",
					Way: "верни подстановку: name: \"${SHARE_NAME:-world-share}-state\" — у каждой раздачи свой том"})
			}
		}
	}

	if !project {
		out = append(out, Finding{
			Why: "имя проекта не названо вовсе — компоуз возьмёт его из имени папки, одинакового у обеих раздач",
			Way: "назови его подстановкой первой строкой файла: name: \"${SHARE_NAME:-world-share}\""})
	}
	if !publish {
		out = append(out, Finding{
			Why: "публикация наружу не названа — до раздачи не дотянется контроллер юзера, стоящий на другой машине",
			Way: "верни публикацию: ports: - \"${SHARE_BIND:-0.0.0.0}:${SHARE_PORT:-8070}:8070\""})
	}
	return out
}

// publication — разбор одной строки внутри списка `ports:`. Короткая запись
// (`- "хост:порт:8070"`) проверяется здесь; длинная (`- target:` / `published:`) —
// по ключу `published`, остальные её ключи нас не касаются.
//
// Длинная запись разобрана не «на всякий случай»: сторож, краснеющий на законной записи
// компоуза, дороже дыры, которую он закрывает.
func publication(n int, line, trimmed string, publish *bool) (Finding, bool) {
	body := strings.TrimSpace(strings.TrimPrefix(trimmed, "- "))
	if key, value := pair(body); key != "" {
		if key == "published" {
			*publish = true
			if !strings.Contains(value, varPort) {
				return Finding{Line: n, Text: line,
					Why: "публикуемый порт зашит — раздача встанет не на том адресе, который юзер назвал, и займёт порт соседней",
					Way: "верни подстановку: published: \"${SHARE_PORT:-8070}\""}, true
			}
		}
		return Finding{}, false // прочие ключи длинной записи — не наше дело
	}

	*publish = true
	v := unquote(body)
	idx := strings.LastIndex(v, ":")
	if idx < 0 {
		return Finding{Line: n, Text: line,
			Why: "публикация без хостового порта — докер назначит его сам, и адрес скоупа окажется не тем, который юзер назвал",
			Way: "назови порт явно: \"${SHARE_BIND:-0.0.0.0}:${SHARE_PORT:-8070}:8070\""}, true
	}
	if !strings.Contains(v[:idx], varPort) {
		return Finding{Line: n, Text: line,
			Why: "хостовый порт зашит — вторая раздача упрётся в занятый порт первой, а юзер получит не тот адрес, который назвал",
			Way: "верни подстановку: \"${SHARE_BIND:-0.0.0.0}:${SHARE_PORT:-8070}:8070\" — порт приходит из адреса скоупа"}, true
	}
	return Finding{}, false
}

// pair — «ключ: значение» одной строкой. Ключом считается только то, в чём нет пробела и
// кавычек: иначе элемент списка (`- state:/state`) читался бы как ключ. Разбор такой же
// грубый, как в `scalar`, и по той же причине — сторож стережёт класс, а не заменяет YAML.
func pair(trimmed string) (key, value string) {
	idx := strings.Index(trimmed, ":")
	if idx < 0 {
		return "", ""
	}
	key = trimmed[:idx]
	if key == "" || strings.ContainsAny(key, " \t\"'-") {
		return "", ""
	}
	return key, strings.TrimSpace(trimmed[idx+1:])
}

// unquote снимает внешние кавычки, если они парные. Внутренности не трогаются: там
// законно любое.
func unquote(s string) string {
	if len(s) >= 2 {
		if q := s[0]; (q == '"' || q == '\'') && s[len(s)-1] == q {
			return s[1 : len(s)-1]
		}
	}
	return s
}

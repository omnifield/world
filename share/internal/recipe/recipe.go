// Пакет recipe — сторож формы записи файла запуска (`share/compose.yaml`).
//
// ┌─────────────────────────────────────────────────────────────────────────────────────┐
// │ ЗАЧЕМ ОН ВООБЩЕ ЕСТЬ. Файл запуска не читал ни один сторож — ни разу (`WORLD2-140`).  │
// │ Всё, что разбирает компоуз, требует докера, докера в девбоксе нет, и проба зоны       │
// │ честно говорила «рецепт живьём не проверен». Звучало как «нужен докер» — и на этом    │
// │ разбор останавливался.                                                                │
// │                                                                                      │
// │ Но СИНТАКСИС ДОКЕРА НЕ ТРЕБУЕТ. Двоеточие с пробелом в незакавыченном значении        │
// │ сломало файл целиком, остановило живой выпуск на машине юзера — и ловится оно         │
// │ разбором строк, без единого контейнера. Проверяемое лежало рядом и не проверялось     │
// │ (`WORLD2` 4.2: важно, ГДЕ мы проверяем, а не как).                                    │
// └─────────────────────────────────────────────────────────────────────────────────────┘
//
// ЧТО ЭТОТ СТОРОЖ НЕ ЕСТЬ: он НЕ парсер YAML и не заменяет `docker compose config`.
// Полный разбор делает компоуз, и он остаётся там, где есть докер. Здесь ловится КЛАСС
// поломок формы записи (`WORLD2` 0.3 п. 3: человек прочтёт, инструмент не примет) — тот
// самый, что уже стоил выпуска, и ловится он ВСЕГДА, а не когда рядом оказался докер.
//
// Правил ровно четыре, и каждое стоит на своей поломке. Больше не заводим: сторож,
// краснеющий на законном файле, учит не смотреть на его красноту — это хуже, чем его
// отсутствие.
package recipe

import (
	"fmt"
	"strings"
)

// Finding — что не так, почему это поломка и что сделать. Форма та же, что у отказа:
// причина и выход обязательны (`WORLD2` 2.3). Сторож, говорящий «строка 66 плохая», —
// это молчание с номером.
type Finding struct {
	Line int
	Text string
	Why  string
	Way  string
}

func (f Finding) String() string {
	return fmt.Sprintf("строка %d: %s\n      строка: %s\n      выход: %s", f.Line, f.Why, strings.TrimSpace(f.Text), f.Way)
}

// Check разбирает файл запуска построчно и возвращает всё, что нашёл. Пустой ответ —
// «класс поломок, который мы стережём, здесь не встречается».
func Check(data []byte) []Finding {
	var out []Finding
	lines := strings.Split(strings.ReplaceAll(string(data), "\r\n", "\n"), "\n")

	// Блочные скаляры (`|`, `>`) пропускаем целиком: их содержимое — текст, и двоеточия
	// в нём законны. Без этого сторож краснел бы на законном файле — а красный сторож,
	// которому не верят, хуже отсутствующего.
	blockIndent := -1

	for i, line := range lines {
		n := i + 1
		if strings.TrimSpace(line) == "" {
			continue
		}
		indent := len(line) - len(strings.TrimLeft(line, " \t"))
		if blockIndent >= 0 {
			if indent > blockIndent {
				continue
			}
			blockIndent = -1
		}
		trimmed := strings.TrimLeft(line, " \t")
		if strings.HasPrefix(trimmed, "#") {
			continue
		}

		// ── правило 1: табов в отступе не бывает ─────────────────────────────
		// YAML запрещает табуляцию для отступа вовсе, а глазами она неотличима от
		// пробелов: файл «выглядит ровным» и не читается.
		if strings.ContainsRune(line[:indent], '\t') {
			out = append(out, Finding{Line: n, Text: line,
				Why: "отступ табом — YAML не принимает табуляцию для отступа, а глазами она неотличима от пробелов",
				Way: "замени табы пробелами: в этом файле отступ — два пробела на уровень"})
			continue
		}

		value := scalar(trimmed)
		if value == "" {
			continue
		}
		if strings.HasPrefix(value, "|") || strings.HasPrefix(value, ">") {
			blockIndent = indent
			continue
		}

		// ── правило 2: кавычка обязана закрыться ────────────────────────────
		if q := value[0]; q == '"' || q == '\'' {
			if len(value) < 2 || value[len(value)-1] != q {
				out = append(out, Finding{Line: n, Text: line,
					Why: "кавычка открыта и не закрыта — дальше YAML читает файл не как ты его видишь",
					Way: fmt.Sprintf("закрой её тем же знаком %q в конце значения", string(q))})
			}
			continue // внутри кавычек законно любое: двоеточия, решётки, подстановки
		}

		// ── правило 3: подстановка обязана быть закавычена ──────────────────
		// Это правило ШИРЕ поломки, из-за которой заведено, и намеренно: значение
		// подстановки задаёт человек снаружи, и что в нём окажется завтра — не наше
		// знание. Закавыченное значение переживает любое содержимое.
		if strings.Contains(value, "${") {
			out = append(out, Finding{Line: n, Text: line,
				Why: "значение с подстановкой ${…} не закавычено — двоеточие, решётка или перенос внутри сломают файл целиком",
				Way: "возьми значение в двойные кавычки: КЛЮЧ: \"${…}\" — текст внутри при этом не сокращают"})
			continue
		}

		// ── правило 4: двоеточие с пробелом в незакавыченном значении ───────
		// Ровно то, что остановило выпуск: YAML читает это как второй «ключ: значение»
		// и отвечает «mapping values are not allowed in this context».
		if strings.Contains(value, ": ") {
			out = append(out, Finding{Line: n, Text: line,
				Why: "двоеточие с пробелом в незакавыченном значении — YAML читает его как второй «ключ: значение» и файл перестаёт читаться ЦЕЛИКОМ",
				Way: "возьми значение в двойные кавычки; текст с двоеточием при этом законен и сокращать его не надо"})
			continue
		}
		// Незакавыченное значение обрезается по ` #` молча — то, что человек считал
		// частью значения, YAML считает комментарием.
		if strings.Contains(value, " #") {
			out = append(out, Finding{Line: n, Text: line,
				Why: "решётка после пробела в незакавыченном значении — YAML молча обрежет значение на ней",
				Way: "возьми значение в двойные кавычки, если решётка — часть значения"})
		}
	}
	return out
}

// scalar — правая часть строки: то, что YAML прочитает как скаляр.
//
// Разбор нарочно грубый и предсказуемый: первое `: ` (или `:` в конце) отделяет ключ,
// остальное — значение. Списочный дефис снимается: `- ключ: значение` устроен так же.
// Тонкостей YAML тут нет и не будет — сторож стережёт КЛАСС, а полный разбор делает
// компоуз.
func scalar(trimmed string) string {
	s := trimmed
	for strings.HasPrefix(s, "- ") {
		s = strings.TrimSpace(s[2:])
	}
	if s == "-" || s == "" {
		return ""
	}
	if idx := strings.Index(s, ": "); idx >= 0 {
		return strings.TrimSpace(s[idx+2:])
	}
	if strings.HasSuffix(s, ":") {
		return "" // ключ без значения — проверять нечего
	}
	// Строка без разделителя вовсе — это элемент списка (`- state:/state`) либо
	// продолжение. Двоеточие без пробела внутри законно, и трогать его нельзя: на нём
	// стоит короткая запись томов и портов.
	return s
}

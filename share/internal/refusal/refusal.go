// Пакет refusal — единственная форма, которой раздача говорит «нет».
//
// Тройка обязательна целиком: код — машине, причина и выход — человеку (`WORLD2` 2.3).
// Пустое «не получилось» — провал самого мира: юзеру нечего чинить.
//
//	{"code":"no-state","why":"по этому адресу состояния ещё нет…","ways":["запиши его: PUT /"]}
//
// ┌─────────────────────────────────────────────────────────────────────────────────────┐
// │ ЭТО НАША ВЕЖЛИВОСТЬ, А НЕ ЧАСТЬ ФОРМЫ СТЫКОВКИ (`WORLD2` 0.3, 3.4).                  │
// │                                                                                      │
// │ Чужая раздача равноправна нашей: она вправе ответить голым `401` без единого байта   │
// │ тела — и это законная раздача. Значит клиент разбирает СТАТУС, а тело читает как      │
// │ подробность, если она приехала. Потребует тело этой формы — он начнёт узнавать        │
// │ «свою» раздачу, а это ровно то, что канон запрещает.                                 │
// └─────────────────────────────────────────────────────────────────────────────────────┘
//
// Своя копия пакета, а не общий с соседом: зоны — разные модули, и раздача обязана
// собираться сама по себе. Общий пакет связал бы личность юзера (её раздают) с
// контроллером (он времянка, `WORLD2` 1.9) — а раздаче про контроллер знать нечего.
package refusal

import "net/http"

// Refusal — отказ. Он же ошибка: `*Refusal` возвращается вместо `error` там, где отказ
// обязан доехать до человека целиком, а не схлопнуться в строку.
type Refusal struct {
	// Status — код HTTP. В теле его нет намеренно: два разных кода одного и того же
	// разъедутся, а машине хватает статуса и `code`.
	Status int `json:"-"`
	// Code — машине. Проба стережёт ЕГО, а не формулировку: проба, привязанная к тексту,
	// зеленеет на верной правке и учит не трогать буквы (`WORLD2` 4.2).
	Code string `json:"code"`
	// Why — причина человеку. Одной фразой и по-человечески.
	Why string `json:"why"`
	// Ways — выходы. Пустым не бывает: отказ без выхода — тупик.
	Ways []string `json:"ways"`
}

func (r *Refusal) Error() string { return r.Code + ": " + r.Why }

// New — отказ. Хотя бы один выход обязателен: без него отказ не собрать, и проверяется это
// не ревью, а сигнатурой.
func New(status int, code, why string, way string, more ...string) *Refusal {
	if status == 0 {
		status = http.StatusInternalServerError
	}
	return &Refusal{Status: status, Code: code, Why: why, Ways: append([]string{way}, more...)}
}

// Раздача скоупа — то, что отдаёт и принимает личность юзера по его адресу (`WORLD2` 3.4).
//
// ┌─────────────────────────────────────────────────────────────────────────────────────┐
// │ ЭТО ВИЛКА, А НЕ СЛУЖБА МИРА (`WORLD2` 0.3).                                          │
// │                                                                                      │
// │ Мир задаёт форму: адрес, пароль и формат состояния. Само изделие — юзерово. Мы        │
// │ выпускаем ОДНУ вилку как удобство, а не как единственно возможную: отдать файл и      │
// │ принять файл умеет что угодно, «хоть ардуино», и такая раздача равноправна нашей.     │
// │                                                                                      │
// │ Отсюда всё остальное в этой зоне: ни одного своего заголовка, ни одной третьей ручки, │
// │ ни одного разбора файла. Всё это делало бы нашу раздачу узнаваемой, а чужую —         │
// │ второсортной.                                                                         │
// └─────────────────────────────────────────────────────────────────────────────────────┘
//
//	go run ./cmd/share          поднять раздачу (по умолчанию :8070)
//	go run ./cmd/share knock    постучаться в поднятую: жива ли она
//	go run ./cmd/share help     что умеет и какими значениями настраивается
//
// ПОЧЕМУ ПОРТ 8070. У соседей заняты 8080 (дверь — вход в мир, `kb:FUND-5`) и 8090
// (контроллер — власть над машиной). Раздача не то и не другое: она стоит ДО мира — юзер
// со своей личностью существует раньше, чем какая-либо дверь поднята, — и порт у неё
// поэтому свой, ниже обоих. Одна машина законно держит все три.
package main

import (
	"fmt"
	"io"
	"log"
	"net/http"
	"os"
	"strconv"
	"time"

	"github.com/omnifield/world/share/internal/api"
	"github.com/omnifield/world/share/internal/state"
)

const (
	defaultAddr = ":8070"
	// Где лежит файл состояния. Умолчание — рядом с запуском, чтобы `go run` у
	// разработчика зоны работал без единой настройки; образ кладёт том в `/state` и
	// называет путь явно (`share/Dockerfile`).
	defaultStatePath = "./.state/scope.json"
)

func main() {
	if len(os.Args) > 1 {
		switch os.Args[1] {
		case "help", "-h", "--help":
			usage(os.Stdout)
			return
		case "knock":
			knock()
			return
		default:
			usage(os.Stderr)
			fmt.Fprintf(os.Stderr, "\nнепонятная команда: %s\n", os.Args[1])
			os.Exit(2)
		}
	}

	addr := env("SHARE_ADDR", defaultAddr)
	path := env("SHARE_STATE", defaultStatePath)
	limit := number("SHARE_LIMIT", state.DefaultLimit)

	// БЕЗ ПАРОЛЯ НЕ ПОДНИМАЕМСЯ, и это не строгость ради строгости. Раздача, поднятая без
	// пароля, отдаёт личность юзера всякому, кто знает адрес, — и узнаётся это по факту,
	// когда отдавать уже поздно. Пустое значение поэтому не «открытый режим», а причина
	// с выходом (`WORLD2` 2.3).
	password := os.Getenv("SHARE_PASSWORD")
	if password == "" {
		fmt.Fprint(os.Stderr, `раздача не поднята: пароль не назван.

причина: раздача закрыта паролем — им доказывают, что состояние по этому адресу твоё
         (`+"`WORLD2` 3.4"+`). Без него личность юзера отдавалась бы всякому, кто знает адрес.

выход:   назови его при подъёме — SHARE_PASSWORD=<пароль>
         в файле состояния его нет и быть не может: это ключ от замка, а не из замка
`)
		os.Exit(2)
	}

	store := state.New(path, limit)
	handler := api.New(api.Options{Store: store, Password: password})

	log.Printf("share: раздача скоупа на %s", addr)
	// Состояние называется В СТАРТОВОЙ СТРОКЕ: «файла ещё нет» и «том смонтирован не тот» —
	// разные беды с разными выходами, а обнаруживаются они иначе только на первом запросе,
	// когда человек уже ждёт свою личность.
	log.Printf("share: состояние — %s (%s); предел записи — %d байт", path, stateState(path), limit)
	// Про сам пароль в журнале — только то, что он назван. Значение не печатается нигде:
	// журнал раздачи попадает в чужие руки ровно так же, как и всё остальное на машине.
	log.Printf("share: пароль назван; внутрь файла раздача не смотрит и его не разбирает")

	srv := &http.Server{
		Addr:    addr,
		Handler: handler,
		// Заголовки читаем с пределом: без него открытое и молчащее соединение держит
		// раздачу занятой сколько угодно.
		ReadHeaderTimeout: 10 * time.Second,
	}
	if err := srv.ListenAndServe(); err != nil {
		log.Fatalf("share: не поднялась: %v", err)
	}
}

func usage(w io.Writer) {
	fmt.Fprint(w, `Раздача скоупа — отдаёт и принимает файл состояния юзера по его адресу.

  share            поднять раздачу (по умолчанию :8070)
  share knock      постучаться в поднятую: жива ли она
  share help       эта подсказка

Ручки — ДВЕ, по одному адресу, файл целиком:
  GET  /    отдать состояние целиком
  PUT  /    принять состояние целиком (последняя запись затирает предыдущую)

Пароль — Basic: curl -u :<пароль> http://<адрес>/
Третьей ручки нет намеренно: она стала бы опознавательным знаком нашей раздачи, а чужая
раздача равноправна нашей (`+"`WORLD2` 0.3, 3.4"+`).

Значения:
  SHARE_PASSWORD=<пароль>          обязательно; без него раздача не поднимается
  SHARE_ADDR=:8070                 где слушать
  SHARE_STATE=./.state/scope.json  где лежит файл состояния (в образе /state/scope.json)
  SHARE_LIMIT=1048576              предел одной записи, байт
  SHARE_KNOCK_TIMEOUT=3            сколько секунд ждёт стук

Отказ приходит тройкой: code (машине), why (причина человеку), ways[] (выходы).
Внутрь файла раздача не смотрит: за содержимым следит тот, кто пишет, — контроллер.
`)
}

// stateState — что по названному пути лежит ПРЯМО СЕЙЧАС. «Файла ещё нет» — законное
// состояние свежей раздачи, а не поломка: юзер её только что поднял, состояние в неё
// запишет контроллер.
func stateState(path string) string {
	info, err := os.Stat(path)
	switch {
	case err == nil && info.IsDir():
		return "ЭТО КАТАЛОГ, а не файл — раздача откажет кодом state-unreadable; проверь, что смонтировано"
	case err == nil:
		return fmt.Sprintf("лежит, %d байт", info.Size())
	case os.IsNotExist(err):
		return "файла ещё нет — законно: первую запись сделает тот, кто заводит скоуп"
	default:
		return "не прочитать: " + err.Error()
	}
}

func env(name, def string) string {
	if v := os.Getenv(name); v != "" {
		return v
	}
	return def
}

func number(name string, def int64) int64 {
	v := os.Getenv(name)
	if v == "" {
		return def
	}
	n, err := strconv.ParseInt(v, 10, 64)
	if err != nil || n <= 0 {
		// Кривое значение не подменяем умолчанием молча: человек его назвал и будет
		// думать, что оно применилось.
		log.Fatalf("share: %s=%q — это не число байт", name, v)
	}
	return n
}

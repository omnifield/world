// Сторожа файла запуска — как команда. Их ДВОЕ, и они стерегут разное:
//
//	форма записи      прочитает ли файл YAML вообще (`recipe.Check`)
//	сосуществование   разведёт ли рецепт две раздачи на одной машине (`recipe.Coexist`)
//
//	go run ./cmd/recipecheck ../share/compose.yaml    прогнать обоих
//
// ПОЧЕМУ ОБА В ОДНОЙ КОМАНДЕ, А ГОВОРЯТ ПОРОЗНЬ. Прогонять их по отдельности человек не
// станет — забудет второго. А сваливать находки в одну кучу нельзя: «файл не читается» и
// «файл читается, но вторая раздача сядет поверх первой» — разные беды с разными выходами.
//
// ЗАЧЕМ ОТДЕЛЬНАЯ КОМАНДА, если то же самое стережёт `go test ./...`. Затем, что пробе
// зоны нужен ВИДИМЫЙ шаг и нужна нарочная порча: проба берёт файл запуска, портит его
// копию и требует, чтобы сторож покраснел. Через `go test` порчу не прогнать, не правя
// исходники, — а проба, которая правит исходники, врёт про то, что проверяет.
//
// В ОБРАЗ ЭТА КОМАНДА НЕ ЕДЕТ: `share/Dockerfile` собирает только `./cmd/share`. Сторож —
// инструмент разработчика зоны, а не часть поставки, которая держит личность юзера.
//
//	код 0   файл чист по тому классу, который сторож стережёт
//	код 1   нашлось: причина и выход названы по каждой находке
//	код 2   файл не назван или не прочитался
package main

import (
	"fmt"
	"os"

	"github.com/omnifield/world/share/internal/recipe"
)

func main() {
	if len(os.Args) < 2 {
		fmt.Fprint(os.Stderr, `не назван файл запуска.

  recipecheck <файл.yaml> [ещё файлы]

Сторожа НЕ заменяют `+"`docker compose config`"+`: полный разбор делает компоуз. Здесь ловятся
два класса, и оба без докера, а значит всегда:

  форма записи      файл перестаёт читаться ЦЕЛИКОМ (`+"`WORLD2-140`"+`, стоило выпуска)
  сосуществование   зашитое имя или порт — вторая раздача сядет поверх первой (`+"`WORLD2-150`"+`)
`)
		os.Exit(2)
	}

	bad := false
	for _, path := range os.Args[1:] {
		data, err := os.ReadFile(path)
		if err != nil {
			fmt.Fprintf(os.Stderr, "не прочитать %s: %v\n", path, err)
			os.Exit(2)
		}
		форма := recipe.Check(data)
		врозь := recipe.Coexist(data)
		if len(форма) == 0 && len(врозь) == 0 {
			fmt.Printf("%s — чист: читается компоузом и разводит две раздачи на одной машине\n", path)
			continue
		}
		bad = true
		назвать(path, "не пройдёт компоузом", форма)
		назвать(path, "две раздачи на одной машине столкнутся", врозь)
	}
	if bad {
		os.Exit(1)
	}
}

// назвать печатает находки одного сторожа. Молчит, когда находок нет: сторож, который
// докладывает «у меня чисто» каждой строкой, тонет в собственном выводе.
func назвать(path, беда string, found []recipe.Finding) {
	if len(found) == 0 {
		return
	}
	fmt.Fprintf(os.Stderr, "%s — %s, находок %d:\n", path, беда, len(found))
	for _, f := range found {
		fmt.Fprintf(os.Stderr, "  %v\n", f)
	}
}

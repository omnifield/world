# его отсутствие в обязательной части стоило выпуска.
файлЗапуска

case "$mode" in
    --green) зелёный ;;
    --red)   красный ;;
    --both)  зелёный; красный ;;
esac
докер

part "итог"
printf '  проверок: %d · красных: %d · не прогнано: %d\n' "$total" "$failed" "$skipped" >&2
if [ "$failed" -gt 0 ]; then exit 1; fi
if [ "$skipped" -gt 0 ]; then
    printf '  \033[33mНЕПОЛНЫЙ ПРОГОН\033[0m — часть проверок не выполнялась (см. выше)\n' >&2
    exit 3
fi
printf '  \033[32mзелено\033[0m\n' >&2

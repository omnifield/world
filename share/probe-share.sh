#!/usr/bin/env bash
# Проба раздачи — ломает нарочно и требует, чтобы она назвала код, причину и выход.
#
#   ./share/probe-share.sh          зелёный прогон: что раздача обязана уметь
#   ./share/probe-share.sh --red    красный прогон: нарочные поломки
#   ./share/probe-share.sh --both   (умолчание) сначала зелёный, потом красный
#
# ┌─────────────────────────────────────────────────────────────────────────────────────┐
# │ ЧТО ПРОБА СТЕРЕЖЁТ                                                                   │
# │                                                                                      │
# │ Не «работает ли раздача», а СВОЙСТВА, которые ей заказаны каноном:                    │
# │                                                                                      │
# │   1. ручек ровно две, и обе по одному адресу — файл целиком (`3.4`);                  │
# │   2. внутрь файла раздача не смотрит: что положили, то и отдали, байт в байт;         │
# │   3. пустые разделы и пустой бренд — законное состояние, а не поломка (`WORLD2-135`); │
# │   4. пароль проверяет сама раздача, и внутри файла его нет (`3.4`);                   │
# │   5. отказ приходит тройкой: код · причина · выходы (`2.3`);                          │
# │   6. НИ ОДНОГО СВОЕГО ЗНАКА В ПРОТОКОЛЕ: чужая раздача равноправна нашей (`0.3`);     │
# │   7. запись целиком затирает предыдущую — цена названа вслух и не «чинится» слиянием; │
# │   8. ФАЙЛ ЗАПУСКА ЧИТАЕТСЯ: форма записи проверяется БЕЗ докера и потому всегда;      │
# │   9. ДВЕ РАЗДАЧИ НА ОДНОЙ МАШИНЕ ЖИВУТ ОДНОВРЕМЕННО: машина не единица личности,      │
# │      единица — АДРЕС (`3.4`), и вторая раздача не садится поверх первой;              │
# │  10. подсказка скриптов зоны — это их шапка ЦЕЛИКОМ, а не зашитый диапазон строк.     │
# │                                                                                      │
# │ Проба стережёт КОД (`"code":"no-creds"`), а не формулировку: проба, привязанная к     │
# │ тексту, зеленеет на верной правке и учит не трогать буквы (`WORLD2` 4.2).             │
# └─────────────────────────────────────────────────────────────────────────────────────┘
#
# ┌─────────────────────────────────────────────────────────────────────────────────────┐
# │ ПОЧЕМУ ПУНКТ 8 СТОИТ В ЧАСТИ, КОТОРАЯ БЕЖИТ ВСЕГДА (`WORLD2-140`).                    │
# │                                                                                      │
# │ Файл запуска не читал ни один сторож — ни разу. Всё, что разбирает компоуз, требует   │
# │ докера, и проба честно говорила «рецепт живьём не проверен». Звучало как «нужен       │
# │ докер», и разбор на этом останавливался — пока двоеточие в незакавыченном значении    │
# │ не остановило живой выпуск на машине юзера.                                          │
# │                                                                                      │
# │ Но СИНТАКСИС ДОКЕРА НЕ ТРЕБУЕТ. Поэтому форма записи стережётся здесь и всегда, а в   │
# │ «не прогнано» остаётся только то, чему докер действительно нужен.                     │
# └─────────────────────────────────────────────────────────────────────────────────────┘
#
# ЧЕГО ЭТА ПРОБА НЕ ПРОВЕРЯЕТ БЕЗ ДОКЕРА: образ, том, здоровье контейнера и ПОЛНЫЙ разбор
# файла запуска компоузом. Нет докера — проба говорит об этом ВСЛУХ и завершается кодом 3:
# НЕПОЛНЫЙ ПРОГОН. Зелёного при неполном прогоне не бывает — «проверили, что смогли» и
# «проверили» разные слова.
#
#   код 0   полный зелёный: прогнано всё
#   код 1   краснота: раздача повела себя не так, как обязана
#   код 3   неполный прогон: часть проверок не выполнялась, и названо — какая
#
# ЧТО НУЖНО НА МАШИНЕ: `go` (собрать раздачу) и `curl` (постучаться). Докер — по желанию:
# без него часть проверок отмечается непрогнанной, а не подменяется догадкой.
set -euo pipefail
export LC_ALL=C

HERE="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
PORT="${SHARE_PROBE_PORT:-18070}"
BASE="http://127.0.0.1:$PORT"
PASS="пароль-пробы"
# Соседние адреса для «двух раздач на одной машине». Порты соседние, а не случайные:
# случайный порт прячет столкновение, которое тут как раз и проверяется.
PORT2=$((PORT + 1))
PORT3=$((PORT + 2))
PASS2="пароль-соседа"

mode=--both
case "${1:-}" in
    --green|--red|--both) mode="$1" ;;
    # Подсказка — это ШАПКА, и кончается она там, где кончается шапка: на первой строке,
    # которая не комментарий. Зашитый диапазон был второй правдой о её границе — и уже
    # соврал: `2,48p` терял два последних абзаца шапки, дописанных после него. Правило
    # заведено ревью 18.08 (`WORLD2-150`), под сторожем — раздел «подсказка» ниже.
    -h|--help) sed -n '1d; /^#/!q; s/^# \{0,1\}//; p' "${BASH_SOURCE[0]}"; exit 0 ;;
    "") ;;
    *)  printf 'непонятный ключ: %s (см. --help)\n' "$1" >&2; exit 2 ;;
esac

total=0; failed=0; skipped=0

part()   { printf '\n\033[1m%s\033[0m\n' "$*" >&2; }
detail() { printf '      %s\n' "$*" >&2; }
ok()     { total=$((total + 1)); printf '  \033[32m✔\033[0m %s\n' "$1" >&2; }
bad()    { total=$((total + 1)); failed=$((failed + 1)); printf '  \033[31m✘\033[0m %s\n' "$1" >&2
           shift; local l; for l in "$@"; do detail "$l"; done; }
skip()   { skipped=$((skipped + 1)); printf '  \033[33m•\033[0m %s — НЕ ПРОГНАНО\n' "$1" >&2
           shift; local l; for l in "$@"; do detail "$l"; done; }

# ------------------------------------------------------------------ обстановка
command -v go   >/dev/null || { printf 'нужен go: проба собирает раздачу из исходников\n' >&2; exit 2; }
command -v curl >/dev/null || { printf 'нужен curl: проба стучится в поднятую раздачу\n' >&2; exit 2; }

TMP="$(mktemp -d)"
BIN="$TMP/share"
CHECK="$TMP/recipecheck"
STATE="$TMP/состояние/scope.json"
LOG="$TMP/журнал"
PID=""
PID2=""
# Имена раздач, поднятых живьём (докером). Прибираются в trap ВМЕСТЕ С ТОМАМИ: том пробы
# переживёт её саму, и следующий прогон найдёт чужое состояние там, где ждёт пустоту.
LIVE_NAMES=()

прибрать() {
    [ -n "$PID" ]  && kill "$PID"  2>/dev/null || true
    [ -n "$PID2" ] && kill "$PID2" 2>/dev/null || true
    local name
    for name in ${LIVE_NAMES[@]+"${LIVE_NAMES[@]}"}; do
        # Порт снятию безразличен — ничего не поднимается; пароль обязателен, его требует
        # сам рецепт (`:?`), и пустышки ему довольно.
        SHARE_NAME="$name" SHARE_PASSWORD=снятие \
            docker compose -f "$HERE/compose.yaml" down -v --remove-orphans >/dev/null 2>&1 || true
    done
    rm -rf "$TMP"
}
trap прибрать EXIT

part "сборка"
if (cd "$HERE" && go build -o "$BIN" ./cmd/share) 2>"$TMP/сборка"; then
    ok "раздача собирается"
else
    bad "раздача не собирается" "$(cat "$TMP/сборка")"
    exit 1
fi
if (cd "$HERE" && go test ./... >"$TMP/тесты" 2>&1); then
    ok "пробы кода зелёные"
else
    bad "пробы кода красные" "$(tail -20 "$TMP/тесты")"
fi

# --------------------------------------------------------------- файл запуска
#
# БЕЖИТ ВСЕГДА И ДОКЕРА НЕ ТРЕБУЕТ — в этом весь смысл раздела (`WORLD2-140`). Сторож
# читает ТОТ САМЫЙ файл, которым раздачу поднимают на машине юзера, а следом проба портит
# его копию и требует, чтобы сторож покраснел: сторож, который никогда не краснел, не
# сторож, а украшение (`WORLD2` 4.2).
файлЗапуска() {
    part "файл запуска — форма записи, без докера"
    local check="$CHECK" recipe="$HERE/compose.yaml"

    if (cd "$HERE" && go build -o "$check" ./cmd/recipecheck) 2>"$TMP/сторож"; then
        ok "сторож формы записи собирается"
    else
        bad "сторож не собрался" "$(cat "$TMP/сторож")"
        return
    fi

    if "$check" "$recipe" >"$TMP/вывод" 2>&1; then
        ok "файл запуска чист — компоуз его прочитает"
    else
        bad "файл запуска не пройдёт компоузом" "$(cat "$TMP/вывод")"
    fi

    # ── порча 1: ровно тот дефект, что остановил живой выпуск ────────────────
    # Снимаем кавычки со значения с подстановкой — текст отказа внутри содержит
    # двоеточие с пробелом, и YAML читает его как второй «ключ: значение».
    sed 's/^\( *SHARE_PASSWORD: \)"\(.*\)"$/\1\2/' "$recipe" >"$TMP/порча-1.yaml"
    if cmp -s "$recipe" "$TMP/порча-1.yaml"; then
        bad "порча 1 не наложилась — проверять нечего" \
            "строка SHARE_PASSWORD в файле запуска выглядит не так, как ждёт порча" \
            "поправь порчу в probe-share.sh, чтобы она снова портила настоящую строку"
    elif "$check" "$TMP/порча-1.yaml" >"$TMP/вывод" 2>&1; then
        bad "ПОРЧА НЕ ПОКРАСНЕЛА: двоеточие в незакавыченной подстановке прошло" \
            "это ровно тот дефект, который остановил выпуск на машине юзера"
    else
        ok "порча «двоеточие в незакавыченной подстановке» краснеет"
        grep -q 'выход:' "$TMP/вывод" \
            && ok "сторож называет причину и выход, а не номер строки" \
            || bad "сторож покраснел без выхода" "$(cat "$TMP/вывод")"
    fi

    # ── порча 2: подстановка без кавычек, но и без двоеточия ─────────────────
    # Правило ШИРЕ поломки: закавычены обязаны быть все подстановки. Иначе следующее
    # двоеточие впишут в текст завтра — и всё повторится.
    sed 's/^\( *image: \)"\(.*\)"$/\1\2/' "$recipe" >"$TMP/порча-2.yaml"
    if cmp -s "$recipe" "$TMP/порча-2.yaml"; then
        bad "порча 2 не наложилась — проверять нечего" "строка image выглядит не так, как ждёт порча"
    elif "$check" "$TMP/порча-2.yaml" >"$TMP/вывод" 2>&1; then
        bad "незакавыченная подстановка прошла" "правило «закавычь значение» не стережётся"
    else
        ok "порча «подстановка без кавычек» краснеет"
    fi

    # ── и обратное: текст с двоеточием ВНУТРИ кавычек законен ───────────────
    # Проверка стоит здесь нарочно: правило — «закавычь значение», а НЕ «сократи текст
    # отказа». Покраснев тут, сторож учил бы резать человечьи причины (`2.3`).
    sed 's/им закрыта раздача/им закрыта: раздача/' "$recipe" >"$TMP/законно.yaml"
    if cmp -s "$recipe" "$TMP/законно.yaml"; then
        bad "проверка «двоеточие внутри кавычек» не наложилась" "текст отказа в файле запуска изменился — поправь проверку"
    elif "$check" "$TMP/законно.yaml" >"$TMP/вывод" 2>&1; then
        ok "двоеточие ВНУТРИ кавычек законно — текст отказа сокращать не надо"
    else
        bad "сторож краснеет на законном файле" "$(cat "$TMP/вывод")" \
            "красный сторож, которому не верят, хуже отсутствующего"
    fi
}

# ------------------------------------------------- две раздачи на одной машине, без докера
#
# ┌─────────────────────────────────────────────────────────────────────────────────────┐
# │ ПОЧЕМУ ЭТО СТЕРЕЖЁТСЯ ЗДЕСЬ, А НЕ ТОЛЬКО ЖИВЬЁМ (`WORLD2-150`, дыра `B3`).            │
# │                                                                                      │
# │ «Две раздачи на одной машине» — свойство РЕЦЕПТА: столкнутся они именем проекта,      │
# │ именем контейнера, именем тома и портом, и все четыре видны в файле без единого       │
# │ контейнера. Оставить проверку только живой части значило бы: на машине без докера     │
# │ зашитое имя проезжает молча — ровно та дыра, что стоила выпуска в `WORLD2-140`.       │
# │                                                                                      │
# │ Живая часть ниже (`сосуществованиеЖивьём`) проверяет ДРУГОЕ и незаменима: что тома    │
# │ действительно разные и что снятие одной раздачи не трогает вторую.                    │
# └─────────────────────────────────────────────────────────────────────────────────────┘
сосуществование() {
    part "две раздачи на одной машине — рецепт, без докера"
    local recipe="$HERE/compose.yaml"

    if [ ! -x "$CHECK" ]; then
        bad "сторож не собран — проверять нечего" "см. раздел «файл запуска» выше"
        return
    fi

    if "$CHECK" "$recipe" >"$TMP/вывод" 2>&1; then
        ok "в рецепте нет ни одного зашитого имени и порта — вторая раздача встанет своей"
    else
        bad "рецепт посадит вторую раздачу поверх первой" "$(cat "$TMP/вывод")"
    fi

    # ── порчи: каждая — своё столкновение на одной машине ────────────────────
    # Порча из ТЗ дословно: «зашить имя или порт раздачи обратно в умолчание → проба
    # обязана покраснеть». Зелёное здесь значит, что `B3` закрыта на бумаге.
    порча "имя проекта зашито в умолчание" \
        sed 's/^name: .*/name: "world-share"/'
    порча "имя контейнера зашито в умолчание" \
        sed 's/^\( *container_name: \).*/\1"world-share"/'
    порча "имя тома зашито в умолчание" \
        sed 's/^\( \+name: \)".*"/\1"world-share-state"/'
    порча "порт публикации зашит в умолчание" \
        sed 's/^\( *- \)".*:8070"$/\1"0.0.0.0:8070:8070"/'
    порча "публикация выброшена вовсе" \
        sed '/^ *- ".*:8070"$/d'

    # ── порчи С ПОДСТАНОВКОЙ ВНУТРИ: обе проходили зелёными (ревью 18.08) ────
    # Сторож искал разделитель портов последним двоеточием строки и находил его ВНУТРИ
    # `${SHARE_PORT:-8070}`. Обе записи ниже выглядят параметризованными и обе ломают
    # `B3`; порчи стоят здесь, а не только в `go test`, потому что рецепт портится ТОТ
    # САМЫЙ, которым раздачу поднимают на машине юзера.
    #
    # Первая бьёт прямо в приёмку п. 2 ТЗ: хостового порта нет вовсе — докер назначит его
    # случайным, и раздача встанет не по тому адресу, который юзер назвал.
    порча "хостового порта нет, подстановка на месте контейнерного" \
        sed 's/^\( *- \)".*:8070"$/\1"${SHARE_PORT:-8070}"/'
    # Вторая: хостовый зашит, подстановка уехала в порт контейнера — вторая раздача
    # упрётся в занятый порт первой.
    порча "хостовый порт зашит, подстановка уехала в контейнерный" \
        sed 's/^\( *- \)".*:8070"$/\1"0.0.0.0:8070:${SHARE_PORT:-8070}"/'

    # ── и обратное: сторожа обязаны говорить о файле РАЗНОЕ, но не противоположное ──
    # Незакавыченная публикация — беда формы записи, и говорить о ней обязан сторож формы.
    # Сторож сосуществования видел в ней «публикация наружу не названа» ПРИ ЖИВОЙ
    # публикации: причина ложная, а человек чинит по причине (`2.3`).
    sed 's/^\( *- \)"\(.*:8070\)"$/\1\2/' "$recipe" >"$TMP/незакавычено.yaml"
    if cmp -s "$recipe" "$TMP/незакавычено.yaml"; then
        bad "проверка «незакавыченная публикация» не наложилась" \
            "строка публикации в рецепте выглядит не так, как ждёт проверка"
    else
        "$CHECK" "$TMP/незакавычено.yaml" >"$TMP/вывод" 2>&1 || true
        if grep -q 'не пройдёт компоузом' "$TMP/вывод" \
           && ! grep -q 'публикация наружу не названа' "$TMP/вывод"; then
            ok "о незакавыченной публикации говорит сторож формы, а не сторож сосуществования"
        else
            bad "сторожа сказали об одном файле противоположное" "$(cat "$TMP/вывод")" \
                "публикация в файле ЖИВАЯ — «не названа» это ложная причина, и по ней чинят не то"
        fi
    fi
}

# `порча <что> <команда портить...>` — портит копию НАСТОЯЩЕГО рецепта и требует красноты.
# Сторож, который никогда не краснел, — не сторож, а украшение (`WORLD2` 4.2).
порча() {
    local what="$1"; shift
    local recipe="$HERE/compose.yaml" f="$TMP/порча.yaml"
    "$@" "$recipe" >"$f"
    if cmp -s "$recipe" "$f"; then
        bad "порча «$what» не наложилась — проверять нечего" \
            "строка в рецепте выглядит не так, как ждёт порча" \
            "поправь порчу в probe-share.sh, чтобы она снова портила настоящую строку"
    elif "$CHECK" "$f" >"$TMP/вывод" 2>&1; then
        bad "ПОРЧА НЕ ПОКРАСНЕЛА: $what" \
            "зелёное здесь значит, что «две раздачи на одной машине» закрыто на бумаге" \
            "сторож — internal/recipe (Coexist), команда — cmd/recipecheck"
    else
        ok "порча «$what» краснеет"
        grep -q 'выход:' "$TMP/вывод" \
            || bad "сторож покраснел без выхода" "$(cat "$TMP/вывод")"
    fi
}

# ------------------------------------------------------------- подсказка скриптов
#
# ┌─────────────────────────────────────────────────────────────────────────────────────┐
# │ ПОЧЕМУ ЭТО ВООБЩЕ ПОД СТОРОЖЕМ (ревью 18.08, `WORLD2-150`).                          │
# │                                                                                      │
# │ `--help` печатал шапку зашитым диапазоном строк (`sed -n '2,28p'`) — то есть число    │
# │ жило ОТДЕЛЬНО от шапки, которую печатает. Две правды о одной границе разъезжаются     │
# │ молча: этой же сдачей число правилось руками с `21` на `28`, а у самой пробы `2,48p`   │
# │ уже терял два последних абзаца шапки, и никто этого не заметил.                       │
# │                                                                                      │
# │ Проба НЕ ПЕРЕСКАЗЫВАЕТ разбор подсказки — пересказ зеленел бы вместе с ошибкой        │
# │ (`WORLD2` 4.2). Она портит КОПИЮ скрипта: дописывает строку последней в шапку и       │
# │ требует, чтобы подсказка её показала. Докера не требует и бежит всегда.               │
# └─────────────────────────────────────────────────────────────────────────────────────┘
подсказки() {
    part "подсказка скриптов — шапка целиком, без зашитых номеров"
    шапкаЦеликом "$HERE/up.sh"
    шапкаЦеликом "$HERE/probe-share.sh"
}

шапкаЦеликом() { # <скрипт> — печатает ли его `--help` шапку до последней строки
    local script="$1" name copy out
    name="$(basename "$script")"
    copy="$TMP/подсказка-$name"
    # Метка встаёт ПОСЛЕДНЕЙ строкой шапки — ровно туда, куда её терял зашитый диапазон.
    # Дописывают в конец шапки чаще всего, и терялось именно это.
    awk 'NR > 1 && !/^#/ && !seen { print "# МЕТКА-ХВОСТА-ШАПКИ"; seen = 1 } { print }' \
        "$script" >"$copy"
    if ! grep -q 'МЕТКА-ХВОСТА-ШАПКИ' "$copy"; then
        bad "$name: метка не встала — проверять нечего" \
            "у скрипта не нашлось ни одной строки кода после шапки — поправь проверку"
        return
    fi

    if ! out="$(bash "$copy" --help 2>&1)"; then
        bad "$name: --help не ответил" "$out" \
            "спросить «что умеет» человек вправе на любой машине"
        return
    fi
    if printf '%s\n' "$out" | grep -q 'МЕТКА-ХВОСТА-ШАПКИ'; then
        ok "$name: --help печатает шапку до последней строки"
    else
        bad "$name: --help потерял хвост шапки" \
            "строку, дописанную последней в шапку, человек в подсказке не увидит" \
            "граница у подсказки обязана быть одна — первая строка не-комментарий, а не номер"
    fi
    # И обратное: подсказка не смеет уходить в КОД. «Печатать файл целиком» — тоже одна
    # правда, но человек получил бы `set -euo pipefail` как часть подсказки.
    if printf '%s\n' "$out" | grep -q 'set -euo pipefail'; then
        bad "$name: --help печатает код, а не шапку" \
            "подсказка обязана кончаться на первой строке кода"
    else
        ok "$name: --help кончается на шапке и не уходит в код"
    fi
}

поднять() { # поднять раздачу с названным паролем; вернуть 1, если не поднялась
    SHARE_ADDR=":$PORT" SHARE_STATE="$STATE" SHARE_PASSWORD="$1" SHARE_LIMIT="${2:-1048576}" \
        "$BIN" >>"$LOG" 2>&1 &
    PID=$!
    local i
    for i in $(seq 50); do
        if SHARE_ADDR=":$PORT" "$BIN" knock >/dev/null 2>&1; then return 0; fi
        kill -0 "$PID" 2>/dev/null || return 1
        sleep 0.1
    done
    return 1
}
снять() { [ -n "$PID" ] && kill "$PID" 2>/dev/null; wait "$PID" 2>/dev/null || true; PID=""; }

# Сосед — вторая раздача рядом с первой, СВОЙ адрес и СВОЁ состояние. Отдельная пара
# функций, а не второй вызов `поднять`: у соседа свой номер процесса, и путать их нельзя —
# «снятие одной не трогает вторую» проверяется как раз этим.
поднятьСоседа() { # <порт> <пароль> <файл состояния>
    SHARE_ADDR=":$1" SHARE_STATE="$3" SHARE_PASSWORD="$2" "$BIN" >>"$TMP/журнал-соседа" 2>&1 &
    PID2=$!
    local i
    for i in $(seq 50); do
        if SHARE_ADDR=":$1" "$BIN" knock >/dev/null 2>&1; then return 0; fi
        kill -0 "$PID2" 2>/dev/null || return 1
        sleep 0.1
    done
    return 1
}
снятьСоседа() { [ -n "$PID2" ] && kill "$PID2" 2>/dev/null; wait "$PID2" 2>/dev/null || true; PID2=""; }

# `кодНа <база> <метод> <путь> <пароль> [тело-файл]` → печатает HTTP-код, тело кладёт в
# $TMP/тело. База отдельным доводом нужна ровно для соседа: он живёт на другом порту.
кодНа() {
    local base="$1" m="$2" p="$3" pw="$4" body="${5:-}"
    local -a args=(-s -o "$TMP/тело" -D "$TMP/шапка" -w '%{http_code}' -X "$m")
    [ -n "$pw" ] && args+=(-u ":$pw")
    [ -n "$body" ] && args+=(--data-binary "@$body")
    curl "${args[@]}" "$base$p"
}
# `код <метод> <путь> <пароль> [тело-файл]` — то же по основному адресу пробы.
код() { кодНа "$BASE" "$@"; }
отказ() { # код отказа из тела
    sed -n 's/.*"code":"\([^"]*\)".*/\1/p' "$TMP/тело" | head -n1
}
естьВыход() { grep -q '"ways":\["' "$TMP/тело" && grep -q '"why":"..*"' "$TMP/тело"; }

# ------------------------------------------------------------------ зелёный
зелёный() {
    part "зелёный прогон — что раздача обязана уметь"

    if поднять "$PASS"; then ok "поднимается и отвечает на стук — команда share knock"
    else bad "не поднялась" "$(tail -5 "$LOG")"; return; fi

    # 1. состояния ещё нет — это законное состояние свежей раздачи, а не поломка
    if [ "$(код GET / "$PASS")" = 404 ] && [ "$(отказ)" = no-state ]; then
        ok "состояния ещё нет — отвечает no-state, а не пустотой"
    else bad "свежая раздача ответила не no-state" "код: $(отказ)" "$(cat "$TMP/тело")"; fi

    # 2. свежий скоуп: пустые разделы и пустой бренд законны (`WORLD2-135`)
    printf '%s' '{"формат":1,"личность":{"имя":"я","бренд":"","описание":""},"ключи":[],"территории":[],"поля":[]}' >"$TMP/свежий"
    if [ "$(код PUT / "$PASS" "$TMP/свежий")" = 204 ]; then
        ok "свежий скоуп с пустыми разделами и пустым брендом принят"
    else bad "свежий скоуп не приняли" "$(cat "$TMP/тело")"; fi

    # 3. отдано ровно то, что положили
    код GET / "$PASS" >/dev/null
    if cmp -s "$TMP/тело" "$TMP/свежий"; then ok "отдаёт байт в байт то, что положили"
    else bad "отданное не совпало с положенным" "$(cat "$TMP/тело")"; fi

    # 4. внутрь не смотрит: берёт заведомо не-JSON
    printf 'ни разу не JSON {{{ \x01\x02' >"$TMP/мусор"
    код PUT / "$PASS" "$TMP/мусор" >/dev/null
    код GET / "$PASS" >/dev/null
    if cmp -s "$TMP/тело" "$TMP/мусор"; then ok "внутрь файла не смотрит — не-JSON проходит целиком"
    else bad "раздача полезла внутрь файла" "$(cat "$TMP/тело")"; fi

    # 5. запись целиком затирает предыдущую — цена названа вслух (`3.4`)
    printf '%s' '{"формат":1}' >"$TMP/короткий"
    код PUT / "$PASS" "$TMP/короткий" >/dev/null
    код GET / "$PASS" >/dev/null
    if cmp -s "$TMP/тело" "$TMP/короткий"; then ok "запись затирает предыдущую целиком, а не сливает"
    else bad "после записи лежит не то, что писали" "$(cat "$TMP/тело")"; fi

    # 6. состояние переживает перезапуск процесса: личность — не времянка (`1.9`)
    снять
    if поднять "$PASS"; then
        код GET / "$PASS" >/dev/null
        if cmp -s "$TMP/тело" "$TMP/короткий"; then ok "состояние пережило перезапуск раздачи"
        else bad "после перезапуска состояние другое" "$(cat "$TMP/тело")"; fi
    else bad "после перезапуска не поднялась" "$(tail -5 "$LOG")"; fi

    # 7. журнал: строка на запрос и ни одного пароля в ней
    if grep -q 'share: GET / → 200' "$LOG"; then ok "каждый запрос оставляет след в журнале"
    else bad "запроса не видно в журнале" "$(tail -5 "$LOG")"; fi
    if grep -q "$PASS" "$LOG"; then bad "ПАРОЛЬ УТЁК В ЖУРНАЛ" "$(grep -n "$PASS" "$LOG" | head -3)"
    else ok "пароля в журнале нет"; fi

    снять
}

# ------------------------------------------------------------------ красный
красный() {
    part "красный прогон — ломаем нарочно"

    # 1. без пароля раздача не поднимается вовсе
    out="$(SHARE_ADDR=":$PORT" SHARE_STATE="$STATE" "$BIN" 2>&1 || true)"
    if printf '%s' "$out" | grep -q 'причина:' && printf '%s' "$out" | grep -q 'выход:'; then
        ok "без пароля не поднимается и называет причину с выходом"
    else bad "без пароля повела себя иначе" "$out"; fi

    if поднять "$PASS" 64; then :; else bad "не поднялась" "$(tail -5 "$LOG")"; return; fi

    # Имена переменных ЛАТИНСКИЕ: bash не поддерживает не-ASCII в именах и падает на
    # `local имя=…` словами «not a valid identifier». Тексты и имена функций — русские.
    проверить() { # <что> <ожидаемый HTTP> <ожидаемый код> <метод> <путь> <пароль> [тело]
        local what="$1" http="$2" code="$3"; shift 3
        local got; got="$(код "$@")"
        if [ "$got" = "$http" ] && [ "$(отказ)" = "$code" ] && естьВыход; then
            ok "$what → $code, причина и выход названы"
        else
            bad "$what" "ждали $http/$code, пришло $got/$(отказ)" "$(cat "$TMP/тело")"
        fi
    }

    проверить "без кред"                401 no-creds        GET / ""
    проверить "неверный пароль"         401 bad-creds       GET / "не тот"
    проверить "третья ручка (POST)"     405 bad-handle      POST / "$PASS"
    проверить "раздел в пути"           404 no-such-address GET /ключи "$PASS"
    проверить "пароль спрашивают раньше пути" 401 no-creds  GET /ключи ""

    # заголовок вызова обязателен: `401` без него — молчание с текстом
    код GET / "" >/dev/null
    if grep -qi '^WWW-Authenticate:' "$TMP/шапка"; then ok "401 приходит с заголовком вызова"
    else bad "401 без WWW-Authenticate" "$(cat "$TMP/шапка")"; fi

    # 405 обязан назвать, что тут можно
    код POST / "$PASS" >/dev/null
    if grep -qi '^Allow: GET, PUT' "$TMP/шапка"; then ok "405 называет обе ручки заголовком Allow"
    else bad "405 без Allow" "$(cat "$TMP/шапка")"; fi

    # пустое тело — стёртая личность, а не пустая
    : >"$TMP/пусто"
    проверить "ноль байт" 400 empty-state PUT / "$PASS" "$TMP/пусто"

    # сверх предела (раздача поднята с SHARE_LIMIT=64)
    head -c 200 /dev/zero | tr '\0' 'x' >"$TMP/толстый"
    проверить "сверх предела" 413 state-too-big PUT / "$PASS" "$TMP/толстый"

    # чужая запись не должна доехать до диска ВООБЩЕ
    printf '%s' 'моё' >"$TMP/моё"
    код PUT / "$PASS" "$TMP/моё" >/dev/null
    printf '%s' 'чужое' >"$TMP/чужое"
    код PUT / "чужой пароль" "$TMP/чужое" >/dev/null
    код GET / "$PASS" >/dev/null
    if cmp -s "$TMP/тело" "$TMP/моё"; then ok "запись под чужим паролем не тронула состояние"
    else bad "чужая запись доехала до диска" "$(cat "$TMP/тело")"; fi

    # НИ ОДНОГО СВОЕГО ЗНАКА В ПРОТОКОЛЕ (`0.3`): по ответу нельзя узнать «нашу» раздачу
    код GET / "$PASS" >/dev/null
    marks="$(grep -iv -E '^(HTTP/|Content-Type:|Content-Length:|Cache-Control:|Date:|Allow:|WWW-Authenticate:|\s*$)' "$TMP/шапка" || true)"
    if [ -z "$marks" ]; then ok "в ответе нет ни одного своего заголовка"
    else bad "в ответе появился свой знак — чужая раздача перестаёт быть равноправной" "$marks"; fi

    снять
}

# ------------------------------------------------- две раздачи рядом, процессами
#
# Докера не требует и потому бежит ВСЕГДА. Здесь стережётся то, что живёт в самой раздаче:
# у двух рядом стоящих ничего общего нет — ни состояния, ни пароля, — а третья, поднятая на
# занятый адрес, называет причину и выход, а не «bind: address already in use» (`2.3`).
соседи() {
    part "две раздачи рядом — процессами, без докера"

    if поднять "$PASS"; then :; else bad "первая не поднялась" "$(tail -5 "$LOG")"; return; fi
    if поднятьСоседа "$PORT2" "$PASS2" "$TMP/сосед/scope.json"; then
        ok "вторая раздача поднялась рядом с первой — обе отвечают одновременно"
    else
        bad "вторая раздача рядом не поднялась" "$(tail -5 "$TMP/журнал-соседа")"
        снять; return
    fi
    local peer="http://127.0.0.1:$PORT2"

    # 1. у каждой своё состояние: запись в одну не видна в другой
    printf '%s' '{"формат":1,"личность":{"имя":"первый"}}' >"$TMP/первый"
    printf '%s' '{"формат":1,"личность":{"имя":"второй"}}' >"$TMP/второй"
    код    PUT / "$PASS"  "$TMP/первый" >/dev/null
    кодНа "$peer" PUT / "$PASS2" "$TMP/второй" >/dev/null
    код GET / "$PASS" >/dev/null
    if cmp -s "$TMP/тело" "$TMP/первый"; then
        кодНа "$peer" GET / "$PASS2" >/dev/null
        if cmp -s "$TMP/тело" "$TMP/второй"; then
            ok "запись в одну раздачу не видна в другой — две личности, а не одна"
        else bad "сосед отдал не своё состояние" "$(cat "$TMP/тело")"; fi
    else bad "первая раздача отдала не своё состояние" "$(cat "$TMP/тело")"; fi

    # 2. пароль у каждой свой: раздача закрыта СВОИМ, а не общим на машину
    if [ "$(кодНа "$peer" GET / "$PASS")" = 401 ]; then
        ok "пароль первой раздачи не открывает вторую"
    else bad "пароль соседа подошёл к чужой раздаче" "$(cat "$TMP/тело")"; fi

    # 3. снятие одной не трогает вторую — она отвечает и состояние на месте
    снять
    if [ "$(кодНа "$peer" GET / "$PASS2")" = 200 ] && cmp -s "$TMP/тело" "$TMP/второй"; then
        ok "снятие одной раздачи не тронуло вторую — отвечает, состояние на месте"
    else bad "снятие одной задело вторую" "$(cat "$TMP/тело")"; fi

    # 4. занятый адрес — причина и выход, а не «bind: address already in use»
    local out
    out="$(SHARE_ADDR=":$PORT2" SHARE_STATE="$TMP/третий/scope.json" SHARE_PASSWORD="$PASS" "$BIN" 2>&1 || true)"
    if printf '%s' "$out" | grep -q "причина:" \
       && printf '%s' "$out" | grep -q "выход:" \
       && printf '%s' "$out" | grep -q ":$PORT2"; then
        ok "занятый адрес назван причиной и выходом, и назван сам адрес"
    else
        bad "занятый адрес отказал невнятно" "$out" \
            "человек обязан узнать, ЧТО занято и что делать — вторая раздача законна (\`3.4\`)"
    fi
    # И отказ «занято» обязан отличаться от отказа «нет пароля»: одинаковый текст на разные
    # беды это молчание в двух экземплярах.
    local nopass
    nopass="$(SHARE_ADDR=":$PORT3" SHARE_STATE="$TMP/третий/scope.json" "$BIN" 2>&1 || true)"
    if [ "$out" = "$nopass" ]; then
        bad "разные беды отказывают одинаково" "«порт занят» и «пароль не назван» неразличимы"
    else ok "«порт занят» и «пароль не назван» — разные отказы"; fi

    снятьСоседа
}

# ------------------------------------------------------------------ докер
докер() {
    part "образ и рецепт"
    if ! docker version >/dev/null 2>&1; then
        skip "образ раздачи собирается и отвечает" \
             "докера на этой машине нет — проверено только то, что бежит без него" \
             "прогнать целиком: на машине с докером ./share/probe-share.sh"
        skip "рецепт краснеет без пароля" "нужен docker compose"
        return
    fi
    if docker build -q -f "$HERE/Dockerfile" -t world-share:probe "$HERE" >/dev/null 2>"$TMP/образ"; then
        ok "образ раздачи собирается"
    else bad "образ не собрался" "$(tail -10 "$TMP/образ")"; fi

    if docker compose version >/dev/null 2>&1; then
        # Рецепт без пароля обязан краснеть ЗДЕСЬ, до отправки на чужую машину.
        if out="$(docker compose -f "$HERE/compose.yaml" config 2>&1)"; then
            bad "рецепт без пароля прошёл проверку" "он поднял бы раздачу без пароля на чужой машине"
        elif printf '%s' "$out" | grep -qi 'SHARE_PASSWORD'; then
            ok "рецепт без пароля краснеет и называет, чего не хватает"
        else bad "рецепт краснеет не о том" "$out"; fi
    else
        skip "рецепт краснеет без пароля" "docker compose не подключён"
    fi
}

# ------------------------------------ две раздачи на одной машине — живьём, докером
#
# ЗДЕСЬ ПРОВЕРЯЕТСЯ ТО, ЧЕГО НЕ ВИДНО НИ В РЕЦЕПТЕ, НИ В ПРОЦЕССАХ: что тома у двух раздач
# действительно разные и что снятие одной не трогает ни контейнер, ни том второй. Сторож
# выше читает файл и знает лишь, что имена РАЗВОДЯТСЯ; развёл ли их докер на самом деле —
# знает только докер (`WORLD2-150`, приёмка 1).
поднятьЖивьём() { # <имя> <порт> <пароль>
    SHARE_NAME="$1" SHARE_PORT="$2" SHARE_BIND=127.0.0.1 SHARE_PASSWORD="$3" \
        SHARE_IMAGE=world-share:probe \
        docker compose -f "$HERE/compose.yaml" up -d --no-build >>"$TMP/живьём-$1" 2>&1 || return 1
    local i
    for i in $(seq 60); do
        if [ "$(docker inspect -f '{{.State.Health.Status}}' "$1" 2>/dev/null)" = healthy ]; then return 0; fi
        sleep 1
    done
    return 1
}
снятьЖивьём() { # <имя> [--with-state]
    local name="$1"; shift
    local -a args=(-f "$HERE/compose.yaml" down --remove-orphans)
    [ "${1:-}" = "--with-state" ] && args+=(-v)
    SHARE_NAME="$name" SHARE_PASSWORD=снятие docker compose "${args[@]}" >>"$TMP/живьём-$name" 2>&1
}

сосуществованиеЖивьём() {
    part "две раздачи на одной машине — живьём"
    if ! docker version >/dev/null 2>&1 || ! docker compose version >/dev/null 2>&1; then
        skip "две раздачи живут одновременно, у каждой свой том" \
             "докера на этой машине нет — рецепт прочитан сторожем выше, но живьём не поднят" \
             "прогнать целиком: на машине с докером ./share/probe-share.sh"
        skip "снятие одной не трогает вторую — ни контейнер, ни том" "нужен docker compose"
        skip "занятый порт называет ДОКЕР, и отказ доезжает причиной" "нужен docker compose"
        return
    fi

    # Поднимаем ТОТ образ, который собрал раздел «образ и рецепт»: тянуть `latest` из ghcr
    # значило бы проверять чужой выпуск вместо своего дерева.
    if ! docker image inspect world-share:probe >/dev/null 2>&1; then
        bad "образа world-share:probe нет — поднимать две раздачи нечем" \
            "он собирается разделом «образ и рецепт» выше; там же сказано, почему не собрался"
        return
    fi

    local one=world-share-probe-a two=world-share-probe-b three=world-share-probe-c
    LIVE_NAMES+=("$one" "$two" "$three")
    local baseA="http://127.0.0.1:$PORT2" baseB="http://127.0.0.1:$PORT3"

    if поднятьЖивьём "$one" "$PORT2" "$PASS" && поднятьЖивьём "$two" "$PORT3" "$PASS2"; then
        ok "две раздачи подняты одним рецептом и стоят рядом"
    else
        bad "две раздачи одним рецептом не встали" "$(tail -20 "$TMP/живьём-$one" "$TMP/живьём-$two" 2>/dev/null)"
        return
    fi

    # 1. том у каждой свой — это и есть «у каждой своя личность» (`1.9`)
    if docker volume inspect "$one-state" >/dev/null 2>&1 && docker volume inspect "$two-state" >/dev/null 2>&1; then
        ok "у каждой раздачи свой том: $one-state и $two-state"
    else
        bad "томов двое не оказалось" "$(docker volume ls --format '{{.Name}}' | grep -F world-share-probe || true)"
    fi

    # 2. запись в одну не видна в другой
    printf '%s' '{"формат":1,"личность":{"имя":"первый"}}' >"$TMP/первый"
    printf '%s' '{"формат":1,"личность":{"имя":"второй"}}' >"$TMP/второй"
    кодНа "$baseA" PUT / "$PASS"  "$TMP/первый" >/dev/null
    кодНа "$baseB" PUT / "$PASS2" "$TMP/второй" >/dev/null
    кодНа "$baseA" GET / "$PASS" >/dev/null
    if cmp -s "$TMP/тело" "$TMP/первый"; then
        кодНа "$baseB" GET / "$PASS2" >/dev/null
        if cmp -s "$TMP/тело" "$TMP/второй"; then ok "запись в одну раздачу не видна в другой"
        else bad "вторая отдала не своё состояние" "$(cat "$TMP/тело")"; fi
    else bad "первая отдала не своё состояние" "$(cat "$TMP/тело")"; fi

    # 3. снятие одной не трогает вторую — ни контейнер, ни том
    if ! снятьЖивьём "$one"; then bad "первая раздача не снялась" "$(tail -10 "$TMP/живьём-$one")"; fi
    if docker ps -a --format '{{.Names}}' | grep -qx "$two"; then ok "снятие одной оставило контейнер второй"
    else bad "снятие одной убрало контейнер второй" "$(docker ps -a --format '{{.Names}}')"; fi
    if [ "$(кодНа "$baseB" GET / "$PASS2")" = 200 ] && cmp -s "$TMP/тело" "$TMP/второй"; then
        ok "вторая отвечает после снятия первой, состояние на месте"
    else bad "снятие одной задело состояние второй" "$(cat "$TMP/тело")"; fi
    if docker volume inspect "$two-state" >/dev/null 2>&1; then ok "том второй раздачи цел"
    else bad "снятие одной унесло том второй"; fi
    # И том СНЯТОЙ раздачи остался: снятие вещи — не стирание личности (`1.9`), её уносит
    # только явное `--with-state`.
    if docker volume inspect "$one-state" >/dev/null 2>&1; then ok "снятие оставило личность снятой раздачи в томе"
    else bad "снятие унесло личность вместе с контейнером" "личность стирается только явным --with-state"; fi

    # 4. занятый порт называет ДОКЕР, и отказ доезжает причиной
    if поднятьЖивьём "$three" "$PORT3" "$PASS"; then
        bad "третья раздача встала на занятый порт" "порт $PORT3 держит $two — докер обязан был отказать"
        снятьЖивьём "$three" --with-state
    else
        # Журнал у каждой раздачи свой — иначе номер порта нашёлся бы в чужой строке, и
        # проба зеленела бы на отказе не о том.
        if grep -q "$PORT3" "$TMP/живьём-$three"; then
            ok "занятый порт краснеет докером, и сам порт назван в отказе"
        else
            bad "отказ по занятому порту не называет порт" "$(tail -20 "$TMP/живьём-$three")" \
                "человеку нужен адрес, а не «не вышло»"
        fi
    fi

    снятьЖивьём "$two" --with-state
    снятьЖивьём "$one" --with-state
}


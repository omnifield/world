#!/usr/bin/env bash
# Шлюз между ресурсами — достижимость и шов до тома, и больше ничего.
#
#   ./gate/gate.sh check     достижим ли ресурс B: дорога · ответ · доступ
#   ./gate/gate.sh up        поднять шов: том ресурса B виден на этой машине путём
#   ./gate/gate.sh down      снять шов
#   ./gate/gate.sh status    что сейчас: адрес, шов, точка
#
# ┌─────────────────────────────────────────────────────────────────────────────────────┐
# │ ЧТО ЭТОТ ИНСТРУМЕНТ ДЕЛАЕТ И ЧЕГО НЕ ДЕЛАЕТ                                          │
# │                                                                                      │
# │ Делает: даёт машине A дотянуться до тома, который лежит на машине B, — и называет    │
# │ вслух, на какой ступени связь порвалась.                                             │
# │                                                                                      │
# │ Не делает: не поднимает туннель (он уже есть и принадлежит хозяину машины), не       │
# │ заводит юзера, не знает, что лежит в томе, и не меряет ресурс машины. Кто такой юзер  │
# │ и что в скоупе — зона `core`; сколько на ресурсе памяти — отдельный инструмент.       │
# └─────────────────────────────────────────────────────────────────────────────────────┘
#
# Почему три ступени, а не одна проверка «работает / не работает». В мире расстояний нет
# (`WORLD2` 5.3): место либо достижимо, либо до него нет дороги — и второе мир обязан
# назвать вслух с причиной и выходом (`WORLD2` 2.3). «Не работает» без ступени — это и есть
# молчание: юзеру нечего чинить. Ступеней ровно три, потому что чинят их разные люди:
#
#   дорога   — до адреса вообще нет пути          чинит хозяин машины: туннель, маршрут
#   ответ    — путь есть, на порту никого         чинит хозяин ресурса B: служба, порт
#   доступ   — служба есть, креды не приняты      чинит юзер: ключ, имя
#
# Отказ печатается двумя строками сразу: человеку — причина и выход, машине — код.
# Код (`GATE-REFUSAL: no-route`) стережёт ПРОБА, а не формулировку: проба, привязанная к
# тексту, зеленеет на верной правке и учит не трогать буквы (`WORLD2` 4.2).
#
# Имена переменных латинские намеренно: bash не поддерживает не-ASCII в именах и молча
# превращает `АДРЕС=…` в «команда не найдена». Тексты и комментарии — русские.
#
# LC_ALL=C выставлен не для красоты: ступени «дорога» и «ответ» различаются по тексту
# системной ошибки (`No route to host` против `Connection refused`), а он переводится.
# На локализованной машине классификация без этого молча схлопнулась бы в одну ступень.
set -euo pipefail
export LC_ALL=C

# ------------------------------------------------------------------ значения
# Адрес ресурса B: `юзер@хост` или `юзер@хост:порт`. Умолчания НЕТ и не будет — угаданный
# адрес однажды укажет на чужую машину, и шлюз будет молча возить чужой том.
ADDR="${GATE_ADDR:-}"
# Путь тома НА РЕСУРСЕ B. Что там лежит — не наше дело: мы отвечаем за то, что путь виден.
REMOTE="${GATE_REMOTE:-}"
# Точка на ЭТОЙ машине, по которой том становится виден. Отсюда его забирает дверь.
MOUNT="${GATE_MOUNT:-$HOME/.gate/mnt}"
# Ключ юзера. Пусто — берётся обычный порядок ssh (агент, `~/.ssh/id_*`): креды принадлежат
# юзеру и его связке (`WORLD2` 3.0), шлюз их не заводит и не хранит.
KEY="${GATE_KEY:-}"
# Сколько ждём ответа. Меньше — быстрее краснеет; больше — терпимее к медленному туннелю.
TIMEOUT="${GATE_TIMEOUT:-5}"
# Инструмент шва. Отдельным значением, потому что его подменяет проба: «инструмента нет» —
# это законный отказ шлюза, и он обязан быть проверяемым на любой машине.
RCLONE="${GATE_RCLONE:-rclone}"

usage() {
    cat <<'USAGE'
Шлюз между ресурсами: ./gate/gate.sh <команда>

  check      достижим ли ресурс B — три ступени: дорога · ответ · доступ
  up         поднять шов: том ресурса B становится виден на этой машине путём
  down       снять шов
  status     что сейчас: адрес, точка, поднят ли шов
  -h --help  эта подсказка

Значения (умолчаний для адреса и пути НЕТ — их называет человек):
  GATE_ADDR=user@10.8.0.2       адрес ресурса B; можно с портом: user@host:2222
  GATE_REMOTE=/srv/scope        путь тома НА РЕСУРСЕ B
  GATE_MOUNT=~/.gate/mnt        точка на ЭТОЙ машине, откуда том забирает дверь
  GATE_KEY=~/.ssh/id_ed25519    ключ юзера; пусто — обычный порядок ssh (агент, id_*)
  GATE_TIMEOUT=5                сколько секунд ждём ответа
  GATE_RCLONE=rclone            инструмент шва

Отказ печатается двумя строками: причина и выход — человеку, `GATE-REFUSAL: <код>` —
машине. Коды: no-address · no-remote · no-name · no-route · no-answer · access-denied ·
no-remote-path · no-seam-tool · mount-failed · no-mount · no-mount-table.

Туннель между машинами шлюз НЕ поднимает: он уже есть и принадлежит хозяину машины.
Шлюз им пользуется и называет вслух, когда его нет.
USAGE
}

# ------------------------------------------------------------------ разговор
say()    { printf '%s\n' "$*" >&2; }
detail() { printf '      %s\n' "$*" >&2; }

# stage <имя> ok|fail [подробность…] — ступень, пройденная или нет. Строка машинная, её
# читает проба; человеку рядом идёт та же ступень значком.
stage() {
    local name="$1" state="$2"; shift 2
    printf 'GATE-STAGE: %s %s\n' "$name" "$state"
    if [ "$state" = ok ]; then
        printf '  \033[32m✔\033[0m %s\n' "$name" >&2
    else
        printf '  \033[31m✘\033[0m %s\n' "$name" >&2
    fi
    local line; for line in "$@"; do detail "$line"; done
}

# refuse <код> <причина> <выход…> — отказ. Причина и выход обязательны оба: «нельзя» без
# выхода — провал самого мира, юзеру нечего чинить (`WORLD2` 2.3).
refuse() {
    local code="$1" why="$2"; shift 2
    printf 'GATE-REFUSAL: %s\n' "$code"
    printf '\n\033[1;31m✗ отказ:\033[0m %s\n' "$why" >&2
    local line; for line in "$@"; do printf '  выход: %s\n' "$line" >&2; done
    exit 1
}

# ------------------------------------------------------------------ адрес
# Адрес разбирается ОДИН раз и в одном месте: разъедутся разборы — ssh пойдёт на один порт,
# а проверка достижимости на другой, и шлюз начнёт стеречь не тот путь, которым сам ходит.
USER_AT=""; HOST=""; PORT=22
parse_addr() {
    [ -n "$ADDR" ] || refuse no-address \
        "адрес ресурса не назван" \
        "назови его: GATE_ADDR=user@10.8.0.2 ./gate/gate.sh $1" \
        "адрес угадывать нечем — умолчания у него нет намеренно"

    local rest="$ADDR"
    case "$rest" in
        *@*) USER_AT="${rest%@*}"; rest="${rest##*@}" ;;
        *)   USER_AT="" ;;
    esac
    # Больше одного двоеточия — это адрес IPv6, а он в этой форме неразличим с портом.
    # Отказываем вслух, а не разбираем как попало: молчаливый разбор увёл бы стук на
    # выдуманный порт, и шлюз краснел бы причиной, которой на самом деле нет.
    case "${rest//[!:]/}" in
        ::*) refuse no-address \
                "адрес «$rest» похож на IPv6 — эта форма шлюзом не разбирается" \
                "назови имя или адрес IPv4: GATE_ADDR=user@10.8.0.2" \
                "нужен именно IPv6 — это отдельная работа, скажи владельцу зоны gate" ;;
    esac
    case "$rest" in
        *:*) HOST="${rest%:*}"; PORT="${rest##*:}" ;;
        *)   HOST="$rest"; PORT=22 ;;
    esac
    [ -n "$HOST" ] || refuse no-address \
        "в адресе «$ADDR» нет хоста" \
        "форма адреса: GATE_ADDR=user@хост или user@хост:порт"
}

ssh_target() { [ -n "$USER_AT" ] && printf '%s@%s' "$USER_AT" "$HOST" || printf '%s' "$HOST"; }

# ------------------------------------------------------------------ ступени
# resolver_kind — чем эта машина умеет разрешать имена: getent · python3 · nslookup · нет.
#
# Спрашиваем и печатаем это вслух (видно в `status`), потому что на машине БЕЗ резолвера
# ступени «имя» не существует, и проба обязана знать об этом, а не краснеть на пустом месте.
resolver_kind() {
    if command -v getent   >/dev/null 2>&1; then printf 'getent';   return; fi
    if command -v python3  >/dev/null 2>&1; then printf 'python3';  return; fi
    if command -v nslookup >/dev/null 2>&1; then printf 'nslookup'; return; fi
    printf 'нет'
}

is_ipv4() {
    case "$1" in
        *[!0-9.]*) return 1 ;;
        *.*.*.*)   return 0 ;;
        *)         return 1 ;;
    esac
}

# resolve_probe — разрешается ли имя. Печатает ok · fail · unknown.
#
# Отдельная ступень со СВОИМ тайм-аутом, а не побочный эффект стука. Разбирать имя по тексту
# системной ошибки нельзя: на живом прогоне 2026-08-14 внутренний резолвер докера на
# несуществующем имени не отвечал ОТКАЗОМ, а висел 16 секунд, — стук выходил по тайм-ауту, и
# шлюз называл ступень «дороги» там, где чинить надо было имя. Ступени чинят разные люди,
# и перепутанная ступень отправляет чинить не туда.
resolve_probe() {
    is_ipv4 "$HOST" && { printf 'ok'; return 0; }
    case "$(resolver_kind)" in
        getent)   timeout "$TIMEOUT" getent ahosts "$HOST" >/dev/null 2>&1 \
                      && printf 'ok' || printf 'fail' ;;
        python3)  timeout "$TIMEOUT" python3 -c \
                      'import socket,sys; socket.getaddrinfo(sys.argv[1], None)' "$HOST" >/dev/null 2>&1 \
                      && printf 'ok' || printf 'fail' ;;
        nslookup) timeout "$TIMEOUT" nslookup "$HOST" >/dev/null 2>&1 \
                      && printf 'ok' || printf 'fail' ;;
        *)        printf 'unknown' ;;
    esac
}

# tcp_probe — есть ли до адреса дорога и отвечает ли на порту хоть кто-то.
#
# Стучимся встроенным в bash `/dev/tcp`, а не `nc`: `nc` есть не везде (в нашем же девбоксе
# его нет), и его отсутствие выглядело бы как «ресурс недостижим» — то есть проверка врала
# бы ровно тем способом, который мы здесь и запрещаем.
#
# Кладёт итог в TCP_RESULT (ok · no-name · no-route · no-answer), ответ системы — в
# TCP_DETAIL. Через переменные, а не печатью в stdout: `$(tcp_probe)` завела бы функцию в
# ПОДОБОЛОЧКУ, и подробность отказа умирала бы вместе с ней — отказы выходили с пустой
# строкой вместо ответа системы. Поймано пробой 2026-08-14.
TCP_RESULT=""; TCP_DETAIL=""
tcp_probe() {
    local out rc
    set +e
    out=$(timeout "$TIMEOUT" bash -c "exec 3<>/dev/tcp/$HOST/$PORT" 2>&1); rc=$?
    set -e
    TCP_DETAIL="$out"

    [ "$rc" -eq 0 ] && { TCP_RESULT=ok; return 0; }
    # 124 — тайм-аут: пакет ушёл и не вернулся. Это дорога, а не закрытый порт: закрытый
    # порт отвечает отказом сразу, а тишина означает, что до машины не доходит вовсе.
    [ "$rc" -eq 124 ] && { TCP_RESULT=no-route; return 0; }

    case "$out" in
        *"Name or service not known"*|*"Temporary failure in name resolution"*|*"nodename nor servname"*|*"unknown host"*)
            TCP_RESULT=no-name ;;
        *"No route to host"*|*"Network is unreachable"*|*"Host is unreachable"*)
            TCP_RESULT=no-route ;;
        *"Connection refused"*|*"Connection reset"*)
            TCP_RESULT=no-answer ;;
        # Незнакомая ошибка ступени не выдумывает: до машины мы дошли (дорога была), а вот
        # ответа не получили — это «ответ». Текст системы при этом печатается как есть,
        # чтобы человек видел настоящую причину, а не нашу догадку о ней.
        *)  TCP_RESULT=no-answer ;;
    esac
}

# ssh_probe — принимает ли ресурс креды юзера.
#
# BatchMode=yes обязателен: без него ssh спросит пароль, и проверка повиснет вместо того,
# чтобы покраснеть. Проба, которая ждёт человека, — не проба.
# Итог — в SSH_RESULT, ответ ресурса — в SSH_DETAIL: та же причина, что у tcp_probe.
SSH_RESULT=""; SSH_DETAIL=""
ssh_probe() {
    local out rc; local -a opts
    opts=(-o BatchMode=yes -o StrictHostKeyChecking=accept-new
          -o "ConnectTimeout=$TIMEOUT" -p "$PORT")
    [ -n "$KEY" ] && opts+=(-i "$KEY" -o IdentitiesOnly=yes)
    set +e
    out=$(timeout $((TIMEOUT * 3)) ssh "${opts[@]}" "$(ssh_target)" true 2>&1); rc=$?
    set -e
    SSH_DETAIL="$out"
    [ "$rc" -eq 0 ] && { SSH_RESULT=ok; return 0; }
    SSH_RESULT=access-denied
}

# ------------------------------------------------------------------ check
cmd_check() {
    parse_addr check
    say ""
    say "ресурс: $ADDR (хост $HOST, порт $PORT)"

    # Ступень «имя» появляется только там, где имя есть что разрешать: у адреса числом её
    # нет вовсе, и печатать пройденную ступень, которой не было, значит врать зелёным.
    local resolved; resolved="$(resolve_probe)"
    case "$resolved" in
        ok)
            is_ipv4 "$HOST" || stage имя ok ;;
        fail)
            stage имя fail
            refuse no-name \
                "имя «$HOST» не разрешается за ${TIMEOUT}с — шлюзу некуда стучаться" \
                "проверь имя или назови адрес числом: GATE_ADDR=${USER_AT:+$USER_AT@}10.8.0.2" \
                "если имя домашнее — оно должно разрешаться на ЭТОЙ машине, а не только на той" \
                "имя верное — значит молчит резолвер машины: чинит её хозяин, не шлюз" ;;
    esac

    tcp_probe
    case "$TCP_RESULT" in
        ok)
            stage дорога ok
            stage ответ ok
            ;;
        no-name)
            stage дорога fail "$TCP_DETAIL"
            refuse no-name \
                "имя «$HOST» не разрешается — шлюзу некуда стучаться" \
                "проверь имя или назови адрес числом: GATE_ADDR=user@10.8.0.2" \
                "если имя домашнее — оно должно разрешаться на ЭТОЙ машине, а не только на той"
            ;;
        no-route)
            stage дорога fail "$TCP_DETAIL"
            # На машине без резолвера ступени «имя» не было вовсе, и честнее сказать это в
            # выходе, чем выдать непроверенное за проверенное (`WORLD2` 4.2: чего не удалось
            # измерить — не записывается).
            local unchecked=()
            [ "$resolved" = unknown ] && unchecked=(
                "имя НЕ проверялось: на этой машине нет ни getent, ни python3, ни nslookup" )
            refuse no-route \
                "канала нет: до $HOST:$PORT не доходит (ждали ${TIMEOUT}с)" \
                "подними туннель на ЭТОЙ машине и проверь маршрут: ip route get $HOST" \
                "туннель поднимает хозяин машины, шлюз его не изготавливает" \
                "туннель уже поднят — проверь, что адрес из его подсети, а не из чужой" \
                ${unchecked[@]+"${unchecked[@]}"}
            ;;
        no-answer)
            stage дорога ok
            stage ответ fail "$TCP_DETAIL"
            refuse no-answer \
                "адрес не отвечает: до $HOST дорога есть, на порту $PORT никого" \
                "проверь на ресурсе B, что служба слушает: ss -lntp | grep :$PORT" \
                "порт нестандартный — назови его: GATE_ADDR=$ADDR:<порт>"
            ;;
    esac

    ssh_probe
    if [ "$SSH_RESULT" != ok ]; then
        stage доступ fail "$SSH_DETAIL"
        refuse access-denied \
            "доступ не принят: $HOST:$PORT отвечает, но креды не приняты" \
            "положи ключ юзера на ресурс B или назови верный: GATE_KEY=~/.ssh/id_ed25519" \
            "проверь имя юзера в адресе — оно часть кред, а не украшение" \
            "ответ ресурса напечатан выше: если это не ssh, на порту стоит не та служба"
    fi
    stage доступ ok

    # Путь тома спрашиваем ТОЛЬКО когда он назван: `check` обязан работать и до того, как
    # человек решил, какой именно том подключать, — иначе проверить дорогу нечем.
    if [ -n "$REMOTE" ]; then
        local out rc; local -a opts
        opts=(-o BatchMode=yes -o StrictHostKeyChecking=accept-new
              -o "ConnectTimeout=$TIMEOUT" -p "$PORT")
        [ -n "$KEY" ] && opts+=(-i "$KEY" -o IdentitiesOnly=yes)
        set +e
        out=$(timeout $((TIMEOUT * 3)) ssh "${opts[@]}" "$(ssh_target)" "test -d '$REMOTE'" 2>&1); rc=$?
        set -e
        if [ "$rc" -ne 0 ]; then
            stage том fail "$out"
            refuse no-remote-path \
                "тома нет по пути $REMOTE на ресурсе B" \
                "проверь путь на самом ресурсе: ssh $(ssh_target) ls -la $REMOTE" \
                "путь называет человек; шлюз каталогов не создаёт — он не знает, что там должно лежать"
        fi
        stage том ok
    fi

    say ""
    say "канал есть: $ADDR достижим, креды приняты"
}

# ------------------------------------------------------------------ up / down / status
# mounted — поднят ли шов ИМЕННО на нашей точке.
#
# Смотрим в таблицу монтирований ядра, а не на то, что каталог непустой: непустым он бывает
# и без шва — например, если в него что-то положили руками, — и проверка зеленела бы на
# оторванном ресурсе. Точку разворачиваем в абсолютный путь: в таблице она абсолютная.
#
# Сравнение точное (awk по второму полю), а не поиском подстроки: путь с `+` или `.` внутри
# регулярка прочитала бы как шаблон, и шов на соседней точке сошёл бы за наш.
mounted() {
    local point="$1"
    [ -d "$point" ] || return 1
    point="$(cd -- "$point" && pwd)"
    mount_table || return 1
    awk -v p="$point" '$2 == p { found = 1 } END { exit !found }' /proc/self/mounts
}

# mount_table — видно ли таблицу монтирований вообще.
#
# Отдельной проверкой, потому что «шва нет» и «проверить нечем» — разные вещи, и вторую
# шлюз обязан назвать, а не выдать за первую. Машина без `/proc` (Windows, macOS) для двери
# и так не годится: дверь живёт в контейнере, а контейнеры у нас Linux.
mount_table() { [ -r /proc/self/mounts ]; }

cmd_up() {
    parse_addr up
    mount_table || refuse no-mount-table \
        "проверить шов на этой машине нечем: таблицы монтирований (/proc/self/mounts) не видно" \
        "поднимай шов на машине, где живёт дверь: у нас это Linux-контейнер" \
        "шлюз намеренно не поднимает того, что не может проверить: непроверенный шов хуже отсутствующего"
    [ -n "$REMOTE" ] || refuse no-remote \
        "путь тома на ресурсе B не назван" \
        "назови его: GATE_REMOTE=/srv/scope ./gate/gate.sh up" \
        "что лежит в томе — не дело шлюза, но ГДЕ он лежит, обязан назвать человек"

    if mounted "$MOUNT"; then
        say "шов уже поднят: $MOUNT"
        return 0
    fi

    command -v "$RCLONE" >/dev/null 2>&1 || refuse no-seam-tool \
        "инструмента шва «$RCLONE» на этой машине нет" \
        "поставь rclone: https://rclone.org/install/ (один бинарь, зависимостей не тянет)" \
        "инструмент нужен ТОЛЬКО на этой машине; на ресурсе B ставить нечего — там хватает ssh" \
        "стоит под другим именем или путём — назови его: GATE_RCLONE=/usr/local/bin/rclone"

    mkdir -p "$MOUNT"

    # Строка подключения собирается на месте, а не хранится в файле настроек rclone: файл
    # настроек — это состояние, которое надо заводить, чинить и синхронизировать, а у нас
    # всё нужное уже есть в значениях. Заодно шлюз не держит чужих кред у себя.
    local conn="sftp,host=$HOST,port=$PORT"
    [ -n "$USER_AT" ] && conn="$conn,user=$USER_AT"
    [ -n "$KEY" ] && conn="$conn,key_file=$KEY"

    local out rc
    set +e
    out=$("$RCLONE" mount ":$conn:$REMOTE" "$MOUNT" \
            --daemon --vfs-cache-mode writes --dir-cache-time 5s \
            --timeout "${TIMEOUT}s" --contimeout "${TIMEOUT}s" 2>&1); rc=$?
    set -e
    if [ "$rc" -ne 0 ] || ! mounted "$MOUNT"; then
        refuse mount-failed \
            "шов не встал: том $REMOTE не подключился к $MOUNT" \
            "проверь связь отдельно: ./gate/gate.sh check" \
            "ответ инструмента: ${out:-(молча)}" \
            "нет /dev/fuse — шов этой машине недоступен: FUSE даёт хозяин машины, не шлюз"
    fi

    say "шов поднят: $ADDR:$REMOTE → $MOUNT"
    say "дверь забирает том отсюда — путь $MOUNT отдаётся ей как обычный каталог машины"
}

cmd_down() {
    # «Шва нет» и «проверить нечем» — разные отказы, и путать их нельзя: во втором случае
    # шов может быть поднят, а мы бы сказали, что снимать нечего.
    mount_table || refuse no-mount-table \
        "проверить шов на этой машине нечем: таблицы монтирований (/proc/self/mounts) не видно" \
        "снимай шов там, где его поднимали, — на машине двери"
    mounted "$MOUNT" || refuse no-mount \
        "шва нет: на точке $MOUNT ничего не смонтировано" \
        "снимать нечего; если ждал другую точку — назови её: GATE_MOUNT=<путь>"

    local out rc=1
    if command -v fusermount3 >/dev/null 2>&1; then
        set +e; out=$(fusermount3 -u "$MOUNT" 2>&1); rc=$?; set -e
    elif command -v fusermount >/dev/null 2>&1; then
        set +e; out=$(fusermount -u "$MOUNT" 2>&1); rc=$?; set -e
    else
        set +e; out=$(umount "$MOUNT" 2>&1); rc=$?; set -e
    fi

    if [ "$rc" -ne 0 ] || mounted "$MOUNT"; then
        refuse mount-failed \
            "шов не снялся с точки $MOUNT" \
            "посмотри, кто держит точку: lsof +D $MOUNT" \
            "ответ инструмента: ${out:-(молча)}"
    fi
    say "шов снят: $MOUNT"
}

cmd_status() {
    say ""
    say "адрес ресурса B : ${ADDR:-(не назван)}"
    say "том на ресурсе  : ${REMOTE:-(не назван)}"
    say "точка на машине : $MOUNT"
    # Чем машина умеет разрешать имена — часть её обстановки, а не мелочь: без резолвера
    # ступень «имя» не существует, и это надо видеть до прогона, а не выяснять по отказу.
    say "резолвер имён   : $(resolver_kind)"
    if ! mount_table; then
        say "шов             : неизвестно — таблицы монтирований не видно"
    elif mounted "$MOUNT"; then
        say "шов             : поднят"
    else
        say "шов             : не поднят"
    fi
    say ""
    say "достижимость этой командой НЕ проверяется — для этого ./gate/gate.sh check"
}

# ------------------------------------------------------------------ разбор ключей
# Ключи разбираем ДО всего остального: `--help` обязан работать и там, где нет ни сети,
# ни инструмента шва, ни настроенного адреса.
case "${1:-}" in
    check)      cmd_check ;;
    up)         cmd_up ;;
    down)       cmd_down ;;
    status)     cmd_status ;;
    -h|--help)  usage; exit 0 ;;
    "")         usage >&2; printf '\nкоманда не названа\n' >&2; exit 2 ;;
    *)          usage >&2; printf '\nнепонятная команда: %s\n' "$1" >&2; exit 2 ;;
esac

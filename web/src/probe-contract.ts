// Образцы ответов для проб — ВЫРЕЗАНЫ ИЗ КОНТРАКТА либо СНЯТЫ С ЖИВОГО ПРОГОНА, а не сочинены
// здесь. Первое даёт форму ответа, второе — законный край его значений (см. конец файла).
//
// Пробы пульта разбирают ответы контроллера. Пока образец этих ответов написан рукой в самой
// пробе, зона проверяет себя своей же выдумкой: форма у контроллера уезжает, а пробы остаются
// зелёными — они ведь по-прежнему разбирают то, что мы сами и придумали. Ровно это и случилось
// с `door`/`alive`: поля не стало (`WORLD2-131`), а пробы web об этом не сказали ни слова.
//
// Поэтому образец берётся ОТТУДА, ГДЕ ЖИВЁТ КОНТРАКТ — из `control/README.md` (таблица ручек
// `WORLD2-102` и примеры ответов рядом с ней). Уехала форма у соседа — пробы пульта краснеют в
// тот же прогон, а не через выпуск.
//
// Читается файл, а не сеть: проба обязана идти на голой машине, без живого контроллера и без
// докера. Дальше по-прежнему разбирает ПУЛЬТ — образец только заменяет выдумку.
//
// Чужую зону это НЕ правит и от неё не зависит в сборке: `control/README.md` только читается,
// и только пробами; в собранный пульт этот файл не попадает (его никто не импортирует из кода).
// Разъехались README соседа и его же код — это вопрос к зоне `control`, и пусть он звучит
// здесь красным, а не молчит.
import { existsSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";

/** Где живёт контракт — считая от корня репозитория. */
const ГДЕ = join("control", "README.md");

/**
 * Ищем ВВЕРХ от каталога запуска, а не считаем путь от этого файла: раннер зовут и из `web/`
 * (`pnpm -C web test`), и из корня, а `import.meta.url` под раннером — вовсе не файловый адрес.
 */
function найти(): string {
  let каталог = process.cwd();
  for (let вверх = 0; вверх < 6; вверх += 1) {
    const путь = join(каталог, ГДЕ);
    if (existsSync(путь)) return путь;
    const выше = dirname(каталог);
    if (выше === каталог) break;
    каталог = выше;
  }
  throw new Error(
    `рядом с ${process.cwd()} не нашёлся ${ГДЕ} — образцы ответов пробы берут из контракта ` +
      "соседа, а не сочиняют: без файла проба проверяла бы выдумку",
  );
}

const КОНТРАКТ = найти();

/** Разобранные образцы ответов из контракта — по одному чтению файла на прогон. */
let разобранные: Array<Record<string, unknown>> | undefined;

/**
 * Все json-блоки контракта, которые разбираются. Неразбираемые пропускаем молча: в доке рядом
 * лежат куски с многоточиями и комментариями, и они не образцы.
 */
function блоки(): Array<Record<string, unknown>> {
  if (разобранные) return разобранные;

  let текст: string;
  try {
    текст = readFileSync(КОНТРАКТ, "utf8");
  } catch (cause) {
    throw new Error(
      `не прочитать контракт соседа (${КОНТРАКТ}): ${cause instanceof Error ? cause.message : String(cause)}. ` +
        "Образцы ответов пробы берут оттуда, а не сочиняют: без файла проба проверяла бы выдумку.",
    );
  }

  const out: Array<Record<string, unknown>> = [];
  for (const кусок of текст.matchAll(/```json\n([\s\S]*?)```/g)) {
    let parsed: unknown;
    try {
      parsed = JSON.parse(кусок[1]!);
    } catch {
      continue;
    }
    if (parsed !== null && typeof parsed === "object" && !Array.isArray(parsed)) {
      out.push(parsed as Record<string, unknown>);
    }
  }
  разобранные = out;
  return out;
}

/**
 * Образец ответа из контракта — тот, где есть названное поле.
 *
 * Не нашли — падаем ГРОМКО и с адресом: пропавший образец значит, что контракт переписан, и
 * молча подставить свой значило бы вернуть ту самую выдумку, ради ухода от которой файл и есть.
 */
export function изКонтракта<T>(поле: string): T {
  const найден = блоки().find((блок) => поле in блок);
  if (!найден) {
    throw new Error(
      `в контракте (${КОНТРАКТ}) нет образца ответа с полем «${поле}» — ` +
        "форма разъехалась, и это вопрос к зоне control, а не повод дописать образец здесь",
    );
  }
  // Приведение к типу пульта — это ЗАЯВКА, и проверяет её проба разбора: она гоняет тот же
  // образец через `liveControl` и краснеет, если формы разошлись (`control.test.ts`).
  return найден as T;
}


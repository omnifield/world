// Образцы ответов для проб — ВЫРЕЗАНЫ ИЗ КОНТРАКТА, а не сочинены здесь. Контракт даёт ФОРМУ
// ответа; законный КРАЙ ЕГО ЗНАЧЕНИЙ форма не показывает, и он собирается отдельно и вслух —
// см. конец файла, там же названо, чем этот край держался раньше и почему больше не держится.
//
// Пробы пульта разбирают ответы контроллера. Пока образец этих ответов написан рукой в самой
// пробе, зона проверяет себя своей же выдумкой: форма у контроллера уезжает, а пробы остаются
// зелёными — они ведь по-прежнему разбирают то, что мы сами и придумали. Ровно это и случилось
// с `door`/`alive`: поля не стало (`WORLD2-131`), а пробы web об этом не сказали ни слова.
//
// Поэтому образец берётся ОТТУДА, ГДЕ ЖИВЁТ КОНТРАКТ — из `control/README.md` (таблица ручек
// `WORLD2-102` и примеры ответов рядом с ней). Уехала форма у соседа — пробы пульта краснеют в
// тот же прогон, а не через выпуск.
//
// Читается файл, а не сеть: проба обязана идти на голой машине, без живого контроллера и без
// докера. Дальше по-прежнему разбирает ПУЛЬТ — образец только заменяет выдумку.
//
// Чужую зону это НЕ правит и от неё не зависит в сборке: `control/README.md` только читается,
// и только пробами; в собранный пульт этот файл не попадает (его никто не импортирует из кода).
// Разъехались README соседа и его же код — это вопрос к зоне `control`, и пусть он звучит
// здесь красным, а не молчит.
import { existsSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";

/** Где живёт контракт — считая от корня репозитория. */
const ГДЕ = join("control", "README.md");

/**
 * Ищем ВВЕРХ от каталога запуска, а не считаем путь от этого файла: раннер зовут и из `web/`
 * (`pnpm -C web test`), и из корня, а `import.meta.url` под раннером — вовсе не файловый адрес.
 */
function найти(): string {
  let каталог = process.cwd();
  for (let вверх = 0; вверх < 6; вверх += 1) {
    const путь = join(каталог, ГДЕ);
    if (existsSync(путь)) return путь;
    const выше = dirname(каталог);
    if (выше === каталог) break;
    каталог = выше;
  }
  throw new Error(
    `рядом с ${process.cwd()} не нашёлся ${ГДЕ} — образцы ответов пробы берут из контракта ` +
      "соседа, а не сочиняют: без файла проба проверяла бы выдумку",
  );
}

const КОНТРАКТ = найти();

/** Текст контракта — одно чтение файла на прогон. */
let прочитанный: string | undefined;

function текстКонтракта(): string {
  if (прочитанный !== undefined) return прочитанный;
  try {
    прочитанный = readFileSync(КОНТРАКТ, "utf8");
  } catch (cause) {
    throw new Error(
      `не прочитать контракт соседа (${КОНТРАКТ}): ${cause instanceof Error ? cause.message : String(cause)}. ` +
        "Образцы ответов пробы берут оттуда, а не сочиняют: без файла проба проверяла бы выдумку.",
    );
  }
  return прочитанный;
}

/** Разобранные образцы ответов из контракта — по одному разбору на прогон. */
let разобранные: Array<Record<string, unknown>> | undefined;

/**
 * Все json-блоки контракта, которые разбираются. Неразбираемые пропускаем молча: в доке рядом
 * лежат куски с многоточиями и комментариями, и они не образцы.
 */
function блоки(): Array<Record<string, unknown>> {
  if (разобранные) return разобранные;

  const текст = текстКонтракта();
  const out: Array<Record<string, unknown>> = [];
  for (const кусок of текст.matchAll(/```json\n([\s\S]*?)```/g)) {
    let parsed: unknown;
    try {
      parsed = JSON.parse(кусок[1]!);
    } catch {
      continue;
    }
    if (parsed !== null && typeof parsed === "object" && !Array.isArray(parsed)) {
      out.push(parsed as Record<string, unknown>);
    }
  }
  разобранные = out;
  return out;
}

/**
 * Образец ответа из контракта — тот, где есть названное поле.
 *
 * Не нашли — падаем ГРОМКО и с адресом: пропавший образец значит, что контракт переписан, и
 * молча подставить свой значило бы вернуть ту самую выдумку, ради ухода от которой файл и есть.
 */
export function изКонтракта<T>(поле: string): T {
  const найден = блоки().find((блок) => поле in блок);
  if (!найден) {
    throw new Error(
      `в контракте (${КОНТРАКТ}) нет образца ответа с полем «${поле}» — ` +
        "форма разъехалась, и это вопрос к зоне control, а не повод дописать образец здесь",
    );
  }
  // Приведение к типу пульта — это ЗАЯВКА, и проверяет её проба разбора: она гоняет тот же
  // образец через `liveControl` и краснеет, если формы разошлись (`control.test.ts`).
  return найден as T;
}

// ── цена, названная соседом ──────────────────────────────────────────────────
//
// Путь с ПАРОЛЕМ меняет чужую машину: контроллер заходит по ssh один раз и кладёт строку в
// её `~/.ssh/authorized_keys` (`WORLD2-141`). Сказать об этом надо ДО кнопки, а жмут её
// здесь, — но в ответе ручки `note` приезжает уже ПОСЛЕ записи: это подтверждение, а не
// предупреждение, и до действия его взять неоткуда.
//
// Поэтому цену пульт держит у себя строкой (`src/Creds.tsx`) — и держит её ДОСЛОВНО из доки
// соседа, а не своими словами. Проба ниже вырезает ту же строку из `control/README.md` и
// требует СОВПАДЕНИЯ знак в знак: поменяет сосед цену или поведение — краснеет здесь, а не
// у человека на чужой машине.

/**
 * Цена пути с паролем, вырезанная из контракта соседа («ЦЕНА, КОТОРУЮ НАДО ЗНАТЬ ДО, А НЕ
 * ПОСЛЕ»).
 *
 * Отрезаем два куска, и оба — про доку, а не про юзера: заголовок цитаты и хвост «Об этом
 * сказано здесь, в подсказке процесса…» (перечень мест, где это написано).
 */
export function ценаИзКонтракта(): string {
  const строка = текстКонтракта().match(/^> \*\*ЦЕНА[^\n]*$/m)?.[0];
  if (!строка) {
    throw new Error(
      `в контракте (${КОНТРАКТ}) нет блока «ЦЕНА, КОТОРУЮ НАДО ЗНАТЬ ДО» — ` +
        "цена пути с паролем переписана или убрана, и это вопрос к зоне control, " +
        "а не повод оставить в пульте прежние слова",
    );
  }
  const безРазметки = строка
    .replace(/^>\s*/, "")
    .replace(/\*\*/g, "")
    .replace(/`/g, "")
    .replace(/\s+/g, " ")
    .trim();
  return безРазметки
    .replace(/^ЦЕНА, КОТОРУЮ НАДО ЗНАТЬ ДО, А НЕ ПОСЛЕ\.\s*/, "")
    .split("Об этом сказано")[0]!
    .trim();
}

// ── край значений ────────────────────────────────────────────────────────────
//
// ГРАНИЦА СВЕРКИ С КОНТРАКТОМ, и она стоила входа в мир (`WORLD2-135`). Образец в доке
// показывает ФОРМУ ответа, но не показывает законный ДИАПАЗОН значений: пример там один, и в
// нём бренд назван. Пустой бренд — тоже законный ответ, и по нему пульт отказывал каждому,
// кто входит впервые, а все пробы зоны при этом были зелёными.
//
// ЧЕМ ЭТО БЫЛО ДО СТУПЕНИ 2 И ПОЧЕМУ БОЛЬШЕ НЕ ТО. Здесь лежал СНИМОК ЖИВОГО ПРОГОНА — ответ,
// снятый с настоящего контроллера 2026-08-16 на выпуске `sha-0ab9078` (`WORLD2-135`). Снимок
// умер вместе с формой: в нём скоуп лежал по пути на машине контроллера (`/scope/я`, поля
// `here` и `path`), а такого адреса больше нет — контроллер отказывает на нём `bad-address`
// (`WORLD2-132`).
//
// ОБНОВЛЕНИЕ 2026-08-21 (`WORLD2-155`): «снять НЕЧЕМ» больше не так. Сквозной прогон поднимает
// настоящий контроллер и настоящую раздачу процессами, без докера (`npm run e2e`), — живой
// ответ свежего скоупа теперь снимается. Работа отдельная и здесь не сделана; сам край с этого
// дня проверяется в браузере (`e2e/pult.spec.ts`, регрессия `WORLD2-135`), а не только тут.
//
// Подправить мёртвый снимок рукой под новую форму было бы худшим из ходов: он перестал бы
// быть снимком, оставшись им по названию, — и следующий читатель поверил бы, что край значений
// проверен живьём. Поэтому край собирается ЯВНО: форма берётся из контракта (уехала у соседа —
// краснеет здесь), а само крайнее значение ставим мы и называем это вслух.
//
// Долг назван и не закрыт: пока в `control/README.md` один образец ответа входа, край значений
// держится нашей рукой. Правильное место для него — второй образец в доке соседа (свежий скоуп
// с пустым брендом); предложка зоне `control` повторена в отчёте по этой задаче.

/**
 * Вход на СВЕЖЕСОЗДАННЫЙ скоуп — первое, что видит всякий новый юзер: имя и пустота.
 *
 * Форма — из контракта, значение — крайнее: бренда нет, потому что под ним отдают своё, а
 * отдавать новичок ещё не начинал. `created` — заведён прямо сейчас.
 */
export function свежийСкоуп<T extends { brand: string; created: boolean }>(): T {
  return { ...изКонтракта<T>("token"), brand: "", created: true };
}

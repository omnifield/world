// Креды к машине — ДВА ВИДА, и вид называет человек (`WORLD2-141`, решение user).
//
// Отдельным файлом, потому что креды спрашиваются в ДВУХ местах: при заведении скоупа (машина,
// на которой встанет раздача) и при добавлении ресурса. Разъедься эти две формы — человек
// получил бы два разных разговора об одном и том же, а цену узнал бы только в одном из них.
//
// **Вид не угадывается по виду строки** — ни контроллером, ни пультом. Угаданный однажды
// примет ключ за пароль, и разбираться человек будет с отказом ssh, а не с нашей догадкой.
// Поэтому на экране это выбор, а не эвристика: «свой ключ» либо «пароль машины», как в PuTTY.
//
// ┌─────────────────────────────────────────────────────────────────────────────────────┐
// │ ЦЕНА НАЗЫВАЕТСЯ ДО КНОПКИ, А НЕ ПОСЛЕ.                                              │
// │                                                                                      │
// │ Путь с паролем ПИШЕТ В ЧУЖУЮ МАШИНУ: контроллер заходит по ssh один раз и кладёт      │
// │ строку в её `~/.ssh/authorized_keys`. Узнать об этом после — значит узнать поздно:    │
// │ действие необратимо в том смысле, что уже случилось (`WORLD2` 2.3, 0.1).             │
// └─────────────────────────────────────────────────────────────────────────────────────┘
//
// В ответе ручки цена приезжает полем `note` — но ПОСЛЕ записи: это подтверждение, а не
// предупреждение, и до действия его взять неоткуда. Поэтому строка ниже живёт у нас — и живёт
// ДОСЛОВНО из доки соседа, а не нашими словами: свой пересказ разъехался бы с его поведением
// на первой же правке. Совпадение знак в знак стережёт проба (`ценаИзКонтракта()` читает
// `control/README.md`) — поменяет сосед цену, покраснеет здесь, а не у человека на машине.
import { Show } from "solid-js";

import type { Creds, CredsKind } from "./control.js";
import { Button, Field, Input, Label, Textarea } from "./ui.jsx";

/**
 * Цена пути с паролем — ДОСЛОВНО из `control/README.md`, блок «ЦЕНА, КОТОРУЮ НАДО ЗНАТЬ ДО,
 * А НЕ ПОСЛЕ». Правится только вслед за соседом, и проба этого требует.
 */
export const ЦЕНА_ПАРОЛЯ =
  "Путь с паролем пишет в чужую машину: одна строка в ~/.ssh/authorized_keys, " +
  "подписанная world-control. Она обратимая — убрал строку, убрал доступ, — но это " +
  "изменение машины юзера, и мир делает его только потому, что юзер сам отдал креды.";

export type CredsFieldProps = {
  creds: Creds;
  onChange: (creds: Creds) => void;
  /** Чем подписать блок: креды спрашиваются про разные машины на разных экранах. */
  подпись?: string;
};

/** Пустые креды — вид назван, значение ещё нет. Умолчание вида ключ: он ничего не меняет. */
export const пустыеКреды = (): Creds => ({ kind: "key", value: "" });

export function CredsField(props: CredsFieldProps) {
  const выбрать = (kind: CredsKind) => {
    if (kind === props.creds.kind) return;
    // Значение чистим ВМЕСТЕ с видом: ключ и пароль — разные секреты, и оставшийся в поле
    // ключ, отправленный как пароль, уехал бы на чужую машину попыткой входа.
    props.onChange({ kind, value: "" });
  };

  return (
    <div class="pult__creds" data-creds={props.creds.kind}>
      <p class="pult__label">{props.подпись ?? "Чем контроллер дотянется до машины"}</p>
      <div class="pult__row" role="group" aria-label="вид кред">
        <Button
          data-creds-kind="key"
          aria-pressed={props.creds.kind === "key" ? "true" : "false"}
          onClick={() => выбрать("key")}
        >
          Свой ключ
        </Button>
        <Button
          data-creds-kind="password"
          aria-pressed={props.creds.kind === "password" ? "true" : "false"}
          onClick={() => выбрать("password")}
        >
          Пароль машины
        </Button>
      </div>

      <Show
        when={props.creds.kind === "password"}
        fallback={
          <Field
            class="pult__field"
            value={props.creds.value}
            onChange={(value) => props.onChange({ kind: "key", value })}
          >
            <Label>Приватный ключ</Label>
            <Textarea rows={3} placeholder="ключ целиком" />
          </Field>
        }
      >
        {/* Цена — ДО поля и до кнопки, а не рядом с результатом. Человек читает её раньше,
            чем наберёт пароль, и может уйти на ключ, ничего не потратив. */}
        <p class="pult__price" data-price="password">
          {ЦЕНА_ПАРОЛЯ}
        </p>
        <Field
          class="pult__field"
          value={props.creds.value}
          onChange={(value) => props.onChange({ kind: "password", value })}
        >
          <Label>Пароль машины</Label>
          <Input type="password" autocomplete="off" />
        </Field>
      </Show>
    </div>
  );
}

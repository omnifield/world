// Пробы экрана входа.
//
// Проверяем не «компонент не упал», а ЧТО написано человеку и ЧТО ушло в контроллер: экран
// входа — единственное место, где человек называет адрес своего скоупа и пароль, и ошибка тут
// стоит ему входа в мир.
import { afterEach, describe, expect, it } from "vitest";

import { SignIn } from "./SignIn.jsx";
import type { Answer, Control, Session } from "./control.js";
import { изКонтракта } from "./probe-contract.js";
import { ввести, дождаться, нажать, осесть, смонтировать } from "./probe-dom.jsx";

let проба: { корень: HTMLElement; снять: () => void } | undefined;

afterEach(() => {
  проба?.снять();
  проба = undefined;
});

// Образцы ответов вырезаны из контракта соседа (`probe-contract.ts`), а не написаны рукой:
// проба, разбирающая нашу же выдумку, зеленеет и тогда, когда контроллер отвечает иначе.
// `since` у ответа входа нет — его и не бывает; пульт ставит там пустую строку.
const ВОШЁЛ: Session = { ...изКонтракта<Omit<Session, "since">>("token"), since: "" };
const АДРЕС = ВОШЁЛ.scope.addr;

/** Контроллер для пробы: помнит, чем его позвали, и отвечает тем, что велели. */
function контроллер(ответ: Answer<Session> | Array<Answer<Session>>) {
  const очередь = Array.isArray(ответ) ? [...ответ] : [ответ];
  const звонки: Array<{ ручка: string; чем: unknown }> = [];
  const следующий = () => (очередь.length > 1 ? очередь.shift()! : очередь[0]!);
  const control = {
    async enter(req: unknown) {
      звонки.push({ ручка: "enter", чем: req });
      return следующий();
    },
    async createScope(req: unknown) {
      звонки.push({ ручка: "createScope", чем: req });
      return следующий();
    },
  } as unknown as Control;
  return { control, звонки };
}

/** Отказ «скоупа нет» — образец из контракта; `said` дописывает пульт, разобрав чужой отказ. */
const ОБРАЗЕЦ_ОТКАЗА = изКонтракта<{ code: string; why: string; ways: string[] }>("code");
const ОТКАЗ_НЕТ_СКОУПА: Answer<Session> = {
  kind: "refusal",
  refusal: { ...ОБРАЗЕЦ_ОТКАЗА, said: "control" },
};

describe("до входа не существует ничего", () => {
  it("на экране только адрес скоупа и пароль — ни ресурсов, ни полей, ни имени", async () => {
    // `WORLD2-102`: «больше на нём нет ничего: ни полей, ни ресурсов — до входа их не
    // существует». Появится здесь список — проба покраснеет.
    const { control } = контроллер({ kind: "ok", value: ВОШЁЛ });
    проба = смонтировать(() => <SignIn control={control} onEntered={() => {}} />);

    const подписи = [...проба.корень.querySelectorAll("label")].map((l) => l.textContent?.trim());
    expect(подписи).toEqual(["Где лежит твой скоуп", "Пароль скоупа"]);
    expect(проба.корень.textContent).not.toContain("Источники ресурса");
    expect(проба.корень.textContent).not.toContain("Поля");
  });
});

describe("вход — адрес и пароль, и больше ничего", () => {
  it("отдаёт контроллеру ровно то, что назвал человек, и сообщает о входе", async () => {
    const { control, звонки } = контроллер({ kind: "ok", value: ВОШЁЛ });
    let вошёл: Session | undefined;
    проба = смонтировать(() => <SignIn control={control} onEntered={(s) => (вошёл = s)} />);

    ввести(проба.корень, "Где лежит твой скоуп", АДРЕС);
    ввести(проба.корень, "Пароль скоупа", "пароль-скоупа");
    нажать(проба.корень, "Войти");
    await осесть();

    expect(звонки).toEqual([
      { ручка: "enter", чем: { addr: АДРЕС, password: "пароль-скоупа" } },
    ]);
    expect(вошёл?.name).toBe(ВОШЁЛ.name);
  });

  it("пароль вводится ПАРОЛЕМ — он не адрес, его не показывают и не пересылают", async () => {
    const { control } = контроллер({ kind: "ok", value: ВОШЁЛ });
    проба = смонтировать(() => <SignIn control={control} onEntered={() => {}} />);

    const подпись = [...проба.корень.querySelectorAll("label")].find(
      (l) => l.textContent?.trim() === "Пароль скоупа",
    )!;
    const поле = проба.корень.querySelector<HTMLInputElement>(`#${CSS.escape(подпись.htmlFor)}`)!;

    expect(поле.type).toBe("password");
  });
});

describe("хода «завести здесь» не существует", () => {
  // `WORLD2` 3.7, решение user 2026-08-16, находка живого прогона (`WORLD2-129`): мир не
  // просто допускал запрещённый ход — он ему УЧИЛ, печатая его первым шагом. Порча приёмки:
  // вернуть «завести здесь» — и эта проба обязана покраснеть.
  it("такого хода нет ни одной кнопкой — ни до отказа, ни после", async () => {
    const { control } = контроллер(ОТКАЗ_НЕТ_СКОУПА);
    проба = смонтировать(() => <SignIn control={control} onEntered={() => {}} />);

    const ходы = () =>
      [...проба!.корень.querySelectorAll("button")].map((b) =>
        (b.textContent ?? "").trim().toLowerCase(),
      );
    expect(ходы().some((т) => т.includes("завести здесь"))).toBe(false);
    expect(ходы()).toContain("скоупа ещё нет — завести по адресу");

    нажать(проба.корень, "Войти");
    await дождаться(
      () => проба?.корень.querySelector<HTMLElement>("[data-refusal]"),
      "блок отказа",
    );

    expect(ходы().some((т) => т.includes("завести здесь"))).toBe(false);
  });

  it("в теле входа нет ни «create», ни имени, ни бренда", async () => {
    // Спрашивается одно и то же, что бы там ни лежало по адресу: разница только в исходе.
    const { control, звонки } = контроллер({ kind: "ok", value: ВОШЁЛ });
    проба = смонтировать(() => <SignIn control={control} onEntered={() => {}} />);

    ввести(проба.корень, "Где лежит твой скоуп", АДРЕС);
    ввести(проба.корень, "Пароль скоупа", "пароль");
    нажать(проба.корень, "Войти");
    await осесть();

    expect(Object.keys(звонки[0]?.чем as object)).toEqual(["addr", "password"]);
  });
});

describe("завести скоуп — там, где он будет лежать", () => {
  it("две пары уезжают раздельно: скоуп, личность и машина", async () => {
    // `WORLD2` 3.4, «Два адреса»: машина — куда дотянуться и что поднять; скоуп — по какому
    // адресу входить. Креды машины юзер даёт руками, потому что скоупа ещё нет.
    const { control, звонки } = контроллер({ kind: "ok", value: { ...ВОШЁЛ, created: true } });
    проба = смонтировать(() => <SignIn control={control} onEntered={() => {}} />);

    нажать(проба.корень, "Скоупа ещё нет — завести по адресу");
    ввести(проба.корень, "Где лежит твой скоуп", АДРЕС);
    ввести(проба.корень, "Пароль скоупа", "пароль-скоупа");
    ввести(проба.корень, "Имя", "егор");
    ввести(проба.корень, "Бренд", "омнифилд");
    ввести(проба.корень, "Имя участка", "vps");
    ввести(проба.корень, "Адрес машины", "world@10.8.0.5");
    ввести(проба.корень, "Креды к машине", "ключ целиком");
    нажать(проба.корень, "Завести скоуп");
    await осесть();

    expect(звонки).toEqual([
      {
        ручка: "createScope",
        чем: {
          scope: { addr: АДРЕС, password: "пароль-скоупа" },
          identity: { name: "егор", brand: "омнифилд" },
          machine: { name: "vps", addr: "world@10.8.0.5", creds: "ключ целиком" },
        },
      },
    ]);
  });

  it("имя участка спрашивается ОТДЕЛЬНО от адреса машины — мир его не выводит", async () => {
    // `WORLD2` 2.5 п. 11: на имени участка стоит адрес локации, и юзер даёт его сам. Слейся
    // эти два поля в одно — два участка на разных машинах могли бы получить один адрес.
    const { control } = контроллер({ kind: "ok", value: ВОШЁЛ });
    проба = смонтировать(() => <SignIn control={control} onEntered={() => {}} />);

    нажать(проба.корень, "Скоупа ещё нет — завести по адресу");
    const подписи = [...проба.корень.querySelectorAll("label")].map((l) => l.textContent?.trim());

    expect(подписи).toContain("Имя участка");
    expect(подписи).toContain("Адрес машины");
  });

  it("раздачу юзер поднял сам — машина не уезжает ВОВСЕ, а не пустым объектом", async () => {
    // Чужая раздача равноправна (`WORLD2` 0.3), и выбор человек делает явно: контроллер
    // отличает «машину не назвали» от «назвали пустую» наличием ключа.
    const { control, звонки } = контроллер({ kind: "ok", value: { ...ВОШЁЛ, created: true } });
    проба = смонтировать(() => <SignIn control={control} onEntered={() => {}} />);

    нажать(проба.корень, "Скоупа ещё нет — завести по адресу");
    нажать(проба.корень, "Раздача уже стоит по этому адресу");
    ввести(проба.корень, "Где лежит твой скоуп", АДРЕС);
    ввести(проба.корень, "Пароль скоупа", "пароль-скоупа");
    ввести(проба.корень, "Имя", "егор");
    нажать(проба.корень, "Завести скоуп");
    await осесть();

    expect(звонки[0]?.чем).toEqual({
      scope: { addr: АДРЕС, password: "пароль-скоупа" },
      identity: { name: "егор", brand: "" },
    });
    expect(проба.корень.querySelector("[data-machine='raise']")).toBeNull();
  });

  it("пустой бренд заведению не мешает — свежий скоуп это имя и пустота", async () => {
    // `WORLD2-135`: пустое законно, и спотыкаться на нём нельзя ни в одной точке.
    const { control, звонки } = контроллер({ kind: "ok", value: { ...ВОШЁЛ, created: true } });
    проба = смонтировать(() => <SignIn control={control} onEntered={() => {}} />);

    нажать(проба.корень, "Скоупа ещё нет — завести по адресу");
    ввести(проба.корень, "Имя", "я");
    нажать(проба.корень, "Завести скоуп");
    await осесть();

    expect((звонки[0]?.чем as { identity: { brand: string } }).identity.brand).toBe("");
  });
});

describe("отказ", () => {
  it("называет причину и ВСЕ выходы, а не код и не «что-то пошло не так»", async () => {
    const { control } = контроллер(ОТКАЗ_НЕТ_СКОУПА);
    проба = смонтировать(() => <SignIn control={control} onEntered={() => {}} />);

    нажать(проба.корень, "Войти");
    const блок = await дождаться(
      () => проба?.корень.querySelector<HTMLElement>("[data-refusal]"),
      "блок отказа",
    );

    expect(блок.dataset.refusal).toBe(ОБРАЗЕЦ_ОТКАЗА.code);
    expect(блок.textContent).toContain(ОБРАЗЕЦ_ОТКАЗА.why);
    // ВСЕ выходы, и в том же порядке: показанная половина — это отказ, у которого выхода нет.
    const выходы = [...блок.querySelectorAll(".pult__ways li")].map((li) => li.textContent);
    expect(выходы).toEqual(ОБРАЗЕЦ_ОТКАЗА.ways);
    expect(блок.textContent).not.toContain("что-то пошло не так");
  });

  it("говорит, КТО произнёс отказ — контроллер или сам пульт", async () => {
    const { control } = контроллер({
      kind: "refusal",
      refusal: {
        code: "control-unreachable",
        why: "контроллер не отвечает по /api/session",
        ways: ["подними контроллер: ./control/up.sh"],
        said: "panel",
      },
    });
    проба = смонтировать(() => <SignIn control={control} onEntered={() => {}} />);

    нажать(проба.корень, "Войти");
    const блок = await дождаться(
      () => проба?.корень.querySelector<HTMLElement>(".pult__who"),
      "кто произнёс",
    );

    expect(блок.textContent).toContain("пультом");
  });

  it("отказ без выходов показывается без пустого блока «что делать»", async () => {
    // Пустой заголовок «Что делать:» без содержимого — это ровно та серая кнопка без
    // объяснения, которую канон запрещает.
    const { control } = контроллер({
      kind: "refusal",
      refusal: { code: "bad-address", why: "в адресе не названа машина", ways: [], said: "control" },
    });
    проба = смонтировать(() => <SignIn control={control} onEntered={() => {}} />);

    нажать(проба.корень, "Войти");
    const блок = await дождаться(
      () => проба?.корень.querySelector<HTMLElement>("[data-refusal]"),
      "блок отказа",
    );

    expect(блок.querySelector(".pult__exit")).toBeNull();
    expect(блок.textContent).not.toContain("Что делать");
  });
});

describe("скоупа по адресу нет — выход, который назвал контроллер", () => {
  it("путь заведения виден до всякого отказа: человеку без скоупа не нужно сперва получить «нет»", async () => {
    const { control } = контроллер({ kind: "ok", value: ВОШЁЛ });
    проба = смонтировать(() => <SignIn control={control} onEntered={() => {}} />);

    const кнопки = [...проба.корень.querySelectorAll("button")].map((b) => b.textContent?.trim());
    expect(кнопки).toContain("Скоупа ещё нет — завести по адресу");
  });

  it("после отказа no-scope форма заведения открывается с ТЕМ ЖЕ адресом и паролем", async () => {
    const { control, звонки } = контроллер([
      ОТКАЗ_НЕТ_СКОУПА,
      { kind: "ok", value: { ...ВОШЁЛ, created: true } },
    ]);
    let вошёл: Session | undefined;
    проба = смонтировать(() => <SignIn control={control} onEntered={(s) => (вошёл = s)} />);

    ввести(проба.корень, "Где лежит твой скоуп", АДРЕС);
    ввести(проба.корень, "Пароль скоупа", "пароль-скоупа");
    нажать(проба.корень, "Войти");
    await дождаться(
      () => проба?.корень.querySelector<HTMLElement>("[data-refusal]"),
      "блок отказа",
    );

    нажать(проба.корень, "Завести скоуп по этому адресу");
    ввести(проба.корень, "Имя", "егор");
    нажать(проба.корень, "Завести скоуп");
    await осесть();

    // Ни адрес, ни пароль не набираются заново — второй запрос уходит с теми же.
    expect(звонки[1]?.ручка).toBe("createScope");
    expect(звонки[1]?.чем).toEqual({
      scope: { addr: АДРЕС, password: "пароль-скоупа" },
      identity: { name: "егор", brand: "" },
    });
    expect(вошёл?.created).toBe(true);
  });

  it("раздачу этот выход поднимать не просит — контроллер сказал, что она отвечает", async () => {
    // `no-scope` значит ровно то, что раздача по адресу ОТВЕЧАЕТ, а состояния в ней нет.
    // Попроси мы поднять её ещё раз — контроллер отказал бы `share-already`. Выбор при этом
    // остаётся видимым и переключаемым: сказанное показано, а не решено за человека.
    const { control } = контроллер(ОТКАЗ_НЕТ_СКОУПА);
    проба = смонтировать(() => <SignIn control={control} onEntered={() => {}} />);

    нажать(проба.корень, "Войти");
    await дождаться(
      () => проба?.корень.querySelector<HTMLElement>("[data-refusal]"),
      "блок отказа",
    );
    нажать(проба.корень, "Завести скоуп по этому адресу");

    expect(проба.корень.querySelector("[data-machine='raise']")).toBeNull();
    expect(проба.корень.querySelector("[data-machine='own']")).not.toBeNull();
  });
});

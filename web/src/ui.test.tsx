// Пробы примитивов пульта.
//
// Раньше кнопка и поле приезжали китом, и стеречь в них было нечего — за них отвечал чужой
// выпуск. Теперь они наши, а значит наши и обещания, на которых стоят экранные пробы:
//
//   • подпись СВЯЗАНА с вводом — иначе поле не найдёт ни человек по клику, ни скринридер,
//     ни `ввести()` из `probe-dom`;
//   • полей на экране несколько, и связи не путаются между собой;
//   • значение возвращается наверх ровно тем путём, каким его вводит человек;
//   • кнопка по умолчанию НЕ отправляет форму.
//
// Последнее — не мелочь и стоит здесь не для красоты: браузерное умолчание внутри формы это
// `submit`, и кнопка «Скоупа нет — завести здесь» отправляла бы форму входа вместо того,
// чтобы открыть форму заведения.
import { afterEach, describe, expect, it } from "vitest";
import { createSignal } from "solid-js";

import { Button, Field, Input, Label, Textarea } from "./ui.jsx";
import { ввести, нажать, смонтировать } from "./probe-dom.jsx";

let проба: { корень: HTMLElement; снять: () => void } | undefined;

afterEach(() => {
  проба?.снять();
  проба = undefined;
});

describe("поле", () => {
  it("подпись связана с вводом, а введённое возвращается наверх", () => {
    const [значение, задать] = createSignal("");
    проба = смонтировать(() => (
      <Field value={значение()} onChange={задать}>
        <Label>Адрес</Label>
        <Input />
      </Field>
    ));

    const подпись = проба.корень.querySelector("label")!;
    const ввод = проба.корень.querySelector("input")!;
    expect(подпись.getAttribute("for")).toBe(ввод.id);
    expect(ввод.id).not.toBe("");

    ввести(проба.корень, "Адрес", "world@10.8.0.5");
    expect(значение()).toBe("world@10.8.0.5");
    expect(ввод.value).toBe("world@10.8.0.5");
  });

  it("сброс значения СВЕРХУ виден в поле: форма очищается после отправки", () => {
    // Поле управляемое — значит оно обязано ходить в обе стороны. Формы пульта чистят себя
    // после удачной отправки (`setName("")` в `World.tsx`), и поле, снявшее значение один раз
    // при создании, оставило бы там прежний текст: человек нажал «Создать поле», поле создалось,
    // а в строке всё ещё висит его имя — и он жмёт второй раз.
    //
    // Проба заведена 2026-08-16 после порчи нарочно: первая редакция примитивов эту связь не
    // стерегла — снимок вместо функции прогон не покраснил.
    const [значение, задать] = createSignal("дом");
    проба = смонтировать(() => (
      <Field value={значение()} onChange={задать}>
        <Label>Создать поле</Label>
        <Input />
      </Field>
    ));

    const ввод = проба.корень.querySelector("input")!;
    expect(ввод.value).toBe("дом");

    задать("");
    expect(ввод.value).toBe("");
  });

  it("многострочный ввод — то же поле: связь та же, значение то же", () => {
    const [значение, задать] = createSignal("");
    проба = смонтировать(() => (
      <Field value={значение()} onChange={задать}>
        <Label>Креды</Label>
        <Textarea rows={3} />
      </Field>
    ));

    ввести(проба.корень, "Креды", "ключ целиком");
    expect(значение()).toBe("ключ целиком");
    expect(проба.корень.querySelector("textarea")!.rows).toBe(3);
  });

  it("два поля рядом не путают свои подписи", () => {
    // Общий на всех идентификатор связал бы обе подписи с одним вводом, и человек, кликнув
    // по «Креды», попал бы в поле адреса. Проба покраснеет ровно на этом.
    const [адрес, задатьАдрес] = createSignal("");
    const [креды, задатьКреды] = createSignal("");
    проба = смонтировать(() => (
      <>
        <Field value={адрес()} onChange={задатьАдрес}>
          <Label>Адрес</Label>
          <Input />
        </Field>
        <Field value={креды()} onChange={задатьКреды}>
          <Label>Креды</Label>
          <Input />
        </Field>
      </>
    ));

    ввести(проба.корень, "Креды", "ключ");
    expect(креды()).toBe("ключ");
    expect(адрес()).toBe("");
  });

  it("подпись вне поля падает внятно, а не молчит несвязанной", () => {
    expect(() => смонтировать(() => <Label>Сирота</Label>)).toThrow(/вне <Field>/);
  });
});

describe("кнопка", () => {
  it("по умолчанию не отправляет форму — отправляет только та, которой сказали submit", () => {
    const нажатия: string[] = [];
    проба = смонтировать(() => (
      <form onSubmit={(event) => {
        event.preventDefault();
        нажатия.push("submit");
      }}>
        <Button onClick={() => нажатия.push("обычная")}>Передумать</Button>
        <Button type="submit">Войти</Button>
      </form>
    ));

    нажать(проба.корень, "Передумать");
    expect(нажатия).toEqual(["обычная"]);

    нажать(проба.корень, "Войти");
    expect(нажатия).toEqual(["обычная", "submit"]);
  });

  it("несёт зацепку оформления и умеет быть недоступной", () => {
    // По `data-slot` одевается весь набор одним правилом `panel.css` — пропадёт зацепка, и
    // кнопки станут системными серыми, а этого никто не заметит до скриншота.
    проба = смонтировать(() => <Button disabled>Ждём</Button>);
    const кнопка = проба.корень.querySelector("button")!;

    expect(кнопка.dataset.slot).toBe("button");
    expect(кнопка.disabled).toBe(true);
  });
});

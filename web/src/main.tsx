// Точка входа пульта: тема, оформление, монтирование.
//
// Ни одного пакета из мира здесь больше нет. Раньше стояли `-style` (два подпути CSS) и
// `-runtime` (`mount`) со склада локации `probe-web` — то есть, чтобы открыть вход в мир,
// нужно было сперва достать инструменты изнутри мира. Канон говорит обратное с самого начала:
// инструмент это удобство, а не условие (`WORLD2` 0.7 п. 6, 3.7).
//
// CSS двумя файлами, и это не дубль: `theme.css` — единственное место с литеральными
// значениями, `panel.css` — только `var(…)`. Порядок важен: токены объявляются до того, как
// на них сошлются.
import "./theme.css";
import "./panel.css";

import { render } from "solid-js/web";

import { Panel } from "./Panel.jsx";

// Точку монтирования ищем сами. Нет её — падаем внятно: пустая страница без единого слова —
// это отказ без причины, ровно то, чего мир себе не позволяет (`WORLD2` 2.3).
const корень = document.getElementById("root");
if (!корень) {
  throw new Error("в документе нет элемента #root — монтировать пульт некуда (см. index.html)");
}

const снять = render(() => <Panel />, корень);

// В деве модуль переигрывается на лету. Без явного снятия прежний корень остался бы жив, и
// вычисления копились бы стопкой под одним и тем же #root.
import.meta.hot?.dispose(() => снять());

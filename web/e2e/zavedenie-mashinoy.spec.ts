// Заведение скоупа С ПАРОЛЕМ МАШИНЫ — путь, на котором контроллер ПОДНИМАЕТ раздачу сам.
//
// ┌─────────────────────────────────────────────────────────────────────────────────────┐
// │ ЭТОТ СЦЕНАРИЙ ЗДЕСЬ НЕ ГОНЯЕТСЯ, И ЭТО СКАЗАНО ВСЛУХ, А НЕ СПРЯТАНО.                  │
// │                                                                                      │
// │ Ему нужен НАСТОЯЩИЙ ПОДЪЁМ ВЕЩИ: контроллер заходит по ssh на названную машину,       │
// │ кладёт свою строку в её `~/.ssh/authorized_keys` и поднимает там раздачу рецептом —    │
// │ то есть докер, и не подставной, а живой. Докера в девбоксе нет; подсунуть вместо       │
// │ подъёма заглушку значило бы вернуться ровно к тому, из-за чего заведена `WORLD2-151`:  │
// │ заглушка проверяет заглушку и зеленеет на сломанном.                                   │
// │                                                                                      │
// │ Поэтому проба ПРОПУСКАЕТСЯ с причиной и с тем, чем её включить. Прогон её — в CI, где  │
// │ докер есть (`WORLD2-154`), и машину туда даёт зона `deploy`: контейнер с живым systemd │
// │ и sshd она уже поднимает своей работой, и второй копии того же рецепта здесь не будет. │
// └─────────────────────────────────────────────────────────────────────────────────────┘
//
// ЧТО НАДО НАЗВАТЬ, ЧТОБЫ ОНА ПОБЕЖАЛА (имена ЛАТИНСКИЕ — не-ASCII в именах переменных
// окружения bash не держит, тот же урок, что у соседа в `probe-control.sh`):
//
//	E2E_MASHINA        адрес машины, куда дотянется контроллер: `world@10.8.0.5`
//	E2E_PAROL_MASHINY  пароль ЭТОЙ МАШИНЫ — тот, что нужен ровно один раз
//	E2E_ADRES_SKOUPA   адрес, по которому встанет раздача: `http://10.8.0.5:8070/`
//
// Плюс `docker` на пути у самого прогона: подъём зовёт его через `deploy/remote.sh`.
//
// ПОЧЕМУ ЭТОТ ПУТЬ ВООБЩЕ ПРОВЕРЯЕТСЯ ОТДЕЛЬНО. На нём мы спотыкались трижды: `WORLD2-141`
// (креды стали объектом `{kind,value}`), `WORLD2-142` (человек заполнил поля машины в форме
// входа) и дефект `no-answer` 20.08. Все три — про ФОРМУ разговора между пультом и
// контроллером, и ловятся они только там, где разговор настоящий.
import { spawnSync } from "node:child_process";

import { expect, test } from "@playwright/test";

const МАШИНА = process.env.E2E_MASHINA ?? "";
const ПАРОЛЬ_МАШИНЫ = process.env.E2E_PAROL_MASHINY ?? "";
const АДРЕС_СКОУПА_НА_МАШИНЕ = process.env.E2E_ADRES_SKOUPA ?? "";

/** Пароль СКОУПА, который встанет на той машине. С паролем машины он не путается. */
const ПАРОЛЬ_СКОУПА = "пароль-скоупа-на-машине";

/** Личность ДРУГАЯ, не стендовая: этот скоуп лежит по другому адресу и живёт своей жизнью. */
const ИМЯ = "клава";

/** Докер на пути. Спрашиваем его так же, как это делают пробы соседей: одной командой. */
const естьДокер = () => spawnSync("docker", ["version"], { stdio: "ignore" }).status === 0;

test("заведение скоупа с ПАРОЛЕМ МАШИНЫ: контроллер поднимает раздачу и говорит, что изменил", async ({
  page,
}) => {
  test.skip(
    !естьДокер() || !МАШИНА || !ПАРОЛЬ_МАШИНЫ || !АДРЕС_СКОУПА_НА_МАШИНЕ,
    "НЕ ПРОГНАНО, нужен докер: подъём раздачи на названной машине идёт настоящим " +
      "`deploy/remote.sh`. Включается докером на пути плюс E2E_MASHINA, E2E_PAROL_MASHINY " +
      "и E2E_ADRES_SKOUPA — см. шапку файла.",
  );

  // Подъём вещи на чужой машине — минуты, а не секунды: там ставится докер, тянется образ и
  // встаёт раздача. Умолчание Playwright (30 с) убило бы прогон на середине честной работы.
  test.setTimeout(600_000);

  await page.goto("/");
  await page.getByRole("tab", { name: "Завести скоуп" }).click();

  // ПЕРВАЯ ПАРА — сам скоуп: где он будет лежать и чем закрыт.
  await page.getByLabel("Где лежит твой скоуп").fill(АДРЕС_СКОУПА_НА_МАШИНЕ);
  await page.getByLabel("Пароль скоупа").fill(ПАРОЛЬ_СКОУПА);
  await page.getByLabel("Имя", { exact: true }).fill(ИМЯ);

  // ВТОРАЯ ПАРА — машина. Она видна умолчанием: «раздачи ещё нет, подними её» — обычный
  // случай, а не редкость. Три вещи называются РАЗДЕЛЬНО, и ни одна не выводится из другой.
  await expect(page.locator("[data-machine='raise']")).toBeVisible();
  await page.getByLabel("Имя участка").fill("vps");
  await page.getByLabel("Адрес машины").fill(МАШИНА);

  // Вид кред называет ЧЕЛОВЕК (`WORLD2-141`): пульт не угадывает его по виду строки.
  await page.getByRole("button", { name: "Пароль машины" }).click();
  // ЦЕНА — ДО КНОПКИ. Проверяется здесь же и на живом экране: строка обязана быть на месте
  // раньше, чем человек наберёт пароль, а не приехать словами `note` после записи.
  await expect(page.locator("[data-price='password']")).toBeVisible();
  await page.getByLabel("Пароль машины").fill(ПАРОЛЬ_МАШИНЫ);

  await page.getByRole("button", { name: "Завести скоуп", exact: true }).click();

  // Завелось: экран мира, а не отказ.
  await expect(page.locator("[data-screen='world']")).toBeVisible({ timeout: 570_000 });
  await expect(page.locator("[data-refusal]")).toHaveCount(0);
  await expect(page.locator("[data-state='created']")).toContainText(АДРЕС_СКОУПА_НА_МАШИНЕ);

  // И СКАЗАНО, ЧТО ИМЕННО ИЗМЕНЕНО НА ЧУЖОЙ МАШИНЕ — словами контроллера, дословно. Пустая
  // строка здесь означала бы, что мир тронул машину юзера и смолчал об этом.
  await expect(page.locator("[data-note='machine']")).not.toBeEmpty();
});

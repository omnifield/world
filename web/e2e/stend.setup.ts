// Стенд: скоуп заводится ПУЛЬТОМ — в браузере, против настоящего контроллера.
//
// Отдельным проектом Playwright (`стенд`), от которого зависят все сценарии. Причина не в
// красоте отчёта: входить, выходить и проверять пустой бренд НЕ ВО ЧТО, пока скоупа нет, — а
// заводить его в каждом сценарии заново значило бы пять раз проверять одно и то же и ни разу
// не проверить вход.
//
// ПОЧЕМУ ЧЕРЕЗ БРАУЗЕР, А НЕ КУРЛОМ В РУЧКУ. Скоуп можно было бы завести одним запросом в
// обход панели — быстрее и короче. Но заведение это один из пяти сценариев приёмки
// (`WORLD2-155`), и путь, которым мир заводят на самом деле, — это форма с ДВУМЯ парами полей,
// на которой мы уже спотыкались трижды (`WORLD2-141`, `WORLD2-142`). Заведи стенд скоуп мимо
// формы — форма осталась бы непроверенной, а прогон выглядел бы полным.
//
// ЗДЕСЬ ПУТЬ БЕЗ МАШИНЫ: раздача по названному адресу уже стоит (её поднял `webServer`), и
// человек говорит это ЯВНО, переключателем. Путь с ПАРОЛЕМ МАШИНЫ — когда раздачи ещё нет и
// контроллер поднимает её сам — лежит в `zavedenie-mashinoy.spec.ts`: ему нужен настоящий
// подъём вещи, то есть докер.
import { expect, test as стенд } from "@playwright/test";

import { АДРЕС_СКОУПА, БРЕНД, ИМЯ, ПАРОЛЬ_СКОУПА } from "./stend";

стенд("скоуп заводится пультом — по адресу, где раздача уже стоит", async ({ page }) => {
  await page.goto("/");

  // ДВЕ ДВЕРИ, и вторая видна до заполнения (`WORLD2-142`): первый юзер мира не нашёл, как
  // завести личность, и заполнил форму входа. Открываем именно вкладку — у кнопки под формой
  // то же слово, и человек их не различает, а проба обязана.
  await page.getByRole("tab", { name: "Завести скоуп" }).click();

  await page.getByLabel("Где лежит твой скоуп").fill(АДРЕС_СКОУПА);
  await page.getByLabel("Пароль скоупа").fill(ПАРОЛЬ_СКОУПА);
  await page.getByLabel("Имя", { exact: true }).fill(ИМЯ);
  // Бренд НЕ заполняем — он и должен уехать пустым (`WORLD2-135`, см. `stend.ts`).
  await expect(page.getByLabel("Бренд")).toHaveValue(БРЕНД);

  // Раздачу поднимать не просим: она уже стоит по этому адресу. Человек говорит это
  // переключателем, а не пустыми полями машины — мир за него не догадывается (`WORLD2` 0.3).
  await page.getByRole("button", { name: "Раздача уже стоит по этому адресу" }).click();
  await expect(page.locator("[data-machine='own']")).toBeVisible();

  await page.getByRole("button", { name: "Завести скоуп", exact: true }).click();

  // Завелось — значит пульт на экране мира, а не на форме с отказом.
  await expect(page.locator("[data-screen='world']")).toBeVisible();
  // И сказано, ГДЕ он лежит: скоуп твой и лежит по адресу, а не в контроллере (`WORLD2` 3.7).
  await expect(page.locator("[data-state='created']")).toContainText(АДРЕС_СКОУПА);
});

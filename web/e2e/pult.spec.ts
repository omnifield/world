// Сквозные сценарии пульта — настоящий браузер, настоящий контроллер, настоящая раздача.
//
// Порядок здесь — порядок ВАЖНОСТИ (`WORLD2-155`), а не удобства: вход · пустой бренд ·
// отказ · выход. Заведение скоупа стоит стендом (`stend.setup.ts`) — им же и проверено, а
// путь с паролем машины лежит отдельно (`zavedenie-mashinoy.spec.ts`): ему нужен докер.
//
// ЧТО ЭТИ ПРОБЫ ЗНАЮТ, ЧЕГО НЕ ЗНАЮТ МОДУЛЬНЫЕ. Модульная проба подставляет `Control` и
// проверяет, что панель сказала ему верные слова. Здесь слов нет вовсе: панель говорит с
// настоящим контроллером по HTTP, и всё, что можно проверить, — то, что видит человек.
// Поэтому и ловится то, чего модульная не ловит: разъехавшийся контракт, проглоченный отказ,
// поле, которое контроллер называет иначе.
import { expect, test } from "@playwright/test";

import { АДРЕС_СКОУПА, ИМЯ, ПАРОЛЬ_НЕ_ТОТ, ПАРОЛЬ_СКОУПА } from "./stend";

/**
 * Войти пультом: адрес и пароль, и больше ничего (`WORLD2` 3.4). Одним куском, потому что
 * входом начинаются три сценария из четырёх, а разъехавшиеся шаги входа означали бы, что
 * проверяются они на разных путях.
 */
async function войти(page: import("@playwright/test").Page, пароль: string) {
  await page.goto("/");
  await page.getByLabel("Где лежит твой скоуп").fill(АДРЕС_СКОУПА);
  await page.getByLabel("Пароль скоупа").fill(пароль);
  await page.getByRole("button", { name: "Войти", exact: true }).click();
}

test("вход в скоуп: адрес и пароль — и панель показывает личность", async ({ page }) => {
  // Шаг 4 потока и главный сценарий приёмки. До сегодня он был проверен только на подменённом
  // `Control`: панель говорила с рукописным объектом, а не с контроллером.
  await войти(page, ПАРОЛЬ_СКОУПА);

  await expect(page.locator("[data-screen='world']")).toBeVisible();
  await expect(page.locator("[data-me-name]")).toHaveText(ИМЯ);
  // Скоуп лежит ПО АДРЕСУ, и панель показывает машину, на которой он раздаётся, — так, как
  // её разобрал контроллер, а не как её набрал человек.
  await expect(page.locator("[data-scope-host]")).toHaveText("127.0.0.1");
  // Ни одного отказа на экране: вход состоялся целиком, а не «вошли, но что-то не спросилось».
  await expect(page.locator("[data-refusal]")).toHaveCount(0);
});

test("пустой бренд не ломает вход — регрессия WORLD2-135", async ({ page }) => {
  // ┌─────────────────────────────────────────────────────────────────────────────────────┐
  // │ ДОСЛОВНО ТОТ СЛУЧАЙ, из-за которого панель не пускала в мир НИКОГО.                   │
  // │                                                                                      │
  // │ Контроллер отдавал законный пустой бренд (`201`, метка выдана), а разбор пульта       │
  // │ требовал непустого и объявлял это поломкой формы. Проверка стояла с первого коммита   │
  // │ пульта, 61 проба была зелёной — живьём не входил никто.                               │
  // │                                                                                      │
  // │ Скоуп стенда заведён без бренда нарочно (`stend.ts`), поэтому проверка идёт на        │
  // │ настоящем пустом бренде живого контроллера, а не на образце, вырезанном из доки.      │
  // └─────────────────────────────────────────────────────────────────────────────────────┘
  await войти(page, ПАРОЛЬ_СКОУПА);

  await expect(page.locator("[data-screen='world']")).toBeVisible();
  // Пустое показывается СЛОВАМИ, а не пустым местом: пустая ячейка заставляет гадать,
  // отвалилось ли что-то (`web/README.md`, «Пустое законно»).
  await expect(page.locator("[data-me-brand] [data-state='empty']")).toBeVisible();
  // И ничем не подменяется — ни именем, ни прочерком: мир не выдумывает за юзера.
  await expect(page.locator("[data-me-brand]")).not.toContainText(ИМЯ);
  await expect(page.locator("[data-refusal]")).toHaveCount(0);
});

test("отказ виден человеку: код, причина и выход — а не пустой экран", async ({
  page,
  request,
}) => {
  // `WORLD2` 2.3: код машине, причина и ВЫХОДЫ человеку. Отказ настоящий — контроллер сам
  // сходил в раздачу с неверным паролем, получил `401` и назвал причину своими словами.
  //
  // СНАЧАЛА СПРАШИВАЕМ ТУ ЖЕ РУЧКУ НАПРЯМУЮ, а уже потом смотрим на экран. Так проверяется не
  // «на экране что-то красное», а ДОСЛОВНОСТЬ: пульт показывает ровно то, что произнёс
  // контроллер, — его причину и ВСЕ его выходы, в том же порядке. Свой пересказ чужого отказа
  // и показанная половина выходов — то же самое, что отказ без выхода.
  const ответ = await request.post("/api/session", {
    data: { addr: АДРЕС_СКОУПА, password: ПАРОЛЬ_НЕ_ТОТ },
  });
  const сказал = (await ответ.json()) as { code: string; why: string; ways: string[] };
  expect(сказал.code).toBe("bad-password");

  await войти(page, ПАРОЛЬ_НЕ_ТОТ);

  const отказ = page.locator("[data-refusal='bad-password']");
  await expect(отказ).toBeVisible();
  await expect(отказ.locator(".pult__reason")).toHaveText(сказал.why);
  await expect(отказ.locator(".pult__ways li")).toHaveText(сказал.ways);
  // И сказано, КТО отказал: свой отказ пульта и чужой отказ контроллера чинят разные люди.
  await expect(отказ.locator(".pult__who")).toContainText("контроллером");
  // Человек остался там, где может исправить: форма входа никуда не делась.
  await expect(page.locator("[data-screen='sign-in']")).toBeVisible();
  await expect(page.locator("[data-screen='world']")).toHaveCount(0);
});

test("выход: панель возвращается к форме входа и чужого не показывает", async ({ page }) => {
  await войти(page, ПАРОЛЬ_СКОУПА);
  await expect(page.locator("[data-screen='world']")).toBeVisible();

  await page.getByRole("button", { name: "Выйти", exact: true }).click();

  // Вернулись ко входу — и вернулись со СЛОВАМИ контроллера о том, что снято, а что он не
  // трогал: человек, вышедший из мира, не должен гадать, цела ли его личность.
  await expect(page.locator("[data-screen='sign-in']")).toBeVisible();
  await expect(page.locator("[data-state='left']")).toBeVisible();
  // Чужого на экране не осталось: ни имени, ни территорий. Останься они — «личность»
  // перестала бы что-то значить (`WORLD2-124`, `WORLD2-132`).
  await expect(page.locator("[data-screen='world']")).toHaveCount(0);
  await expect(page.locator("[data-me-name]")).toHaveCount(0);
  await expect(page.locator("body")).not.toContainText(ИМЯ);
});

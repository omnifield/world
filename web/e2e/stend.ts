//
// Одним файлом, потому что читают его ДВОЕ и врозь: `playwright.config.ts` (он поднимает
// раздачу и контроллер и должен знать, на чём они слушают) и сами сценарии (они называют
// пультом тот же адрес и тот же пароль). Разъедься эти два знания — прогон поднимал бы одно,
// а проверял другое, и зелёное значило бы «мимо».
//
// ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО: подставного контроллера, подставной раздачи и подставного ответа.
// Прогон идёт против НАСТОЯЩИХ бинарей соседей, собранных из этого же дерева (`WORLD2-155`).
// Заглушка, проверяющая заглушку, — то, из-за чего 61 проба была зелёной, а живьём в мир не
// входил никто (`WORLD2-135`, `WORLD2-151`).
import path from "node:path";


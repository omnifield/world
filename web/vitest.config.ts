// и node спотыкается о расширение: «Unknown file extension ".jsx"». Отсюда inline: такие модули
// проезжают через плагин Solid, как и наш собственный код.
//
// Правило по РАСШИРЕНИЮ, а не по списку имён: список пришлось бы дописывать на каждой новой
// транзитивной зависимости кита (первым отвалился `@kobalte/core`, следом `solid-prevent-scroll`),
// и он молча отстаёт. Расширение же и есть признак: `.jsx` — это непреобразованный исходник.
//
// Место добавки — здесь, а не в пресете, потому что чинить её у себя мы можем сегодня, а
// принадлежит она зоне `build`: любой потребитель, который возьмёт `-ui` и напишет пробу на
// компонент, упрётся в то же самое. Заявка наверх названа в web/README.md.

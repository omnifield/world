// Раннер проб. Раньше пресет приезжал за точкой `@omnifield/probe-web-build/vitest`; теперь
// он здесь целиком, и это ровно три поля — пресет и был тонким.
//
// Три вещи, без которых проба Solid-компонента не работает (дока Solid по тестированию,
// сверено 2026-08-16):
//
//   1. `vite-plugin-solid` в плагинах — он делает JSX-трансформ и в раннере тоже;
//   2. `resolve.conditions: ["development", "browser"]` — иначе `solid-js/web` разрешится в
//      СЕРВЕРНУЮ ветку и `render()` падает «Client-only API called on the server side»;
//   3. `environment: "jsdom"` — без документа рендерить некуда.
//
// Плагин в режиме `test` подставляет условия и jsdom и сам, но держим их явно: так требует
// дока, и конфиг не висит на внутренностях плагина, которые тот вправе поменять выпуском.
//
// Чего здесь БОЛЬШЕ НЕТ: правила `server.deps.inline` по расширению `.jsx`. Оно стояло из-за
// кита на `@kobalte/core` — тот и его соседи отдают по условию `solid` непреобразованный JSX
// файлами `.jsx`, и раннер спотыкался о расширение. Кита не стало, спотыкаться не о что,
// и заявка «починить это в зоне build» вместе с ним отпала.
import solid from "vite-plugin-solid";
import { defineConfig } from "vitest/config";

export default defineConfig({
  plugins: [solid()],
  resolve: {
    conditions: ["development", "browser"],
  },
  test: {
    environment: "jsdom",
    // Модульные пробы живут в `src`, и раннер смотрит ТОЛЬКО туда. Умолчание vitest забирает
    // все `*.spec.ts` дерева, а с ними и сквозной прогон из `e2e/` — тот написан под другой
    // раннер (Playwright) и в jsdom не бежит вовсе. Два раннера на одних файлах — это красное
    // на месте, где ничего не сломано.
    include: ["src/**/*.test.ts", "src/**/*.test.tsx"],
  },
});

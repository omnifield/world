#!/usr/bin/env node
// check-run.mjs — проверка прогона стенда.
//
// Отвечает на один вопрос: ЧТО ИЗ МИРА СТЕНД ПРАВДА ПРОВЕРИЛ. Не «красиво ли»
// и не «много ли событий», а какие правила сработали механикой, какие не
// сработали ни разу, и назвал ли отказ причину.
//
// Отказ без причины считается провалом, а не мелочью: мир, который не
// объясняет, для нас не мир.
//
// Зависимостей нет — папка отдаётся кому угодно как есть.
//
//   node unity/check-run.mjs unity/run-2026-08-07-01

import { readFileSync, existsSync, readdirSync } from 'node:fs'
import { join, basename } from 'node:path'

const RUN = process.argv[2]
if (!RUN) { console.error('нужен путь к папке прогона'); process.exit(2) }

// Закрытый список — ровно шесть правил мира. Отказ вне списка это находка,
// и она обязана быть видна, а не утонуть в свободном тексте.
const ПРАВИЛА = {
  'no-place':              'вещь не может быть нигде',
  'plot-capacity':         'на участке нет места под вторую постройку',
  'requires-provides':     'требования части не покрыты тем, что дают соседи',
  'wrong-rung':            'вещь не своего масштаба',
  'instance-not-portable': 'чужой экземпляр нельзя забрать',
  'no-schema':             'построено не по схеме',
}

// Отговорки вместо причины. Список короткий намеренно: длинный ловил бы
// нормальные короткие причины.
const ОТГОВОРКА = /^(не\s?льзя|нельзя|invalid|not allowed|forbidden|error|denied|—|-)?[.!]?$/i

const красное = [], жёлтое = [], заметки = []
const бей = s => красное.push(s)
const жёлт = s => жёлтое.push(s)

// ── события ──────────────────────────────────────────────────────────────────

const путьСобытий = join(RUN, 'events.jsonl')
if (!existsSync(путьСобытий)) { console.error(`✗ нет ${путьСобытий} — проверять нечего`); process.exit(2) }

const события = []
readFileSync(путьСобытий, 'utf8').split(/\r?\n/).forEach((строка, i) => {
  if (!строка.trim()) return
  try { события.push({ ...JSON.parse(строка), _строка: i + 1 }) }
  catch { бей(`строка ${i + 1}: не разбирается как JSON`) }
})

const сработали = new Map()
let прошло = 0, отказано = 0

for (const e of события) {
  const где = `событие ${e.seq ?? '?'} (строка ${e._строка})`
  for (const поле of ['ts', 'attempt', 'allowed']) {
    if (e[поле] === undefined) бей(`${где}: нет обязательного поля «${поле}»`)
  }

  if (e.allowed === true) { прошло++; continue }
  if (e.allowed !== false) continue
  отказано++

  if (!e.rule) { бей(`${где}: отказ без поля «rule»`); continue }

  if (e.rule === 'other') {
    заметки.push(`${где}: отказ вне шести правил — «${e.reason || 'без описания'}». Это НАХОДКА, разобрать отдельно`)
  } else if (!(e.rule in ПРАВИЛА)) {
    бей(`${где}: правило «${e.rule}» вне закрытого списка. Либо опечатка, либо это «other» + описание`)
    continue
  }

  сработали.set(e.rule, (сработали.get(e.rule) || 0) + 1)

  const причина = (e.reason || '').trim()
  if (!причина) бей(`${где}: отказ без причины. Мир, который не объясняет, для нас не мир`)
  else if (ОТГОВОРКА.test(причина)) бей(`${где}: причина — отговорка («${причина}»), а не объяснение`)
  else if (причина.length < 12) жёлт(`${где}: причина очень короткая («${причина}») — проверь, объясняет ли она`)

  if (!(e.suggest || '').trim()) жёлт(`${где}: нет «suggest» — отказ объясняет, но не подсказывает выход`)
}

// ── намерение против исхода ──────────────────────────────────────────────────
//
// Без `intent` «правило не сработало» значит и «не выражено механикой», и
// «не пробовали» — различить нельзя. С ним видно точно, и это главное, что
// проверка вообще умеет сказать.

const пробовали = new Map()   // rule → сколько раз целились
const попал = new Map()       // rule → сколько раз попали
const промах = []             // целились в одно, вышло другое

for (const e of события) {
  const i = e.intent
  if (!i) continue
  if (i === 'allow') {
    if (e.allowed === false) {
      промах.push(`событие ${e.seq}: шаг должен был ПРОЙТИ, но отказано правилом «${e.rule}» — «${e.reason || ''}»`)
    }
    continue
  }
  пробовали.set(i, (пробовали.get(i) || 0) + 1)
  if (e.allowed === true) {
    промах.push(`событие ${e.seq}: целились в «${i}», но шаг ПРОШЁЛ — правило не сработало на своём же случае`)
  } else if (e.rule === i) {
    попал.set(i, (попал.get(i) || 0) + 1)
  } else {
    промах.push(`событие ${e.seq}: целились в «${i}», сработало «${e.rule}» — не то правило`)
  }
}

const безНамерения = события.filter(e => !e.intent).length

// ── покрытие правил ──────────────────────────────────────────────────────────

const непроверено = Object.keys(ПРАВИЛА).filter(r => !сработали.has(r))

// ── прочие артефакты прогона ─────────────────────────────────────────────────

const артефакты = [
  ['run.json', 'что за прогон и какие заглушки поставлены'],
  ['world.json', 'снимок мира — по нему проверяется размещение без картинки'],
  ['report.md', 'ответы на три вопроса задания'],
]
const нехватает = артефакты.filter(([f]) => !existsSync(join(RUN, f)))
const снимки = existsSync(join(RUN, 'shots')) ? readdirSync(join(RUN, 'shots')).filter(f => /\.(png|jpe?g)$/i.test(f)).length : 0

// ── заглушки из run.json ─────────────────────────────────────────────────────

let заглушки = []
if (existsSync(join(RUN, 'run.json'))) {
  try { заглушки = JSON.parse(readFileSync(join(RUN, 'run.json'), 'utf8')).stubs || [] } catch { бей('run.json не разбирается') }
}

// ── отчёт ────────────────────────────────────────────────────────────────────

const П = s => console.log(s)
П(`\nПРОГОН ${basename(RUN)}`)
П(`событий: ${события.length} · прошло: ${прошло} · отказано: ${отказано}`)

П(`\nПОКРЫТИЕ ПРАВИЛ — ${Object.keys(ПРАВИЛА).length - непроверено.length} из ${Object.keys(ПРАВИЛА).length}`)
for (const [r, что] of Object.entries(ПРАВИЛА)) {
  const n = сработали.get(r), ц = пробовали.get(r)
  let состояние
  if (n && попал.get(r)) состояние = `сработало ${n}×, целились ${ц}×`
  else if (n) состояние = `сработало ${n}×, но не на том шаге, куда целились`
  else if (ц) состояние = `ПРОБОВАЛИ ${ц}×, НЕ СРАБОТАЛО — не выражено механикой`
  else состояние = `не пробовали ни разу — ${что}`
  П(`  ${n && попал.get(r) ? '✓' : ц ? '✗' : '·'} ${r.padEnd(23)} ${состояние}`)
}

if (безНамерения) {
  П(`\n  Событий без «intent»: ${безНамерения}. По ним «не сработало» и «не пробовали» неразличимы.`)
}
if (промах.length) {
  П(`\nЦЕЛИЛИСЬ НЕ ТУДА (${промах.length}) — это дефект стенда либо контракта, не мелочь:`)
  промах.forEach(s => П(`  ✗ ${s}`))
}

if (заглушки.length) {
  П(`\nЗАГЛУШКИ, названные самим стендом (${заглушки.length}):`)
  заглушки.forEach(s => П(`  · ${s}`))
}

if (нехватает.length || !снимки) {
  П(`\nНЕ ХВАТАЕТ В ПАПКЕ:`)
  нехватает.forEach(([f, з]) => П(`  · ${f} — ${з}`))
  if (!снимки) П(`  · shots/ — то, что в JSON не выразишь: читается ли карта, виден ли отказ в момент отказа`)
}

if (заметки.length) { П(`\nНАХОДКИ:`); заметки.forEach(s => П(`  ! ${s}`)) }
if (жёлтое.length) { П(`\nЖЁЛТОЕ:`); жёлтое.forEach(s => П(`  ⚠ ${s}`)) }
if (красное.length) { П(`\nКРАСНОЕ:`); красное.forEach(s => П(`  ✗ ${s}`)) }

П(`\n✗ ${красное.length} · ⚠ ${жёлтое.length} · промахов ${промах.length} · находок ${заметки.length}`)
П(красное.length
  ? 'Красное — форма журнала нарушена либо отказ не объясняет.'
  : промах.length
    ? 'Форма соблюдена, но не всякий шаг задел то правило, в которое целились.'
    : 'Форма соблюдена. Сколько мира при этом проверено — смотри покрытие выше.')
process.exit(красное.length || промах.length ? 1 : 0)
